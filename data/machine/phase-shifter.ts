/**
 * 移相器 —— 把"数条纹"换成"读相位"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 前面那句话只对了一半：缺的是 PZT，不是压电
 * ═══════════════════════════════════════════════════════════════════════
 *
 * `euv-mirror.ts` 第 155 行列了三处缺件，第一条是：
 *
 *   "① 压电移相器（PZT → 锆钛酸铅 → **铅**，本层没有铅）"
 *
 * 铅那一半对：全表没有 `mat/lead` 这个条目（grep 到的四处，都是"没有它"的注释）。
 * 但结论下早了 —— **PZT 要的是铅、锆、钛三样，而石英一样都不要。**
 * 单晶石英的 d₁₁ = 2.3 pm/V，是 PZT 的 1/200（d₃₃ ≈ 400 pm/V），
 * 可它不需要任何本层没有的元素：`std/quartz-resonator-general` 就在清单里，
 * 而那只振子拆开就是**一片 X 切单晶、两面已经镀好铝电极**。
 *
 * 厚度不写 `need`：振子的交付窗口是 32–1000 kHz，对应 **2.9–90 µm**，
 * 而 **d₁₁·V 与片厚无关**（厚只影响场强与刚度）—— 所以哪一档都能用，
 * 本文件按 100 kHz 那一端（28 µm）算例。
 *
 * 移相堆要的正是这个。**所以"没有 PZT"不等于"没有压电"** —— 差别只在
 * 位移小 200 倍，于是靠两件东西补：**堆叠**（n 片串联机械、并联电气）与**杠杆**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 先纠一个数：λ/100 不是步进，λ/8 才是
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 任务书写的是"λ/100 步进、4 步法"，两个数其实不是同一个东西：
 *
 *   分辨率   λ/100 = 5.89 nm      一段面形要读到多细
 *   步进     λ/8  = 73.6 nm       4 步法每步转 90°，**位移**要 λ/8
 *
 * 因为双程：位移 d 改光程 2d，相位 φ = 4πd/λ；一步 90° ⇒ d = λ/8。
 * 两者差 12.5 倍。**若按 λ/100 = 6 nm 去设计行程，4 步法第一步就走不出 90°。**
 * 所以本文件的行程按 λ/8 定，而 λ/100 只作为"读数分辨率"的目标。
 *
 * 换算（钠 D 线 589.0 nm，与 `plant/interferometer` 同一条线）：
 *
 *   一条条纹 = λ/2 = 294.5 nm（位移）
 *   90°      = λ/8 = 73.6 nm
 *   一个条纹 = 一个 λ = 589.0 nm（光程；位移是它的一半）
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四条替代路线，逐条过一遍（数字都摆出来）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * **路线 1 压电石英 —— 选它。**
 *
 *   单片       2.3 pm/V × 1000 V = 2.30 nm；要 6 nm 得 **2609 V**，
 *              要 90°（73.6 nm）得 **32 kV** —— 单片不可能。
 *   32 片堆    73.6 pm/V：6 nm = **81.5 V**，73.6 nm = **1000 V**。
 *   3:1 杠杆   0.221 nm/V：6 nm = **27 V**，0.59 nm（λ/1000）= **2.7 V**。
 *
 *   电极：不用做 —— 振子的两面本来就是蒸铝电极，拆帽取片即可。
 *   接线：33 片 0.05 mm 铜箔夹在片间（奇数片一极），靠预压接触，**不用焊** ——
 *        焊料其实凑得出（`mat/tin` + `mat/silver` = 96.5Sn3.5Ag，221 °C），
 *        但这两样都不在本文件的投料清单里，所以只能压接。
 *   线性度：石英不是铁电体，d₁₁ 的线性 < 0.1%，迟滞 < 0.01%（见问题 2）。
 *   行程为什么只要 221 nm：8 帧、每帧 31.6 nm（143 V），7 步共 221 nm = 3λ/8 = 270°，
 *        够一次采集；再要一整个条纹就得 λ/2 = 294.5 nm，本层给不出。
 *        工业 PZT 台是 10–100 µm，本层只有它的 1/50–1/450 —— 这是这条路的全部代价。
 *
 * **路线 2 波长移相 —— 不可行（差 10⁴ 倍）。**
 *
 *   Δφ = 2πLΔλ/λ²。要 90°（Δφ = π/2）：
 *
 *     L = 1 mm（菲索薄隙）  Δλ = λ²/4L = **87 pm**
 *     L = 10 mm             Δλ = **8.7 pm**
 *     L = 100 mm            Δλ = **0.87 pm**
 *
 *   而钠焰的谱线本身就有 **0.4 pm** 宽（2000 K 的多普勒展宽：Δλ/λ = 6.5×10⁻⁷）。
 *   要"调 87 pm"又要"带宽窄于 0.4 pm"，等于要一台分辨本领 1.5×10⁶ 的单色仪，
 *   而且中心波长要读到 10⁻⁶ 相对值 —— 那是**稳频单频激光**，正是同一份文件
 *   第 157 行列的第二处缺件。转动光栅、改气压都改变不了"谱线是原子给的、
 *   你只能滤不能移"这件事。**结论：不是难，是差四个数量级。**
 *
 * **路线 3 偏振移相 —— 物理通，但那是另造一台仪器。**
 *
 *   两束正交圆偏振 + 转检偏器：相位 = 2θ，**与波长、行程都无关**，
 *   这是它最大的好处（θ 由正弦规 + 量块标定，角度可溯源到长度）。
 *   石英波片也做得出：X 切石英 Δn = 0.0089，λ/4 对应厚 **16.5 µm**，
 *   正好在振子的厚度窗口里 —— 甚至可以用**谐振频率**给厚度定值
 *   （f·d ≈ 2.87 MHz·mm：174 kHz ↔ 16.5 µm）。
 *   它输在别处：① 要偏振分束（本层只能拿玻璃片堆到布儒斯特角当分束器）、
 *   两块 λ/4、一个分度转台，**而且参考臂必须与测试臂分开** —— 本层的
 *   `plant/interferometer` 是菲索式共光路，改不成偏振型，等于另造一台；
 *   ② 16.5 µm 自支撑片要抛到 λ/10 且不能塌；③ 读数还是那双眼（同一条降级）。
 *   **留着当第二条路：等第一台偏振干涉仪存在时，它的相位步进比压电稳 1000 倍。**
 *
 * **路线 4 机械推挽 —— 粘滑吃掉它（差 20–170 倍）。**
 *
 *   差动丝杠 1 µm/格再分 100 份 = 10 nm/份，要 6 nm 的步子得插值到 0.6 份 ——
 *   几何上做得到。热也不是问题（100 mm 钢杠 11.5 nm/K，短时漂移 0.005 nm/s）。
 *   致命的是**干摩擦的粘滑**：仪器丝杠在 10–100 nm 上不是连续走，是"粘住—弹开"，
 *   而全表没有滚珠丝杠、没有静压导轨、也没有一滴油（没有 lubricant/oil/grease）。
 *   0.6 nm 的重复性要压在粘滑幅度的 **1/20 以下**，做不到。
 *   柔性铰链那一半是对的（无摩擦、无爬行）—— 所以它进了主方案，当导向与杠杆。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 问题 1：6 nm 的步进怎么保证？要多少伏，什么放大器？
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 电压：**6 nm = 27 V（经杠杆）；一个 90° 步 = 333 V；满行程 1000 V。**
 *   单片要 2609 V（6 nm）/ 32 kV（90°），所以堆叠不是优化，是唯一出路：
 *   32 片串联机械 → 73.6 pm/V，一级 3:1 柔性杠杆 → 0.221 nm/V。
 *   片取 28 µm（100 kHz 那一端）：1 kV 对应场强 **36 kV/mm**，
 *   石英击穿 ~600 kV/mm，余量 17 倍。
 *
 * 放大器：**本层没有运放可用 —— 这一条要查清，不能含糊。**
 *   `std/opamp-chip-general` **存在**（`data/material/analog.ts:50`，
 *   5 µm 节点、10–30 门、失调 mV 级、激光修调没有、靠手调零），
 *   但它**不在这个文件的 5 项 std 白名单里**；即使放行也用不上 ——
 *   它的输入是毫伏级、输出是几伏，**1 kV 那一段本来就要另做级**。
 *   同理：`std/thyristor-general`、`std/control-board-discrete` 也都不在清单里。
 *
 *   所以放大器是**机电的**：一台 1000 V 他励直流发电机 + 手轮励磁变阻器 +
 *   4 只薄膜电容滤波。换向器本身就是整流器 —— 全表**没有任何整流元件**
 *   （没有硒堆、没有氧化铜整流器；晶闸管倒是有，但不在本文件清单里），
 *   直流只能由换向器给。
 *   纹波：24 槽 × 1500 r/min = 600 Hz，薄膜电容滤波后 0.1%；
 *   而堆叠自己是 3.5 nF 的电容，纹波电流 µA 级。
 *
 * 关键设计决定：**电压不必准，只必须重复。**
 *   因为**没有能测它的表**：`std/dvm-general`、`std/millivoltmeter-general`、
 *   `std/mirror-galvanometer-general` 全都不在清单里；`std/zener-reference-general`
 *   在清单里，但没有检流计就接不进闭环。
 *   于是不去测电压，改去测**相位**（问题 3）—— 刻度的绝对值 ±1% 无所谓，
 *   重复性 0.1% 就够（0.1% × 27 nm = 0.027 nm）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 问题 2：重复性 —— 迟滞、蠕变、预热，各有多大？
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 迟滞：**石英 ≈ 0（< 0.01%）**。原因不是"调得好"，是**它不是铁电体**：
 *   PZT 的 10–15% 迟滞来自畴壁移动，石英没有畴壁。所以本层缺铅这件事，
 *   反而换来一个"没有迟滞、没有老化"的执行器。
 *   代价在别处：d₁₁ 小 200 倍，于是要靠 32 个界面与一级杠杆 —— **迟滞换成了蠕变。**
 *
 * 蠕变：晶体本身 < 0.01%/十倍时间；真正的蠕变源是
 *   ① 32 个研合界面（预压 0.3 N 下的接触松弛）：按 0.05–0.1% 估；
 *   ② 钢片簧的滞弹性（同一量级）。
 *   合计 221 nm × 0.2% = **0.44 nm（分钟尺度）**，而一次采集只有 32 s，
 *   期间只走到 **0.02 nm**。跨班次的重复性靠"每次重新标定"（问题 3）。
 *
 * 预热：**晶体 0 分钟**（直流下不漏电、不发热，漏电流 µA、电容 3.5 nF）；
 *   要预热的是**发电机**：励磁绕组是铜，电阻温度系数 0.4%/K、热时间常数 ~10 min
 *   → 输出电压 0.4%/K。**预热 1 h** 才进 ±0.1 K → 电压重复性 **0.04% = 0.011 nm**。
 *   这是"移相器要提前一小时开机"的全部理由，不是石英要热，是铜要热。
 *
 * 预算（一次 8 帧采集，32 s）：
 *
 *   电压重复性   0.011 nm
 *   界面 + 铰链  0.02  nm
 *   热（共模后） 0.0009 nm
 *   读数（眼）   0.47  nm   ← **λ/1000 = 0.589 nm 是被它吃满的**
 *
 * **结论：机构做到 0.03 nm，读数只到 0.5 nm。这条路的真瓶颈是"没有光电探测器"。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 问题 3：标定 —— 怎么知道推了 6.0 nm 而不是 5.4 nm？
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 量块不行：`std/gauge-block-working` 是 ±0.1 µm = 100 nm，对 6 nm 差 17 倍。
 * 而且它不该被用在这儿 —— 量块是**宏观长度**的基准，移相器要的是**相位**。
 *
 * **用条纹本身，而且这才是正解，不是退让：**
 *
 *   ① 极大→极小之间相位恰好差 π，位移恰好 **λ/4 = 147.3 nm**。
 *      比例由钠波长给定（相对不确定度 10⁻⁷），不是由电压给定。
 *      极值定位到 0.022 条纹（1% 强度读数、sin 顶部是二次的）→ 比例 **±4%**。
 *      **4% 就把"6.0 还是 5.4（差 10%）"分开了。**
 *   ② 8/16 帧最小二乘（I_k = a + b·cos(φ + kδ)，δ 也当未知数解）：
 *      δ 的不确定度 ~0.1%，一次给全 a、b、φ、δ —— **步进不需要预先知道。**
 *   ③ 两个独立来源对得上才算标定成功：晶体常数给的 73.6 pm/V×3 = 0.221 nm/V，
 *      与条纹给的 147.3 nm/刻度差 —— 两者差 < 4% 说明 32 个界面都通。
 *      ⚠️ **但"少一片"只有 1/32 = 3.1%，正好落在 4% 的标定误差里看不清**：
 *      所以虚接不能靠标定发现，只能靠 1 kV 全压试验（虚接的那片上没有电压，
 *      爬弧起头的位置就是它）。这是"自校准"买不到的东西 —— 它给比例，不给通断。
 *
 * **最深的一句：我们根本不需要知道"推了 6.0 nm"，只需要知道"相位转了多少度"。**
 * 相位是条纹读的，"nm"只是把设计值翻译一遍。这条一定下来，电压就不必准了（问题 1）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 问题 4：热 —— 5×10⁻⁴ K 的要求，选共模还是短时？
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 先看清那个数是什么：100 mm 钢件、6 nm 位移 ⇒ ΔT = 6×10⁻⁹/(11.5×10⁻⁶ × 0.1)
 * = **5.2×10⁻⁴ K**；恒温间是 19–21 °C（±1 K）⇒ 差 **1900 倍**。
 *
 * 但这个对比错在把**绝对温区**当成了**漂移率**：
 *
 *   ±1 K 的静态差只给相位加一个常数 —— **算法吃掉它，不损失任何东西。**
 *   真正吃掉 λ/1000 的是**采集期间**的温度变化。
 *   而"漂移率"这个条件**模型写不出来**（`Condition` 只有 min/max，没有 dT/dt）。
 *
 * 所以选**共模抵消**，因为它是唯一能写进结构的办法（不依赖那个写不出的条件）：
 *
 *   不共模：100 mm 钢件自由膨胀 = **1150 nm/K**。恒温间双金属片死区 ±0.5 K、
 *           周期 ~20 min ⇒ 峰值 2.6×10⁻³ K/s ⇒ 32 s 内 **96 nm = 0.33 条纹**。
 *           差 160 倍，任何"快"都救不了。
 *   共模：  参考镜座与工件压在同一块 HT250 平台上（同料、同温、同一热时间常数），
 *           差模只剩**气隙 100 µm** 那一项 = 11.5×10⁻⁶ × 10⁻⁴ = **1.2 nm/K**
 *           ⇒ 32 s 内 **0.10 nm**。1000 倍，够了。
 *
 * 共模救不了的那一项：菲索的测试束比参考束**多穿两次平晶**
 *   （10 mm 熔石英，n·α + dn/dT ≈ 9.5×10⁻⁶/K）= **190 nm/K**。
 *   它靠**铁罩**（30 kg，热时间常数 τ = C/(hA) ≈ 5 h，对 20 min 的室温循环
 *   衰减 T/(2πτ) ≈ 100 倍）：190 × 2.6×10⁻³ × 32 / 100 = **0.16 nm**，余量 3.7 倍。
 *
 * **"4 步在 1 s 内完成"在本层做不到**：眼睛读一帧约 4 s，8 帧 32 s。
 * 所以答案是：**共模（结构）为主，铁罩 + 32 s（操作 + 屏蔽）为辅；
 * 决定性的是共模 —— 它把 1150 nm/K 变成 1.2 nm/K，短时只是把残余再压 100 倍。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级点（按严重程度，八条）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  1. **读数靠眼睛**（清单里没有光电二极管：`std/photodiode-general` 存在但不在
 *     白名单），单帧 1% ⇒ 8 帧 0.47 nm。机构 0.03 nm，读数 0.5 nm —— 瓶颈在读数。
 *  2. **行程只有 3λ/8 = 221 nm**，扫不满一整圈（要 λ/2 = 294.5 nm）⇒
 *     **没有相位解包裹**：一跳过 π 的台阶就丢。只能测连续面形，测不了陡台阶
 *     与薄膜厚度突变 —— 所以要做那块 λ/8 台阶样板，给突发相位一个锚。
 *  3. **参考面仍只有 λ/4**：移相把**分辨**从 15 nm（1/20 条纹）提到 0.5 nm，
 *     但**准确度**还是被平晶卡住（面形的绝对值仍是 λ/4 级，见 euv-mirror 第 9 条）。
 *  4. **没有胶**（本文件清单里没有树脂；全表唯一的一种是 `mat/phenolic-resin`，
 *     而它恰恰是**蠕变源** —— 酚醛在亚微米位移上一生都在流动，量块从不胶接就是这个道理）
 *     ⇒ 32 片只能研合 + 预压：界面会蠕变、怕振动、怕脏；而**测不了氧**
 *     ⇒ 研合面的氧化膜只能靠"擦干净、当场合"的手艺，不能靠气氛控制。
 *  5. **1 kV 在 0.6 kPa 下走不远**：帕申最低点 327 V @ 0.57 Torr·cm，
 *     1 kV 要 ~15 mm 气隙（100 kPa 下只要 0.33 mm）。所以引线封进玻璃套管
 *     （10 kV/mm，壁厚 1 mm 就够），套管一裂就成电弧。
 *  6. **电源带宽 ~1 Hz、纹波 0.1%、预热 1 h**：做不了闭环（没有电容测微那一套 ——
 *     `std/sensor-general` 是通用件，电容桥要检流计，不在清单里），只能开环 + 每次标定。
 *  7. **偏振那条路留着没走**：它不需要 1 kV、热稳定性好 1000 倍，
 *     但要另造一台偏振干涉仪 —— 等那台存在了，换过去。
 *  8. **共模只到"同一块平台"这一级**：铁的 α 有 3% 的批间差、平台上下有温差，
 *     残余 1–3 nm/K 仍要靠 32 s 采集压住。
 */


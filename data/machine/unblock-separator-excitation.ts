/**
 * 励磁电源 —— 第二条来路：**一台并励直流发电机 + 铸铁电阻栅 + 三刀双投刀开关**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么要有这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 严格算术闭包（设备也算进闭包）里，磁选机卡在 `excitation` 上。原路线
 * `make/separator-excitation`（data/material/entry.ts）要三样东西，三样都不在
 * 这十台设备之内：
 *
 *   std/rectifier-rotary-general   旋转变流机。标准件，本质是"外购"
 *   mat/resistance-wire            镍铬电阻丝。镍铬要铬铁（矿热炉），细拉丝要
 *                                  std/wire-die 之外的拉丝台
 *   mat/sheet-steel                冷轧板。板材要轧机，钣金要 plant/sheet-shop
 *
 * 本文**不换零件、换做法**：产出仍是 `plant/magnetic-separator/excitation`，
 * 两条路线并存（同一产出有多条 Route 在模型里就是 OR，原路线照留）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 直流不是"变"出来的，是"换向"出来的
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 旋转变流机是"一台交流机 + 同一根轴上的换向器"。这台机组只留
 * 后半句：**它自己就是发电机**，被主机的传动轴拖着转，电枢里感应的交流电压
 * 在换向片上就地整成直流。没有交流输入、没有滑环、没有电网可接 —— 也就不需要
 * 那台"把交流变成直流的机器"，只需要一台"发直流电的机器"。
 *
 * 需要的材料只有三样，全在本层的料单上：
 *
 *   铜换向片 + 铜刀片   mat/copper            24 片，装配后车圆、下刻
 *   铸铁磁极与电枢      mat/iron-ht200        磁轭兼机座、两块极靴、60 片叠片
 *   碳电刷              mat/carbon            Bosch 碳（CO₂ + H₂），换向就靠它
 *   玻璃丝包线          mat/glass-covered-wire 电枢 3 股并绕、并励绕组 1 600 匝
 *   耐火黏土            mat/refractory        换向片间绝缘、栅条支承、刷握绝缘
 *   45 钢               mat/steel-45          主轴、电刷压簧、刀开关轴
 *
 * 励磁电流是绕出来、通上直流就有的东西；而**没有直流就没有磁**（entry.ts 的
 * 电磁磁体那一条）。所以这一件补的不是线圈，是那个"通上直流"的动作本身。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 这台机组的数（都是估，算式在下面，能被反驳）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 电机：2 极、24 只线圈（无槽叠片电枢）、每只 7 匝、3 股 φ1.0 并绕 → Z = 336 导体。
 * 每极磁通 Φ = 0.0124 Wb（极面 200 × 100 mm = 0.02 m²，气隙磁密 0.62 T）。
 *
 *   E = p·Φ·Z·n / (60·a) = 1 × 0.0124 × 336 × 1450 / (60 × 2) ≈ 50 V
 *
 * 端电压：满载 40 V / 9 A（360 W）—— 扣电枢压降 9 × 0.45 ≈ 4 V、电刷 2 × 1.5 V。
 * 片间电压 = 50 / 12 ≈ **4.2 V**（12 只线圈串联成一条支路，相邻两片就差一只线圈）。
 *
 * 磁场：每极 800 匝（共 1 600 匝）× 平均匝长 0.6 m = 960 m φ1.0，
 *       铜 6.8 kg、热态 28.5 Ω、自励点 1.5 A / 2 400 安匝 / B = 0.62 T。
 * 电枢：168 匝 × 0.55 m × 3 股 = 277 m，铜 1.9 kg、热态 Ra 0.45 Ω。
 *
 * 磁铁那头（make/separator-magnet 的 60 kg 铜：按 8 股 φ1.0 并绕、约 1 000 匝、
 * 热态 4.5 Ω 估）：40 V 时 9.2 A → 9 200 安匝 → 气隙 1.0 T 上下。串栅 1.87 Ω
 * 后 6.4 A → 6 400 安匝 → 0.95 T。**这就是"可调直流"的全部范围。**
 *
 * 效率（估）：
 *
 *   出 360 W
 *   电枢铜耗  9² × 0.45              = 36 W
 *   磁场      40 V × 1.4 A           = 56 W
 *   电刷      3 V × 9 A              = 27 W
 *   铁耗      2 mm 铸铁片 + 氧化层   ≈ 15 W
 *   机械      轴承、电刷摩擦、风阻   ≈ 20 W
 *   合计 154 W → **η ≈ 70%**（经皮带再打 95% → 机组 67%）
 *
 * 对比：旋转变流机 80–85%，汞弧整流器 ~65%，硅整流 95% 以上 —— 但硅要单晶与
 * 封装（半导体层永久外购），旋转变流机要那台外购件。**70% 是本层能自己长出来
 * 的那一档。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 七处降级 —— 每一处都能算，每一处都落在具体的地方
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **电枢没有硅钢片，也没有槽。**
 *    没有轧机、没有冲床、没有绝缘漆 —— 硅钢片这一条整个不成立。替代是：铸铁
 *    圆筒在车床上**一片一片切断**，60 片 × 2 mm，片间绝缘靠**发黑层**（550–600
 *    的湿空气里长 2–5 µm 的 Fe₃O₄），不是漆膜。
 *
 *      · 涡流：整块铸铁电枢按 P ≈ (π²/6)·(f²B²d²/ρ)·V 估 —— f = 24 Hz、B = 0.62 T、
 *        d = 0.12 m、ρ = 1.0 µΩ·m、V ≈ 2.5 dm³，得**十几 kW**，根本转不起来。
 *        车成 2 mm 片后按 d² 掉 1/3 600，只剩几 W；铸铁电阻率又是硅钢的 6 倍，
 *        再白送一倍余量。所以效率表里那 15 W 主要不是涡流，是**磁滞 + 片间接触**
 *        —— 后者才是这条路线的真麻烦（见下一条）。**但 2 mm 是切断刀能切到的
 *        极限，工业是 0.5 mm：同样的涡流，片厚差 4 倍就是 16 倍。**
 *      · 片间不是"绝缘"，是"有点电阻"：Fe₃O₄ 的电阻率 10⁻⁴ Ω·m 量级，而漆膜
 *        是 10¹²。压紧力一大，片间就导通，等效片厚变回整块。所以两端压圈只能给
 *        **中等**压力 —— 松了绕组甩出去，紧了涡流回来。这是路线里最难受的一处。
 *      · 没有槽：绕组直接绕在光滑圆柱外面，靠玻璃丝带箍住（ρv² = 8 960 × 10.6²
 *        ≈ 1.0 MPa，几道带子就够）。代价在气隙上：**4 mm 对真机的 1 mm，同样的
 *        磁密要 3 倍的安匝**（0.62 T × 4 mm / µ₀ ≈ 2 000 A·t，气隙一项就吃掉
 *        磁场绕组的全部余量），磁场铜因此重到 6.8 kg。
 *
 * ② **只有一种线径：φ1.0。**
 *    `mat/glass-covered-wire` 只有 φ1.0 铜 / φ1.4 外径这一个规格
 *    （data/material/unblock-wire.ts），整个模型里也没有别的绝缘线。于是：
 *    电枢要 3 股并绕才带得动 9 A（2.5 A/mm²），磁场要绕到 1 600 匝才把损耗压到
 *    56 W。**真机按 4–6 A/mm² 选线径，这里一根线打天下。** 铜 8.7 kg（真机
 *    2–3 kg），磁场损耗占输出 16%，效率从 85% 掉到 70% —— 这 15 个点全是线径。
 *
 * ③ **换向片间绝缘是耐火黏土，不是云母。**
 *    云母能劈到 0.05 mm、能和铜一起磨平；黏土片只能烧到 1.2 mm，且烧成后
 *    石英与莫来石硬度 6–7 莫氏，**比铜（HB 45）硬得多**。所以必须**下刻**：
 *    装配、车圆之后，在车床上按 24 分度把片间绝缘挖到铜面以下 0.9 mm。不刻，
 *    电刷就被绝缘顶起来一跳一跳地打火，一跳就是一片火花。24 处 × 1 mm 宽，
 *    是这条路线最费工的一道。
 *
 * ④ **火花是常态，不是故障。**
 *    电抗电压 e = L·di/dt：换向的那只线圈电流从 +4.5 A 反到 −4.5 A，电刷宽
 *    12 mm、换向器 φ120 × 24.2 r/s → 周速 9.1 m/s → 换向时间 1.3 ms；L ≈ 0.4 mH
 *    （7 匝、无槽、闭合铁心小）→ **e ≈ 3 V**。而碳刷的接触压降只有 1.5–2 V：
 *    e 比它高，火花能量无处可去，只能烧在电刷后沿与换向片边上。
 *    真机的三样解药一样都没有 —— 换向极要额外的磁极与绕组，均压线要每隔几片
 *    焊一根跨接铜排，叠片冲片要冲床与硅钢片。
 *    **它敢这么干的唯一理由是电压**：片间只有 4.2 V（真机的设计上限是 15–20 V），
 *    24 片上的 4 V 火花烧十年也烧不穿绝缘 —— 它烧的是电刷和换向片的边，
 *    那是耗材与可再车的位置，不是绝缘。
 *
 * ⑤ **电刷是 Bosch 碳，不是石墨。**
 *    `mat/carbon` 是 CO₂ + 2H₂ → C + 2H₂O 的产物（data/material/chain.ts），
 *    没有 2 500 °C 的石墨化炉、也没有铜石墨烧结 —— 所以是**无定形碳**：电阻率
 *    比石墨高一个量级（10⁻⁴ 对 10⁻⁵ Ω·m），摩擦系数高，含铜量为零。
 *    后果三条：接触压降 1.5 → 2 V（40 V 的机器上就是 5% 的电压与功率）；
 *    摩擦大，弹簧压力要给到 20–25 kPa（石墨 15 kPa），机械损耗再涨；
 *    磨损快，**电刷是耗材**。
 *    ⚠️ 但本模型没有给它记消耗的位置：`Item.consumption` 只挂在设备上，而这一件
 *    是"件"。所以磨损只能写在这里，也**不给寿命数字**（规范第 4 条）。
 *
 * ⑥ **调流只有 ±10%，因为磁路在拐点上。**
 *    铸铁栅 0 → 1.87 Ω 能把磁铁电流从 9.2 A 压到 6.4 A（−30%），但铸铁在
 *    0.9 T 以上 dB/dH 掉一半 → 气隙磁密只从 1.05 掉到 0.95 T（−10%）。
 *    这不是路线偷工，是饱和磁路的算术：要把场降到 0.5 T，安匝要从 9 200 压到
 *    1 900（约 5 : 1）、电流 9.2 → 1.9 A，那要串 16.5 Ω —— 铸铁做 16.5 Ω 得
 *    600 m 长（3 × 12 的片），是现在这 60 m 的十倍，栅箱放不下。
 *    **弱场那一段本来就不归它**：entry.ts 里 0.2 T 的弱磁路是另一套。
 *    还有热漂：栅条 77 W / 1.8 m² 表面 → 稳态温升 30–40 K，铸铁 α ≈ 0.0012 /K
 *    → 电阻涨 8–10% → 冷机调好的档，跑半小时场强自己掉 6–8%。刻度要按热态标。
 *
 * ⑦ **并励自励靠剩磁，起励有一步手扳。**
 *    并励发电机建压的条件是"磁化曲线斜率 > 磁场回路电阻"。这台机气隙 4 mm、
 *    曲线平缓，斜率约 29 V/A，而磁场电阻热态 28.5 Ω —— **只差 2%**。也就是说
 *    刀开关或端子上一欧姆的接触电阻就能让它起不来。所以起励不靠"刚好成立"：
 *    先把磁场绕组接成**串励**（借负载电流，串励没有临界电阻问题），电压自己
 *    涨到 40 V 以上，再扳刀开关改回并励、让电压站住。这一步是人扳的，顺序错了
 *    就是一次空转。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么这够一台磁选机的励磁用
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 四条，都落在磁选机这个负载本身的脾气上：
 *
 * **① 负载自己就是滤波器。** 24 片换向器天生有纹波，而磁铁线圈是 5 H 的电感：
 *   时间常数 L/R = 5 / 4.5 ≈ 1.1 s，纹波周期 1 / (24 × 24.2) ≈ 1.7 ms，
 *   纹波比约 1.7 / 1 100 ≈ **0.15%**。磁选机对磁场的要求是"稳在几个点"，不是
 *   "没有纹波" —— **不需要平波电抗器，那 60 kg 铜就是电抗器。**
 *
 * **② 调的是 ±10% 的微调，不是全程调压。** 分选指标（精矿品位与回收率）随场强
 *   是缓变的，现场要的是"这一批矿偏硬、场加大一点"这样的手调。从零到满是
 *   **合闸**（刀开关），不是调流。entry.ts 原话说"磁场强度靠串电阻调"——
 *   串的那只电阻本来就只做微调。
 *
 * **③ 功率占比小，不值得为它造一条整流链。** 磁选机整机：滚筒传动 1.1–2.2 kW，
 *   励磁 0.36 kW —— 15–25%。为四分之一不到的负载去要单晶硅、封装、散热器，
 *   是拿整条半导体链换一只 0.36 kW 的电源。
 *
 * **④ 启停是人工的，慢。** 合闸、拉闸、调档都是人扳刀开关，动作秒级；拉闸时
 *   磁铁 5 H 的储能 ½LI² = ½ × 5 × 9.2² ≈ **210 J**，直接断会 L·di/dt = 5 × 920
 *   ≈ 4 600 V 打穿线圈绝缘。所以刀开关是三刀双投：先落到**放电触头**上，让
 *   9.2 A 经 1.87 Ω 的栅续流（电压只有 17 V，时间常数 2.7 s），再把主刀片抬起。
 *   **栅的第二份工作就是这个续流电阻** —— 它不需要十几欧，它需要的是 1–2 Ω 与
 *   一点热容，而这正是铸铁做得到的那一档。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它没有解决什么
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   · **拖动它的电机不在模型里。** 本路线按"由磁选机的传动轴经皮带带动"写 ——
 *     那台电机与 `make/separator-drive` 是同一处口子：全模型没有电机的整机条目
 *     （data/material/entry.ts 文件头那一段"一处更大的缺口：电机"）。
 *     好处是白得的：主机停转，励磁自动消失 —— 这正是电磁磁选机要的（不带料
 *     不耗电、也不会吸住工具）；代价是励磁不能独立于主机开。
 *   · **磁铁线圈的线径没写。** `make/separator-magnet` 只有"铜 60 kg"，没有线径
 *     与匝数。本路线的电压（40 V）是按"8 股 φ1.0、约 1 000 匝、热态 4.5 Ω"估的
 *     那一条算出来的 —— 两条路线要对一次口径，否则电压对不上。
 *   · **电刷与换向片的磨损没有刻度**（见降级⑤），不给寿命数字。
 *   · **铸铁的电阻率取 1.0 µΩ·m**（HT200 常见值 0.6–1.1）。若取 0.6，栅条要
 *     100 m、栅箱大一倍。这是本路线唯一一个凭材料常数而不是几何的数。
 *   · **没有电压表。** 本层能读直流电压的只有动圈检流计（要 0.2 T 的永磁），而
 *     40 V 量程还要一串高阻值分压电阻 —— 又是本层没有的东西。所以栅的 8 档
 *     **只能按试选结果标**：同一批矿、同一给料量，看滚筒上被吸住的矿层厚薄，
 *     把档位标成"薄 / 中 / 厚"，而不是安培数。这不是省略，这是没有仪表时的做法。
 *   · 没有做过短路与超速试验。刀开关按 12 A 连续、20 A 短时写。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 质量账
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   玻璃丝包线  10 kg   电枢 2（277 m，铜 1.9）+ 磁场 8（960 m，铜 6.8）
 *   铜           3 kg   换向片与升高片 1.4、刀片与刀座 0.6、接线排与端子 0.6、
 *                       栅的分接排与夹子 0.4
 *   HT200      190 kg   机座兼磁轭 55、极靴 22、叠片坯 20（60 片 + 切口损耗）、
 *                       换向器座与压圈 4、刷握与端盖 6、皮带轮 3、刀座与栅箱 12、
 *                       栅条 15.6（50 根 × 1.2 m × 36 mm²）
 *                       → 净重 138 kg，按 1.4 倍浇注（浇冒口）190
 *   45 钢        4 kg   主轴 φ40 × 300（2.9）、电刷压簧 4 片 0.1、刀开关轴与
 *                       弹簧 0.4、栅条卡簧 0.6
 *   耐火土       2 kg   片间绝缘 24 片、栅条支承垫 100 块、刷握绝缘套 4、刀开关
 *                       底板；薄片烧成开裂多，按三倍投
 *   碳         0.5 kg   电刷 4 只（10 × 20 × 30，11 g/只）+ 备用 4 只，
 *                       磨弧面与钻刷辫孔废掉一半
 *   尾矿砂     240 kg   砂型：190 × 1.25（与 make/crusher-cast 同一个比）
 *   水          14 kg   型砂调湿 6% × 240；发黑那一道的水蒸气也从这里出
 *
 * 产出 `plant/magnetic-separator/excitation` 是 `part`、`unit: '件'`、没有 mass，
 * 校验只在产出全部以 kg 计时才断言守恒（src/core/describe.ts 的 unbalanced 那一段）。
 * 所以**不写 `unbalanced_zh`** —— 它与 make/magnet-drum-copper、make/crusher-cast
 * 同一个口径：进 460 kg 料，出 1 件。
 *
 * 一句实话：一台 0.36 kW 的机组，铁 190 kg、砂 240 kg —— 比它的功率难看。
 * 原因是栅和机座都是铸铁浇的，而铸铁的电阻率与磁导率都低，只能靠体积堆。
 * 这也正是它比旋转变流机重、比它便宜（不用外购件）的原因。
 */


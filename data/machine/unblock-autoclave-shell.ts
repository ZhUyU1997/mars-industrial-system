/**
 * 高压釜壳体（`plant/autoclave/shell`）的替代路线 —— **两层灰铸铁缩套筒 + 一件螺栓平板端盖**。
 *
 * 这是全项目压力最高的零件之一（`plant/autoclave` holds 10–35 MPa、150–550 °C），
 * 也是"没有那台设备、就没有那条路"最硬的一处：原路线要一台能锻几吨重筒体的水压机，
 * 而本层的锻锤（`plant/forge`，空气锤）连"砧座是它最勉强的一次"都写进注释了。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 一、原路线为什么不通：三处缺口，一处比一处硬
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 原路线（`data/machine/autoclave.ts` 的 `make/autoclave-shell`）：
 *
 *   mat/steel-40cr 1 + needs[plant/milling-machine, plant/grinder, plant/forge] + lathe
 *   注释写着"厚壁 40Cr 锻件掏空，两端法兰加厚"、`make/autoclave-shell` 的工序是
 *   "粗车 → 探伤 → 精镗内孔 → 车法兰密封面"
 *
 * 三处缺口：
 *
 * ① **材料**。40Cr = 铁 982 + 碳 4 + 铬铁 14（`make/steel-40cr`），铬铁要 140 : 1 的富集
 *    （`mat/ferrochrome` 的注释），而熔炼要到 1550–1650。
 * ② **锻件**。30 MPa 的筒体不能卷，只能锻 —— 而 `plant/forge` 是空气锤，"大型锻件
 *    （几吨以上的筒体）它做不了"（forge.ts 文件头）。**锻不出来**，不是"贵"。
 * ③ **探伤**。原路线里那个"探伤"两个字，在本层没有对应条目：没有射线、没有超声、
 *    没有磁粉。它是这条路线唯一一处**连替代做法都想不出来**的工序 —— 因为它不是
 *    "拿什么做"，是"拿什么看"。见第七节：水压试验替代不了它，只能替代一小部分。
 *
 * 所以这一条要回答的不是"怎么把 40Cr 换成别的钢"，是：
 * **一件不能焊、不能锻、不能探伤的脆性材料，能不能做出一个 10 MPa 的容器。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 二、工业怎么干，以及它每一件在这里缺什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 工业的 10–35 MPa 高压釜（水热、浸出、苯酚水解、哈伯）是三样东西叠起来的：
 *
 *   筒体    厚壁锻钢（40Cr / 2.25Cr-1Mo）掏空，或厚钢板卷焊（壁厚 60–120 mm）
 *   封头    锻制或卷焊的半球/椭圆封头，与筒体**焊**成一体
 *   密封    金属缠绕垫 / 透镜垫 / 卡环快开，几十只大螺栓
 *   检验    100% 射线或超声 + 焊后消除应力热处理 + 1.25–1.5 倍水压试验
 *
 * 逐条对到本层：
 *
 *   锻钢筒体   ✗ 没有能锻 5 t 筒体的设备（水压机不在八大类器具里）
 *   卷焊筒体   ✗ 没有厚钢板（`mat/sheet-steel` 是 1–2 mm 冷轧板），也没有焊接探伤
 *   焊封头     ✗ 同上，而且铸铁根本不能焊
 *   金属缠绕垫 ✗ 要不锈钢带（`mat/stainless-steel` 在闭包外）
 *   大螺栓     ✓ 45 钢 + 空气锤，M24 的锻件它做得了
 *   100% 探伤  ✗ 没有射线源、没有超声仪
 *
 * 六行里只有一行通。所以这一条是把"压力边界"从**钢的焊接结构**改成
 * **铁的铸造结构**：铸铁不能焊，那就一处焊缝都不要 —— 全部用铸件 + 螺栓 +
 * 缩套，接缝靠"金属对金属 + 铜垫 + 预紧"，不靠熔合。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 三、尺寸不是挑的，是从车床反推的：φ386 是这台机器的天花板
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 种子里那台车床是"400 mm 级普通／精密车床，整机约 2.2 t"（lathe.ts 第四节），
 * 即最大回转直径约 400 mm。这一条的所有尺寸都被它夹住：
 *
 *   内孔 φ250 → 算出来的壁厚 68 → **外径 φ386**
 *   φ386 < 400，余量 14 mm（半径 7 mm）—— 这就是"能车"与"不能车"的分界线
 *
 * 为什么内孔不能再大：内孔 φ300 就要约 80 mm 壁、外径 φ460，车床装不进去；φ250 是
 * 唯一一个"壁厚够、外径刚好进卡盘"的点。**一个零件的直径，是被另一台设备的
 * 回转直径定死的** —— 与 `unblock-aluminium-cathode` 里"阴极块 0.5 m 宽定了整条
 * 热平衡"是同一类事。
 *
 * 代价是产量：内腔 φ250 × 1 150 = **0.056 m³（56 L）**，一批浆料约 100 kg。
 *   ⚠️ **实际批量是 70 kg**（阀门那条校正）：水在 250 °C 膨胀 25%，
 *   56 L 装满在 20 °C、到 250 °C 要 70 L，所以充装率只能 70%（1 K = 5.6 MPa，满釜会顶开安全阀）。
 * 工业的浸出高压釜是 10–100 m³，**这台是它的 1/200 到 1/2000**。这不是"小一号"，
 * 这是"另一个量级" —— 记在降级②。
 *
 * 结构上还有一个更硬的约束，它决定了"为什么非得是两层套"：
 *
 *   内筒要有一端封闭（不然两端都要盖 + 螺栓），而**整体铸出的封闭端与筒体同径**
 *   （φ340 的端板）；缩套的箍要从**开口那一端**套进去，一路滑到中间。
 *   所以内筒必须是**一根光管 + 一个同径的厚端板**，两端都不能有法兰 —— 一有法兰，
 *   箍就套不进去。这不是设计选择，是装配顺序的物理。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四、壁厚：三个公式，三个数（50 / 66 / 只算内筒）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 许用应力先定死（后面所有的数都从它出来）：
 *
 *   HT250 抗拉（30 mm 试棒）        Su = 250 MPa
 *   250 °C 折减（灰铸铁到 300 还有 9 成）    ×0.92 → 230 MPa
 *   安全系数                        n = 9
 *   ────────────────────────────────────────────
 *   许用应力                        σ_allow = 25 MPa
 *
 * n = 9 不是随手取的，它是三件事乘起来（常规压力容器的 n 是 3–4）：
 *
 *   3.0  常规压力容器的底数
 *   ×2.0 脆性 —— 铸铁没有屈服，缺陷处的应力集中**不会重分配**，只会裂
 *   ×1.5 没有无损探伤 —— 缺陷的尺寸、位置、数量都是未知数（第七节）
 *   ────
 *   9.0  （工业规范对灰铸铁压力容器的许用应力也在 Su/10 这个量级，与本层同档）
 *
 * 于是同一个 φ250 内孔，三种算法给出三个壁厚：
 *
 *   ① 薄壁膜公式     t = p·r/σ = 10×125/25 = **50 mm**   —— 两层"完全摊平"才有的厚度
 *   ② Lamé 厚壁公式  σ_bore = p(K²+1)/(K²−1) = 25 → K = 1.5275 → **t = 66 mm**（取 68）
 *   ③ 只算内筒       K = 170/125 = 1.36 → σ_bore = 33.5 MPa（n 掉到 6.9，见第六节）
 *
 * 这一条取 ②：**68 mm = 45（内筒）+ 23（一道箍）**，外径 φ386。
 * 取 ② 不取 ① 的理由是第五节：① 是"两层完全摊平"才有的厚度，而摊平要的过盈量
 * 与本层的量具能力是同一个量级 —— 所以设计按"两层贴合等于一个整体"算，那个"等于"
 * 就是 Lamé。**预应力只当余量，不当依据。**
 *
 * ── 一张表：压力往上走，灰铸铁就不只是"更厚"，是"没有解" ──
 *
 *   设计压力   膜厚度   整体 Lamé 厚度   外径     这台车床
 *   5 MPa      25 mm    28 mm           φ306     ✓
 *   10 MPa     50 mm    66–68 mm        φ386     ✓（这一条）
 *   15 MPa     75 mm    125 mm          φ500     ✗ 装不进
 *   25 MPa    125 mm    **无解**         —        —
 *   30 MPa    150 mm    **无解**         —        —
 *   35 MPa    175 mm    **无解**         —        —
 *
 * "无解"不是算不出数，是**数学上不存在**：Lamé 的孔边环向应力随壁厚单调下降，
 * 但它的下界就是内压本身（K → ∞ 时 σ_bore → p）。所以 p ≥ σ_allow = 25 MPa 时，
 * 灰铸铁的整体容器**再厚也扛不住** —— 35 MPa 不是"更难做"，是"另一类材料"。
 *
 * 这张表是这一条路线最重要的一句话：**灰铸铁的高压天花板不是 35 MPa，是 25 MPa
 * （理论上任何厚度）/ 15 MPa（车床装得下）/ 10 MPa（铸得实、又探不了伤）。**
 * 机器的 10–35 里，这条路只站在最下面那一格。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 五、缩套：为什么只套一道箍，以及 17 µm 的窗口
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 19 世纪炮管的办法是对的：把几层筒热套在一起，让**内层在受压之前先被外层压住**，
 * 于是内壁的工作应力从"孔边最高"被摊平到"整圈都差不多"。摊平之后要的壁厚就是
 * 薄壁膜的 ①（50 mm）而不是 Lamé 的 ②（66 mm）—— 表面上省 16 mm、约 140 kg 铁。
 *
 * **但这 16 mm 在灰铸铁上拿不到**，原因是箍自己：一个受外压 p_c 的薄筒，内壁环向
 * 拉应力 = p_c·(a²+b²)/(b²−a²)，那个系数只与 r/t 有关：
 *
 *   箍 23 mm（本路线）      a=170、b=193，r/t = 7.4   → 系数 **7.9**
 *   箍 11.5 + 11.5（三层）  a=170、b=181.5，r/t = 15   → 系数 **15.3**
 *
 * 同样 1 MPa 的接触压力，薄箍的内壁要比厚箍多扛一倍。而摊平内筒要的 p_c 在 2 MPa
 * 上下（下面算），薄箍在那里已经是 31 MPa —— 过了许用的 25。
 *
 * 所以分三层不是"更保险"，是**把预应力的窗口从 17 µm 压到 5 µm**，而 5 µm 在本层
 * 根本量不出来。**层数不是越多越好：层多到箍比管子薄，预应力就全被箍吃掉。**
 *
 * 反过来再退一步，连"省料"这件事都退掉了：要让 50 mm 的那条路成立，摊平要的
 * p_c ≈ 5 MPa，而接这个接触压力的箍得满足 (a²+b²)/(b²−a²) ≤ 5（即 b/a ≤ 1.22）——
 * 那要 35 mm 厚。30（内筒）+ 35（箍）= 65 mm，**又回到整体铸造那个数**。
 * 19 世纪的炮管能省料，是因为它的内管是钢（许用 200 以上），箍的压力放大系数
 * 对它不要紧；灰铸铁的许用只有钢的 1/8，这个技巧就失效了。
 * **一句话：多层缩套在脆性材料上换不到更薄的壁。**
 *
 * 于是只套一道 23 mm 的箍，界面在 r = 170（E = 120 GPa、ν = 0.25），协调方程：
 *
 *   δ = 1.42×10⁻¹² · [11.28·p_c − 2.35·p]      [m；p_c 与 p 都以 MPa 计]
 *   → 装配态（p = 0）p_c ≈ **6.3×10¹⁰ · δ**
 *
 * 四个点定死这个窗口：
 *
 *   δ = 0（贴住，没有过盈）  p = 10 时 p_c = 2.09 → 孔边 **24.4**、箍内壁 16.6
 *                            两条都过线（n = 9.4 / 13.9）—— **这就是本路线的设计态**
 *   δ = 10 µm                工作时 p_c = 2.73 → 孔边 **21.6**、箍内壁 **21.4**
 *                            两边正好摊平（n = 10.6）—— 预应力的全部红利，12%
 *   δ = 17 µm                工作时箍内壁到 **25**（许用）—— 窗口的硬上限
 *   δ > 17 µm                装配态看不出来（箍只有 15 以下），**一打压就过 25**
 *
 * 17 µm 是什么概念：
 *
 *   · 车床车一个 φ340 的铸铁件，圆度 0.03 mm —— **是窗口的两倍**
 *   · 铸铁线膨胀 12×10⁻⁶/K，φ340 上 **3 K 温差 = 0.012 mm** —— 而本层没有温度计
 *   · 选配打号能配到 ±0.005 mm，但"配出来的那个数"在 450 °C 那一趟退火、
 *     以及吊装与装夹里还会再动一次
 *   · 而"没有超声"，所以套完之后**没有任何办法验证它到底压住没有**
 *
 * 结论要分两层写：
 *
 *   ① **做得出 0–17 µm 里的某一个值，保证不了它落在窗口里。** 窗口的量级与本层的
 *      能力是同一个量级 —— 不是"做不到"，是"不能算进设计"。
 *   ② 而这一条最要紧的是：**δ = 0 就是安全的那一端。** 套松了只损失 12% 的余量
 *      （孔边 24.4，n 还有 9.4），套紧了**当场裂，而且是在打压的时候裂**。
 *      于是宁可套松 —— **这是全文唯一一处"探不了伤也没有后果"的地方：因为两个
 *      可能的装配态都过线。**
 *
 * 缩套在这条路线上真正买到的是三件别的东西：
 *
 *   ① 一件 68 mm 的大铸件拆成三件（内筒 398 kg、箍 170 kg、端盖 56 kg），
 *      每一件都进得了 400 级车床，每一件坏了只报废一件
 *   ② 一条**会先漏的界面** —— 这是铸铁唯一能买到的"先漏后破"，见第六节
 *   ③ 45 mm 的筒比 68 mm 的整体筒铸得实（凝固模数 22.5 对 34 mm），
 *      而且它的内孔与外圆**两个承压面都是车出来的**，不是铸态皮
 *
 * 顺便把"自增强"也判掉，因为它是同一件事的另一种做法：**自增强要求内壁真的
 * 塑性化（0.2–0.5% 的残余应变），而灰铸铁的延伸率只有 0.3–0.5%，内壁到不了
 * 塑性就断了。** 钢制 30 MPa 釜靠自增强把弹性极限抬 1.5 倍；铸铁没有这条路，
 * 只能靠几何（缩套）—— 而几何给的只有 12%，不是 33%。**两扇门都只开一条缝，
 * 所以壁厚就是 68。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 六、爆破、安全系数、失效模式：脆断没有先兆，界面是人为造的先兆
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 三条爆破路线（σ_ult = 230 MPa，容器内径 φ250、长 1 150、容积 0.056 m³）：
 *
 *   ① 两层贴合、铸件无缺陷    σ 增长率 2.44 MPa/MPa → p_b = 230/2.44 = **94 MPa**（n_b = 9.4）
 *   ② 箍没贴住，只有内筒在扛  σ 增长率 3.35          → p_b = **69 MPa**（n_b = 6.9）
 *   ③ 内筒有一处 20% 缩松     有效强度 184，增长率 3.35 → p_b = **55 MPa**（n_b = 5.5）
 *
 * 设计点 10 MPa 对这三条的安全系数是 **9.4 / 6.9 / 5.5**。这个设计**不是**按爆破
 * 反推的，是按 σ_allow 反推的 —— 所以 ① 到 ③ 之间只差 1.7 倍，而 ① 到"设计点"
 * 差 9.4 倍。**脆性材料的余量全在许用应力那一侧，不在爆破那一侧。**
 *
 * 失效模式，两条，必须分开说：
 *
 *   脆断（铸铁的唯一模式）  延伸率 0.3–0.5%，没有屈服段，没有鼓包、没有伸长、
 *                            没有"先变形后断"。裂纹到临界尺寸就**碎**，而且碎块有动能：
 *                            10 MPa 下的储能 pV = 564 kJ，按蒸汽等温膨胀算是
 *                            pV·ln(p/p₀) = **2.6 MJ ≈ 0.6 kg TNT**。
 *   泄漏（界面给的）         内筒裂了 → 10 MPa 的水进到配合面 → 界面压力只有 0–3.2 MPa
 *                            （第五节）→ 水沿界面走到箍的端面渗出来 → **看得见**。
 *                            这是"先漏后破"，但它**只在内筒上成立**：
 *                            端盖是单件，它裂了没有第二层接住，直接碎。
 *
 * 所以这条路线有一条听起来很奇怪、但必须写进设计的规则：
 * **配合面的接触压力必须小于设计压力**（p_c < 10 MPa）。压得越紧越"安全"是钢的直觉；
 * 在铸铁上，压得比内压还紧的界面会把唯一的早期征兆堵死。本路线的 p_c 在 0–3.2 MPa
 * 之间（第五节），不是"没套紧"，是**故意留的漏道**。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 七、没有无损探伤，意味着"1.5 倍水压试验只筛得掉一个 16 mm 的洞"
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 工业为什么要 100% 射线/超声：铸铁的缺陷（缩松、冷隔、夹砂、气孔）**都在壁厚中间**，
 * 机加工一刀也削不到。而水压试验能看见的只有"漏"与"裂"，看不见"里面有没有"。
 *
 * 把这句话算成数：试验压力 1.5 × 10 = **15 MPa**：
 *
 *   15 MPa 下孔边应力 = 2.44 × 15 = **36.6 MPa**
 *   36.6 / 230（抗拉）= **16%**
 *   → 要在这个压力下裂，缺陷必须把 45 mm 的内筒壁挖到 **剩 7 mm**（去掉 84%）
 *
 * 也就是说：**1.5 倍水压试验只能筛掉"铸件浇塌了"那一类灾难性缺陷。**
 * 它筛不掉 3 mm 的缩松 —— 而 3 mm 的缩松在 10 MPa 上一点都不危险（n_b 还有 6），
 * 真正危险的是它**会长**（腐蚀 + 每批一次的交变，见第十节）。
 *
 * 那要不要把试验压力抬到 2 倍、3 倍？不能：
 *
 *   2 倍（20 MPa）→ 孔边 48.8 MPa，是 ③ 那条最坏爆破路线（55 MPa）的 89%
 *   → **试验压力本身会把一件"本来能用"的铸件试裂，而且裂了不带征兆**
 *
 * 1.5 倍是这条路线**唯一站得住**的数：它在最坏爆破的 27%，在许用应力的 1.5 倍。
 * 它证明的是"这件东西在 15 MPa 上不裂、不漏"，不是"它能扛 15 MPa 的疲劳"。
 * **一句要写进工艺卡的话：这是漏气试验，不是强度试验。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 八、为什么直径、壁厚、螺栓数都要从"车床"往回推
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 这一节是编排原则，不是力学：**所有需要切削的面，都在装配之前车完。**
 *
 * 因为套好的筒体是 φ386 × 1.15 m × 624 kg，而车床是 400 级、顶尖距 1 m 上下、
 * 承重 200–300 kg。**装配之后一次也上不了机床。** 于是三个铸件各自的活要在自己身上
 * 干完：
 *
 *   内筒   φ340 h6 外圆（箍的配合面）、φ250 内孔（深径比 4.6 的深孔镗）、
 *          开口端面（密封面）、16 只 M24 螺孔（φ300 分度 22.5°）
 *   箍     内外圆各一刀，内孔按内筒实测值**选配打号**
 *   端盖   密封面（平面度 0.02）、16 只 φ26 过孔（与筒体**配钻**，一件一号）
 *
 * 深孔镗是这里最不像"普通车床"的一道：φ250 × 1 150，用一根 φ90 的镗杆伸出 1.2 m，
 * 分四次走刀、每次半径 1.5 mm，两头支承（前支承用一块钻好中心孔的废端盖板）。
 * 自重让镗杆下垂，孔会"鼓"—— 中间比两头大 **0.15–0.3 mm**；反向再走一刀能压到
 * 0.1 mm 上下。**这个鼓形是本路线给不出的精度**，记在缺口里：它不影响强度
 * （多 0.3 mm 的壁），只影响搅拌桨的间隙与清洗。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 九、温度：250 °C 是灰铸铁的舒适上限，而"冷料进热釜"会把它当场裂开
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 机器的 holds 是 150–550 °C。这一条只敢站 150–250 的下半段，两个理由：
 *
 * ① **"生长"（growth）**。350 °C 以上，铸铁里的石墨被炉气/水汽氧化，体积永久膨胀
 *    （0.5–2%/年量级），法兰面会走形、螺栓会松、密封面会翘 —— 这**不可逆**。
 *    250 °C 在安全侧。
 * ② **热冲击**。冷料直接进热釜，壁面的瞬时温差能到 230 K：
 *
 *      σ = E·α·ΔT/(1−ν) = 120 GPa × 12×10⁻⁶ × 230 / 0.75 = **441 MPa**
 *
 *    而抗拉是 230。**一桶 20 °C 的浆料倒进 250 °C 的釜里，它当场裂。**
 *    钢釜也怕这个（钢的 σ 相同，但它能局部屈服、能焊接补），铸铁不能。
 *
 * 所以这条路线有一条比强度更硬的**操作纪律**（本层没有联锁、没有温度计，
 * 只有顺序）：
 *
 *   加料    必须在冷态（< 80 °C）开盖加，或者从进料管**慢**加（≤ 2 K/min 的壁温变化）
 *   升温    ≤ 1 K/min（内壁与外壁的温差 < 15 K，热应力 < 30 MPa）
 *   泄压后  不许立刻开盖（10 → 0.1 MPa 的闪蒸会把釜内温度拉低 40 K）
 *
 * 1 K/min 升温的那笔账：单批从 20 到 250 要 3.8 h，一年 700 批 → 2 700 h 的升降温，
 * 占掉全年三分之一的机时。**这是"不能焊、不能探伤"最后落到日历上的代价。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 十、介质：碱与中性浆料可以，硫酸不行（差 300 倍）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 壳体是裸铸铁，内孔里没有衬里（φ250 × 1.15 m 的孔，砖砌不进去、衬 PTFE 也没有
 * 那条路线）。于是腐蚀速率直接决定寿命：
 *
 *   中性/弱碱浆料（水热合成、碱浸、拜耳法的稀释段）
 *       铸铁 250 °C 约 0.1–0.2 mm/年 → 45 mm 内筒留 5 mm 余量 → **200 年以上**
 *       （实际寿命由交变与密封定，不由腐蚀定）
 *
 *   10% 硫酸、250 °C（真正的酸浸）
 *       碳钢在 10% H₂SO₄ 的 60 °C 是 5–10 mm/年，每升 100 K 大致翻一倍
 *       → 250 °C 是 **50–100 mm/年** → 45 mm 的内筒 **撑不到一年（3–6 个月）**
 *
 * 差 300–500 倍。所以这一条路线**只接碱与中性浆料**；酸浸要衬（`mat/silica` 的
 * 硅质涂料能拖慢，不能当衬），记在降级⑦与缺口里。原注释里"用于水热/浸出工艺"
 * 那半句，在这里被削成"水热 + 碱浸"。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 十一、kg 账（每个数都能对上）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 几何先定死（后面全用它）：
 *
 *   内筒    内 φ250、外 φ340、长 1 150，+ 封闭端板 φ340 × 80
 *           π/4(0.340²−0.250²)×1.15 = 0.04796 m³；端板 π/4×0.1156×0.08 = 0.00726
 *           合计 0.05522 m³ × 7.2 kg/L = **398 kg**
 *   箍      内 φ340、外 φ386、长 900   π/4(0.386²−0.340²)×0.9 = 0.02361 → **170 kg**
 *   端盖    φ340 × 85（含 16 只 M24 的螺栓圈）                     → **56 kg**
 *   铸件合计 398 + 170 + 56 = **624 kg**（浇注量 800，收得率 78%）
 *
 *   45 钢  16 只 M24×130（0.48 kg）7.7 + 螺母 1.6 + 垫圈 0.8      → **10 kg**
 *   铜垫   φ264/φ252 × 4，退火                                     → **1 kg**（含切边）
 *
 *   出一件 ≈ 624 − 车屑 31（5%）+ 10 + 1 = **604 kg**
 *
 *   进 800 铁水 + 10 钢 + 1 铜 + 160 型砂 + 90 面砂 + 60 芯砂 + 100 水 + 12 石灰
 *      = **1 233 kg**
 *   差 629 = 浇冒口 176（回炉）+ 车屑 31（回炉）+ 型砂 160（循环，只记新砂）
 *          + 面砂 90 + 芯砂 60（芯砂混了黏结剂与烧失，不复用）+ 水 100 + 石灰 12
 *   **176 + 31 + 160 + 90 + 60 + 100 + 12 = 629** ✓
 *
 * 铜那 1 kg 值得单说：风化层里铜 30 ppm、选到 25% 的精矿要 8 000 : 1，所以
 * **1 kg 的铜垫背后是 8 t 风化层** —— 全釜最贵的材料按克算，而它只干一件事：
 * 在 10 MPa、250 °C 上压出一圈不漏的线。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 十二、降级（七处，带量级）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① **压力 10 MPa，而机器要 35。** 35 MPa 对灰铸铁不是"更厚"：整体 Lamé 在
 *    p ≥ 25 MPa 上无解（孔边应力 ≥ 内压），膜公式要 175 mm 壁 / φ600 外径（车床装不进）。
 *    所以这台釜只服务水热与碱浸的**下半段**；苯酚水解（30 MPa、350 °C）与哈伯
 *    （15–30 MPa、450 °C）仍然是锻钢的活，一条都没被救回来。
 *
 * ② **产量 56 L 对工业的 10–100 m³ —— 1/200 到 1/2000。** 内孔 φ250 是被车床
 *    的回转直径逼出来的（φ386 < 400）。加一批浆料约 100 kg，工业是每釜几十吨。
 *
 * ③ **重量 604 kg 对锻钢同孔同压的约 150 kg —— 4 倍。** 每 MPa 的金属：
 *    铸铁 60 kg/MPa，锻钢 15 kg/MPa。而压力上限还只有人家的三分之一。
 *
 * ④ **多层缩套在灰铸铁上换不到更薄的壁，连它自己那 12% 的红利也拿不到。**
 *    要摊平到 21.6 需要 10 µm 的过盈，而窗口只有 17 µm 宽、车床圆度就 30 µm、
 *    3 K 温差 12 µm —— 能做出某一个值，保证不了落在窗口里。所以壁厚按无预应力的
 *    24.4 MPa 走（n = 9.4）。而"靠缩套把壁从 68 减到 50"这条路是**堵死**的：
 *    50 mm 要 p_c ≈ 5 MPa，接得住 5 MPa 的箍得 35 mm 厚（b/a ≤ 1.22），总壁又回到 65。
 *    **19 世纪那套工艺的前提是内管用钢；换成许用只有钢 1/8 的铸铁，技巧本身就失效。**
 *
 * ⑤ **没有无损探伤。** 只有 1.5 倍水压（15 MPa），而它只能筛掉"把 45 mm 挖到剩
 *    7 mm"的缺陷 —— 因为 15 MPa 上的应力只有抗拉的 16%。2 倍试验会试裂好件。
 *    **这条路线把安全押在 n = 9 的壁厚上，不押在检验上。**
 *
 * ⑥ **脆断 + 2.6 MJ。** 延伸率 0.3–0.5%，没有屈服、没有鼓包；10 MPa 的储能
 *    pV·ln(p/p₀) = 2.6 MJ ≈ 0.6 kg TNT（水压试验时只有 1.3 kJ，差 2 000 倍）。
 *    所以试压要进土坑、身后堆 1 m 砂袋墙；端盖裂了没有第二层接住。
 *
 * ⑦ **只接碱，不接酸。** 10% H₂SO₄、250 °C 上铸铁 50–100 mm/年 → 45 mm 的内筒
 *    撑 3–6 个月；碱浆料 0.1–0.2 mm/年 → 200 年。差 300–500 倍。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 十三、已知缺口（都不在这条路线能解决的范围里）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  · **没有无损探伤，这一条永远补不上。** 要补它得先有射线源（要电 + 钨靶 + 真空）
 *    或超声（要压电陶瓷 —— 见 `data/material/ceramic.ts` 那条还在半路上的链）。
 *    在那之前，这条路线只能是"用厚度买安全"。
 *  · **没有压力源。** 15 MPa 的水压试验要一台手压泵、一根 φ10 的高压管、一只
 *    25 MPa 的压力表 —— 三样都不是条目，而且本层唯一 hold 得住 15 MPa 的设备是
 *    `plant/autoclave` 自己（要试釜体，先有一台釜）。**这是本文件最直的一处自指。**
 *    数据里没有 `pressure` 的 `under`（写了会报 `no_machine`），所以压力这件事
 *    全写在注释里，校验器看不见它。
 *  · **没有 0.6 kPa 下的水。** 火星表面水在 0.01 °C 就沸腾（三相点 611 Pa），
 *    所以试压回路必须是**密闭的**（水箱 + 泵 + 釜一个回路），漏了不是滴水，是闪蒸
 *    （1 kg 水 → 117 m³ 蒸汽）。型砂里的水当天用、当天盖。
 *  · **没有扭矩扳手。** 16 只 M24 要 190 N·m（= 1 m 杆 + 19 kg 铁砣），误差 ±30%
 *    → 预紧力 28–52 kN，垫片比压 92–171 MPa。这一件**恰好**对误差不敏感（要 30 就够），
 *    但"恰好"不是设计出来的，是运气。
 *  · **没有温度计。** 过盈量的量测温度、升温速率（1 K/min）、250 °C 的判据，
 *    三件事全都要读数，而热电偶在本层还在缺口的名单上。现在只能靠"同一间屋、
 *    同一个上午"和示温笔。
 *  · **深孔镗的鼓形 0.15–0.3 mm。** φ250 × 1 150（深径比 4.6）用 φ90 镗杆两头支承、
 *    反向走刀压到 0.1 mm 上下。它不影响强度，影响搅拌桨间隙与清洗。要更好得有一台
 *    深孔钻镗床，本层没有。
 *  · **端盖上的开孔没写。** 搅拌轴要穿过端盖（`plant/autoclave/agitator` 是另一件
 *    零件），进料、排气、测温、观察窗也都要开孔。φ60 的孔在 φ340 的盖子上，
 *    应力集中 2.5 倍 → 24.4×2.5 = 61 MPa（许用是 25），要一圈 40 mm 的补强凸台；
 *    而**补强凸台与盖板的过渡，正是没有探伤时最不该有的那种几何**。这一条留给
 *    agitator 与 valves 那两条路线，本文件不假装它不存在。
 *  · **装配后再也上不了机床。** φ386 × 624 kg 进不了 400 级车床 —— 所有配合面、
 *    密封面、螺孔都必须在装配前干完，而这意味着**任何一处装配后的修配都得拆开重来**，
 *    每拆一次，选配的号就废一次。这是"两层套"在工艺上的真实代价。
 */


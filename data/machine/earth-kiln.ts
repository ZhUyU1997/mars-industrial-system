/**
 * 土窑 —— 全模型唯一一台**不用任何金属件**的机器。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它是被一次算术逼出来的
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 报告里加了一条"严格算术"：把**设备也算进闭包**（一条路线要能开，执行设备与
 * 在场前提都得"在"）。结果从 388 项掉到 19 项 —— 只有 8 条种子、火星料、与这台窑。
 *
 * 原因是一个环：
 *
 *   炼钢要熔化炉 → 熔化炉的炉壳要钢板 → 钢板要轧机 → 轧机要钢
 *
 * 这个环**不是数据写错了**，是真实世界里的第一道门：工业文明的起点不是冶金，
 * 是**用土做一台能烧到 1000 °C 的窑** —— 人类烧陶烧了五千年，才炼出第一炉铜。
 *
 * 所以这一条补的是种子清单缺的那一项：一台**没有金属件**的炉子。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 怎么做：夯土 + 火道 + 拱顶
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   取土   风化层 + 水，和成泥（风化层含黏土矿物，加水就有塑性）
 *   夯筑   夯成窑壁与拱顶，留火口、烟道与窑门
 *   阴干   几天到几周（模型没有时间）
 *   烧窑   先用小火烘干，再烧到 1000 —— 第一次烧会把窑壁自己烧成陶
 *
 * **第一次烧完，这座窑就不再是土的了**：窑壁被烧结成陶质，耐火度提高一档。
 * 这是人类最早的"用火造材料"：火把土变成陶，陶装得住更高的火。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它能干什么，不能干什么
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   能     烧陶、烧石灰（900）、烧黏土砖（1000）、烘干、退火
 *   不能   熔铁（1538）、烧玻璃（1400）、烧高铝砖（1500）
 *
 * **它是一段梯子的第一级**：土窑（1100）→ 黏土砖 → 砖砌窑（1300）→ 高铝砖
 * → 高温窑（1600）→ 炉衬与坩埚 → 才轮到熔化炉。
 *
 * ⚠️ 一处本层还没有的东西：**鼓风**。土窑靠自然抽风只能到 900 上下，
 * 要上 1100 得吹风；而木风箱要木头、皮囊风箱要皮革，火星两样都没有。
 * 出口在射流：用一股压缩气体引射空气（文丘里），而压缩气体要压缩机 ——
 * 那还是台机器。所以这台窑先按"自然抽风 900–1100"写，鼓风留作缺口。
 */


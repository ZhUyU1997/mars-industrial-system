/**
 * 空分换热器 `plant/air-separator/heat-exchanger` —— 第二条来路：
 * **铸铁壳 + 浇出来的铜管 + 铸铁管板，没有一道工序要卷板、焊接、钎焊。**
 *
 * 这一份是**解锁**用的：把换热器从"等钣金工位 + 等轧机"改成"只等铁与铜"。
 * 它不是要替掉原路线 —— 多条路线产出同一个 Item 是 OR，两条并存：
 * 有轧机、有钣金工位时走原路线（钢壳卷焊 + 管束钎焊，轻、效率高），
 * 没有时走这一条（铸铁壳 + 胀接管束，重、粗，但开得了工）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 这个零件原本是什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * data/material/entry.ts 的 `AIR_SEPARATOR_PARTS` 给它的注释只有一句：
 * 「铜管束 + 钢壳，把压缩热带走，也是冷凝 CO₂ 的地方」。原路线
 * `make/airsep-heat-exchanger` 三行：
 *
 *   uses         mat/copper q(1) + mat/sheet-steel q(1)
 *   needs        lathe
 *   performedBy  plant/sheet-shop
 *
 * 也就是说它要的三件事全落在钣金工位上：
 *
 *   钢壳卷圆      要卷板机            plant/sheet-shop 的活
 *   管板与筒体    要焊                plant/sheet-shop 的活
 *   管束与管板    要钎焊（或胀焊）     plant/sheet-shop 的活
 *
 * 而这两样东西现在都不在闭包里，两处断点各是各的：
 *
 *   mat/sheet-steel       路线 needs `plant/radiator`、执行者是 `plant/rolling-mill`
 *                         （data/material/chain.ts 的 `make/sheet-steel`）—— 轧机不在那七台里
 *   plant/sheet-shop      五件：frame / ram / blade / drive / welder。前两件刚被解锁
 *                         （unblock-sheet-frame.ts 的铸铁机架、unblock-sheet-ram.ts 的
 *                         铸铁滑块），后三件仍压着刀片（40Cr）与焊机；而按
 *                         unblock-airsep-compressor.ts 文件头数过的那七台，整个工位还站不起来
 *
 * 所以这一条不去修钣金工位，**是绕开它**：把三道焊接工序换成三种不焊的连接 ——
 * 浇（筒体）、螺栓加石墨垫（管板）、机械胀接（管束）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 做法：绕管式，一根管从下管板绕到上管板，壳里一个接头都没有
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 三样东西，三样都不焊：
 *
 *   筒体   HT200 浇成 φ250 × φ230 × 700（壁厚 10），两端车止口装端盖
 *   管板   HT250 车成 φ240 × 30 两块，各钻铰 8 个 φ16.3 孔，孔位在 φ176 圆上
 *   管束   8 根 φ16 × φ8 铜管，各 1.5 m，盘在 φ160 铸铁芯筒上（节距 24，升高 65）
 *
 * 一根管怎么走：从下管板的孔穿出 → 绕芯筒 2.7 圈 → 从上管板的孔穿出 → 两头各胀一次。
 * 八根管分**两种旋向交替**盘，八个出口才在管板上拉得开；孔位是一根一根划出来的，
 * 没有钻模也没有分度头（见降级③）。
 *
 * 这一条最要紧的判据是：**没有钎焊，就不许有中间接头。** 所以管子必须一根通到底
 * —— 也就必须整根 1.5 m 一次成形，而本层没有拉管机（拉管要拉管机，见降级②），
 * 只能**浇**。
 *
 * 面积与体积（都是几何，可核）：
 *
 *   管外面积   A = 12 m × π × 0.016 m = 0.60 m²
 *   芯体包络   φ192 × 520 mm ≈ 0.015 m³
 *   比表面积   0.60 / 0.015 ≈ 40 m²/m³
 *   铜重       12 m × π/4 (16² − 8²) mm² × 8930 kg/m³ = 12 × 1.35 = 16.2 kg
 *
 * 「回热器」三个字的用处：压缩过的温热混合气走管程（自上而下），
 * 分选后返回的氮氩冷气走壳程（自下而上）—— 逆流。冷量不是外面给的，
 * 是这一台自己省下来的：进出温差的那一份，全靠这 0.60 m² 拦住。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 换热效率比板翅式低多少 —— 三个数
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   ① 单位面积的传热系数 U
 *        光管气-气（气速 5–10 m/s、管径 8–16 mm）：20–35 W/(m²·K)
 *        板翅式（同工况，有翅片扰动）：                80–150 W/(m²·K)
 *      → **低 3–5 倍**。
 *
 *   ② 比表面积 β（同一体积里塞得进多少平方米）
 *        本设计        40 m²/m³（上面算的）
 *        板翅式        1000–2500 m²/m³（翅片把通道切成毫米级）
 *      → **低 25–60 倍**。
 *
 *   ③ 两者相乘，UA/体积
 *        本设计        30 × 40 ≈ 1.2 kW/(m³·K)
 *        板翅式        100 × 1500 ≈ 150 kW/(m³·K)
 *      → **低约 120 倍，也就是两个数量级。**
 *
 * 于是"体积大多少"有了一个可算的答法：**同样的有效度，体积大 100–200 倍。**
 *
 *   逆流、两侧热容相当（C_r ≈ 1）时 ε = NTU / (1 + NTU)，NTU = UA / C_min。
 *   本层流量按 make/airsep-compressor-lathe 的数算（1.4 m³/min 的进口体积流量）：
 *
 *     进口 0.6 kPa、210 K   ρ = 600 / (287 × 210) ≈ 0.010 kg/m³
 *     质量流量               0.0233 m³/s × 0.010 ≈ 0.23 g/s
 *     热容流                 C_min ≈ 0.23 g/s × 1.0 kJ/(kg·K) = 0.23 W/K
 *
 *   ε = 0.95 要 NTU = 19 → UA = 4.4 W/K
 *     本设计      A = 4.4 / 30 = 0.15 m²（3 m 管）→ 体积 3.8 L
 *     板翅式      A = 4.4 / 100 = 0.044 m²       → 体积 0.03 L
 *     比值        3.8 / 0.03 ≈ **127 倍**
 *
 * ⚠️ 但这一条要和自己较一次劲：**在本层的流量下，"效率"这个指标不是瓶颈。**
 * 做出来的 12 m 管（不是 3 m）对应 NTU = 18 / 0.23 ≈ 78，ε = 0.987 —— 板翅式
 * 在这个流量下当然也能到 0.99。也就是说**有效度并没有被牺牲**，被牺牲的是
 * 体积（15 L 对 0.03 L）与质量（见下）。这一条路线买的是"开得了工"，
 * 不是"效率一样"；而它恰好因为流量小，把效率这一头躲过去了。
 *
 * 反过来说清能力边界：ε ≥ 0.90 要 NTU ≥ 9，即 C ≤ 18 / 9 = 2 W/K ——
 * **这台换热器的流量上限约 2 g/s。** 再往上要加层数（每层多绕 8 根管），
 * 而管数受管板孔位与车床钻孔的限制（见降级③）。这是个能算出来的天花板。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 降级：五处，都可算
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① **管束是光管，没有翅片。** 翅片要冲压或滚轧成带再嵌、钎焊，本层三样都没有。
 *    于是面积只能靠"多绕几米"堆：同样传热量的板翅式芯体是一个拳头大的盒子，
 *    这一台是一个 15 L 的圆筒。**差两个数量级（见上一节的 127 倍）。**
 *    多出来的不只是体积：15 L 的壳体、12 m 的铜管、两块管板，全是质量。
 *
 * ② **铜管是浇出来的，不是拉出来的。** 拉管要拉管机（穿孔 + 多道拉拔 + 退火），
 *    本层没有；能走的路只剩砂芯立浇。代价三条，条条都是数：
 *
 *      壁厚     浇 4 mm，拉管 0.8–1.2 mm  →  铜重 3–4 倍（1.35 kg/m 对 0.34–0.50 kg/m）
 *      内壁     砂芯面 Ra 25–50 µm，拉管 0.8 µm  →  管内侧 h 低 20–30%（估）
 *      收得率   铜水吸气（氢）出气孔，车掉 1 mm 表层 + 浇冒口 → 成品/投料 = 16 / 26 ≈ 62%
 *
 *    还有一条硬约束：砂芯做不长。φ8 × 1.5 m 的芯子偏芯 0.5 mm，管壁就一边 3.5
 *    一边 4.5 —— 所以**一段只能 1.5 m**，而真实回热器是一根 30 m 的管绕到底。
 *    本设计用 8 根并联代替那一根（见"为什么能用"②）。
 *
 * ③ **胀接代替钎焊。** 16 处管-管板连接全靠机械胀（滚柱胀管器 + 45 钢锥芯），
 *    没有一处是焊的、也没有一处是钎的。
 *
 *      胀量    0.20–0.25 mm。钢件可以胀到 0.4，铸铁孔桥性脆，胀过一点就裂，
 *              而裂了看不出来 —— 只有打完压才知道，所以管板要备一块报废的
 *              （HT250 投料 30 kg 里含着一块试钻孔的废件）
 *      强度    拉脱强度约为钎焊的 1/5（估）；许用压差 0.3 MPa 量级
 *      孔数    车床上单孔钻铰 + 划线分度，孔距误差 0.2 mm（钻模是 0.02）。
 *              孔距再密就钻不准，所以一张管板上只有 8 个孔 —— 这是"多少根管"
 *              的真正上限，不是铜不够
 *
 *    这条降级**在本层不致命**，理由见"为什么能用"③：两侧都是同一类气体，
 *    漏是内漏，掉的是效率，不是安全。
 *
 * ④ **壳是铸铁，不是钢板卷焊。** 壁厚 10 mm 对 3 mm 冷轧板，重 2.5 倍（38 kg 对 15 kg）；
 *    抗拉强度不到钢的一半、延伸率近乎零，所以只能做成"厚壁筒 + 螺栓法兰 + 石墨垫"
 *    的低压容器。还有一笔热惯性：铸铁件共 78 kg，从 210 K 到 300 K 要吸 78 × 0.5 × 90 ≈ 3.5 MJ ——
 *    一台 1 kW 的加热器要一小时。**这是"慢"，不是"不行"**：空分本来就慢，
 *    它没有一台设备是几十秒里换工况的。
 *
 * ⑤ **壳侧没有折流板，也没有导流筒。** 折流板要钻孔、要装拉杆，而且会把壳侧
 *    气流切成横掠——那是提 U 的手段。这里靠螺旋管束自己把气流拧成旋流，
 *    传热比直管束好一点、压降也大一点，两头都不精确。**代价说不成数，只能说"没有"。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 结霜与冰堵 —— 在这台机器上，霜是主角
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 三个凝华点，都按分压算：
 *
 *   CO₂（95%，0.1 MPa 下分压 95 kPa）   194.7 K 凝华（-78.5 °C，就是干冰）
 *   CO₂（95%，0.6 kPa 下分压 0.57 kPa） 约 147 K —— 火星原压下要冷到这么低才出霜
 *   水（0.03%，分压 0.18 Pa）           约 200 K —— 水比 CO₂ 先结，但量少
 *
 * 量的账（同一份流量）：
 *
 *   水   0.23 g/s × 0.03% = 0.07 mg/s ≈ **6 g/天**     太少，堵不死，只能在冷端结一层
 *   CO₂ 0.23 g/s × 95%   = 0.22 g/s   ≈ **19 kg/天**   —— 这就是产品本身
 *
 * 所以：**冰堵不是主要风险，干霜才是**；而干霜之所以危险，是因为它按 19 kg/天
 * 的量级往上长 —— 一旦冷端温度掉到 195 K 以下，几小时就能把通道填掉。
 *
 * ⚠️ 时态：本层现在还跑不到这个工况。压比只有 8
 * （0.6 kPa → 4.8 kPa，见 unblock-airsep-compressor.ts 降级①），4.8 kPa 下 CO₂
 * 分压 4.6 kPa、凝华点约 163 K，而本层连 4.8 kPa 的气都还没有稳定产出来。
 * 所以**现在不结霜**。但换结构时必须按设计点算 —— 板翅式与光管在这件事上的
 * 差别是结构性的，不是操作性的。
 *
 * 结构上的差别只有一条：**通道有多宽。**
 *
 *   板翅式   翅片间距 1.5–2 mm，霜层长到 0.7 mm 就堵掉一半
 *   绕管式   节距 24 − 管径 16 = 8 mm 净空，没有翅片，霜只长在光管外圆上，
 *            霜层 4 mm 才把净空吃掉
 *
 * 同一段时间里板翅式先堵，**差 5–6 倍**。这不是"效率低反而好"，是两种结构在
 * 结霜工况下的次序不同：板翅式用翅片买面积，接到霜就变成买堵。
 *
 * 化霜也不一样。光管的外圆是完整圆柱面 —— 停车、从壳侧灌热风或干氮，霜化了就走，
 * 冲得到、吹得到；翅片之间的霜**吹不到**，只能拆开或等它自己化。本层现成的热源是
 * 土窑（400–1100）的热风，一根管子接过去就行。
 *
 * 一句话：**在必须周期性化霜的空分里，耐堵比高效更值钱。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么它仍然"能用" —— 四条
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① **流量小到效率不是瓶颈。** 0.23 g/s 对应 C = 0.23 W/K，UA = 18 W/K 时
 *    NTU ≈ 78、ε = 0.987。同这个流量下板翅式也是 0.99 以上 —— 两者打平，
 *    而这一台是拿 15 L 换来的打平。**体积与质量在这里都不紧**：多出来的是铁与铜，
 *    两样的链都在闭包里；紧的是"能不能不用钣金工位开得了工"，而这一条正好答了它。
 *
 * ② **八根并联代替一根 30 m。** 每根 1.5 m 是砂芯能力的上限（降级②），
 *    八根并联后总长 12 m、面积 0.60 m²，够 NTU ≈ 78。并联的代价是流量分配：
 *    八条流道阻力不一致时，冷的那几条先结霜、先堵 —— 所以八根管**同一炉浇、
 *    同一刀车、同一根芯轴**，把差异压到最小（这是工艺上的"配对"，不是设计）。
 *
 * ③ **内漏不是事故。** 管程与壳程都是 0.1 MPa 量级的空气类气体（CO₂/N₂/Ar），
 *    胀接处漏一点，就是从管侧串到壳侧 —— 损失几个点的冷量，不燃、不爆、不污染、
 *    不停机。**这正是可以不做钎焊的理由**：钎焊买的是"不漏"，而这里漏得起。
 *    （反例写在别处：radiator.ts 的氨回路就不许漏 —— 氨有毒、铜还怕氨。）
 *
 * ④ **材料与工序全在闭包里。** 铁 → HT200/HT250（`make/iron-ht200`、`make/iron-ht250`，
 *    执行者熔炼炉、1350–1450）；铜（`mat/copper`）；45 钢（胀管器与螺栓）。
 *    执行设备只有机器人、熔炼炉、土窑、车床、磨床 —— 全在那七台里，
 *    量块在 `needs` 里当判据，不干活。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 它没有解决什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   · 只通了换热器这一个零件。空分的分离罐与机架仍要 `plant/sheet-shop`，
 *     节流阀仍要 `plant/milling-machine`（unblock-airsep-compressor.ts 数过）。
 *     一条路线只拆一个堵点。
 *   · 不写 `under: pressure`。这台机器自己就是承压的那一件，而它在这里是**零件**
 *     （category = part），不是设备；就算写成设备，本层也没有哪台机器 holds 得住
 *     pressure（`plant/clean` 有 100–500 kPa，但它不在这七台里，也不干这个）。
 *     **这是模型缺口，不是遗漏。**
 *   · 型砂与芯砂不进 `uses`：砂型、砂芯、芯骨是每炉都要重做的，而条目表里没有
 *     "型砂"这一项 —— 与 `make/radiator-panel`（砂型铸散热板）同一处缺口。
 *     芯骨用的 45 钢 φ4 记在 `mat/steel-45` 里，因为它是会留在铸件里被切掉的那一段。
 *   · 结霜周期算不出来：模型没有时间维，"多久化一次霜"这句话写不成字段。
 *     能写的只有温度区间，而霜的厚度是时间的函数。
 *
 * 质量账：投料 26 + 110 + 30 + 9 + 2 + 80 = 257 kg，产出是 `unit: '件'`
 * （data/material/entry.ts 第 332 行），模型对"件"不判质量守恒，所以不写
 * `unbalanced_zh` —— 填了反而会多出一条 `declared_unbalanced` 提示，
 * 而这条路线并没有需要豁免的地方。同 unblock-airsep-compressor.ts 的处理。
 */


/**
 * 温控器（`std/temp-controller-general`）的第二条来路 ——
 * **一根刚玉棒、一片夹起来的双金属、一只微动开关、一根千分螺丝**。
 *
 * 先说清楚它与 `std/process-controller-general` **不是一件东西**（这两件挨着，
 * 最容易写混）。grep 两个条目看得见差别：
 *
 *   process-controller（data/material/process-control.ts 第 45 行）
 *     数字：计算机 + 模拟开关 + 数字表当 ADC + 2 只接触器 + 32 点记录
 *     它是**给高温炉的**：8 路输入、程序曲线、记录历史
 *   temp-controller（data/material/analog.ts 第 58 行）
 *     模拟：2 只运放（P 与 I）+ 1 只比较器 + 镍铬电阻网络 + 热电偶输入
 *     它是**给电阻炉的**：1 路输入、一个设定值、一对触点输出
 *
 * 所以这一件要的"替代"比上一件**低一整档**：不是"能不能闭环"，是
 * "**能不能在 900 °C 上可靠地开一下、关一下**"。上一件用膨胀杆 + 擒纵 + 凸轮 +
 * 烟熏记录（六件套），这一件只需要三件：**棒、杠杆、开关**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一、为什么这一件不用热电偶（与上一件同一个判据，但结论更快）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 闭包里那支热电偶是**铜-铁 T 型，0–200 °C、9.9 µV/K**（`unblock-thermocouple.ts`
 * 第 249 行、`unblock-metrology-hvac.ts` 第 224 行：它是给电阻炉低温段用的）。
 * 而电阻炉要管到 900 —— **量程差 4.5 倍**：
 *
 *   0–200 的丝在 900 上没有分度表；铜到 400 就软、铁到 900 已是一层氧化皮
 *   就算换一对能到 900 的丝（镍铬-镍硅），它的 41 µV/K 在 900 上是 37 mV ——
 *   而一只继电器要 0.5 W：**mV 级放大的四个数量级缺口依旧在**（上一件算过）
 *
 * 所以这一件与上一件一样，**不用电测**。差别只在"用哪根棒"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 二、石英的价值在"不胀"，不在"胀"（纠正一个直觉）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 最省事的想法是"一根石英棒推一只微动开关"（石英是手边最耐热的透明材料）。
 * 算一下就知道它推不动：
 *
 *   熔融石英 α = 0.55e-6/K，棒 300 mm 在外、880 K（20 → 900）
 *     ΔL = 300 × 880 × 0.55e-6 = **0.145 mm**
 *   而快跳开关的触点间隙是 **0.3 mm** —— **推不动**
 *
 * 换刚玉（70% Al₂O₃ 的莫来石-刚玉，α 5.5e-6/K）：
 *
 *   ΔL = 300 × 880 × 5.5e-6 = **1.45 mm**（十倍），灵敏度 **1.65 µm/K** ✓
 *
 * **但石英不能扔 —— 它的位置是"参考支架"，不是"感温棒"。** 冷端的开关座
 * 若装在铸铁壳上，壳热 50 K 就把读数推走：
 *
 *   铸铁/钢支架 300 mm 热 50 K：300 × 50 × 11.5e-6 = **0.17 mm = 105 K 的假信号**
 *   石英支架同一个 50 K：300 × 50 × 0.55e-6 = **0.008 mm = 5 K** ✓
 *
 * 也就是说：**感温用刚玉（要胀），定心用石英（要不胀）** —— 一根棒加一块板，
 * 两个材料各干各的活。这与上一件的"高铝棒 + 石英参考棒"是同一个道理，
 * 只是上一件要差动到 1600，这一件到 900 就够，所以结构可以砍掉一半。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三、双金属与充液毛细管：都到不了 900，但一个能到 300
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   双金属      铜/45 钢，差 5e-6/K。**到 400 以上就退火、蠕变**：铜在 300 就软，
 *               夹紧力一松，读数就漂。所以它只能做低温头（0–300）
 *   充液/蒸汽压式 本层能封的液体只有水（临界 374）与硅油（到 300）——
 *               900 上要钠（沸点 883）或汞（356），两样都没有条目
 *
 * 所以这台控制器做成**两个头、一个身子**：低温头用双金属（换头即换量程，
 * 与那五片孔板、两支膨胀棒是同一个办法），高温头用刚玉棒。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四、设定、死区与摆动（全部是可算的数）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   杠杆      4:1 刀口（一根 45 钢杠杆，刀口在磨床上磨到 0.005）
 *   开关      快跳式微动开关：触点间隙 0.3 mm、**死区 0.05 mm**（动作/复位之差）
 *   螺丝      M8×0.5、100 格 → 5 µm/格
 *
 *   高温头    1.65 µm/K × 4 = **6.6 µm/K**（开关端）
 *             死区 0.05 mm ÷ 6.6 µm/K = **7.6 K**；设定 5 µm/格 ÷ 1.65 = **3 K/格**
 *   低温头    铜/钢夹持双片 200 mm：ΔL = 200 × 400 × 5e-6 = 0.40 mm，**1.0 µm/K**
 *             × 4 = 4 µm/K；死区 **12.5 K**；设定 **5 K/格**
 *             （这一头管时效 120–180、低温回火、镀槽 20–60 —— 12.5 K 的死区
 *              对它们够；但**做不了等温淬火那种 ±3 K 的活**）
 *
 * 摆动（电阻炉：热容 25 kJ/K、5.0 kW 电阻带、900 上热损 2 kW）：
 *
 *   关断时降温 2/25 = 0.08 K/s → 死区 7.6 K 要走 **95 s**
 *   通电时升温 (5−2)/25 = 0.12 K/s → 回升 7.6 K 要 **63 s**
 *   → **周期 158 s、占空比 40%、摆幅 ±3.8 K、一天 547 次通断**
 *
 * 静差：双位控制的稳态温度落在死区的**中点**，而设定值只能卡在死区的一边 ——
 * 所以有一个 **半个死区（3.8 K）的静差**，且它随炉子的散热变（夏天/装料多时更大）。
 * PID 的那一项积分就是消这个静差的；**这一台没有积分，所以这个 3.8 K 消不掉。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五、没有刻度怎么标定：三个定点，其中一个是铜
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 机械表的刻度不是"印"的，是**算出来 + 校出来**的：刻线按 α 与杠杆比算，
 * 三点按物理常数校。
 *
 *   ① **冰水 0 °C**（闭式陶槽，冰与水共存）—— 零点
 *   ② **沸水 100 °C**（湿法槽加压到 100 kPa —— 火星 0.6 kPa 下水 0 °C 就沸，
 *      不压住就没有 100 这个点）
 *   ③ **铜的熔点 1 084.6 °C**（土窑烧到 1 100 把铜熔化，停火缓冷，
 *      **冻结平台**上指针不动的那一刻刻一道）
 *
 * 三点定一条滑线（机械表的刻度不一定是直线：刀口是圆弧、杠杆比随行程变），
 * 中间的温度按 α 与杠杆比算 —— **α 是材料常数，杠杆比拿量块量**，
 * 所以"没有刻度"不是问题，问题是"三个定点够不够"。
 *
 * ⚠️ 铜那一点贴着土窑的上限：窑顶 1 100、铜 1 084.6，**只有 15 K 的余量**。
 * 窑温的波动是 ±30 —— 所以这一步要靠"烧到 1 100 再停火自然冷"，不能靠"稳在 1 090"。
 * 这是这条路线最窄的一处。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 六、它只给一对触点 —— 而这正好是对的
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   传感器 → 杠杆 → 微动开关（铜触点，2 A 220 V 交流）→ **电阻炉自己的接触器**
 *   → 45 钢电阻带（32 V 抽头下 5.0 kW / 155 A，见 `unblock-resf-heating.ts`）
 *
 * 控制器**不碰那 155 A**：功率回路是炉子的（`std/contactor-general` 在炉子的
 * `composedOf` 里，已通）。这不是降级，是分工 —— 工业上的温控表也只给继电器输出。
 *
 * 但它与 PID 温控器有一处真的不一样：**PID 表能把温度信号送出去**（给记录仪、
 * 给上位机、给另一台表做串级），而这一台只有一根指针和一对触点。
 * **它是一台"自用"的表，不是一台"能联网"的表。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 七、精度、寿命与维护（三个数，一个比一个难看）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   精度    **±10 K（新标）** = 设定读半格 ±1.5 + 静差 3.8 + 插深差 3 mm 的 8
 *            （三项 RSS 后 9 K）；一个月不重标再叠上棒老化的 9 K → **±20 K**
 *            棒老化：900 上 0.005% 的收缩，300 mm 上是 0.015 mm = 9 K/100 h
 *   寿命    棒 400 h 换（或每月重标）、触点 547 次/天 → 2×10⁵ 次/年 →
 *            **每两个月锉一次、每年换一对**
 *   维护    每年 ~20 次（锉触点 6、换棒 3、重标 12、换簧 1）；**电子表是 0 次**
 *
 * 那一句"坏了能修"在这里比上一件更实在：全部磨损件只有**一根棒、一对触点** ——
 * 凸轮、擒纵、程序盘一个都没有。棒是砖窑烧的，触点是铜片锉的，杠杆是 45 钢磨的。
 * 而它的故障形态也都看得见：触点烧黑、棒断、杠杆卡（三样都能在一小时内换）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 八、kg 账（一件，算式在每条 uses 下）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   进 15.27 kg → 一件约 11.2 kg：
 *     耐火料 4.5 → 3.15   HT200 3.0 → 2.40    HT250 0.8 → 0.62
 *     45 钢 1.6 → 1.34    铜 0.6 → 0.52       铜线 0.15 → 0.135
 *     玻包线 0.2 → 0.18   碳 0.12 → 0.11      石灰 0.5 → 0.30
 *     硅石 0.45 → 0.28    矿渣 0.3 → 0.27     水 1.5 → 0.60
 *     尾矿 0.6 → 0.48     风化层 0.8 → 0.64   矿棉 0.15 → 0.14
 *   差 4.10 kg = 浇冒口与回炉铁 0.78 + 耐火废坯 1.35 + 水 0.90 + 45 钢车屑 0.26
 *     + 石灰损耗 0.20 + 硅石熔制与粘坩埚 0.17 + 风化层烧失 0.16
 *     + 尾矿筛余 0.12 + 铜车屑 0.08 + 矿渣余料 0.03 + 玻包线 0.02
 *     + 铜线 0.015 + 碳粉 0.01 + 矿棉切割 0.01
 *
 * ⚠️ 条目没有 `mass`（analog.ts 第 58 行只声明 id / unit / category），
 * 产出按台计，所以 `unbalanced` 判据不会触发 —— 这一段是给人读的。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 九、降级（八处，比较对象：两只运放的模拟 PID 温控器）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① **精度差一个数量级**：PID 的稳态误差 ±1–2 K；这一台 **±10 K**（5–10 倍），
 *      而且其中 3.8 K 是**双位控制的静差，原理上消不掉**（没有积分项）。
 *   ② **摆幅差一个数量级**：PID 把温度贴在设定值上（±1 K）；这一台是
 *      **±3.8 K 的死区摆动**，加上静差 3.8 K，实际温度在设定值下方 4–8 K 处来回。
 *      对淬火（±15）、氮化（±20）够用，对球化退火（±10）**卡在边上**。
 *   ③ **没有输出信号 —— 从"1 路模拟量"掉到 0**：原版能把温度送给记录仪、
 *      送给上位机、给另一台表做串级；这一台只有一根指针。**"可记录"与
 *      "可计算"在这里一起没了**（上一件还有一条烟熏线，这一件连烟熏盘都没有）。
 *   ④ **维护量从 0 次/年 到 20 次/年**：锉触点 6 次、重标 12 次、换棒 3 次、
 *      换簧 1 次。电子表在坏之前是 0 次 —— 而它坏了不能修（要换芯片）。
 *   ⑤ **设定分辨率 3 K/格**（高温头）、**5 K/格**（低温头）；PID 的电位器是连续的。
 *   ⑥ **响应慢**：刚玉棒的时间常数约 14 s（φ8 的棒在 900 上），而热电偶是 2–3 s
 *      —— 慢 5 倍。它不影响稳态（炉子的时间常数是几百秒），但"看到温度变了"
 *      这件事要等 15 s，操作工的手感会被拖慢。
 *   ⑦ **棒是耗材，而且它老化是单向的**：900 上 0.005%/100 h 的收缩让读数
 *      **越用越偏低**（不是漂，是**单调地偏**），所以必须按月重标 —— 而重标要
 *      三个定点（一次一夜）。
 *   ⑧ **它不能在 900 上"看见"自己**：这一台没有冷端补偿、没有断偶报警。
 *      棒断了、杠杆卡了、触点粘了，**指针还停在原来的位置** —— 三种故障都表现为
 *      "温度不涨了但表没动"。而 PID 表有一个断偶检测（输入开路 → 输出关断）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 十、缺口（六处，写清卡在哪一步）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① **模型没有"控制品质"这个维度。** 温控器的好坏是"超调、静差、摆动、
 *      稳定时间"四个数，而条目上只有 id / unit / category。所以这条路线
 *      最要紧的那些数只能写在注释里（与上一件的处境一样）。
 *   ② **`std/temp-controller-general` 与 `std/process-controller-general` 的
 *      差别只写在文件里，模型里没有"它能干什么"这一栏。** 两台都是
 *      `unit: '台'` 的 part，谁都可以装到任何一台炉子上 —— 而它们的量程、
 *      输入、输出完全不同。这是这一轮最该记下的一处模型缺口。
 *   ③ **铜的定点贴着土窑的上限**（1 100 对 1 084.6，15 K 余量），而窑温波动 ±30。
 *      要稳，得有一条"能稳在 1 100 的小炉子"的路线 —— 那就是这台电阻炉本身，
 *      而它要等这只温控器才通（**一个温和的循环**：标定用窑，窑的上限不够）。
 *   ④ **没有断偶/断棒检测。** 模型没有"传感器失效"这个状态；现实里它是最常见的
 *      故障（上一件也一样）。所以操作卡上只能写"每炉看一眼指针动不动"。
 *   ⑤ **双金属的蠕变没有数据。** 铜在 250 上就开始退火，夹紧力每年掉多少、
 *      读数漂多少，本层没有试验手段（要一台恒温箱 + 一支标准表）。
 *   ⑥ **触点寿命 2×10⁵ 次是估的。** 铜触点在 2 A 220 V 交流上的电寿命取决于
 *      灭弧（这一台没有灭弧栅 —— 触点只有 2 A，电弧很小），而"每年换一对"
 *      是按 10⁵ 次的下限估的。
 */


/**
 * 扩散炉炉管（`plant/diffusion-furnace/tube`）的第二条来路 —— **不透明耐火陶管**。
 *
 * 一句话：石英管要 2000 °C 和一台玻璃车床，本层两样都没有；退到耐火黏土陶管，
 * 三节 φ110 内径、1.8 m、磨口 + 铸铁法兰 + 泥封。
 * 代价六笔：看不见、漏、不能热装热出、等温区短、内壁被磷咬、温区封顶 1100。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一、先回答：石英管能不能做 —— 不能
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 既有那条（data/machine/diffusion.ts 的 `make/diffusion-tube`）是这么写的：
 *
 *   高纯石英砂 1 + 不锈钢 1 + PTFE 1 · 电弧炉 1900–2200 熔制拉管 · 磨口 · 法兰配作
 *
 * 三关，第一关就过不去：
 *
 *   ① 温度。熔融石英的软化点（10⁷·⁶ Pa·s）是 1665 °C，而**拉管要的是工作点
 *      （10⁴ Pa·s），在 2000 以上** —— 既有路线写 1900–2200，正是这个窗口。
 *      本层温度上限是熔化炉 1650（data/floor/seed.ts），砖窑 1500。差 350–550 K。
 *      1650 的石英只是"软得能弯"，黏度还在 10⁷ 量级：它塌，不流，拉不成管。
 *
 *   ② 拉管设备。石英管在工业上只有两条路，本层两条都缺：
 *
 *        连熔法   连续加砂、钼或石墨坩埚、垂直下拉 —— 石墨要 2800–3000 石墨化，没有
 *        二步法   先熔成锭，再在**玻璃车床 + 氢氧焰**上重加热、拉细、扩口、封接法兰
 *
 *      玻璃车床是"两头顶尖同步回转 + 一排火焰"的专用机床，本层没有；
 *      氢氧焰焊枪也没有（氧能电解出来，但枪与玻璃工这一整套不在本层闭包里 ——
 *      写这条路线时闭包是 19 台设备，没有一台能同时给"火焰"与"同步回转"）。
 *
 *   ③ 退火这一关反而通：石英玻璃 1100–1200 退火消应力，扩散炉自己就在这个温区。
 *
 * 所以这条路线不写"石英管的低配版"。**玻璃管也不行**：砖窑能出玻璃
 * （`make/glass-brick-kiln`，1400–1500），可那是钠钙玻璃 —— 软化点约 720、应变点约 510。
 * 炉管要 1000–1200，管子在第一次升温里就塌，差 280–480 K，而这正是这台炉子的工作温区。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 二、退到哪一步：耐火黏土陶管（**不是**高铝 / 莫来石管）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 本层已有一级现成的温度梯子：土窑 1100 → 黏土砖 → 砖窑 1500 → 耐火料。
 * 耐火料（`make/refractory-brick`：风化层 1000 + 石灰 100 + 水 150 → 800，砖窑 1300–1400）
 * **再烧一次到 1400–1450**，就是"半烧结"的陶管：
 *
 *   显气孔率  25% → 20%        第二次烧结把颗粒颈部烧粗，气孔缩而不闭
 *   抗折      10–15 MPa → 30–40 MPa   砖 → 半瓷，还不到瓷（真瓷 60–120）
 *
 * ⚠️ **为什么不写"高铝 / 莫来石管"**：莫来石-刚玉质要 Al₂O₃ 45% 以上的料，
 * 而本层没有高铝矾土 —— `data/material/bootstrap.ts` 那条降级③的原话是"没有
 * Al₂O₃ 富集的高铝砖（那要高铝矾土，本层没有）"。风化层耐火料的 Al₂O₃ 只有 9%、
 * Fe₂O₃ 17–20%。所以这根管子是**铁质黏土-钙长石质**的，不是莫来石-刚玉质的。
 * 名字与实物必须对齐：谁把它当莫来石管用，就会在 1200 上算错寿命（见降级⑥）。
 *
 * 尺寸（三个数各有出处）：
 *
 *   内径 φ110   硅片是 φ100 × 0.7（data/material/wafer.ts）。既有那条写 φ80 ——
 *               片根本装不进去，那是一处旧缺口，本文件不改它，只把自己这条定对。
 *   外径 φ138   壁 14 mm。陶管靠壁厚换强度与抗热震：薄壁件一冷一热就裂。
 *   长 1.8 m    三节：热段 1.0 + 冷端 0.4 × 2。分节的理由不是长度，是**窑膛与立烧**：
 *               1.8 m 一件要 2 m 的窑膛和一根 2 m 的模芯，本层都没有；立烧时直度靠
 *               重力自己校，越长越歪。
 *
 * **铸铁管 + 内衬连"更差"都算不上，是不成立**：HT200 / HT250 的长期上限 400 °C
 * （本项目多处口径），炉管 1000–1200 是 3 倍超限。铁在这里不是"软一点"，
 * 而是氧化起皮，加上与 POCl₃ 的氯生成 FeCl₃ 挥发 —— 落到片上是铁污染。
 * 所以那条不写。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三、这不是石英管（四处，必须明说）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① 不透明。石英管的全部方便来自"整根都是窗"；这根不是，只有一个 φ10 观察孔。
 *   ② 有铁。管体铁 12–14%，高纯石英砂按 99.9%（铁 10 ppm 量级）—— 差四个数量级。
 *      铁是硅里的深能级复合中心，少子寿命掉一档：整面结的二极管与太阳能电池还认，
 *      往后晶体管的漏电会难看。
 *   ③ 不气密。四道接缝（2 端锥面 + 1 承插口 + 1 观察孔），没有弹性垫片可用 ——
 *      PTFE 与橡胶两条链都不通，只有磨口对研 + 矿棉绳 + 石灰尾矿泥。
 *   ④ 温度不均匀。铁法兰与承插口是冷点，等温区被切成一段（降级④）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四、降级（比较对象：既有那条 φ80 石英管）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① **看不见 —— 反馈从"实时"退成"事后"，这是最要紧的一笔。**
 *
 *      石英管里能看见三件事：舟推到位没有、片倒没倒、片面的颜色（氧化层厚度直接读颜色：
 *      100 nm 淡黄、300 nm 紫红、500 nm 蓝）。陶管只剩一个 φ10 观察孔：
 *
 *        拔开看   能看到"舟与片在不在、有没有倒片"；看不到片面 —— 孔小，视线从 30–40°
 *                 斜进去，看到的是片的边缘
 *        一拔就漏 孔口进空气，POCl₃ 遇氧提前气相成核，片上长一层 P₂O₅"白毛"，
 *                 一批几十片一起废
 *        孔口降温 冷风进来，孔边局部掉 50–100 K，要 10–15 min 才回稳
 *
 *      换成的办法是**陪片**：每批在同一位置放一片陪片，出炉后磨角染色看结深，
 *      或两点探针 + 毫伏表读方块电阻（误差 2 倍级，比四探针差一档，但没有四探针）。
 *      于是废品从"当炉发现"变成"整炉报废"。
 *
 *   ② **气密差 4–5 个数量级。**
 *
 *      石英管那条：不锈钢法兰 + 氟橡胶 O 圈，漏率 10⁻⁷–10⁻⁶ Pa·m³/s 量级。
 *      这一条：磨口对研 + 矿棉绳 + 泥封，一件弹性件都没有，10⁻²–10⁻¹ Pa·m³/s 量级
 *      （对研面本身 10⁻³–10⁻²，泥封干裂再加一个量级）—— **差 4–5 个数量级**。
 *
 *      后果不是"漏点气"这么轻：漏进来的空气带水，1000 以上把 POCl₃ 水解成 HCl + H₃PO₄，
 *      既咬管壁又打乱磷源浓度。所以这条路线**不能用鼓泡瓶的载气流量当磷量的刻度**
 *      （那是石英管那条的前提）：只能"定载气、定时长、看陪片" —— 磷量从**可定量**
 *      退成**可重复而不可定量**。
 *
 *   ③ **不能热装热出 —— 周期约 3 倍。**
 *
 *      石英管的用法是"炉子一直 1000，片舟从冷端推进去"。凭什么能这么干：算一下
 *      冷舟贴到 1100 管壁上的热应力，σ ≈ E·α·ΔT/(1−ν)：
 *
 *        石英玻璃  72 GPa × 0.55×10⁻⁶ × 1080 / 0.83 ≈ **52 MPa**，抗折 50–70 MPa → 擦边过
 *        本管体    30 GPa × 6×10⁻⁶ × 1080 / 0.80 ≈ **243 MPa**，抗折 30–40 MPa → 差 6–8 倍
 *
 *      **这就是石英管能推舟、陶管不能的原因，也是这条路线全部麻烦的源头。**
 *      于是装片 / 取片必须在 300 以下，升温 ≤ 3 K/min、降温 ≤ 3 K/min（大件陶管的
 *      安全速率，没有程序控温就靠人看火色与时间）。一次循环：石英管 4–6 h；
 *      这条 12–18 h（升 6–7、保温、降 6–8）。模型没有时间这一栏，这个代价只能写在这里。
 *
 *   ④ **等温区 1.0 m → 0.6 m，装片 50 → 30 片。**
 *
 *      铁法兰（两端）与承插口（炉口）是冷点，各掉 100–200 K，±5 K 的等温区只剩中间
 *      0.55–0.65 m。按片距 20 mm 排：石英管 1.0 m 装 50 片，这条 30 片 —— **0.6 倍**。
 *
 *   ⑤ **内壁会被磷咬 —— 寿命 20–40 炉次，不是几年。**
 *
 *      石英管的好处写在 diffusion.ts 文件头："不与磷反应 —— 只有石英"。陶管相反：
 *      P₂O₅ 在 1000 以上与 Al₂O₃ / SiO₂ 生成磷酸铝、磷酸硅。Al₂O₃ 的摩尔体积
 *      25.7 cm³/mol、AlPO₄ 是 47.5 —— 按 Al 计固相体积涨 **3.7 倍**，内壁必然起壳、
 *      逐层剥落，渣落在片上就是颗粒沾污。
 *
 *      内壁刷一层硅石洗涂料（2 kg 硅石 + 水，随烧成玻璃化，0.3–0.5 mm）把反应面换成
 *      90% SiO₂ —— 等于"在黏土管上贴一层石英"。但涂层 α 0.5、管体 α 6，差 12 倍，
 *      冷热一循环就开裂脱落。**这不是解决，是把寿命从 10 炉次拉到 20–40。**
 *
 *   ⑥ **温区封顶 1100（不是 1200）。**
 *
 *      铁质黏土的荷重软化点 1200–1300（Al₂O₃ 只有 9%、铁又高，比标准黏土砖低一档），
 *      留 50 K 余量，炉子的实际可用上限就是 1150。而扩散炉自己标 900–1200
 *      （data/machine/diffusion.ts 的 holds）。于是：栅氧 950–1000 能用，源漏扩散
 *      1000–1050 能用；场氧与隔离扩散那两条 1100 擦边；**1200 那一段让掉了。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五、做法（一遍走完）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   耐火料 35 + 硅石 5 + 石灰 3 + 尾矿 6 + 水 16 + 矿棉 0.8 + HT200 6 + 45 钢 1.5
 *     → φ138 / φ110 × 1.8 m 陶管一件（三节 + 两端铸铁法兰 + 8 条 M12）
 *
 *   砸料过筛 → 掺尾矿熟料粉与石灰、加水闷料 → 铁管芯上卷管（热段 + 两节冷端，留承口与观察孔）
 *   → 阴干 2–3 周、校直 → 刷内壁硅石洗涂料 → 立着烧 1400–1450（垫砂、随窑冷）
 *   → 磨两端锥面（1:10）与端面、配堵头 → 浇铸铁法兰与卡箍 → 车锥面、车 45 钢螺栓
 *   → 沸水煮洗去可溶盐 → 承插口塞矿棉绳 + 泥封、两端对研压紧 → 试漏
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 六、已知缺口
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① 漏率写不出数：没有压力表、没有氦检、没有真空泵（plant/vacuum-pump 不在本层闭包里）。
 *      能做的只有冷态刷石灰浆看气泡，和热态看陪片 —— "漏多少"这件事在模型里没有刻度。
 *   ② 没有程序控温："≤ 3 K/min"是判据，不是读数；窑与炉子都靠火色、靠人守。
 *   ③ 模型没有时间：阴干 2–3 周、保温 8 h、周期 12–18 h 只能写在注释里。
 *   ④ 观察孔给的"看"是残的：孔小、角度差，看得到有没有片，看不到片面。
 *   ⑤ 没有测温锥这一栏：测温锥记在熔化炉的消耗里（data/floor/seed.ts），砖窑这一边
 *      借用同一支，模型里没有它的位置。
 *   ⑥ 型砂、泥芯、冷铁这类工装不在条目里（与 unblock-electrolyzer-ceramic 同一处缺口）；
 *      换管用的备件也没有栏 —— 模型没有"维修件"。
 *
 * ⚠️ 时态：上面说"没有"的都是**现在**没有。
 *    其中一条刚变：煮洗那一道要 `plant/wet-bench`，而**它现在通了**
 *    （unblock-wet-bench.ts 这一轮补上的）—— 所以这一句是"现在有"，不是"那时有"。
 *    也正是因为"现在有"，这条路线才敢把煮洗写成一道工序；上一轮它还是断的。
 */


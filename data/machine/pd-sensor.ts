/**
 * 100 kV 试压台的局放（PD）传感器 —— 把「有没有局放」变成可听，不是局放仪。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 它补的是哪一格
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * `data/machine/implant.ts` §七 R8 第 11 行写着：100 kV 试压台已经有
 * `plant/hv-test-bench/source-100k`（100 kV / 22 µA）与
 * `plant/hv-test-bench/divider-100k`（1 GΩ、1000:1、1–2 %），
 * 但「局放仪仍 0 台」—— 能加电压、能读电压，不能判「有没有局放」。
 *
 * 本文件给 `plant/hv-test-bench` 装一件 `plant/hv-test-bench/pd-sensor`：
 * UHF 环天线 + 铝屏蔽盒 + PTFE 绝缘 + 宽带前放 + 50 Ω 接头。
 * 它把 100 kV 下的局放从「看不见」变成「听得到」，
 * **不把它变成可定量的 pC 读数**。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么是 UHF 环天线
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 局放是 ns 级电流脉冲，频谱从几十 MHz 铺到 1 GHz 以上。取 100–1000 MHz：
 *   · 低于 100 MHz，电晕、变频器、接触器的干扰密集；
 *   · 高于 1 GHz，同轴与接头的损耗大，本层的铜/PTFE 电缆做不长。
 *
 * 环天线测磁场（dB/dt），对高压端的强电场不敏感，适合放在 SF₆ 箱外。
 * φ100 mm 单匝、铜管 φ4.8 mm：
 *
 *     A = π × 0.05² = 7.85e−3 m²
 *     m = ρ_Cu × π × 0.1 × π × 0.0024²
 *       = 8 960 × 0.3142 × 1.810e−5 = **0.051 kg**  ✓ 与 0.05 kg 对上
 *     L ≈ μ₀ a [ln(8a/r) − 2]
 *       = 1.2566e−6 × 0.05 × [ln(166.7) − 2] = **196 nH**
 *     L/R = 196e−9 / 50 = 3.9 ns → 40 MHz 以上是微分响应，正好落在 UHF 段
 *
 * 阻抗 50 Ω：环 + 空气芯 1:4 阻抗变换 + N 型接头。本层没有铁氧体，
 * 所以变换器是空气芯的 —— 带宽够、体积大、损耗约 1–2 dB（估）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四个窗口怎么来的（都是设计窗口，不是校准值）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * bandwidth 100–1000 MHz
 *   环天线 + 无源匹配的窗口。1 GHz 上环周长 0.314 m ≈ 1λ，方向图已经裂瓣，
 *   所以这是「能收到」，不是「平坦响应」。它**不是**前放的增益带宽 ——
 *   前放那一半见下面 gain 与 R8 ③。
 *
 * sensitivity 5–50 pC
 *   按 1 ns 上升沿的等效视在电荷估：q = 5 pC ⇒ i = q/t = 5 mA；
 *   0.4 m 处 H = i/(2πr) = 5e−3 / 2.513 = 2.0 mA/m；
 *   环开路电压 V = μ₀ A dH/dt = 1.2566e−6 × 7.85e−3 × 2.0e6 = **19.6 mV**。
 *   50 Ω 负载上还要乘 jωL 的分压（L = 196 nH）：
 *   100 MHz 上 ~0.41 ⇒ 8 mV；1 GHz 上 ~0.041 ⇒ 0.8 mV。
 *   40 dB（100×）⇒ 0.8–0.08 V；60 dB（1 000×）⇒ 8–0.8 V。
 *   50 pC 在 100 MHz 上 40 dB 已到 8 V（接近饱和），
 *   所以 60 dB 只用于 5–10 pC 的小信号。
 *   以上只算到检波前；检波损失（本层没有二极管，靠前放非线性）与音频增益
 *   都没有标定，所以 5–50 pC 只是量级。
 *   **这个 5–50 pC 是「等效视在电荷」，不是 IEC 60270 的校准读数**：
 *   没有 UHF <1 ns 校准源，天线到 PD 源之间的 UHF 传递函数没有标定（R8 ①）；
 *   标准 1 µs 校准链已建（pd-calibrator.ts），不能直接搬到 UHF。
 *
 * gain 40–60 dB
 *   两级前放：40 dB 用于 10–50 pC，60 dB 用于 5–10 pC（1 GHz 端 5 pC
 *   只有 0.8 mV，60 dB 才够）。
 *   ⚠️ `std/opamp-chip-general` 的 GBW 只有 ~1 MHz（`se-detector.ts:148`、
 *   `film-monitor.ts:274` 都按这个数算）：40 dB 闭环带宽 10 kHz、
 *   60 dB 只有 1 kHz。所以这个「宽带前放」实际是**音频包络放大器**，
 *   不是 UHF LNA。100–1000 MHz 的增益在本层做不出来 —— 见 R8 ③。
 *
 * impedance 50 Ω
 *   天线/电缆接口。50 Ω 是为了直接接同轴、接分压器的低压臂；
 *   它**不是**「PD 源的源阻抗」—— PD 源的阻抗不是 50 Ω，这里只是接口标准。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * R8 —— 降级、升级路线与缺口（不编能力）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① UHF 段没有 <1 ns 校准源；标准 1 µs 已有
 *    现在：`pd-calibrator.ts` 已给 1–100 pC、0.5–2 µs、±5–10 % 的校准源与
 *          0.01 V/pC 电荷放大器；标准脉冲下可以把「音频响度」标成 pC。
 *    仍缺：UHF 段要 <1 ns 快源（雪崩管/水银继电器/阶跃恢复二极管），本层 0 台；
 *          所以 5–50 pC 的 UHF 窗口仍是估的，标准 1 µs 校准不能直接搬过来。
 *    原规格：IEC 60270 的视在电荷测量，校准不确定度 ≤5–10 %。
 *    缺口：标准 1 µs 链已建；UHF <1 ns 链、PDI 仍 0。差的是**UHF 计量链**，
 *          不是标准 pC 链。5–50 pC 在 UHF 标定前只能当「有/无」用。
 *
 * ② 没有 PDI/相位分辨：听不到放电「发生在工频的哪一段」
 *    现在：只有包络的响度与节奏，分不出 0°/90°/180°/270° 的放电相位，
 *          也分不出「一只气泡」与「沿面爬电」的图谱。
 *    原规格：PRPD（相位分辨局放）图谱，相位窗 ≤1°、峰值保持、
 *          ≥100 个工频周期。
 *    升级：50/60 Hz 相位零点（从 `source-100k` 的调压器/同步触点取）
 *          + 峰值检波 + 1 MHz 计数链（本层有，1 µs = 0.018° @ 50 Hz）
 *          + 示波器/记录器（本层 0 台）。
 *    缺口：相位时基本身够（1 MHz 对 50 Hz 是 0.018°），缺的是
 *          **检波与记录**；没有示波器，波形看不见。差 1 台峰值保持/记录器，
 *          量级是「看不到」，不是「差几倍」。
 *
 * ③ 100–1000 MHz 的增益做不出来：前放只有 ~1 MHz GBW
 *    现在：天线覆盖 100–1000 MHz，前放是 1 MHz 运放；40 dB 闭环 10 kHz，
 *          60 dB 闭环 1 kHz。整机是「UHF 天线 + 音频包络放大器」，
 *          不是 UHF 接收机。本层也没有检波二极管条目；包络检波只能靠
 *          前放输入级的非线性（很粗，随电平/温度漂），严格说这不是一台
 *          成型的 PD 检波器。
 *    原规格：40–60 dB、100–1000 MHz 的 LNA，噪声系数 ≤3 dB。
 *    升级：RF 低噪声管（SiGe HBT / GaAs HEMT）或 50 Ω MMIC；
 *          按单级算，40 dB @ 1 GHz 要的增益带宽积是 100 × 1 GHz = **100 GHz**
 *          （60 dB 要 1 THz），而本层运放的 GBW 是 1 MHz 级 ——
 *          差 **5–6 个数量级**，也要新的半导体链。
 *    缺口：**这一条是本文件最硬的一处「不编能力」**。`gives` 里的
 *          100–1000 MHz 是天线/无源窗口，不是前放的增益窗口；模型没有
 *          「天线带宽」与「电子学带宽」两个字段，只能写在一处并在此说明。
 *
 * ④ 放置与背景 —— 这是使用条件，不是传感器本身的能力
 *    100 kV 下天线放在 SF₆ 箱外、离高压 300–500 mm：
 *      E(300 mm) = 100 kV / 0.3 m = 3.3 kV/cm，空气击穿 ~30 kV/cm ⇒ 9 倍余量；
 *      E(500 mm) = 2.0 kV/cm ⇒ 15 倍余量。
 *    先测背景：源不开、源开不带试品、源开带试品，三次的响度要分开；
 *    否则听到的是电晕/变频器/接触器，不是试品的 PD。
 *    ⚠️ 金属 SF₆ 箱对 UHF 是屏蔽的：只有 PTFE 法兰/绝缘缝隙漏出的分量
 *    能出来。若箱子完全密封，天线听到的是箱外背景 —— 这一条只能靠
 *    「箱子留一个 PTFE 窗」解决，不是传感器能解决的。
 *
 * ⑤ 它不解决「100 kV 整柱 PD 签字」
 *    配套：`plant/hv-test-bench/source-100k`（100 kV / 22 µA）
 *          + `plant/hv-test-bench/divider-100k`（1000:1）。
 *    本传感器只把「有没有局放」变成可听；签字要的是：
 *      · 100 kV 无局放源（本层源纹波 3 %、22 µA，不是 PD-free）；
 *      · 校准器 + PD 检测器（①）；
 *      · 屏蔽间/背景 ≤1 pC（本层没有）；
 *      · 整柱 34 级在 100 kV 下 1 min 的 PD 记录（`implant.ts` R8 #11）。
 *    所以 `implant.ts` R8 #11 的「局放仪仍 0 台」**不因本文件关闭**；
 *    它从「连听都听不到」降到「能听到有/没有」，签字仍差一整条计量链。
 *
 * ⑥ 模型缺口：没有成品率，所以本条不写 `mass`
 *    投入 0.45 kg（铜 0.05 + 铝 0.2 + PTFE 0.1 + 铜 0.1），成品约 0.4 kg，
 *    差的是屏蔽盒开孔/折边、接头车屑与天线端头料。写 `mass: 0.45` 会把
 *    废料算进成品；写 `mass: 0.4` 又会被 `mass_mismatch` 判错 ——
 *    该检查只认「投入 kg = 单件质量」，没有成品率字段。
 *    这是模型表达力缺口，不是漏写。R8 升级：给 `Route` 加成品率，
 *    或允许 `unbalanced_zh` 参与零件质量账 —— 两者都要改 core，先提议。
 *
 * ⑦ UHF <1 ns 源/PDI：**不立种子，保持红**
 *    UHF <1 ns 源要雪崩管/水银继电器/阶跃恢复二极管；PDI 要相位检波/
 *    峰值保持/记录器。本层两条链都是 0。
 *    按 R9，立一台进口 UHF PD 整机做种子，也会像 `plant/nanoindenter`
 *    一样“R9 未闭合”—— 那不是解决，只是把红换成黄。
 *    所以本文件只把 UHF 通道做到“能听 + 标准 1 µs 能标”，
 *    **UHF <1 ns/PDI 明确记为进口整机项，不写本地路线、不立种子**。
 *    要做，就买一台完整 UHF PD 检测仪（含快源/相位），并接受它不可复制。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 配套的一笔账（不改既有文件，只记在这里）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * `source-100k` 的空载 102 kV、22 µA 时 100 kV ⇒ 内阻约
 * (102 − 100) kV / 22 µA = **91 MΩ**。`divider-100k` 的注释是 1 GΩ：
 * 100 kV 上取 ~100 µA，工作点会被拉到 ~93 kV（−7 %）。
 * 若分压器实际是 10 GΩ（每只 1 GΩ），则是 ~10 µA，工作点在 101 kV 附近
 * （对 102 kV 空载只掉 ~1 %）—— 这两个数必有一个要核。本文件不碰既有两件；
 * 在 PD 试验之前，先把「100 kV 工作点」的负载账核清，否则天线听到的是
 * 93 kV 下的电晕，不是 100 kV 的 PD。
 */


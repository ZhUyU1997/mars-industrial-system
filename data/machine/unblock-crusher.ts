/**
 * 破碎机的第二条路线 —— 铸造 + 车磨：不用铣镗床，也不用锻锤。
 * 材料只有铸铁与 45 钢（外加铜、碳粉、尾矿砂、水），设备只有熔炼炉、土窑、车床、磨床、机器人。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么要有这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 「严格算术」口径下（设备也算进闭包），从种子与火星料出发只长出 7 台设备：
 *
 *   plant/robot · lathe · plant/grinder · plant/melting-furnace
 *   plant/gauge-block · plant/earth-kiln · plant/brick-kiln
 *
 * 而 `plant/ore-beneficiary/crusher` 原来只有一条路线（data/material/refining.ts
 * 的 `make/beneficiary-crusher`），它的 needs 是：
 *
 *   lathe ✓ · plant/grinder ✓ · plant/milling-machine ✗ · plant/forge ✗
 *
 * 铣镗床与锻锤都不在那 7 台里，而且它们自己卡在「钢板要轧机、轧机要钢」上。
 * 于是整条选矿线停在第一个零件上 —— **破碎机是选矿厂的咽喉**：
 * 没有它，球磨机吃不到 10 mm 以下的料，后面四台一件也开不了工。
 *
 * 所以这里补一条**替代路线**（同产出的第二条，模型按 OR 读），把
 * 「铣」与「锻」两道工序就地降级成「车 + 磨 + 配刮」：
 *
 *   要铣平面、要锻毛坯   →  铸出来，再以车代镗、配刮（见降级①）
 *   要 40Cr 锻件淬硬     →  45 钢渗碳淬火，或 HT300 白口化（见降级③）
 *
 * **旧路线不删。** 它是"有铣镗床与锻锤时该走的工艺"，这一条是那之前能开工的那条。
 * 两条并存正是模型要的样子：多条路线产同一件，编年史由设备决定。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 这台机器是什么：颚式，铸铁机架 + 两块颚板咬
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 一块固定颚板、一块装在动颚上跟着偏心轴摆，土块落到两块之间被**折断**，
 * 从下面排出去。它不磨也不筛，只咬。
 *
 * 三件事决定了它的零件表：
 *
 *   1. 受力最大的是机架与动颚 —— 所以它们最重（1700 / 2800 kg，六成）
 *   2. 真正跟石头见面的只有颚板 —— 所以它是**唯一的消耗件**（见下）
 *   3. 摆动来自偏心轴 —— 所以轴要车，而且**偏心那一段只能靠花盘 + 垫块**车出来
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 颚板是消耗件，不是零件 —— 三套里先装一套，另两套随机器走
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 进料是风化层原土（砂 + 砾）。细料在两块颚板之间是**磨**而不是**折**，
 * 而颚板又是这台机器上唯一直接吃磨的东西 —— 所以它按"套"换，不按"修"。
 *
 * 三套是有来处的，不是随手多写：一套在机上，一套在备件箱，一套在磨平
 * （颚板磨钝了可以上磨床磨平再用一次，磨两次就到极限 —— 再磨就咬不住料了）。
 * **机器是不能停的**（选矿线一停，球磨机、浮选槽全跟着停），所以换颚板这件事
 * 必须在半小时里做完 —— 那就只能整块换下来。
 *
 * ⚠️ 模型里没有"备件"这一栏：`Component.wear` 只能挂在某台机器的 composedOf 上，
 * 而破碎机在 `plant/ore-beneficiary` 的 BOM 里只占一行（qty 1）。所以备用颚板
 * 只能记成**多投的 45 钢**。数量比别人多，是因为它是耗材，不是因为写重了。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 数字：整机约 2.8 t，按件计，产出不核 kg
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 条目 `plant/ore-beneficiary/crusher` 是 `part`、`unit: '件'`、没有 `mass` ——
 * 所以校验**不会**替我们核质量守恒（只对 kg 产出核）。账记在这里，口径与
 * data/machine/lathe.ts 一致：厂商只给整机重量，不给零件级重量，所以是**估**。
 *
 *   机架 1300 + 动颚 400                    HT250/HT300      1700 kg
 *   飞轮 2×130 + 皮带轮 90 + 轴承座 110      HT200             460 kg
 *   颚板 3 套 × 2 块 × 65 + 偏心轴 110 + 肘板 3×25
 *                                           45 钢（或 HT300）  575 kg
 *   铜瓦（偏心轴两端 + 肘板座）              mat/copper         40 kg
 *   ────────────────────────────────────────────────────────────────
 *   净重合计 2775 kg ≈ 2.8 t（PE-250×400 级：进料 210 mm、出料 20–50 mm）
 *
 * 另有三样**不进产品**的投入：
 *
 *   尾矿砂 3000   砂型。铸件与型砂的重量比 1 : 1.1，回用九成
 *   水      250   型砂调湿（4–8 wt%）。烘干即走
 *   碳粉     40   固体渗碳剂，按渗碳件重量的 7%（575 × 0.07 ≈ 40）
 *
 * 于是：进 6065 kg，出 1 件。差的那些不是丢了 —— 2775 进了产品，3000 是砂型
 * （回用，损耗约一成），250 是水（蒸发），40 是渗碳剂（烧掉）；浇冒口与切屑
 * 回炉，在模型的 `uses` 里表达不了（那需要"回炉路线"与"余量"两栏，都没有）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四处降级 —— 每一条都写清代价落在哪
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① 没有铣镗床 → **以车代镗 + 配刮**，零件不互换
 *    机架的两只轴承座孔，在车床花盘上装铣头镗出来。孔本身能圆，但**两孔的
 *    同轴度**到不了 IT7 —— 车床没有坐标工作台，两孔是分两次装夹镗的。
 *    补救只有配作：铜瓦与偏心轴成对配刮，**换瓦要连轴一起配**。
 *    这与 make/lathe-tailstock 的"同轴度靠刮不靠加工精度"同一个道理，
 *    只是那台车床的轴是静止的，这里要转起来。
 *
 * ② 没有能恒温的热处理炉 → **颚板硬度不足**
 *    土窑（400–1100，种子之一）烧得到 900，但它是**自然抽风**的窑：温度由火
 *    与料层决定，不是由仪表决定。固体渗碳要在 900–950 待 6–8 小时，实际是一路
 *    看着火色走，上下飘 ±50 °C。淬完**不回火** —— 回火要 500–600 恒温两小时，
 *    土窑做不到"恒"。
 *    结果：渗层一毫米上下、且深浅不匀，磨掉这一层就只剩 HB 200 的基体。
 *    **寿命比高锰钢短得多**，而原路线那句"真正的材质是高锰钢，这里用 40Cr
 *    代用，寿命打折"说的正是同一件事 —— 本层连 40Cr 都还没有。
 *    三套颚板就是为这条降级买的。
 *
 * ③ 没有轧机、也没有散热器 → **45 钢这一条本身还没通**，整机跟着铸铁化
 *    `make/steel-45` 的 `needs` 里有 `plant/radiator`，而散热器自己还卡在泵、
 *    集管与管路上（data/machine/radiator.ts）。所以"颚板 + 偏心轴 + 肘板"
 *    这一子句里给了第二条选项：**HT300**。代价分两处落：
 *
 *      颚板    砂型里下冷铁**白口化**，浇出来就是硬面（HRC 40 上下，不用热处理）
 *              —— 但脆，咬进一块 150 mm 的铁质结核就崩角
 *      偏心轴  灰铸铁抗压不抗弯，只能把轴径按钢的 1.4 倍放粗（抗弯强度差约
 *              2.5 倍，用截面补回来），转速从 300 降到 200 r/min，破碎比从
 *              6 : 1 压到 4 : 1 —— **同一台机器，只当粗碎用**
 *
 *    铸铁轴不是不能转：19 世纪磨坊的传动轴就是铸铁的。**它不是不行，是要粗、要慢。**
 *    一句话：有钢用钢；没钢就是"低转速、小破碎比、常换颚板"的那一台，
 *    两样都不是高锰钢（那要锰 12%，本层的锰链没建）。
 *
 * ④ 没有筛分、没有给料机 → **出料粒度不可控，颚板磨得更快**
 *    颚式破碎机只咬不筛。进料是砂与砾混在一起的原土，细料在两块颚板之间是磨
 *    不是折 —— 这是颚板寿命的第二个杀手，和 ② 叠在一起。
 *    而"咬到多细"只能靠垫片调排料口，调一次停半小时；真正的答案（预先筛分，
 *    细料不进破碎机）要一台筛，`plant/ore-beneficiary` 的五件里没有它 ——
 *    **那是这条线的下一个缺口，不是这一条路线的。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 已知缺口
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 螺栓、键、弹簧、三角带、轴承 —— 一台真的颚式破碎机一样也少不了，而这一条
 * 路线一件也没写。不是漏了，是它们没有条目：本层只能用材料（`uses` 收材料与
 * 零件，而零件要 `std/` 标准件，那几样还卡在别的链上）。模型只会报"这个零件
 * 没有产出"，报不出"这台机器少装了五样东西" —— 缺口记在这里，等标准件那几条通。
 */


/**
 * 绕线机控制单元 —— 第四条来路：**一块种子控制板 + 一只人手扳的倒顺开关**。
 * 半自动，不是自动。这是它全部的代价，也是它唯一的理由。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么要有这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * `plant/winder/control`（data/machine/forming.ts 的 WINDER_PARTS）原来有三条路线，
 * 三条各要一样**外购件**：
 *
 *   make/winder-control        std/power-device-general + 控制板
 *   make/winder-control-relay  std/counter-mechanical-general + 接触器 ×2
 *   make/winder-control-ic     std/logic-chip / counter-chip + 接触器 ×2
 *
 * 功率器件已经退出种子清单，而它自己的路线
 * （data/material/localize.ts 的 `make/power-device`）要晶闸管、旋转变流机与钣金工位
 * —— 钣金工位不在这七台里。机械计数器、接触器、芯片呢，前提给的只是手与算
 * 都属于"要装到被控对象上、或被消耗"的器件，得自己造。
 *
 * 只有控制板不同。它是**"算"**：前提给的机器人自带控制器与算力，而且它不接进
 * 被控对象，只决定做什么 —— 所以后来把它放回种子清单。引用它是允许的，
 * 判据是现成的，不是为本文件新开的例外。**这是本路线唯一一处"外购"。**
 *
 * 于是问题只剩一句：除了"算"，绕线机还需要"通断"与"换向"，这两件事谁来干？
 * 接触器不能买，功率器件造不出 —— 那就只剩下一样：**人**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 半自动：板子数数，人手扳闸
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 三件事，只有一件是"算"：
 *
 *   数圈数   控制板 + 凸轮盘 + 一对铜触头。主轴每转一圈，凸轮顶一下触头，
 *            板子收一个脉冲，界面上的数字加一。**板子是通用件，带人机界面，
 *            所以"显示"也不用另做。**
 *   通断     人手扳倒顺开关：铸铁外壳、铜触片、耐火黏土绝缘座。车床车得出来，
 *            砖窑烧得出绝缘件 —— 四台机器、五样料，一件 std 都不要。
 *   换向     同一只开关扳到另一边。板子不管，因为它接不了主回路。
 *   排线     不归它管：`plant/winder/traverse` 本来就是挂轮带动的主轴丝杠，
 *            主轴转一圈丝杠走一个线径。**这一条把"排线控制"整件事摘掉了。**
 *
 * 所以这不是自动绕线机。真实的一台是：把匝数预置进计数器，到数自动停、自动换向、
 * 自动换层。这一台是：**界面上的数字在涨，人看着它，到数了自己按停，自己扳到
 * 另一边，再把排线挂轮换到下一个线径。**
 *
 * 产能与精度差在哪（每一处都是人的反应时间进了工艺）：
 *
 *   匝数   0.3–0.5 s 的反应时间 × 主轴转速。300 r/min（5 r/s）时多绕 1–3 匝；
 *          60 r/min 时不到 1 匝。所以**慢转是这条路线的工艺条件，不是操作习惯**。
 *   精度   层间不平：排线本身靠挂轮与丝杠，没错；错在换层、换向是人扳的，
 *          换向瞬间线会松一下（摩擦张力轮跟不上瞬时反转），端部因此比自动机松。
 *          嵌线时端部尺寸散差大一档，端部绑扎前要多一道理线。
 *   产能   一人一台。自动机一人看四到六台 —— 差的是**看守**，不是转速。
 *          主轴转速本身到得了（走的是那只 7.5 kW 电机），卡住的是"人得在跟前"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五处降级 —— 每一条都写清代价落在哪
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① 没有接触器 → **没有互锁，也没有过载保护**
 *    make/winder-control-relay 那句"两只接触器互锁，按错不会短路"在这里没有对应物。
 *    运转中直接扳到反向，主回路里只有一个铸铁壳与一对铜触片：电弧烧触头、
 *    电机受反接冲击，**没有任何东西替你拦一下**。
 *    补了一半：鼓轮上的铜触片按"先断后合"排布（扇形错开、中间留 5 mm 无铜区，
 *    即一个机械的"停"位），机械上保证换向时先断开再接通。但"停机后换向"与
 *    "运转中反向"的区别，只有人知道 —— 这是路线，不是保护。
 *
 * ② 开关通流有限 → **4 kW 以上不能直接倒顺**
 *    倒顺开关（HZ10 一类）额定 10–16 A；三相 380 V 电机按 2 A/kW 估，
 *    极限在 5–8 kW。但触头会氧化、散热差（见降级③⑤），按 4 kW 装机。
 *    而绕线机主轴是 `std/motor-7.5kw-4p`。所以真实用法是：
 *    **起停用铁壳开关（不换向），换向只在停机、低速时做**；或者按 4 kW 装机、
 *    降一档转速绕。代价落在粗线、大骨架的活上 —— 那几种活这一台干不了。
 *
 * ③ 绝缘是耐火黏土烧结的，**不是胶木，也不是瓷**
 *    绝缘底板、触头座、鼓轮绝缘套都是黏土压制后入砖窑 1300–1400 烧结
 *    （与 `make/refractory-brick` 同一个窑、同一个温区）。它耐热、便宜、本地能烧，
 *    但**显气孔率 25%**（工业砖 18%，见 data/material/bootstrap.ts 那三处降级），
 *    吸潮：湿度一上来，绝缘电阻从几十兆欧掉到几兆欧。
 *    所以它只做 ≤ 4 kW 的主回路与板子的低压输入。
 *    这也是**没有写 `mat/phenolic-resin` 的原因**：酚醛要苯酚 + 甲醛
 *    （data/material/aromatics.ts），那条链比耐火土贵得多，而这里只需要一块
 *    能在几兆欧上站住的板子。
 *
 * ④ 计数靠机械触点 → **会丢脉冲，也不分方向**
 *    凸轮 + 铜触头每转给一个脉冲。触点会氧化、磨损、抖动；丢一个脉冲就是
 *    **少算一圈**，而模型里没有任何东西能发现它（没有第二路计数可比对）。
 *    更麻烦的是**分不出正反转**：倒车时脉冲照样在涨，人要自己记"刚才倒了几圈"。
 *    真实的自动机用两路相位差 90° 的脉冲判方向，那要两只触头 + 板子认相位 ——
 *    本层既没有第二只触头的定位精度，也没有那个程序。
 *
 * ⑤ 触头靠手工研配 → **接触压力不匀，触头是耗材**
 *    没有模具、也没有磨这一道：铜触片装上去之后对着车好的鼓面涂红丹研配，
 *    再靠簧片弯折量定接触压力。副产品是接触电阻散差大，15 A 下温升能差十几度；
 *    寿命靠换触头 —— 1 kg 铜里有一部分就是留给换的（与 make/crusher-cast
 *    把三套颚板写进材料账同一个做法：模型没有备件栏，只能多投料）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 数字与写法
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 五样料，一样 std：
 *
 *   std/control-board-general   1 件   种子（data/floor/seed.ts）。带人机界面，
 *                                      所以"显示圈数"不用另做。
 *   mat/iron-ht200             12 kg   外壳 5.2 + 端盖 0.8 + 鼓轮 0.6 + 轴与手柄 0.5
 *                                      + 凸轮盘 0.2 + 接线盒 0.8 ≈ 8.1 kg 净重；
 *                                      按 1.5 倍浇注（浇冒口与切屑不入模型）→ 12
 *   mat/copper                  1 kg   三块扇形触片 24 + 六只静触头 9 + 凸轮触头与簧片 4
 *                                      + 引线与端子 6 ≈ 43 cm³ × 8.9 g/cm³ ≈ 0.38 kg；
 *                                      余量给锉削、弯折与换触头（降级⑤）。
 *                                      与三条既有路线同一个口径（都是 1 kg）
 *   mat/refractory              1 kg   绝缘底板 0.21 + 六只触头座 0.04 + 鼓轮套 0.04
 *                                      ≈ 0.3 kg；薄片烧成开裂多（降级③），按三倍计
 *   mat/tailings               15 kg   砂型：12 kg 铸件 × 1.25（与 make/crusher-cast 同比）
 *   mat/water                   1 kg   型砂调湿 6% × 15 ≈ 0.9
 *
 * 质量账**不进校验的门**：产出 `plant/winder/control` 是 `part`、`unit: '件'`、
 * 没有 `mass`，而校验只在产出全部以 kg 计时才断言守恒（src/core/describe.ts 的
 * unbalanced 那一段）。所以不写 `unbalanced_zh` —— 它与 make/mill-spindle-45steel、
 * make/crusher-cast 同一个口径：**进 30 kg 料，出 1 件。** 账记在这里：
 * 12 kg 铁里约 8 kg 成了产品、4 kg 是冒口与切屑（回炉，模型没有这一栏）；
 * 15 kg 砂回用九成；1 kg 水蒸发；铜与耐火土各约三成是锉屑与废砖。
 *
 * 温度只写两段，都落在维持得住它的设备上：
 *
 *   浇注        1350–1450  熔炼炉（1200–1650）—— 与 make/iron-ht200 同一个出炉温度
 *   烧绝缘件    1300–1400  砖窑（1300–1500）—— 与 make/refractory-brick 同一温区
 *
 * 车、装配两段不写 `under`：车床与机器人没有 `holds`，它们靠几何与手，不靠维持
 * 一个条件。也不写 `pressure`：整条路线在 0.6 kPa 的现场气压下做（data/floor/mars.ts），
 * 没有一道工序要加压。
 *
 * `needs` 只要量块：触头开距、鼓轮外径、轴颈尺寸用量块叠起来比 —— 它不加工，
 * 是判据，所以留在 needs 里。四段工序的执行设备（熔炼炉、车床、窑、机器人）
 * 都在 `steps` 里，不进 needs，否则读起来像那几台不用干活（`redundant_need` 也会报）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它让电机绕组有来路 —— 但只解掉一处卡点
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 绕线机卡在"电机 → 绕组 → 绕线机"这条环上：十几条路线指名要它（电机的嵌转子绕组
 * 与绕线、接触器的线圈、变压器的绕组分段、仪表的动圈、电位器的绕制……）。
 * 它整机五件零件里，机架、主轴、排线丝杠三件的路线用到的设备全在七台之内，
 * **唯独控制单元这一件没有那样的路线** —— 三条来路都停在 std/ 外购件上。
 * 本文件补的就是这一处：控制单元不再等任何一件 std（除那块本来就该在种子里的板子）。
 *
 * ⚠️ 但绕线机的 BOM 里还有一只 `std/motor-7.5kw-4p`，而那只电机的绕组又要绕线机
 * （data/machine/motor.ts 文件头第三条已经写下这个环）。**本文不动那个环。**
 *
 * 另外两处也还开着，记在这里，不当成已解决：
 *
 *   · 张力轮要 40Cr，而 40Cr 要铬铁（data/material/chain.ts 的 make/steel-40cr）；
 *     铬铁要矿热炉，矿热炉不在这七台里。所以"整机五件里四件有路线"这句话，
 *     只在机架、主轴、排线丝杠三件上完全成立。
 *   · 铜与 HT200 的上游：make/iron-ht200 要 mat/iron，make/iron 要海绵铁与石灰，
 *     海绵铁要还原炉（data/material/bootstrap.ts）—— 那些设备一台也不在本文件里。
 *     本文证明的是**拓扑**：控制单元不再挂在外购件上；不证明"明天就能开工"。
 *   · 主回路电缆与端子、按钮与指示灯、凸轮盘的键与弹簧 —— 本层没有这几样的小件
 *     条目，只能记成"多投的铜与铁"。它们不影响拓扑，影响装配的实录。
 */


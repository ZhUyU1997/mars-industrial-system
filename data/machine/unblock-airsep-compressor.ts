/**
 * 空分压缩机 —— 第二条来路：**只用车床与磨床，不经铣床**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么要有这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 严格算术（报告最后一节：设备也算进闭包）从种子出发只长出 48 / 473 项。
 * 空分卡在压缩机上，而原来那条 `make/airsep-compressor` 是：
 *
 *   45 钢叶轮 → 车 → **铣叶片** → 磨（动平衡去重）
 *
 * 它要 `mat/steel-45`，还要 `plant/milling-machine`。两样都不可及，而卡住的原因
 * 是同一个 —— **那只标准电机**（`std/motor-7.5kw-4p`）：
 *
 *   mat/steel-45            路线 needs `plant/radiator`；散热器上装着那只电机
 *   plant/milling-machine   卡在主轴（要锻件与千分尺）、进给丝杠（要 45 钢）
 *                           与同一只电机上；它的床身、立柱、工作台反倒都造得出来
 *
 * 电机的五个零件要 45 钢、硅钢、漆包线与轴承 —— 这几样全在闭环之外。所以
 * **不是"铣床做不出来"，是铣床装不起来**：绕开它，比造出它便宜得多。
 *
 * 本文不换工艺，**换机型**。判据只有一条：**这台机器的每一个工作面都是回转面。**
 * 是，就只用车与磨；不是（平面、空间型线、螺旋面、键槽），本层就做不出。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 机型：单级单作用往复活塞机，φ200 × 150
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   缸筒内孔       镗 → 磨（圆柱面）
 *   活塞、活塞环    车外圆、切环槽（回转面）
 *   曲轴           偏心装夹车曲拐与轴颈（回转面）
 *   飞轮、皮带轮    车端面与外圆（回转面）
 *   阀座、阀瓣      车 45° 锥面（圆锥面）
 *
 * 被否掉的三件事，理由都同一句：
 *
 *   离心叶轮（原设计）  叶片是空间型线，只能铣
 *   罗茨鼓风机          8 字形转子型线，也要铣 —— "车床花盘装铣头"在本层没有铣头
 *   螺杆机              转子是螺旋面，同样要铣
 *
 * 两处"不铣"的具体做法，写在这里是因为它们没有额外的料与设备：
 *
 *   汽道   在缸盖铸件里留芯孔，铸出来就是通的（铸件来自熔化炉）
 *   键槽   曲轴与飞轮用锥面 + 端面摩擦 + 紧定螺钉，不用键（键槽要插床或铣床）
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级：四处，都可算
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **单级，压比只能取 8。** 温度比 = 8^0.286 ≈ 1.81：进气 210 K（火星常温）→
 *    排气 380 K，铸铁环干运转还撑得住。而空分要的是 0.6 kPa → 100 kPa 量级，
 *    也就是 167 : 1，单级温度比 167^0.286 ≈ 4.3 → 908 K（约 635 °C），
 *    铸铁环与石墨填料都到不了。工业上是三级带中间冷却；本层做不出级间冷却器
 *    （要板、要焊、要管束），只能把三台这样的机串联，级间热靠铸铁机身与自然对流
 *    散掉 —— **等熵效率从 0.75 掉到 0.45（估）**。
 *
 * ② **容积效率约 0.6，工业机约 0.9。** 密封只有两样：铸铁活塞环与石墨填料。
 *    没有可及的橡胶与润滑油（有机链、橡胶链都不在闭包里），缸壁靠铸铁里的
 *    片状石墨自润滑。代价是漏气与磨损：**漏气量比工业机高一个量级（估）**。
 *
 * ③ **曲轴是铸件，不是 45 钢锻件。** `mat/steel-45` 的路线 needs `plant/radiator`，
 *    而散热器要那只标准电机 —— 闭包里到不了；只能与缸筒同炉浇成 HT300。
 *    铸铁曲轴的疲劳强度低，**转速限到 300 rpm**（工业机 750–1000），飞轮按此配重。
 *
 * ④ **排气量约为同等缸径工业机的十分之一。** 这一条是算出来的：
 *
 *      φ200 × 150 单作用：π/4 × 0.2² × 0.15 ≈ 4.7 L/转
 *      300 rpm  →  4.7 × 300 ≈ 1.4 m³/min
 *      同缸径工业双作用机约 12 m³/min（转速高 2.5 倍、双作用、余隙小）（估）
 *
 *    **差一个数量级 —— 这就是"造得出来"与"够用"之间的距离。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它没有解决什么
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   · 只通了**压缩机这一个零件**。空分整机仍长不出来：换热器、分离罐、机架要
 *     `plant/sheet-shop`，节流阀要 `plant/milling-machine`，`std/motor-7.5kw-4p`
 *     也还没进闭包。这几样都不在本文范围 —— 一条路线只拆一个堵点。
 *   · 压比 8 不是空分要的 167 —— 要通那一步，得先有能造级间冷却器的那条链。
 *   · 不写 `under: pressure`：压缩机自己就是加压的那台设备，而它在这里是**零件**
 *     （`plant/air-separator/compressor`，category = part），不是设备；就算写成设备，
 *     也没有哪台机器 holds 得住 pressure。**这是模型缺口，不是遗漏。**
 *
 * 质量账：投料 557 kg 全是 kg 项，产出物是 `unit: '件'`（见 data/material/entry.ts），
 * 模型对"件"不判质量守恒，所以不写 `unbalanced_zh` —— 填了反而会多出一条
 * `declared_unbalanced` 提示，而这条路线并没有需要豁免的地方。
 */


/**
 * 铣床主轴 —— 第二条来路：**45 钢圆钢，不锻、不 40Cr**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么要有这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 严格算术（报告最后一节：设备也算进闭包）里，铣床卡在自己的主轴上 ——
 * 报告"卡在哪"那一列写的就是 `plant/milling-machine ← plant/milling-machine/spindle`。
 * 原来那条 `make/mill-spindle`（data/machine/tools.ts）要四样：
 *
 *   mat/steel-40cr           铬要整条铬铁矿链（铬铁 → 40Cr）
 *   plant/forge              锻件的执行者
 *   std/bearing-spindle-p5   主轴轴承，P5 级
 *   std/micrometer-0-25      千分尺
 *
 * 四样里**没有一样是铣床自己**，但四样各自都挂在下一层还没走通的路线上 ——
 * 于是"造铣床"实际是"等四样东西"。本文把主轴单独重写：只用本层已有的手
 * （车床、磨床、机器人、土窑、量块）与一样已经会做的材料（45 钢）。
 *
 * 判据一句话：**不新增设备，不引用任何 `std/` 条目，材料只有一样。**
 * 满足它，主轴就从"等设备"变成"等材料"；材料能一段一段补，设备不行。
 *
 * 同一个条目两条路线是允许的（src/core/describe.ts 开头第 ② 条：多条 Route
 * 产出同一 Item 是 OR）。两条并存的意思是：有 40Cr、有锻件、有 P5 轴承时走
 * 那一条（性能好）；没有时走这一条（性能打折，见下）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级：四处
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **45 钢代 40Cr，并且不锻。**
 *    40Cr 里那 0.9% 的铬是淬透性的来源（配方见 data/material/chain.ts 的
 *    make/steel-40cr）。同一根 φ80 的棒（铣床主轴的直径），
 *    铬让 40Cr 硬得更深；45 钢只有表层能成马氏体，心部还是珠光体 + 铁素体。
 *    代价是轴颈的硬度与抗弯疲劳低一档 —— 补偿是把表层硬度做足（回火取低限），
 *    并把危险截面留在磨过的轴颈上（磨过的表面没有脱碳层、没有刀痕）。
 *
 *    不锻的代价是另一条：锻件的纤维流线沿轴向连续，车削把流线切断，扭转
 *    疲劳强度因此下降。换来的是**不等 plant/forge** —— 它自己也要一条链。
 *
 * ② **端部 7:24 锥孔"车后研配"，没有内圆磨。**
 *    锥孔是这台机器与刀柄之间唯一的定位面。种子里那套磨床写的是"外圆、内圆、
 *    导轨三样"（data/floor/seed.ts），可数据里没有一条路线指名内圆那一台去磨
 *    内锥 —— data/machine/tools.ts 对这条主轴的注释更直接："锥孔要内圆磨，
 *    而内圆磨未建"。这一件按"没有内圆磨"处理，于是锥孔的终加工只能是
 *    "车到半精，再用涂色研具对研"（哪天把内圆那一台落成能被指名的设备，
 *    这一段换成磨锥孔，这处降级就撤掉）。
 *
 *    影响落在**跳动**上，而且是一层一层放大的：研具靠手感引导，锥面与两端
 *    已磨好的轴颈之间没有机床保证同轴度，只能靠对研时反复找正。刀柄装上后，
 *    刀具的径向跳动因此比磨出来的锥孔大一档 —— 换刀之后铣出来的面会留下台阶，
 *    而台阶不是尺寸误差，是**位置误差**，没有任何一道后续工序能修它。
 *
 *    锥孔同时承担传扭：**不铣键槽**（键槽要铣床，而铣床正是这条路线要造的那台），
 *    扭矩全靠 7:24 锥面自锁与摩擦 —— 重切削时的传扭上限比带键的低。
 *
 * ③ **调质那一段不写温度条件。**
 *    淬火 830–860，回火再低一档。干这活的应该是电阻炉（`plant/resistance-furnace`，
 *    holds 100–1100），可那台炉子自己还缺一条走得通的路线；在场而又到得了这个
 *    温区的只有土窑（400–1100），而土窑是烧砖、烧玻璃、焙烧的窑 —— 夯土壁、
 *    自然抽风、看火色，没有炉门与热电偶。**"烧得到"不等于"维持得住"**，
 *    所以这一段只写工序名与执行者，不写 `under`。
 *
 *    这是本轮取的保守写法，说清取舍：写上去校验也过（830–860 落在土窑
 *    400–1100 之内），但那样声明的是"土窑守得住 830–860"，而它守不住 ——
 *    守不住的温度不该进 `under`。代价留在上面那两行里：硬度散差与脱碳层深度
 *    都说不准，精车必须按最坏情况多留余量。等电阻炉通了，这一段换成它、
 *    补上 830–860，这一处降级就撤掉。
 *
 * ④ **量具降一级：量块 + 卡规，没有千分尺。**
 *    原路线要 `std/micrometer-0-25`，而千分尺不在种子清单里。这条路线用
 *    K 级量块定义"多粗算对"，卡规给通止。读数分辨率从千分尺的 1 µm 掉到
 *    卡规的量级，于是轴颈尺寸只能靠**磨床的进给**保证，量具只判"在不在带里"。
 *    这是四处降级里唯一一处落在测量而不是加工上 —— 判据降级比能力降级更危险，
 *    因为它不表现为"做不好"，而表现为"不知道好不好"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 轴承：这一版不装，留给装配
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 原路线把 2 只 `std/bearing-spindle-p5` 写在 uses 里 —— 主轴单元是"轴 + 轴承"。
 * 这条路线**产出的是一根光轴**：轴承不进 uses，也不进 needs。
 *
 * 取舍：轴承的选配本来就发生在装配那一步 —— 轴颈磨到尺寸之后，才知道该配多大的
 * 轴承。写进车削路线，等于假装轴颈尺寸是给定的。所以本层只保证"轴颈磨到能装
 * 轴承"，轴承在装配时按实测配：有 P0 级就配 P0（间隙靠磨轴颈修正），没有就退到
 * **滑动轴承**（轴瓦刮研配间隙）—— 转速上限与刚度各降一档，发热与间隙漂移各大
 * 一档。**引用任何 `std/` 条目，这条路线就重新挂在还没走通的标准件链上**，
 * 而绕开那条链正是它存在的理由。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 数字与写法
 * ═══════════════════════════════════════════════════════════════════════
 *
 * · 1 kg 45 钢 → 1 件：与原路线 make/mill-spindle（data/machine/tools.ts）同一个
 *   口径 —— 证明拓扑（谁要谁、谁造谁），不证明量。产出按件计、零件没有质量基准，
 *   模型只在进出都以 kg 计时才断言质量守恒（src/core/describe.ts 的 unbalanced
 *   那一段），所以这里不写 `unbalanced_zh`：这条路线没有需要豁免的地方，
 *   填了只是个不会触发的字段。
 * · 不写 `pressure`：车、磨、研配都在 0.6 kPa 的现场气压下做。0.6 kPa 略低于
 *   水的三相点 610 Pa（data/floor/mars.ts），水不能以液态敞开存在，所以这一版
 *   按干切 + 油雾走，没有一道工序要加压。
 * · 其余四段都不写 `under`：车与磨靠机床的几何精度，研配靠手，量块靠标准 ——
 *   它们不靠"维持某个条件"完成。调质那一段也不写，理由见降级 ③。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它没有解决什么
 * ═══════════════════════════════════════════════════════════════════════
 *
 * · 只通了主轴这一件。铣床整机还缺装配清单上的那只标准电机
 *   `std/motor-7.5kw-4p` —— 它装在每一台设备里，是整条设备链最后、也是最大的
 *   一处环（报告"卡在哪"那一节现在专门打一行盯它）。另外五个专用件里，床身、
 *   立柱、工作台、铣头四件是铸铁（熔炼炉 + 车床 + 磨床，材料侧不剩堵点），
 *   进给丝杠与本文同吃 45 钢 —— 45 钢通了，它也就通了。
 * · 内圆磨与淬火炉这两个缺位写在降级 ②③ 里，不在这里重复。
 * · 主轴与轴承的界面（轴颈公差带、预紧量）没有写进数据：模型不记公差。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一处"那时没有、现在有了"
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 45 钢这条材料以前是走不通的：make/steel-45（data/material/chain.ts）的 needs
 * 里挂着 plant/radiator，而散热器的循环泵（make/radiator-pump）要用铣床车泵体
 * —— 转一圈又回到这台机器。data/machine/unblock-airsep-compressor.ts 的文件头
 * 记的就是这道门（它因此把曲轴改成了铸铁）。
 *
 * 现在那道门开了：make/steel-45 的 needs 按 make/iron 同一个理由清空
 * （小批量靠地面导热，连续生产才要风冷散热器）。
 * 所以这条路线不是"只写在纸上"的那一种：**45 钢在场，它就长得出主轴。**
 * 这也是它与那份铸铁曲轴的分别 —— 那一件是"绕开"，这一件是"等到门开"。
 */


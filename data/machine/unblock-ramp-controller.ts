/**
 * 程序升温控制器（`std/ramp-controller-general`）的第二条来路 ——
 * **一只八段凸轮盘、一根刚玉棒、一只差动杠杆、三层超温保护**。
 *
 * 这一件是前两件的**交集**，所以它第三次用到同一套东西：
 *
 *   `unblock-process-controller.ts`  的**程序盘**：重锤 + 擒纵 + 45:1 + 8 齿星轮
 *                                    （那一件上它推动"遮板"，改的是占空比）
 *   `unblock-temp-controller.ts`     的**感温头**：刚玉棒 + 石英参考支架 + 4:1 杠杆
 *                                    （那一件上它推一只开关，做的是双位）
 *
 * 而两者的**接法**不一样，这一点最要紧：
 *
 *   温控器      棒的位置 与 **螺丝给的固定设定值** 比  → 通/断
 *   程序升温    棒的位置 与 **凸轮盘给的随时间走的设定值** 比 → 通/断
 *
 * 也就是说：程序升温器 = 温控器 + 一只会转的设定值。**多出来的那部分只有一只盘**，
 * 而盘上刻的是"工艺"。
 *
 * 原路线（`make/ramp-controller`，data/material/ramp.ts 第 61 行）是
 * PROM + 计数器 + 运放做 DAC + **一只温控器** + 薄钢板；它要 metrology-room 与
 * `std/curve-tracer-general`。而这一条不能把温控器当积木用（料单里没有 std/ 件），
 * 所以传感、比较、通断都得自己再做一遍 —— 只是**同样的三件，只做一次**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一、程序段数、斜率与"一只盘一个工艺"
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   段数      **8 段**（盘上一圈 8 条凸轮，45° 一段）
 *   时基      **30 min/格**（4 h/圈，45 齿棘轮）或 **60 min/格**（8 h/圈，90 齿棘轮）
 *             —— 换时基是**换一只棘轮**，不是调速（这一件的"时间"只有两种走法）
 *   斜率      **0–20 K/min**（一段 30 min 最多爬 600 K = 盘面 7.2 mm 的升程）
 *             0 就是保温段；20 是球化退火的降温速率（本层最陡的一档）
 *   升程      盘面 0–12 mm ↔ 设定值 0–1000 K（**12 µm/K**）
 *
 * 数据里那三条工艺（ramp.ts 第 10–14 行）正好把这张表撑满：
 *
 *   淬火前预热   5 K/min 升到 830（166 min ≈ 5.5 格）＋ 保温 30 min（1 格）  = 6.5 格 ✓
 *   球化退火    10 K/min 升到 780（78 min ≈ 2.6 格）＋ 保温 4 h（30 min/格要 8 格）
 *               ✗ **装不下** → 换 60 min/格：1.3 + 4 + 0.65（20 K/min 冷）＝ 6 格 ✓
 *   氮化        升到 540 ＋ 保温 8 h → 只有 60 min/格 的 8 格刚好装下（保温占满）✓
 *
 * 所以"一只盘一个工艺"不是口号，是算术：**盘的段数与格子长度是死的，工艺的长短
 * 是活的**，两者对不上就得重铣一只盘（或者换一只棘轮，把格子拉长一倍）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 二、斜率精度：三个误差源，一个压着另一个
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   走时     擒纵 40 s/齿 → 45 齿 = 30 min/格。齿形与销子会磨，走时 **±5%**
 *            （本层没有秒表，校走时靠数数与"一天差多少"）
 *   盘形     凸轮轮廓用铣床的分度头铣，轮廓误差 **±0.05 mm**
 *            → 设定值 ±0.05/0.012 = **±4 K** → 斜率 ±4 K/30 min = **±0.13 K/min**
 *   跟随     双位环的摆幅 ±3.8 K + 棒的滞后 14 s（0.25 K/s × 14 = 3.5 K）
 *            → 实际温度**在曲线上下 ±6 K** 走
 *
 *   → **斜率精度 ±6%**（5 K/min 时 ±0.3 K/min；20 K/min 时 ±1.2 K/min），
 *     一条曲线的总时间误差 ±5%（4 h 上 ±12 min）。
 *
 * ⚠️ 这个 ±6% 对"淬火前预热"够（830 ±25 K 的带子），对**球化退火不够**：
 * 球化的升温速率决定碳化物的球化程度，±6% 的速率差在一炉里能看出组织差。
 * 而工业的 PROM 版是 **±0.1%**（晶振分频）—— **差 60 倍**（第七节③）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三、三层超温保护（这一件必须有，温控器那一件自己承认没有）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 一只机械式的双位控制器最怕的是"它以为温度没到"：棒断了、杠杆卡了、触点粘了，
 * 三种故障都表现为**继续加热**。所以这一件把"停"做成三层，一层比一层笨：
 *
 *   ① **程序走完的停车爪**（正常停）
 *      第 8 段走完，星轮转过第 8 齿、进到无齿的那一格，一只停车爪落进去
 *      → 顶开主触点 + 翻跳牌。
 *      这是"工艺结束"，不是保护。
 *   ② **超温锁扣开关**（整定 **1000 °C**，要人复位）
 *      与主开关**共用同一根棒**，但触点在刻度盘 1000 那个位置；
 *      一旦碰到，一只 45 钢的锁扣咬住、**机械地锁死**（不是弹簧回位）——
 *      温度降下来它也不会自己合上，必须人手扳。
 *      为什么是 1000：炉子用到 900（淬火 830–860 的上限余量），炉衬高铝砖的上限
 *      1100 —— **1000 正好在两者之间**。
 *   ③ **易熔丝**（断点 **1 084.6 °C**，铜；不可复位，只能换丝）
 *      一根 φ2 的铜丝吊住一只 **2 kg 铁重锤**，丝穿过炉顶的一只陶套管、
 *      下端埋在炉膛均温区。铜一化，重锤落下，**砸开一只闸刀**（串在炉子的电源上）。
 *      为什么是铜：料单里熔点最低的金属就是它 —— 锡（232）、铅（327）、铝（660）
 *      **都不在料单上**（锡与铅连条目都没有）。所以这一层的整定值不是"比设定点
 *      高 50 K"，而是 **1084.6 —— 一个"炉子快烧穿了才断"的值**。
 *
 * ⚠️ 三层里只有第三层**不依赖那根棒**。①②共用一根棒：**棒一断，两个开关都读
 * "冷"，炉子一路烧到铜化** —— 这正是第三层存在的理由。**一只表最危险的故障，
 * 是它不知道自己坏了；而唯一不撒谎的是"铜化了没有"。**
 *
 * ⚠️ 易熔丝的实际断点不是 1084.6，而是 **1000–1080 的一段**：φ2 的铜在 900 以上
 * 会蠕变（2 kg 的拉力 = 6.2 MPa，铜在 1000 的蠕变强度只有 10 MPa 量级），
 * 而且它在空气里氧化、直径每小时掉十几微米量级。所以它**不是一支精确的温度计，
 * 是一只"最后的说谎者"**（第七节⑤）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四、曲线走完怎么停，以及怎么再来一炉
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   走完    第 8 段末 → 星轮转进无齿的那一格 → 停车爪落下 → 主触点被顶开、
 *           跳牌翻起。
 *           同时重锤到底（4 h 或 8 h 的弦正好走完）—— **两道都断，是故意的**：
 *           万一停车爪卡住，弦走完也让盘停转，温度就停在最后那一段上不再爬。
 *   降温    没有风扇、没有水冷：**炉子自然降温**（900 上 0.08 K/s，降到 100 要 2.7 h）。
 *           高铝砖的热震极差，快冷会裂 —— 自然冷是"不得不"，也是"正好"。
 *   再来一炉 ① 把星轮拨回第 1 格（一只拨销，30 s）② 摇重锤上弦（2 kg × 300 mm，
 *           40 圈）③ 按一下跳牌复位 ④ 易熔丝若断过，换一根 φ2 铜丝（剪 200 mm、
 *           两端用铜卡子压住 —— 不许打结，打结处会先断）
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五、它还是"一只盘一个工艺"
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 盘是 φ200×8 的铸铁盘，轮廓用铣床分度头一齿一齿铣出来（每段 45°、升程 0–7.2 mm）。
 * 换一条曲线要：
 *
 *   画工艺卡（人）→ 按升程表算 8 个点（半小时）→ 铣一只新盘（2–3 天，含浇铸）
 *   → 装盘 → 走一遍曲线核对（4–8 h）
 *
 * 而 PROM 版是"重烧一片 PROM"（1 h）。**这是这一件最实在的一处降级：
 * 时间尺度差两个数量级，而且那只盘是铸铁的，做出来就退不回去。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 六、精度、寿命与维护
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   温度跟随   ±6 K（摆幅 3.8 + 滞后 3.5 —— 沿曲线走时两者叠加）
 *   斜率       ±6%（走时 5% + 盘形 2.7%）
 *   段切换点   ±4 K（盘形的 ±0.05 mm）→ 在 5 K/min 上是 **±48 s**
 *              （盘的 45° 分度差 0.5° 只值 20 s，比它还小）
 *   走时       30 min/格 ±1.5 min（±5%）；一天快/慢 1–2 min
 *   寿命       盘（铸铁，10⁴ 次启停的磨损）、星轮 8 齿（白口，10⁵ 次）、
 *              触点（**每炉 91 次**（4 h，周期 158 s）× 每年 200 炉 = 1.8×10⁴ 次/年
 *              → 每季锉一次、每年换一对）
 *   维护       每年 ~30 次（锉触点 4、换棒 2、重标 6、上油 12、换丝 2、换簧 2、
 *              校走时 2）；**电子版是 0 次**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 七、kg 账（一件，算式在每条 uses 下）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   进 24.8 kg → 一件约 18.5 kg：
 *     耐火料 6.0 → 4.08    HT200 5.5 → 4.40    HT250 1.2 → 0.94
 *     HT300 0.5 → 0.28     45 钢 4.0 → 3.36     铜 1.6 → 1.38
 *     铜线 0.25 → 0.225    玻包线 0.3 → 0.27    碳 0.15 → 0.14
 *     石灰 0.6 → 0.36      硅石 0.5 → 0.315     矿渣 0.4 → 0.36
 *     水 1.8 → 0.72        尾矿 0.8 → 0.64      风化层 1.0 → 0.80
 *     矿棉 0.2 → 0.184
 *   差 6.35 kg = 耐火废坯 1.92 + 浇冒口与回炉铁 1.58 + 水 1.08 + 45 钢车屑 0.64
 *     + 石灰损耗 0.24 + 铜车屑 0.22 + 风化层烧失 0.20 + 硅石熔制与粘坩埚 0.185
 *     + 尾矿筛余 0.16 + 矿渣余料 0.04 + 玻包线 0.03 + 铜线 0.025
 *     + 矿棉切割 0.016 + 碳粉 0.01
 *
 * ⚠️ 条目没有 `mass`（ramp.ts 第 46 行只声明 id / unit / category），产出按台计，
 * 所以 `unbalanced` 判据不会触发 —— 这一段是给人读的。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 八、降级（八处，比较对象：PROM + 计数器 + DAC + PID 的电子版）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① **换一条曲线的时间差两个数量级**：电子版重烧一片 PROM 约 1 h（不含排产）；
 *      这一台要**重铣一只铸铁盘** 2–3 天。**盘是铸铁的，做出来就退不回去** ——
 *      一只盘 = 一个工艺，工艺改了盘就废。这是这一件最贵的一处。
 *   ② **斜率精度差 60 倍**：电子版晶振分频 ±0.1%；这一台 ±6%（走时 ±5% 打底）。
 *      对淬火预热够，对球化退火（速率决定碳化物形态）**不够**。
 *   ③ **8 段 vs 任意长程序**：一条"升温-保温-升温-保温-降温"的工艺要 5–7 段，
 *      所以这只盘最多做两个保温点。再多就要一只更长的盘（盘径 200 已经到头 ——
 *      再大，分度头与铣床都装不下）。
 *   ④ **没有断电记忆**：电子版记得"程序走到第几段、还剩多久"；这一台一停电就
 *      停在原地，而重锤的能量还在 —— **它不会知道中间停了 20 min**。
 *      所以停电一次，这一炉就只能按"多保了 20 min"重新算。
 *   ⑤ **超温只有一个整定值**（1000），后备更是固定 1084.6；电子版可以任意设。
 *      而这三层里有两层共用那根棒 —— **棒一断，前两层全失效**（第三节）。
 *   ⑥ **超温后不能自恢复**：换铜丝 + 扳锁扣 + 重对零（棒被烤过，零点漂 3–8 K），
 *      一次 30 min；电子版自动复位。
 *   ⑦ **重锤 4 h / 8 h 一上弦**：忘了上弦，盘停在原地、温度停在最后那一段 ——
 *      而"停在最后那一段"可能是 900 的保温，也可能是正在爬升的中途（更糟）。
 *   ⑧ **一件 18.5 kg、四十多个零件**（电子版是一只 1 kg 的表）：齿轮 3 对、擒纵 1 套、
 *      星轮与棘轮各 1 只、凸轮盘 1 只、棒 1 根、触点 4 对、易熔丝 1 根。
 *
 * ⚠️ 但有一处比电子版强，而且不是精神安慰：**它的程序是"看得见"的。**
 * 一只 φ200 的铸铁盘，8 段凸轮就是 8 段工艺 —— 操作工把盘拿在手里，能摸出
 * "这一段陡、这一段平"。而一片 PROM 里是什么，没有人看得见（除非再拿一台
 * 读片机）。**在火星上，"能被人检查"本身是一种可靠性。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 九、缺口（六处，写清卡在哪一步）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① **模型没有"程序"这个维度。** `std/ramp-controller-general` 与
 *      `std/temp-controller-general` 在模型里都是 `unit: '台'` 的 part，
 *      差别只写在文件里。这条路线最要紧的那几个数 —— 段数、格子长度、斜率 ——
 *      没有一个能写在条目上。
 *   ② **模型没有"失效"这个状态。** 三层保护（停车爪、锁扣、易熔丝）都是"在
 *      某种失效下才动作"的装置，而模型里没有"失效"这一栏 —— 所以它们只能活在
 *      注释与操作卡里。这与温控器那一件的缺口④是同一条。
 *   ③ **易熔丝的断点算不准。** 铜在 900 以上的蠕变强度与氧化速率都没有本层数据；
 *      "1000–1080 的一段"是估的。要测，得有一条"能在 1000 上保温若干小时"的炉子
 *      —— 而那台炉子要这只控制器才通（**一个温和的循环**）。
 *   ④ **盘的轮廓与温度的关系是"几何"的。** 12 µm/K 这个数把盘面的 0.05 mm
 *      放大成 4 K；而盘的升程表是人算的 —— 算错一个点，那条曲线就错 4 K，
 *      且**没有任何一处会报错**（它只是"照盘走"）。
 *   ⑤ **没有记录。** 电子版能把实际曲线画在烟熏玻璃上（ramp.ts 的验收就是
 *      "跟计划曲线比"）；这一台**没有记录盘** —— 要验曲线，得另找一支热电偶
 *      贴在炉子上看（而闭包里那支只有 0–200）。
 *   ⑥ **走时没有校时手段。** 本层没有秒表（那条一直没解），校 30 min/格
 *      只能靠"数数"与"一天快慢多少"；±5% 这个数有一半是"校不准"，不是"走得不准"。
 */


/**
 * 光学高温计电流表的替代路线：**动铁式串联表 + 双线悬丝**（0–2 A、±2%、无磁铁无游丝）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一、先把这一件的活看清：条目自己已经把取舍写定了
 * ═══════════════════════════════════════════════════════════════════════
 *
 * `plant/pyrometer/ammeter`（data/machine/pyrometer.ts 第 108 行）的注释：
 *
 *   动圈   要永磁 0.2 T，灵敏度高、刻度均匀，**但磁体要做**
 *   动铁   不要磁铁，线圈通电自己产生磁场，**但刻度不均匀、精度 ±2%**
 *   选择   动铁 —— "这一台只用来读负载电流，要的是重复性不是精度"
 *
 * 既有路线（第 166 行）要的是：mat/copper + mat/iron-ht250 + **mat/glass**，
 * needs `lathe` + `plant/comparator`，四道工序里写着"软铁片 + **游丝** + 指针"。
 *
 * 两处卡住：**mat/glass 不在料表**（本层能做玻璃，但它与这条路线要的不是一个东西），
 * 而 **`plant/comparator` 不在这一轮的 39 台里**。还有一处是隐的：**游丝**
 * —— 磷青铜或恒弹性合金、0.05 mm 的丝，本层都没有（没有拉丝模，φ1.0 是最细的）。
 *
 * 所以这条路线要解的是三件：玻璃窗、比较仪、游丝。前两件换成"不要"，
 * 第三件换成别的支承 —— 而 2 A 的量程、±2% 的精度、动铁式的原理，一律照旧。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 二、"能不能直接借毫伏表"：三条量化理由，答案是不能
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 最省的想法是：1 A 过 0.1 Ω 的分流电阻 = 100 mV，正好是毫伏表的活。算一遍：
 *
 * ① **串联压降**：0.1 Ω × 2 A = **0.2 V**，而灯丝满共只有 1.5 V（1.5 A 时）
 *    —— 表一接进去，灯丝电压掉 13%，**电流跟着变 13%**。这是"测量改变被测对象"
 *    的教科书案例：你要读的是灯丝电流，而你的表把它改掉了。毫伏表那份文件算过，
 *    它的回路是 1.52 Ω、满度 1.5 mV —— 那是**并联**在分流器上的，不是串联在
 *    灯丝回路里的。
 * ② **量程对不上**：100 mV 是毫伏表满度（1.5 mV）的 **66 倍**。要接，得在它前面
 *    再串一只 1/66 的分压器 —— 而分压器又是铜线绕的，于是把①刚绕开的温漂
 *    又从窗口递了回来。
 * ③ **铜分流器的温度系数**：α = 0.0039/K → **0.39%/K**。板温变 10 K 就是 3.9%，
 *    折到温度上（第五节）是 **30 K**。而整台高温计在 1600 处的预算只有 ±30 K
 *    —— **一只分流电阻就能把它吃干净。** 工业用锰铜（2×10⁻⁵/K，差 200 倍），
 *    本层没有锰也没有镍。
 *
 * 还有一条不是算术的：毫伏表是计量室的一件（`std/millivoltmeter-general`），
 * 不是高温计的零件。**高温计不能没有表** —— 借来的表不是零件。
 *
 * 所以：独立做一只。而动铁式正好把③那条**从根上避开**（第三节）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三、为什么串联电流表不怕电阻温漂（这一节是本件的全部底气）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 电压表是**并联**的：读数 ∝ 流过表头的电流 ∝ V/R_表 —— R 随温度变，读数就变，
 * 这就是上一份（毫伏表）文件里 0.39%/K 的来源。
 *
 * 电流表是**串联**的：**电流是被测回路强制的，与表的电阻无关**（表串在里面，
 * 回路自己决定流多少）。而动铁式的转矩 ∝ (N·I)²，只认**安匝数**、不认电阻。
 * 于是：
 *
 *   **线圈用铜（α 0.39%/K）没问题** —— 它的电阻变 1%，电流也不变（灯丝那边
 *   有调压电阻顶着）；读数不变。
 *
 * 这不是小事：它是"本层没有锰铜"这件事在这件仪器上**不构成障碍**的原因。
 * 同一个铜，在电压表里是灾难（0.39%/K），在电流表里是无害的。
 *
 * 代价换到别处：表的电阻虽然不影响**读数**，却影响**灯丝回路**（第二节①）。
 * 本设计把线圈压到 30 匝、0.06 Ω：2 A 下压降 0.12 V = 灯丝 1.5 V 的 **8%**
 * —— 还是要算进去，但已经是"标定时把表接在回路里"就能吸收的量级（第八节③）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四、动铁式：30 匝、平方律、软铁片的 μ
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 机构（与毫伏表那份文件同一套机芯，只换可动件）：
 *
 *   固定线圈   φ1.0 铜线 30 匝、绕在 φ35×30 的陶瓷骨架上、0.06 Ω、展开 3.3 m
 *   可动件     软铁片 10×10×0.2（0.16 g）两片：一片固定在线圈内壁，一片在可动件上
 *              —— **排斥式**：两片被同一个线圈磁化，同名极相斥，可动片被推出去
 *   支承       双线悬丝（两根玻璃纱、跨距 3 mm、长 50 mm、配重 1.6 g）
 *   指针       一根纱 + 一片碳旗，绕竖直轴扫 60°
 *
 * 转矩算一遍（2 A 满度）：
 *
 *   H = NI/L = 30 × 2 / 0.03 = 2.0 kA/m → B = μ₀H = 2.5×10⁻³ T
 *   排斥力 F ≈ B²·A/(2μ₀) = (6.3×10⁻⁶ × 2×10⁻⁵)/(2 × 1.26×10⁻⁶) = 5.0×10⁻⁵ N
 *   力臂 15 mm → 转矩 7.5×10⁻⁷ N·m
 *   悬丝 k = W·d²/(4L) = 1.6 g / 3 mm / 50 mm = **7.1×10⁻⁷ N·m/rad**
 *   → 满度偏转 7.5e-7 / 7.1e-7 = 1.06 rad ≈ **60°** ✓（配重 1.6 g 正好；减到 0.8 g 会到 120°，撞固定片）
 *     标定时按实际调 —— 这一步是装配出来的，不是算出来的）
 *
 * 平方律：转矩 ∝ I²，所以偏转 ∝ I²。**1 A 处只有 1/4 的偏转** —— 这是动铁式的
 * 老毛病（条目注释里那句"刻度不均匀"就是这个）。后果见第八节①。
 *
 * 软铁片的 μ 是两个变量的函数，两个都在装配车间里：
 *
 *   应力     初始磁导率随应力变，**±1% / 10 MPa**。装配时螺钉压 5 MPa
 *            就是 0.5% 的读数偏移 —— 所以片子要退火（第③道 800–900），
 *            而且夹紧力要用**弹簧片**给（定值），不能靠螺钉拧的手感
 *   温度     −0.1%/K（软铁在 20–60 °C 的 μ 温度系数），比铜的 0.39%/K 小 4 倍
 *            —— 这正是"动铁比铜分流好"的第二个理由
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五、读数怎么变成温度：dT/T = 0.4 × dI/I
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 这台表读的是灯丝电流，而灯丝电流决定**亮度温度**。关系是灯丝那条：
 * 功率 P = I²R 全变成辐射 P = εσAT⁴，而碳的电阻随温度**下降**（负温度系数）
 * → T⁴ ∝ I²·R(T) ∝ I²·T⁻¹ → **T ∝ I^0.4**。微分：
 *
 *   **dT/T = 0.4 · dI/I**
 *
 * 于是表的每一个误差都折成温度：
 *
 *   电流误差      1100 °C（1373 K）      1600 °C（1873 K）
 *   ±0.5%（重复性）   ±2.7 K               ±3.7 K
 *   ±1%             ±5.5 K                ±7.5 K
 *   ±2%（表的准度）   ±11 K                 ±15 K
 *   ±3.9%（铜温漂）   ±21 K                 ±29 K   ← 分流方案会是这样
 *   ±1%（铁温漂 10K） ±5.5 K                ±7.5 K  ← 本设计
 *
 * 关键的一句：**表的"绝对准确度"（±2%）会被标定表吸收掉** —— 每台高温计用自己
 * 这只表、在两个定点上标一次，"指针位置 → 温度"的表就是这台仪器自己的。所以
 * 进不了标定表的只剩三样：**重复性（±0.5%）、温漂（±0.1%/K）、应力松弛**。
 * 这也是条目注释那句"要的是重复性不是精度"的算术版。
 *
 * 反过来：**如果走"分流 + 毫伏表"，那 3.9%/K 的温漂是进不进标定表的**
 * —— 它随板温变，而标定表是一个固定的表。这就是第二节③那条否决的真正分量：
 * 它不是"准度差一点"，是"这只表每天都不一样"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 六、标定：安培刻度靠电，温度刻度靠定点
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 两套刻度，两套标法：
 *
 *   **安培刻度（0–2 A，100 格）**
 *     要一只已知电流。本层没有标准电流源，所以反过来做：让电流过一只**计算电阻**
 *     （铜排 200×20×5 mm + 两根引线，R = ρL/A，ρ 取书上的 1.7×10⁻⁸、几何用量块量，
 *     合起来 **±1%**），用计量室里那台数字电压表（±0.2%）量它两端的 10 mV
 *     → I = U/R，合起来 **±2%**。
 *     这就是这只表"±2%"的来源：**不是表头差，是电流基准差。**
 *
 *   **温度刻度（指针位置 → °C）**
 *     装到高温计上以后，在两个定点上对灯丝隐灭：铜凝固 1084.62 °C、铁碳共晶
 *     1153 °C（与 make/pyrometer-optical 那份文件的标定同一套）。这两点把
 *     "指针位置 ↔ 温度"钉住，中间按 T ∝ I^0.4 内插、往上外推 450 K 到 1600。
 *     所以**表盘上最要紧的数字不是安培，是那两条刻痕**。
 *
 * 一句话：**安培刻度是给人看的（±2%），温度刻度才是真的（±10 K）**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 七、kg 账
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   进 3.65 kg → 1 台约 1.46 kg：
 *     铸铁 1.20（壳 φ110×50 + 底座，浇注 1.60）
 *     45 钢 0.12（调零螺钉与偏心轮、悬丝夹头 2 对、表盖压框、指针的配重杆）
 *     软铁 0.01（四片 10×10×0.2 的片子，两片用两片备）+ 铜 0.045（接线柱 4）
 *     铜线 0.05（线圈 30 匝 3.3 m + 引线）+ 剥下的铜 0.02
 *     玻璃纱 0.005（两根悬丝 + 指针）+ 碳 0.003（指示旗）+ 矿棉 0.005（防尘毡）
 *   差 2.19 kg = 水 1.00（磨与洗，全走掉）+ 耐火料 0.30（陶瓷骨架、绝缘柱，全耗）
 *     + 石英粉 0.10（磨软铁片与刻度盘，全耗）+ 铸铁浇冒口 0.40 + 45 钢切屑 0.13
 *     + 软铁锻造与磨屑 0.09 + 铜切屑 0.015 + 铜线头尾 0.05 + 碳耗 0.047
 *     + 玻包线剥坏 0.01 + 矿棉边角 0.045（算式在 unbalanced_zh）
 *
 * 软铁那 0.01 kg 是全表最贵的一克：0.1 kg 的软铁锻到 0.2 mm、磨到 ±0.005，
 * 出来四片 0.16 g 的片子 —— **净重 0.6 g，投料 100 g**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 八、降级（六处，带量级）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **平方律刻度：1 A 处只有 1/4 偏转，前 1/3 的刻度挤成一团。**
 *    **读数分辨（读半格）**：1600 附近（1.5 A）每半格 **3.3 K**、1100 附近（0.7 A）每半格 **11 K** —— 低端
 *    差 3.3 倍，而低端（暗红端）恰恰最难判。工业动圈表是线性刻度
 *    （每格都一样），或者用整形极靴的排斥式把平方律压成 1.5 次方。
 *
 * ② **软铁片的应力与温度：μ 随应力 ±1%/10 MPa、随温度 −0.1%/K。**
 *    装配的螺钉压 5 MPa 就是 0.5% 的偏移；而**淬火/退火不良的片子三个月内会
 *    自己松弛 10–20%** → 读数漂 1–2% → **每季度重标一次**。工业用坡莫合金
 *    （μ 高 20 倍、应力敏感性低一半），本层没有镍。
 *
 * ③ **表的串联电阻 0.06 Ω 对灯丝 1 Ω 是 6%**：2 A 下压降 0.12 V = 灯丝 1.5 V 的 8%（电阻比 6%）—— 表接进去，灯丝电流就变 6–8%。
 *    所以标定必须在"表已接入"的回路里做 —— 换一只表要重标整台高温计。
 *    （灯的调压电阻能把电流调回 1.5 A，但**刻度与电流的对应关系变了**。）
 *
 * ④ **没有锰铜 → 不能走"分流 + 毫伏表"那条路：铜的 0.39%/K 折成 29 K/10 K。**
 *    本路线用"串联"绕开了它 —— 但这条降级要留着，因为它是选择串联动铁的
 *    第一理由，也是"为什么不能省掉这只表直接借毫伏表"的答案。
 *
 * ⑤ **只有一档量程（0–2 A）**：灯丝电流在 0.7 A 时指针落在 1/4 处、刻度最挤的
 *    那一段。工业表有 0.5/1/2 A 三档（换分流或换抽头），本层没有分流器可换
 *    —— 换量程就得换线圈，那是另一只表。
 *
 * ⑥ **温度刻度只能标两点**（铜 1084.62、铁碳共晶 1153），1100–1600 那一段是
 *    外推 450 K → **±20 K**（与 make/pyrometer-optical 那份文件的结论一致）。
 *    表头自己只贡献 ±4 K —— **大头还在定点上，不在表上**。这一条与"表越准
 *    整机就越准"的直觉相反：整机的瓶颈从来不是表。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 九、已知缺口（都不在这条路线的范围里）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  · **算不出绝对安培**：本层没有标准电流源（银库仑计要银、铜库仑计要硫酸铜，
 *    两样都不在料表）。所以安培刻度靠"计算电阻 + 数字电压表"，±2% —— 而"2 A
 *    到底是多少安"，在这颗行星上其实没人知道（只有"这只表的 2 A 与那只表的 2 A
 *    一样"）。温度刻度不受这个影响（定点是绝对的），所以整机照旧能用
 *  · **表的读数不进控制回路**：这台表是给人看的（人调灯丝电流、人判隐灭、
 *    人抄数）。高温计本来就没有自动读数（`make/pyrometer-optical` 那份文件
 *    写的就是"一次 20–40 s、要人在照门后"）
 *  · **游丝那一条换成了悬丝**：没有磷青铜、没有 0.05 mm 的丝。悬丝的刚度是
 *    几何给的（W·d²/4L），撞一下就变（与毫伏表那份文件同一条降级）
 *  · **表壳没有玻璃窗**：原路线用 mat/glass，本层的料表里没有它；所以表是敞口的
 *    —— 计量间里看（与干涉仪、dvm 那两份文件同一个办法），装在炉子边就要加罩
 *  · **没有比较仪**：原路线 needs `plant/comparator`（用来量刻度盘与线圈的同轴）。
 *    本路线用 `plant/gauge-block` 与车床的量表代替 —— 精度低一档（0.01 对 0.001），
 *    对 ±2% 的表够用
 *  · **电不进模型**：磁化? 不用（动铁不磁化）；标定的定点炉与电压表都不进 uses
 */


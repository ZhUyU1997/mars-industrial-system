/**
 * 磁选滚筒 —— 第二条来路：**铸铁筒体 + 铜外套**，不经不锈钢，也不经钣金工位。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么要有这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 严格算术（报告最后一节：设备也算进闭包）从种子出发只长出 48 / 473 项。
 * 磁选机卡在滚筒上，而原来那条 `make/separator-drum`（data/material/entry.ts）是：
 *
 *   不锈钢板 1 → 卷圆 → 纵缝焊 → 车端面 → 磨外圆        执行者 plant/sheet-shop
 *
 * 它要两样闭包里都没有的东西：
 *
 *   mat/stainless-steel   18/8 的配料是铁 643 + 碳 1 + 铬铁 276 + 镍 80，
 *                         而镍的富集是 250 : 1、铬铁矿是 140 : 1 —— 两样的
 *                         冶炼设备（电解精炼、矿热炉）都还没进闭包
 *   plant/sheet-shop      钣金工位自己就是"要造的机器"，它的五个零件还在别的链上
 *
 * 本文**不换零件、换材料与工艺**：产出仍是 `plant/magnetic-separator/drum`，
 * 两条路线并存（模型里同一产出有多条路线就是 OR，原路线照留）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 判据只有一条：筒的外表面必须是非磁性的
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 这条不能谈判：筒壁在磁极与矿粉之间，是磁路的一部分。用普通钢，磁通从筒壁里
 * 就闭合了，工作面吸不住矿；更糟的是筒壁自己被磁化成一圈磁极，矿粉粘在筒上，
 * **整台机器变成一块吸铁石**。
 *
 * 闭包里能当"非磁性金属"用的只有**铜**：
 *
 *   铜不导磁，相对磁导率 ≈ 1，对磁通是透明的  ← 用它
 *   铝的路线在 data/material/aluminium.ts 里有，但整条铝链不在闭包里
 *   不锈钢（原路线）不在闭包里，见上
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 结构：铸铁筒体 + 6 mm 铜外套，φ600 × 800
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   铸铁筒体，取最普通的一档 HT200          ≈ 199 kg（投料按 200 kg 计，含浇冒口）
 *     筒壁 12 mm（车后外径 φ588）  π × 0.588 × 0.8 × 0.012 = 0.01773 m³
 *                                  × 7.2 t/m³                ≈ 128 kg
 *     两端盘 φ600 × 15，两件        2 × π/4 × 0.6² × 0.015 = 0.00848 m³ × 7.2
 *                                                             ≈  61 kg
 *     轴毂（带键槽）                                           ≈  10 kg
 *
 *   铜外套 6 mm                                             ≈ 100 kg
 *     展开面积 π × 0.6 × 0.8 = 1.51 m²；1.51 × 0.006 = 0.00905 m³ × 8.96
 *                                                             ≈  81 kg
 *     纵向搭接边 + 两端包边 + 铜铆钉                            ≈  11 kg
 *     切边损耗与回炉按 8% 计                                    ≈   8 kg
 *
 * 尺寸是"10–20 t/h 筒式磁选机"的量级估，不是型号参数 —— 模型没有体积，
 * 这里只需要一个能把铜量算出来的几何。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 成本：一只滚筒的铜，背后是三千五百吨土
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 铜的富集比 **8333 : 1**（风化层 30 ppm → 精矿 25%，0.25 / 0.00003 = 8333，
 * 见 make/copper-concentrate），再走熔炼与电解两段：
 *
 *   1000 kg 精矿 → 250 kg 泡铜（make/blister-copper）
 *    250 kg 泡铜 → 240 kg 纯铜（make/copper，回收 98%）
 *
 * 于是每 1 kg 铜要 4.17 kg 精矿，也就是 **4.17 × 8333 ≈ 34.7 t 风化层**；
 * 100 kg 铜 = **3 470 t 风化层**。
 *
 * 对比：筒内那只电磁铁的线圈是 60 kg 铜，2 082 t 土（见 make/separator-magnet）。
 * **滚筒比磁铁更费铜 —— 贵在"非磁性"三个字上，不在精度上。**
 * 这是这只滚筒贵的唯一原因，也是它只造一台的原因。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级：四处，都能算
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **铜皮下面还是铁，磁场被分掉一部分。** 铜对磁通透明，铸铁不透明：12 mm 铁筒
 *    的磁阻比磁极前那 2 mm 气隙小得多，磁通优先从铁筒里闭合，工作面只剩漏出来的
 *    那一层。原路线的不锈钢筒是**整壁非磁性**，磁场能直接穿出去。
 *    后果：只选得了强磁性的矿（磁铁矿 Fe₃O₄），赤铁矿这类弱磁性的选不了 ——
 *    **对本项目够用**：风化层里要选出来去还原的，正是磁铁矿。
 *    真正的修法只有一条 —— 筒壁整壁用铜：8 mm 整体铜筒 = π × 0.6 × 0.8 × 0.008
 *    × 8 960 ≈ 108 kg 铜，只比现在这 81 kg 铜皮多 27 kg。**在磁场路径上，
 *    铁筒省不下铜，只省了铜的厚度。** 那是第三条路线的事，本文不做。
 *
 * ② **铜是软的，铜皮是磨损件不是结构件。** 铜 HB 45–60（退火）到 HB 100（冷作），
 *    304 不锈钢 HB ≈ 150–200 —— 硬度只有它的二分之一到三分之一。筒面圆周速度
 *    π × 0.6 × (20/60) ≈ 0.63 m/s（20 rpm，筒式磁选机的常规转速），矿粉就贴着
 *    这个面擦过去。
 *    **两处补救，都是"换件不换机"**：铜皮按可换件做（铆接而不是焊，磨穿了换一圈皮，
 *    筒体不动）；或者干脆做成可换衬板 —— 4 mm 铜衬板挂在铜皮上，磨穿只换衬板。
 *    ⚠️ 本层没有铜的冲刷磨损数据，**不给寿命数字** —— 编一个数是违反规范第 4 条的。
 *
 * ③ **圆度靠手艺，不靠卷板机。** 6 mm 铜板卷 φ600：没有卷板机，手工卷 + 车床辊压头
 *    整圆 + 环形样板透光校。铜软、车削让刀，圆度与圆柱度比卷板机卷出来的低一档。
 *    跳动只影响矿层厚薄与磁场间隙，不影响能不能选 —— 但它决定了这台滚筒不能快转。
 *
 * ④ **铜与铸铁不能焊，只能铆。** 铜 17 × 10⁻⁶ /K、铸铁 11 × 10⁻⁶ /K，温差 100 K 时
 *    φ600 上的周长差 = π × 600 × (17 − 11) × 10⁻⁶ × 100 = **1.13 mm**。
 *    焊死就把铜皮拉裂、或把铆钉剪断 —— 所以纵缝与两端包边全用铜铆钉，
 *    铆钉孔开长圆留伸缩，两端再压一道包边挡住矿粉钻进夹层。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它没有解决什么
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   · 只通了**滚筒这一个零件**。磁选机的电磁线圈（60 kg 铜）、励磁电源、机架、
 *     传动、料斗还各自卡在别的链上 —— 机架要 plant/milling-machine，料斗要
 *     plant/sheet-shop。滚筒通了不等于磁选机通了。
 *   · ① 的磁场损失是选材的代价，不是工艺能修的。
 *   · **铜板那一段没有单列。** `mat/copper` 到 6 mm 铜板之间是轧制，而轧机不在闭包里；
 *     本文按"铜以板/带形态投入"写 —— 这是模型里已有的一个口子（make/separator-magnet
 *     也是直接拿 mat/copper 绕线圈，中间没有拉丝）。要真核，得先有 mat/copper-plate 那条。
 *   · 车铁筒外圆到 φ588 要求车床能装下 φ600 × 800 的回转件，而**车床的最大回转
 *     直径在模型里没有这一项** —— 本文按"装得下"写，这是一个未进条目的前提。
 *
 * 质量账：投料 200 kg 铸铁 + 100 kg 铜 = 300 kg，产出物是 `unit: '件'`
 * （见 data/material/entry.ts 文件头"同样没有质量"）。模型只对 kg 产出判质量守恒，
 * 对"件"不判，所以不写 `unbalanced_zh` —— 写了反而是给没有的错开豁免。
 */


/**
 * 直接还原炉加热器的第二条来路 —— **两座砖砌蓄热塔（热风炉）**，不碰电阻丝、
 * 不碰硅碳棒、不碰薄板壳、不碰钣金工位。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 它补的是什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 严格算术闭包只到 10 台设备（机器人、车床、磨床、熔炼炉、量块、铣镗床、砖窑、
 * 土窑、锻炉、绕线机）。还原炉卡在 `heater` 上：原来的 `make/reduction-heater`
 * （data/material/entry.ts）是这样的 ——
 *
 *   uses         mat/refractory + mat/sheet-steel
 *   needs        lathe
 *   performedBy  plant/sheet-shop
 *
 * 两处都够不着：`mat/sheet-steel` 的路线要 `plant/rolling-mill` 与
 * `plant/radiator`（data/material/chain.ts 的 `make/sheet-steel`），而
 * `plant/sheet-shop` 五件里焊机与刀片还没解锁（data/machine/tools.ts 的
 * `SHEET_PARTS`）。**钢板与钣金工位都在"第一个铁"那个环里**，所以这一件不是
 * "忘了写"，是"写出来也长不出来"。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 做法：两座蓄热塔，一台热风炉
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 零件定义（data/material/entry.ts 的 `plant/reduction-furnace/heater`）自己写的
 * 就是"耐火格子砖 + 燃烧室 + 换向阀"，并且说明了为什么不用电热元件。这条路线
 * 照它做，只是把"薄板壳"换成"砖壳 + 铸铁冷端"，把"钣金工位"换成"砌筑 + 浇铸"：
 *
 *   两座格子砖塔   内径 0.66 m、格子段高 3.2 m、中央火道 φ0.20 贯通全高
 *   砖壁           内 114 耐火砖 + 外 230 土砖 = 344 mm（与 unblock-reduction-shell.ts
 *                  的炉体同一套砖厚；原因也一样：砖只承温与承重）
 *   燃烧室         就在火道底部 —— 烧嘴插进火道下口，火苗沿火道往上走，
 *                  到塔顶拐弯，往下穿过格子砖。**火道既是燃烧室，也是热风出口**
 *   格子砖         直砖井字架空砌，40% 通流（异型格子砖要砖模与压机，本层没有）
 *   三只阀         每塔底部一只冷端三通阀（工艺气进 / 烟气出，砂封，铸铁）；
 *                  两塔共用一只水冷铸铁热风阀（900 °C，这是全机唯一的热态密封）
 *   烧嘴           铸铁水冷烧嘴，氢 + 氧，火焰用回流蒸汽稀释到 1250 °C
 *   引射器         铸铁蒸汽引射器（无转动件）把烟气回流到烧嘴，回流比 4
 *
 * 一个周期 1 h：A 塔烧 30 min（火道 → 塔顶 → 格子砖 → 塔底烟气出），B 塔送
 * 30 min（工艺氢 20 °C 从塔底进 → 格子砖 → 塔顶 → 火道 → 塔底热风阀 → 炉子），
 * 然后换向。**送风不断、烧嘴不断**，只是烧嘴在另一座塔上。
 * 这就是高炉热风炉（Cowper）的拓扑，反过来念的那一半也一样：热的一头全是砖，
 * 冷的一头才允许有铁。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 为什么不把氢和氧直接通进炉膛烧（最省事、也最错的一种）
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 炉膛里那 7.1 kg/h 的氢就是还原剂。往里通氧，先烧掉的是**要用来还原的那份
 * 氢**，还原气氛当场没了；局部 2000 °C 还会把料烧粘成一块（海绵铁 sticking），
 * 出炉的是铁疙瘩不是粉。所以燃烧必须发生在**另一个腔**里，两者之间只允许有
 * 砖 —— 砖是热的中介，不是气的通道。这条路线全部的密封设计都服从这一条：
 *
 *   ① 燃烧侧与工艺侧的气只在砖的**表面**交替流过，从不混合；
 *   ② 热风阀是唯一的热态**密封件**（烧嘴也热，但它是水冷的喷口，不是密封面），
 *      阀座做在**烟气侧**：漏的方向是"氢往烟道漏"，
 *      漏过去随蒸汽排走（火道里没有氧，烧不起来），而不是"蒸汽往炉膛灌"；
 *   ③ 炉膛微正压 +1～2 kPa（见 unblock-reduction-shell.ts），漏的方向永远朝外。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 为什么不走另外两条路
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 铁管换热器（燃烧气走管外、氢走管内）：铸铁长期用温上限 ~400 °C（这个数在
 * unblock-reduction-shell.ts 里已经算过一次），900 °C 的管壁只能靠水冷压住，
 * 寿命 6–12 个月。**真正的理由不是寿命，是失效模式**：管子一裂，燃烧气直接窜进
 * 氢里，炉内气氛一夜报废，而且裂在管内、看不见。蓄热式的失效是"出口温度掉下来"
 * 与"砖掉皮"，两者都看得见、都能局部换。**可观察、可局部修，胜过效率高。**
 *
 * 外燃烧碳（水煤气发生器旁路）：碳 1 kg 给 32.8 MJ，91 kW 要 10 kg/h 碳 + 27 kg/h
 * 氧，氧气账比烧氢更贵（烧氢 2.7 kg/h 氢只要 22 kg/h 氧，而氧是电解制氢的副产，
 * 不要额外的电）。更要紧的是烟气成分：烧碳的烟气里有 CO₂ 与灰，格子砖半年被灰
 * 堵死，还得停下来清灰；烧氢的烟气只有水蒸气，凝下来 25 kg/h 能回电解槽，砖面
 * 不被灰堵。**所以这条路线烧氢 —— 尽管氢是电换来的。**
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 温控精度：没有仪表，靠火色
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 测温件在数据里是有的（热电偶在 make/sensor-assembly 那一档，光学高温计是
 * `plant/pyrometer`，带镜头、滤光片、标定），但把它们接到一座砖砌加热器上要开
 * 测温孔、要护套管、要冷端补偿、要恒温间标定 —— 那是另一条链，不在这条路线的
 * 工序里。这条路线靠**火道砖壁的火色**：
 *
 *   800 °C   暗樱桃红        ← 低了，还原慢
 *   900 °C   亮橙红          ← 目标
 *   1000 °C  橙黄            ← 顶了，再上去砖和格子先遭殃
 *
 * 人眼在这三档之间能分出 50 K，分不出 10 K。所以**温控带 ±50 K**（工业上热电偶
 * 闭环是 ±10 K，差 5 倍）。这不是小事：920 °C 以上海绵铁开始粘结，一出粘块，
 * 竖炉就下料不畅 —— 所以目标定 870，宁低勿高，低了只是慢，高了是废品。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 三笔账（都能算，算式在路线注释里）
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   热负荷  25 kW —— 7.1 kg/h 氢从 20 加热到 900（一批 1.9 t 风化层、57 kg 氢、8 h）
 *   蓄热    1600 kg 格子砖 × 1.03 kJ/(kg·K) × 250 K = 412 MJ，一个周期只取 45 MJ
 *           → 床温每周期掉 27 K，出口 900 → 873，仍在 850–900 带内
 *   气速    工艺侧 1.2 m/s、烟气侧 3.0 m/s；格子砖阻力 0.8 kPa，引射器给 2–3 kPa
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 降级（六处，按代价从大到小）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① **热效率只有 27%。** 25 kW 进氢、54 kW 从 36 m² 的外壳走掉、12 kW 随 180 °C
 *    烟气走 → 燃料 91 kW（2.7 kg/h 氢）。这不是砌得糙，是表面积的账：工业热风炉
 *    0.075 m²/kW，这里 1.46 m²/kW（**差 19 倍**）—— 砖墙 344 mm 是温度定的，
 *    炉子只有 25 kW 却是负荷定的，两个数一除就是损耗。炉子做大 4 倍，外壳只大
 *    1.6 倍，效率能回到 42%。**小炉子上，这条路线的意义是"能开工"，不是"省"。**
 * ② **折算成电差 5 倍。** 氢来自电解（工业值 50 kWh/kg），2.7 kg/h 氢 = 135 kW 电，
 *    换 25 kW 热 —— 电→热 18%。电阻丝直接烧是 90% 量级。**拿 5 倍的电换一条
 *    不依赖镍铬与硅碳棒的来路。**
 * ③ **砖衬 1–2 年**（工业砖衬 5–8 年）。热面耐火砖含 Fe₂O₃ 17–20%
 *    （`make/refractory-brick` 的降级①），900 °C 氢气里被还原、起皮、粉化；
 *    格子砖的棱角更薄，先烂。每次停炉补一层热面（每塔约 300 kg 砖）。
 * ④ **热风阀一断水就烧穿。** 铸铁在 900 °C 只靠水套活着（热虹吸，不要泵 ——
 *    与排料阀同一个理由）。断水 10 min 阀盘就变形。寿命 1–2 年（热疲劳）。
 * ⑤ **换向靠一双手。** 每 30 min 扳两台冷端三通阀 + 一台热风阀 + 烧嘴，没有
 *    联动、没有限位。顺序错一步 = 把烟气灌进炉子，那一批料的金属化率报废。
 * ⑥ **冷端密封是砂封 + 石墨。** 三通阀用尾矿砂砂封代替机加工的阀座：许可压差
 *    1–2 kPa、漏率约 1% 流量；石墨盘根在 300 °C 以下的蒸汽里能用，超过 400
 *    就氧化 —— 所以阀杆必须留在冷端。
 *
 * 还有一处不是降级、是时态：`mat/mineral-wool` 现在**有**路线
 * （`make/mineral-wool-kiln`，砖窑 1400–1500）。这条路线仍用"114 耐火 + 230 土砖"
 * 的实心砖壁，是因为矿棉是砖窑熔、人工拉出来的粗纤维（15–25 µm），松散充填沉降
 * 比砂还厉害；等矿棉毡稳定了，换成"114 耐火 + 114 矿棉 + 114 土砖"能把外壳热流
 * 从 1.5 kW/m² 压到 0.6 —— 结构不用改，只换中间那一层。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 材料为什么只有这八样
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 这张清单是**算出来的**（逐条在路线注释里），不是挑出来的。按严格算术的口径查
 * 一遍，八样都到得了：
 *
 *   `mat/refractory`   8400  —— make/refractory-brick（风化层 + 石灰，砖窑 1300–1400）
 *   `mars/regolith`   16950  —— 行星地板，不要路线（土砖的料，现场制坯）
 *   `mat/water`        5220  —— make/water
 *   `mat/lime`          620  —— make/lime-gypsum（砖窑 1300–1400）
 *   `mat/iron-ht200/250/300`、`mat/iron` 1200 —— make/iron-htXXX 那一组（阀、箱、托架、环箍）
 *   `mat/steel-45`       95  —— 阀杆、阀盘、烧嘴内筒、拉杆（没有钢就用 HT300 大截面顶上）
 *   `mat/carbon`          6  —— 石墨盘根与垫圈（冷端，300 °C 以下）
 *   `mat/tailings`      260  —— 砂封与垫层的尾矿砂（磁选剩下的就是它）
 *
 * 两样**没有**写进 uses，说清是哪一种"没有"：
 *
 *   氧与氢    它们是**运行消耗**，不是变成零件的东西。烧嘴每运行小时 22 kg 氧 +
 *             2.7 kg 氢，和 `mat/hydrogen` 在 make/metallized-regolith 里的位置
 *             一样 —— 那属于还原炉的运行账，不是这一件的制造账。
 *   循环水    热风阀的水套是热的搬运工，不消耗。这 5.2 t 水全是砌筑、制坯与试压。
 *
 * 三处**不用**：电阻丝（镍铬合金是另一条冶炼链）、硅碳棒（同上）、薄板壳
 * （轧机 + 钣金工位，正是这一条要绕开的东西）。
 */


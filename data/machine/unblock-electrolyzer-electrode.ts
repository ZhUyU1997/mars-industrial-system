/**
 * 电极（`plant/electrolyzer/electrode`）的第二条来路 —— **一块铸铁板，不镀镍**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么需要这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 电极正是电解槽的开步：`plant/electrolyzer ← plant/electrolyzer/electrode`。
 * 而电解槽是全厂氢与氧的唯一来源 —— 电极不出来，整条还原链一起停。
 *
 * 它原来那一条（data/machine/process.ts）是：
 *
 *   make/electrolyzer-electrode   薄钢板 1 + 镀镍液 1
 *                                 → 下料冲孔 → 碱洗酸洗 → 电镀镍（50–60 °C）
 *                                 plant/sheet-shop · plant/wet-bench · plant/plating-bath
 *
 * 四样东西今天都要现造：板、钣金工位、湿台、镀槽。头一样已经有别的走法，
 * 第二样只是缺零件：
 *
 *   板        make/sheet-steel-forged（bootstrap.ts）已经把板从轧机上摘下来了 ——
 *             锻板要的是 plant/forge（空气锤），那是另一条独立链
 *   钣金工位  它的五个零件还在别的链上（frame / ram / blade / drive / welder）
 *
 * 但这两处通了也不够 —— **最里面那一环是镍**：
 *
 *   镀液 1000 kg = 硫酸镍 250 + 镍 20 + 盐酸 30 + 水 700
 *   硫酸镍 1000 kg = 镍 250 + 硫酸（data/machine/plating.ts）
 *   镍 ← 电解精炼 make/nickel ← 镍铁（矿热炉 1600–1700）← 红土矿浮选
 *
 * 所以这条路线要回答的不是"板从哪来"，是"**没有镍，电极做不做得出来**"。
 *
 * 做法是把工艺整个换掉：铁换一种形态来（HT250 灰铸铁，从**浇注**来而不是从
 * **轧制**来），表面换一种做法来（不镀 —— 就把铁自己钝化出来的那一层氧化膜
 * 当工作面），导电耳随铸而不是焊。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么这里一点镍都没有
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 镍本来是最该写的那一样：碱液里铁会溶，镍耐蚀、又是析氢的好催化面。
 * 而用量小得可笑 —— 一片极板的镀层只要 **约 30 g** 镍：
 *
 *   极板两面 0.075 m² × 2 = 0.15 m²，镀 25 µm（原路线写 20–40 µm）
 *   0.15 × 25×10⁻⁶ = 3.75×10⁻⁶ m³ = 3.75 cm³ × 8.9 ≈ 33 g
 *
 * 换成缠绕镍丝也一样（φ0.5 绕 20 m ≈ 35 g）。**所以这不是用量问题，是链条问题**：
 * 今天连这 30 g 也拿不出来。
 *
 *   make/nickel（电解精炼镍）     ← plant/electrorefining
 *   plant/electrorefining 的零件  ← 衬 PTFE 的钢槽（要钣金工位）· 铜母线 · 铣镗床
 *   再往上游                      ← make/ferronickel ← plant/submerged-arc-furnace（1600–1700）
 *                                   而矿热炉要 plant/radiator，散热器要铜管与翅片
 *
 * 这三台设备各自又卡在别的零件上 —— 所以镍不是"再等一条路线"，是好几个设备层。
 * 这条路线**只用铸铁**，把镍的代价写在降级①。
 * 等 make/nickel 通了，这一条的最小改动是**加一道镀镍**（plant/plating-bath 的路线
 * 写在 data/machine/plating.ts，缺的是它自己的槽与镍），不是换材料 ——
 * 那时 30 g 镍就把槽压拉回 1.95 V。
 *
 * 顺带记一笔模型账：原路线按 1 kg 镀液/片计，折成镍 ≈ 83 g（1000 kg 镀液 =
 * 250 硫酸镍 + 20 镍，1000 kg 硫酸镍 = 250 镍 → 0.25 × 0.25 + 0.02 = 0.0825），
 * 是镀层本体的两倍半，差额是镀液的带出与补加 —— 见 data/machine/plating.ts。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 判据：这条路线上的每一件料，今天都要算得出来
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   HT250     make/iron-ht250：铁 970 + 碳 30，熔化炉 1350–1450
 *   HT200     make/iron-ht200：铁 966 + 碳 34，同上（备选，见 uses 第一条）
 *   石灰      make/lime-gypsum：烧石膏 CaSO₄ → CaO + SO₂，砖窑 1300–1400 分解
 *             （分解率只有 60–70%，所以那条路线同时出硫酸原料 —— 见 bootstrap.ts）
 *   铜        make/copper-cement：胆铜法，硫酸浸出 + 铁置换，机器人做
 *
 * 四样都在闭包里。三样**故意不用**的：
 *
 *   镍 mat/nickel          见上一节 —— 不是量不够，是链没通
 *   耐火砖 mat/refractory  今天反而**有**土法版（make/refractory-brick，砖窑 1300–1400，
 *                          风化层 + 石灰 + 水）。这条路线用不上它，因为它不需要炉衬：
 *                          坩埚与炉衬记在熔化炉的 composedOf 里，是设备零件，不按件消耗
 *   氧化铝 mat/alumina     要酸厂加压浸出 + 工业窑（plant/kiln 1200–1750）—— 现在没有
 *
 * ⚠️ 时态：镍与氧化铝"现在没有"是现在时；耐火砖是"有、但这里
 *    用不上" —— 两件事写法不同，别混。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 几何：0.25 × 0.30 m 的板，是车床定的
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 极板尺寸的约束不是电解槽，是**车床**。种子里那台是 400 mm 级
 * （data/floor/seed.ts，data/machine/lathe.ts 文件头）：
 *
 *   0.25 × 0.30 的对角线 √(0.25² + 0.30²) = 0.390 m = 390 mm
 *   花盘上四角到轴心 195 mm，离 200 mm 的回转半径只剩 **5 mm**
 *
 * 所以四角必须倒圆到 R20，否则一转就扫到导轨。这条天花板决定了两件事：
 * 板只能做到 0.28 m 见方这一档，而一槽的极板面积得靠**多片并联**凑 —— 见降级④。
 *
 * 厚度：铸态 8 mm → 车到 7 mm → 磨到 6 mm（每面各留 0.5 给车与磨）。
 * 铸铁不能做得像钢板那样薄：砂型铸造薄壁件冷却快，边角出白口（渗碳体），
 * 车刀在上面打滑、砂轮也磨不动。8 mm 已经是"薄壁件"了 —— 砂型要干、要预热。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 质量账（一件）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   铸件毛坯   板 0.075 m² × 8 mm = 600 cm³ × 7.2          4.32 kg
 *              导电耳：60 × 80 × 10 凸台 + φ40 × 25 轴颈    0.58 kg
 *              合计                                          4.90 kg
 *   浇冒口     板类件浇注系统按铸件 30%                     1.5 kg（回炉）
 *   炉料       4.90 + 1.5 = 6.4，加烧损取                   6.5 kg HT250
 *
 *   成品       铁：板 450 cm³ × 7.2 = 3.24 + 耳 0.55        3.8 kg
 *              铜：两片 40 × 50 × 12 压接片 0.43
 *                  + 40 × 4 × 100 软铜带 0.14 + 垫圈 0.03    0.6 kg
 *
 *   进 6.5 + 0.2（石灰）+ 0.6（铜）= 7.3 kg → 出 1 件（约 4.4 kg）
 *   差 2.9 = 浇冒口 1.5 + 干铁屑 1.0 + 熔渣 0.3 + 烧损 0.1
 *
 * 铁屑是板从 8 mm 车磨到 6 mm 的那 150 cm³ × 7.2 = 1.08，取 1.0；
 * 熔渣 0.3 = 石灰 0.2 + 型砂与氧化皮 0.1。浇冒口与铁屑都回炉，不进这件。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级（比较对象：原路线那块"薄钢板 + 25 µm 镍"）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **没有镍镀层：析氢过电位高 0.15–0.25 V，电耗 +10%。**
 *
 *    阴极（析氢）：镍在 30% KOH、80 °C、0.2 A/cm² 下 η ≈ 0.15–0.25 V
 *    （活化镍；Raney 镍更低）；铁表面（含石墨片与铁氧化物）≈ 0.35–0.45 V。
 *    差 **0.15–0.25 V**，全落在槽压上。
 *
 *    阳极（析氧）**反而不是过电位的事**：铁氧化物（FeOOH / Fe₂O₃）本身就是
 *    析氧催化剂 —— 铁甚至是 NiFe 催化剂的活性组分，析氧过电位不比镍高。
 *    代价换了个地方，在降级②：它一边催化一边溶。
 *
 *    合起来：槽压 1.95 V → 2.10–2.20 V。电耗可以算：
 *
 *      1 Nm³ H₂ = 1000 / 22.414 mol × 2F = 44.6 × 2 × 96485 = 8.6×10⁶ C = 2391 Ah
 *      2391 Ah × 2.0 V = 4.78 kWh/Nm³
 *      2391 Ah × 2.2 V = 5.26 kWh/Nm³        →  **+0.48 kWh/Nm³ ≈ +10%**
 *
 *    对全厂的意义不是"多花点电"：氢是还原剂，每 kg 氢要 8.9 kg 水去电解
 *    （data/material/chain.ts），电解槽的整流容量与冷却盘管
 *    （plant/electrolyzer/cell-cooling）都要跟着多留一成。
 *
 * ② **阳极不是过电位的问题，是溶解 —— 阳极 2–3 年一换，阴极 5 年以上。**
 *
 *    阳极电位约 +0.7 V vs SHE（对 RHE 是 1.6–1.7 V），铁在这一段进入过钝化区，
 *    生成可溶的高铁酸盐：Fe + 8OH⁻ → FeO₄²⁻ + 4H₂O + 6e⁻。**六电子，一溶就没了。**
 *
 *    算法（量级）：一片极板两面 0.15 m² × 0.2 A/cm² = 300 A。
 *
 *      0.1% 的电流漏给溶铁：0.3 A × 8000 h = 2400 Ah = 8.64×10⁶ C
 *      → 8.64×10⁶ / 96485 = 89.5 mol e⁻ → /6 = 14.9 mol Fe = **0.84 kg/a**
 *      → 摊到两面 0.15 m² 上，板厚一年掉 0.8 mm（均匀算是七八年才穿）
 *
 *      1% 就是 8.4 kg/a —— 一块 3.24 kg 的板不到 5 个月就没了。
 *
 *    所以这条路线的寿命**完全取决于"铁的自钝化能把法拉第溶铁压到多低"**，
 *    而本层没有这个数（缺口①）。取 0.1% 量级：均匀溶解七八年，但阳极是
 *    沿石墨片的坑蚀（石墨在阳极被氧化成碳酸盐，留下空腔，坑里的铁再溶），
 *    坑深常是均匀值的 3–5 倍 —— **阳极板按 2–3 年一换**。
 *
 *    阴极侧相反：强阴极极化（−1.2 ~ −1.3 V vs SHE，析氢电位）下，铁是被
 *    自己的氢保护着的（这也是电解槽阴极能用铁的老理由），腐蚀 <0.01 mm/a ——
 *    **阴极板 5 年以上**。
 *
 *    于是维护上多出一个动作，镀镍路线没有：**阳极板降级当阴极用**。换下来的
 *    阳极板减薄了但还够，转去阴极位；阴极位要等它的板到期才腾得出来，所以
 *    降级不是"随时"，是按槽的检修节奏走。整槽的更换周期因此被阳极拖到
 *    2–3 年一轮（镀镍那条约 8–10 年，量级估计），一轮只换阳极那一半。
 *
 * ③ **铸铁脆、石墨片多 —— 6 mm 的板是 1.5 mm 钢板的 3.7 倍重。**
 *
 *    钢板：0.075 m² × 1.5 mm × 7.85 = 0.88 kg；铸铁板 3.24 kg → 3.7 倍。
 *    抗拉 HT250 是 250 MPa 级，但**没有塑性**：钢板撞一下鼓个包，铸铁撞一下
 *    裂到边上。所以极板不能"整面压紧"，只能靠导电耳一处夹持、其余自由悬挂
 *    （顺带也消掉装配应力）。
 *
 *    石墨片还是阳极侧的腐蚀通道：灰铸铁的碳以片状石墨存在，石墨在阳极被氧化
 *    （C + 6OH⁻ → CO₃²⁻ + 3H₂O + 4e⁻），表面一层层掉"砂"。坑蚀的起点就是它，
 *    见降级②。HT250 的石墨片比 HT200 细，这一处能好一点 —— 这是选牌号的唯一理由。
 *
 * ④ **极板做不大 —— 一槽几十片并联，接头与极距都是代价。**
 *
 *    400 mm 的车床把板卡在 0.28 m 见方以下；原路线的薄钢板可以整片 0.6 × 0.7 m。
 *    同一槽面积要 5–6 倍的片数（0.075 m² 对 0.42 m²）。片数一多：
 *
 *      每片一套导电耳与铜压接（铜量与接触点 ×5–6）
 *      极板间距的累积误差（几片偏一点，电流分布就不均）
 *      装配与检修工时（一片一拆，不能整片吊出）
 *
 *    也有好处：小板的热应力小，坏了只换一片；整块 0.42 m² 的铸铁大板更脆，
 *    一裂就是整片报废。
 *
 *    ⚠️ 模型粗粒度：`plant/electrolyzer` 的 composedOf 里极板只计 1 件
 *    （data/machine/process.ts），所以"一槽几十片"在这份数据里体现不出来。
 *    那是模型的 `qty`，不是物理 —— 这里写清楚，免得以后有人按 1 片算产氢量。
 *
 * ⑤ **铜-铸铁的压接面是电偶，烂的是铁那一侧。**
 *
 *    Fe/Cu 在碱雾里构成电偶，铁是阳极。压接面一旦渗进碱液，先烂的是铸铁耳的面，
 *    铜片反而越用越亮。所以耳面留 2 mm 加工余量，检修时车/磨掉一层再压紧；
 *    铜片做成**包住耳面两侧**的形状，用几何挡碱雾 —— 模型里没有密封材料条目。
 *
 *    铜的量价：0.6 kg × 34.7 t 风化层/kg ≈ **21 t 土**（风化层含铜 30 ppm，
 *    富集 8333 : 1，见 make/copper-concentrate）。一片极板的铜比它的铁贵两个
 *    数量级 —— 这是这条路线最贵的一笔，也是"能不用铜就别用"的地方。
 *
 * ⑥ **去应力退火用土窑 —— 退了，但退到什么程度不知道。**
 *
 *    铸铁件不退了应力，车完磨完自己会慢慢弯（板越薄越明显）。560–620 是
 *    铸铁去应力的常规区间，土窑的 holds 400–1100 落得进去。
 *
 *    但土窑没有控温：温度靠观色（暗红 ≈ 600），保温时间靠"烧几筐柴"，
 *    冷却是随窑冷。结果是"退过，残余应力还剩多少说不清" —— 板可能磨完放几天
 *    再翘。模型里没有残余应力这个刻度，写不出"退了 85%"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 已知缺口
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① 法拉第溶铁的效率没有数据。降级② 那个"2–3 年"是从 0.1% 反推的：
 *      0.01% 就是二十年以上，1% 就是五个月 —— 这条路线成不成立就在这一个数上，
 *      而它今天没有出处。要测也简单（称重 + 分光测电解液里的铁），但那是实验，
 *      不是本层能写出来的东西。
 *
 *   ② 腐蚀率（mm/a）同样没有出处。上面"阴极 <0.01 mm/a"是"强阴极极化下铁
 *      基本不溶"的量级判断，不是实测；"阳极 0.1–0.5 mm/a"那类文献值本层没核过，
 *      所以只在降级②里用法拉第算式代替，不写 mm/a。
 *
 *   ③ 型砂、泥芯砂、冷铁、三角试片都没有条目。砂型铸造这四样是工装 ——
 *      模型没有"工装"这一类（夹具、模具同样处境）。按件被吃掉的只有金属与石灰，
 *      所以这条路线的 `uses` 里看不见砂。
 *
 *   ④ 寿命写不进字段。`Component.wear` 是按运行小时算损耗，而电解槽的
 *      composedOf 只写 qty（data/machine/process.ts），没有极板这一处装配点；
 *      2–3 年 / 5 年只能写在注释里。
 *
 *   ⑤ 这条路线只通**电极一个零件**。电极通了不等于电解槽通了：隔膜要 PTFE、
 *      整流要功率器件、槽体要钣金（槽体另见 data/machine/unblock-electrolyzer-ceramic.ts
 *      的陶质版）。电极是第一步，不是最后一步。
 */


/**
 * 数字电压表的替代路线：**补偿法电位差计 + 千分螺丝字轮**（4 位显示、2.5 位准确）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一、原路线卡在哪：整条半导体链
 * ═══════════════════════════════════════════════════════════════════════
 *
 * `make/dvm`（data/material/clock.ts 第 134 行）是双斜积分式的：
 *
 *   运放 2 + 计数器芯片 1 + 石英谐振器 1 + 齐纳基准 1 + 镍铬丝 + 机械计数器 + 表壳
 *
 * 双斜积分的妙处原注释写得很准：**它不需要精密电阻，只需要稳定的时间与基准**。
 * 而在这个星球上，时间有石英、基准有齐纳 —— 可惜这两样**都长在半导体链上**：
 *
 *   运放/比较器/计数器   ✗ 平面管、芯片、光刻，一样都不在这 29 台里
 *   齐纳基准             ✗ 它是"一只反偏的平面管发射结"—— 没有平面管
 *   石英谐振器           ✗ 要单晶石英（无瑕的 X 切片），`std/quartz-resonator-general`
 *   镍铬丝               ✗ 镍链是圆的
 *
 * 所以这条路不是"缺一件料"，是**整条链的形状**：数字表是这条链的最末端，
 * 它前面排着芯片、管子、光刻。要做它，得先把整条电子链建起来。
 *
 * 而它的用途等不起：
 *
 *   计量间的读数      "从指针看第几格"变成"一个数"（metrology.ts 第 174 行）
 *   过程控制器的 ADC  数字表当 ADC（process-control.ts 第 64 行）—— 那条路已改机械式，
 *                    绕开了它，但计量间还等着
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 二、五种"不要半导体"的做法
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **电位差计（补偿法）—— 选这条**。用一只已知电压的**可调分压**去平衡被测电压，
 *    检流计指零。它的三件：分压器、检流计、基准。前两件本层都能做，
 *    第三件（标准电池）没有 —— 这是这条路唯一真正的洞，第三节解决。
 *
 * ② **机械逐次逼近（凸轮 + 权电阻）**。把二分法的电阻链（1/2、1/4、1/8…）用凸轮
 *    切换，人（或触点）逐位比较 —— 这就是一台"机械 SAR ADC"。**否决的理由是精度**：
 *    它的准确度由**电阻比**定，而本层没有可调电阻（没有锰铜、没有电阻箱、没有电桥
 *    可以修整阻值）。而补偿法的准确度由**长度比**定 —— **长度是本层唯一被绝对标定
 *    过的量**（K 级量块、钠 D 线）。把电压变成长度，是把一个测不准的量换成一个
 *    测得准的量，这是整条路线的核心。
 *
 * ③ **伺服式（光点 + 差分热电偶）**。那是 1900 年代的自平衡记录仪：光点落在双热电偶
 *    上，温差生电动势，驱动可逆电机。**否决的理由是"没有那个电机"**：`std/motor` 是
 *    另一条链的零件（本文件的料表里没有它），而且热电偶的 µV 要推动一台电机，
 *    中间必须有放大 —— 又回到半导体。所以这台表**不自动**。
 *
 * ④ **静电计**。它不要磁、不要放大，但它读的是电荷：输入电容 10 pF、绝缘子 10¹⁵ Ω。
 *    作为**指零**器它可以用（指零时无电流），但它的零漂与摩擦电噪声在 µV 量级，
 *    而这台表要读的是 1 µV。**否决：噪声与信号同量级。**
 *
 * ⑤ **干脆做指针表**。那就是 `std/millivoltmeter-general`（已单独一条路线），
 *    它的读数是"指针在第几格"，估读到 1/5 格 —— **它给不出一个"数"**。
 *    而 dvm 这个条目存在的理由就是"一个数"：能记、能抄、能复核。
 *
 * 所以：**补偿法 + 长度比 + 机械字轮**。它是"手动"的（人追光点），
 * 但读出来的确实是四位数字。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三、把电压变成长度：滑线、铁皮、千分螺丝
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 补偿法的电路只有三样：基准、滑线、检流计。基准给出一个电流，滑线上每毫米落多少
 * 毫伏是定的；把被测电压跨接在其中一段上，移动触点直到检流计指零 ——
 * **触点的位置就是电压**。于是"读电压"变成"读长度"。
 *
 * 滑线用什么：本层只有 φ1.0 的铜线与 0.01 mm 的铁皮（锻出来的）。
 * 铜太软（一压一个坑）、太导电（200 mm 只有 4 mΩ，被引线淹没）。所以：
 *
 *   铁皮   0.01 × 1 mm 的锻铁带、ρ = 1×10⁻⁷ Ω·m → **10 Ω/m**、Ra 0.4
 *   滑线   2.0 m 张紧在两根刀口上（1 N），有效段 190 mm = 1.9 Ω
 *   回路   热电堆 0.8 Ω + 铁皮 20 Ω = 20.8 Ω
 *   基准    16 对热电偶、15.8 mV → 回路电流 0.76 mA
 *   满度    0.76 mA × 1.9 Ω = **1.44 mV ≈ 1.5 mV**（与上一份文件的铜-铁偶对齐）
 *
 * 读数的机构（这是"数字"的全部来路）：
 *
 *   千分螺丝  M10×0.5，鼓轮 200 格 → 0.0025 mm/格
 *   字轮      4 位（0–9 ×4），经 15:4 的变速齿轮咬在丝杠上
 *   换算      1.44 mV / 190 mm = 7.6 µV/mm → 鼓轮 0.01 mm = **0.076 µV**
 *   显示      0–1500，**单位 µV，四位数字**
 *
 * 也就是说：分辨率是 0.076 µV，而噪声（第五节）在 0.5 µV 上下 ——
 * **字轮画到四位，能信的是三位**。这一条写在第六节。
 *
 * 为什么用长度而不用电阻比：铁皮的电阻随温度走（铁 α = 0.006/K），它的长度不走。
 * 而**长度是同一根铁皮上量的**：分压比 = 长度比，铁皮自己在分子分母里同进同出，
 * **温度系数约掉**（比值法）。这就是为什么计量间的 ±1 K 对这台表不构成误差，
 * 只要它内部没有温度梯度（0.1 K 的梯度 = 0.04%）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四、基准：没有韦斯顿电池，只有一锅沸水
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 补偿法要一只"已知电压"。标准电池（韦斯顿，1.0183 V）要镉汞合金 —— 两样都没有；
 * 齐纳管要半导体。本层唯一被绝对标定过的东西是**温度**（冰点/沸点），
 * 所以基准只能从温度借：
 *
 *   16 对铜-铁热电偶串联，冷端在冰点瓶（0.01 °C）、热端在沸水浴（99.7 °C）
 *   每对 0.986 mV → **15.8 mV**（±0.2%）
 *   腿要短粗：每对 0.05 Ω（16 对共 0.8 Ω），否则它的电阻会成为回路的 10% 以上
 *
 * 这一换，代价写在两处：
 *
 *   **绝对准确度**：热电偶的塞贝克系数只有书本值 ±0.2%，而韦斯顿电池是 ±0.002%
 *   —— **差 100 倍**。这就是 4 位里只有 2.5 位的根子（第六节）
 *   **时间**：沸水浴必须**在测量期间一直保持沸腾**（掉 0.5 K，基准就掉 2%）。
 *   所以每次测量前要烧水、等它稳定 20 min —— 电子表是"开机 30 min 自动校零"
 *
 * 沸水浴的稳定度是本层能给的最好：沸腾的水在分钟级上稳到 ±0.05 K（±0.2%）。
 * 而这个温度**是不是 99.7**，由活塞压力计给的压力定（上一份文件那套：φ50 活塞上
 * 压 20 L 水 = 100.3 kPa）。压不准不要紧：它只影响"这个是 99.7 还是 99.6"，
 * 不影响"它在测量期间没变"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五、输入阻抗与共模：补偿法的两个"白拿的好处"和一个"白给的坏处"
 * ═══════════════════════════════════════════════════════════════════════
 *
 * **输入阻抗：平衡时是无穷大。** 这是补偿法的定义 —— 指零时，被测源与滑线之间没有
 * 电流。所以**被测源的内阻不影响读数**：一支 1 kΩ 的源与一支 1 Ω 的源，读数一样。
 * 电子 DVM 的 10 MΩ 会对 1 MΩ 的源造成 10% 的负载误差；这台表在这件事上是 0。
 * 漏电由陶瓷绝缘柱与烘过的石英砂干燥剂保证：**≥10¹² Ω**（1.5 mV 下落 1.5 fA）。
 *
 * 但"平衡时"这三个字是全部的限定：
 *
 *   不平衡时   被测源要能推 0.76 mA 进 20.8 Ω 的回路 —— 对小源（热电偶 1 Ω）没事，
 *              对高阻源就是一记重载，甚至可能把它拉垮
 *   没有隔离   回路与地之间没有隔离变压器、没有差分放大。**共模抑制 0 dB**：
 *              1 V 的共模电压经 1 kΩ 的源阻抗，就是 1 mA 灌进 20.8 Ω 的回路
 *              → 20.8 mV 的假电压（满度的 **1400%**）
 *   必须浮空   所以被测源必须完全浮空。炉子上那支热电偶一旦护套接地，
 *              这台表读到的就是地环路电流，不是热电势
 *
 * 电子表的共模抑制是 120 dB（10⁻⁶），这台表是 0 dB（1）—— 差一百万倍。
 * 它没有"抑制"，它只有"你别把共模接进来"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 六、四位：字轮是刻的，准确度是 2.5 位
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 把"数字"拆成两件事，这台表的答案不一样：
 *
 *   **分辨（数字到几位）**  ✓ 四位。字轮是 4 个 0–9，由千分螺丝经 15:4 的齿轮带动；
 *                          0.01 mm 的鼓轮格 = 0.076 µV。四位是**刻出来的**，不是算的
 *   **准确度（数字有多准）** ✗ 2.5 位。基准 ±0.2%、长度比 ±0.05%、热电势残差
 *                          0.5 µV（0.03%）→ 合成 **±0.2%**，也就是 1/500 —— 2.7 位
 *
 * 工业 4½ 位表的"4½"说的是**准确度**（1/20000 = 0.005%）。这台表的四位说的是
 * **分辨**，准确度只有 2.5 位。**"4 位"这个词在两处意思不同，不能混用。**
 *
 * 末位（1 µV）为什么不能信：
 *
 *   碳触头在铁皮上滑动，接触点的热电动势随摩擦跳 1–5 µV（碳-铁是一对偶）
 *   换向法（正反向各测一次取平均）能把稳定的热电势抵消，抵不掉**跳动**的
 *   所以末位在 ±1 字上抖，**半数读数里它是对的**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 七、kg 账
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   进 5.65 kg → 1 台约 2.42 kg：
 *     铸铁 1.70（底座 φ260×20 + 框 + 字轮罩，浇注 2.2）
 *     45 钢 0.27（千分螺丝、鼓轮、齿轮 3 只、字轮 4 只、磁针 2 支、开关刀 4、
 *       钢镜 φ8、弹簧）
 *     铁皮 0.02（0.01×1×2000 的锻铁带：整条滑线 + 热电堆的铁腿）
 *     铜 0.11（接线柱 4、开关座、滑线端夹、热电堆的铜腿）
 *     铜线 0.25（检流计线圈 600 匝 28 m）+ 剥下的铜 0.03
 *     玻璃纱 0.01（悬丝 2 根 + 指针）+ 碳 0.01（指示旗、触头）
 *     石英砂 0.02（干燥剂，留在壳里）+ 矿棉 0.005（防尘毡）
 *   差 3.23 kg = 水 1.50（清洗 + 沸水浴，全走掉）+ 耐火料 0.40（陶瓷绝缘柱、
 *     开关座、轴套，全耗）+ 铁皮锻造氧化皮与剪边 0.18 + 铸铁浇冒口 0.50
 *     + 45 钢切屑 0.27 + 石英砂磨料 0.18 + 铜切屑 0.04 + 碳耗 0.05
 *     + 铜线头尾 0.05 + 玻包线剥坏 0.01 + 矿棉边角 0.045（算式在 unbalanced_zh）
 *
 * 一处与前两份一样：**没算空气**。这里没有氧化增重 —— 铁皮只是锻与磨，
 * 而磨掉的氧化皮已经在"铁皮锻造"那一栏里。热电偶的氧化？那在热电堆那一步，
 * 量太小（0.3 g），并进铁皮那一栏了。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 八、降级（六处，带量级）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **"数字"是真的，"自动"是假的：一次读数 40–60 s 对电子表的 0.3 s（150 倍）。**
 *    字轮给的是一个数（能记、能抄、能复核），但平衡靠人眼追光点、正反向各一次。
 *    不能进控制回路、不能连续记录 —— 而 dvm 这个条目原本的另一半用途
 *    正是"当 ADC 喂给过程控制器"（那条路已经改成机械式控制器，绕开了它）。
 *
 * ② **基准 0.2% 对韦斯顿电池的 0.002%（100 倍）。** 4 位显示、2.5 位准确：
 *    第 3 位就已经是"参考值"，第 4 位是"分辨"不是"准确"。而且每次测量期间
 *    沸水浴必须一直在沸腾（掉 0.5 K = 2%），所以每次测量前要烧水等 20 min。
 *
 * ③ **共模抑制 0 dB 对 120 dB（差一百万倍）。** 没有隔离、没有差分放大：
 *    1 V 共模 / 1 kΩ 源阻抗 → 20.8 mV 假电压（满度的 1400%）。被测源必须浮空，
 *    炉子上那支热电偶一旦护套接地，这台表就只剩地环路的读数。
 *
 * ④ **热电势**：输入回路里铜-铁端子（7–10 µV/K）、碳-铁触头（10–20 µV/K）。
 *    手温 0.5 K 的梯度就是 4–10 µV（满度的 0.3–0.7%）。换向法把**稳定**的部分
 *    抵消到 0.5 µV，但要求正反向两次之间温度稳在 0.05 K 内 —— 这正是它要
 *    40–60 s 的原因（快了温度还在动，慢了温度又动了）。
 *
 * ⑤ **滑线是铁皮，不是锰铜**：铁的 α = 0.006/K（锰铜 2×10⁻⁵，差 300 倍）。
 *    比值法把"整体同温"的那部分约掉了，但**有效段的两端与中段之间 0.1 K 的梯度**
 *    就是 0.06% 的误差 —— 所以整根铁皮要装在一条 6 mm 的铜带上（等温带），
 *    而这一条没有泵：靠铜带的热容把梯度压到 0.1 K。
 *
 * ⑥ **量程只到 16 mV**：这是一台**数字毫伏表**，不是通用数字电压表。要高量程就得有
 *    高阻分压器（锰铜或碳膜），而铁皮只有 10 Ω/m —— 做 1 MΩ 要 100 km。
 *    所以"0–10 V 的流程信号"它根本测不了。而量程越高、输入阻抗越低（不平衡时
 *    就是 20.8 Ω），这是补偿法本身的形状。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 九、已知缺口（都不在这条路线的范围里）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  · **电不进模型**：磁化冲 20 A、检流计的灯、沸水浴的炉子 —— 三处都靠电，
 *    而全表的路由都不写电
 *  · **沸水浴是工装**：它与上一份文件那只活塞压力计是同一套东西，不进 uses
 *  · **校验偶与冰点瓶也是工装**：冰点瓶（密封的冰-水，611 Pa）随表走一只
 *  · **"一个数"传不出去**：字轮是给眼睛的，没有接口。要把它送进控制器，
 *    得有人抄 —— 而抄错一位，整条链就错 10 倍。这一条是 dvm 与"数字仪器"
 *    之间最后那一步，本层过不去
 *  · **没有恒温室**：标定要在温度稳定的地方做，而 19–21 °C 的房间是
 *    `plant/metrology-room` 自己 —— 它正是这台表要解开的那一件（循环）。
 *    路线的解法是：**比值法不需要恒温**，只需要"内部无梯度"，所以标定可以在
 *    任何一间不通风的屋里做，只要记录温度（±1 K 不影响，0.1 K 的梯度才影响）
 *  · **字轮的进位机构是"间歇"的**：4 只字轮的十进位靠一只四齿星轮，接触处
 *    会磨；一年后第 2 位会跳字（工业计数器用硬质合金）。这条写进维护账
 *  · **钢镜的面形没法量**：φ8 的钢镜磨到 Ra 0.01，但它的面形（λ/4？）没有干涉仪，
 *    只能用刀口仪看直不直 —— 光点会拉成一条线，读数靠线的中心
 */


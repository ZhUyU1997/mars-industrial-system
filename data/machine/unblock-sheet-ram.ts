/**
 * 折弯滑块与上模 `plant/sheet-shop/ram` 的**第二条来路** —— 铸铁本体 + 45 钢可换刃条。
 *
 * 这一份是**解锁**用的：把 ram 从"等两台机器"改成"只等两种料"，让钣金工位接着往上长。
 * 它不是要替掉原路线 —— 多条路线产出同一个 Item 是 OR，两条并存。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 这个零件原本是什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * data/machine/tools.ts 的 `SHEET_PARTS` 写得很清楚：**折弯滑块与上模**，
 * "45 钢锻件，铣出 V 形槽，淬硬"，"滑块与导轨的间隙靠配刮，不靠装配公差 ——
 * 与溜板同理"。原路线 `make/sheet-ram` 总共三行：
 *
 *   performedBy  plant/milling-machine          铣 V 槽与导轨面，出形状
 *   uses         mat/steel-45  q(1)             45 钢锻件（锻炉在 needs 里）
 *   needs        plant/grinder, plant/forge     磨床出精度，锻炉出毛坯
 *
 * 所以它是一个"要铣、要锻、要淬"的钢件 —— 三件事在本层各差一台设备。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么需要这一条
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 严格算术口径（设备也算进闭包）下，从种子与火星料出发只长出七台设备：
 *
 *   plant/robot · lathe · plant/grinder · plant/melting-furnace
 *   plant/gauge-block · plant/earth-kiln · plant/brick-kiln
 *   （这一条 data/machine/unblock-crusher.ts 的文件头数过一遍）
 *
 * 原路线要的铣镗床与锻炉都不在那七台里，而它们各自还压着一整条零件链
 * （铣镗床六件见 data/machine/tools.ts，锻炉五件见 data/machine/forge.ts）。
 * 把那一整条链排在滑块前面，等于让钣金工位等两台机器 —— 而滑块是折弯动作的
 * **那一半**：没有它，机身与传动丝杠造得再准也弯不出一块板。
 *
 * 判据一句话：**只用那七台里的五台，只用本层会做的两种料。**
 * 五台是机器人、熔炼炉、土窑、车床、磨床；量块在 `needs` 里当判据，不干活。
 * 两种料是 HT300 与 45 钢 —— 两样的路线现在都只吃铁与碳，执行者都是熔炼炉
 * （data/material/chain.ts 的 `make/iron-ht300`：铁 968 + 碳 32；
 * `make/steel-45`：铁 995.5 + 碳 4.5）。
 *
 * 于是这一条卡的**不是材料，是工序**：一件十二道，每一道都有设备能干。
 *
 * ⚠️ 时态：`make/steel-45` 的 `needs` 现在是空的，不挂
 * plant/radiator。别把 unblock-mill-spindle.ts 文件头那句"45 钢要散热器"当现在时
 * 抄过来 —— 那句写的时候是那样，现在不是了。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 做法：一件铸铁滑块，两根磨出来的斜条，一副可换的刃口
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   本体    HT300 浇成 145 kg 的滑块，导轨面与镶条槽留 1.5 mm 加工余量
 *   刃口    45 钢 30 kg 车成三根直条，淬硬后磨出 45° 斜面，压进本体的直槽
 *   精度    车床带铣头出形状，磨床出平面度，刮研出贴合 —— 三样接力，见下两节
 *
 * 全部改动集中在**一句话**：V 形槽不再是一个要铣的成形面，而是两根磨出斜面的
 * 直条拼出来的。磨床能磨平面，磨不了 V 槽；V 槽拆成两个 45° 平面之后，磨床就
 * 能接下这一件活。同一条道理管刃口：磨钝了不是修槽，是换条。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 导向精度从哪来 —— 三处，没有一处是"装出来的"
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① 贴合：滑块的两条导轨面与机身导轨面**对研**。涂色、见亮点刮去，一遍一遍，
 *    刮到 25×25 mm 里 12–16 个点。接触刚度就来自这些点，不来自螺栓拧多紧。
 * ② 间隙：楔铁（斜镶条）压紧，间隙可以收到零；磨损之后重新收紧楔铁即可，
 *    不换件、不加垫。灰铸铁导轨的传统做法，车床溜板是同一套。
 * ③ 平行度：滑块两条导轨面的平行度**不需要外部基准** —— 它们在磨床上同一次
 *    装夹里磨出来，一个基准、一刀接一刀，平行度是"同一次装夹"的副产品。
 *
 * 三处合起来，导向精度的链子是：
 *
 *   机身导轨面（磨出来的）→ 对研的接触斑点 → 楔铁把间隙收到零 → 滑块只能沿它走
 *
 * 滑块自己**不带"有多直"的证明**：它的直线度就是机身导轨的直线度，它只保证密合。
 * 这句话是这条路成立的全部理由，也是它的全部弱点 —— 代价落在互换性上（降级②）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 没有铣床，平面度靠什么保证 —— 四级递减，最后一级是手
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   铸    砂型里铸出来，导轨面朝下           出余量，不出平面（1.5 mm）
 *   粗    车床花盘上装铣头（第 5 段）         出形状：一个平面靠一条直线进给
 *   半精  导轨磨磨面（第 7 段）               平面度的真正出处，基准是磨床台面
 *   精    与机身导轨对研 + 刮（第 8 段）      出接触斑点，出"共形"
 *
 * "车床带铣头"这一招不是这一条发明的：锻炉砧座（`make/forge-anvil`）、绕线机机架
 * （`make/winder-frame`）、铣床工作台的 T 型槽（`make/mill-table`）、钣金机身
 * （data/machine/unblock-sheet-frame.ts）都是这么写的 —— 车床上唯一能走直线的
 * 进给是溜板，而铣一个平面正好只要一条直线。代价种子里那句注释已经说清：
 * "车床带铣头也能凑，但刚性与精度都不够"（data/machine/lathe.ts）。所以它只到
 * "形状"这一级，平面度还差两道。
 *
 * ⚠️ 缺的那一级是**研磨平板**（`plant/comparator/lapping-plate`：三块两两对研，
 * 不靠任何基准就能把自己磨平 —— data/machine/comparator.ts）。本层没有它：平板要
 * 1 kg 熔融氧化铝，刚玉要电弧炉 2000–2200 °C，氧化铝要酸法提铝那整条链。
 * 于是本层的"平"永远是**相对**的：
 *
 *   相对磨床台面   几微米量级，磨得出来
 *   相对机身导轨   靠对研的斑点，刮得出来
 *   绝对平面       没有；而且**量不出来** —— 没有平板，也没有检验平尺
 *
 * 显示剂同样没有条目：红丹是氧化铁粉调油，本层只有 `mat/iron` 与油，没有"红丹"
 * 这一项。所以涂色**不进 `uses`**（克级用量、且它是判据不是料），记在这里当缺口 ——
 * 与 data/machine/unblock-sheet-frame.ts 的降级②写的是同一处缺口。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 滑块与刀口的寿命 —— 把寿命从整件挪到小件
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 本体（HT300，145 kg）
 *   灰铸铁不能靠淬火提高表面硬度，导轨面的耐磨性来自**石墨与接触面积**，不来自
 *   硬度。好处是它自己带润滑：片状石墨在摩擦面上起固体润滑剂的作用，缺油的容忍度
 *   比钢对钢高一档（钢对钢缺油就是冷焊、拉伤）。坏处是磨粒会**嵌**进石墨里，
 *   嵌进去的砂反过来研磨对偶面 —— 所以滑块与机身之间要刮油、要挡尘，而这一条在本层
 *   只有一块铸铁挡边，挡不住细尘。
 *   寿命的形状：磨损 → 楔铁收紧 → 刮研重配 → 导轨面再磨一次（吃掉 0.1–0.2 mm）
 *   → 楔铁的补偿量用完才报废。**本体是可修的，不是一次性的。**
 *
 * 刃口（45 钢，30 kg，三根可换）
 *   45 钢含碳 0.45%，没有能形成合金碳化物（Cr、W、Mo、V）的元素 —— 淬到 HRC 50
 *   上下就是它的上限，耐磨靠马氏体硬度，不靠碳化物。真正的刃口钢（Cr12MoV 那一类）
 *   本链没有：`SHEET_PARTS` 给剪板刀片的 40Cr 已经是"代用、寿命打折"，而**这一条
 *   连 40Cr 都不用**（它进不了白名单，也不该进）—— 刃口这一档比刀片再降一级。
 *   所以磨损**快**，寿命靠三件事补：
 *     · 可换    松两颗压紧螺钉换一根：30 kg 的钢，不是 145 kg 的铸件
 *     · 可掉头  斜条两端各磨一段工作棱，钝了掉头，一根当两根用
 *     · 可修磨  钝得不深时上磨床重磨斜面，磨掉的量由垫片补回来
 *   顶不住的是**崩**：淬火后不回火（降级③），刃口是淬火态 —— 高硬度、低韧性。
 *   吃到偏载、吃到厚料、吃到料边就崩。所以刃条要宽、支承要满、不许悬空。
 *   这不是设计偏好，是没有回火炉的必然结果。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四处降级 —— 每一条都写清代价落在哪
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① 材料：45 钢锻件 → HT300 灰铸铁
 *
 *    45 钢（抗拉 600 MPa 量级）换成 HT300（抗拉 300 MPa 量级，牌号里的"300"
 *    就是它），差一半，而差的方向恰好是滑块最怕的那个：**抗弯与抗冲击**。
 *
 *    补偿三处，都是真的：
 *      · 断面积加倍   145 kg 的铸铁滑块比同功能钢件厚得多；抗弯刚度按截面惯性矩走，
 *                     厚一倍就是八倍
 *      · 危险截面受压 折弯反力把滑块往上顶，导轨面承压不承拉；灰铸铁抗压强度约是
 *                     抗拉的 3–4 倍（片状石墨的典型比值）
 *      · 限载荷       这一台只当小折弯机用（1 m 宽、薄板），不按 100 t 的机器设计
 *
 *    换回来的不是省事，是**配对**：铸铁滑块对铸铁机身是机床导轨的经典组合，
 *    配刮后接触刚度高、吸振、缺油不易咬死。钢滑块对铸铁机身在手工刮研条件下，
 *    磨粒一进去就是拉伤。
 *
 *    为什么不用 45 钢铸件？铸钢要冒口与正火，而本层没有能恒温的热处理炉；铸钢的
 *    收缩也比灰铸铁大一倍，1 m 长的件变形更难控。铸铁是这里唯一"浇出来就像个样子"的料。
 *
 * ② 结构：铣出来的成形面 → 磨出来拼起来的成形面，**互换性没了**
 *
 *    V 形槽在原路线上是一刀铣出来的成形面。这一条把它拆成三件：
 *
 *      本体上铸一条直槽（槽底是平面） → 两根 45° 斜条磨出来压进去 → V 出来了
 *
 *    拆的理由是设备：磨床磨平面、磨不了 V 槽；车床带铣头能走直线、出不了准角。
 *    拆开之后每一面都是平面，每一面磨床都能磨 —— 用平面拼出角度，是没有铣床时
 *    唯一走得通的那条路。
 *
 *    代价三处：
 *      · 45° 的角度靠**量块垒出的正弦**（sin θ = h/L），不靠磨床的角度工作台
 *        （本层没有）。量块的分辨率够（K 级 0.1 µm），但两根斜条的**对称度**只能
 *        装上去之后用对研补 —— 于是 V 槽的中心线是"研出来的"，不是"加工出来的"
 *      · 接缝多两处（斜条与槽底、斜条与压紧面）。折弯反力走接缝，接缝会微动，
 *        微动就会磨 —— 所以压紧要足、支承要满
 *      · 滑块与机身成了一**对**，不能互换：对研出来的滑块只属于那一台机身，
 *        换一块要连着刮。备件不是"拿来就装"的零件，是一块还要配作的毛坯
 *
 * ③ 热处理：淬得上，回不了火 —— 刃口是淬火态
 *
 *    45 钢淬火 820–860，土窑（400–1100）到得了，所以这一段的温区写得出来。
 *    但淬火之后要**低温回火**（180–220）才算一把能用的刃 —— 而本层没有任何一台
 *    设备 hold 得住 180–220：
 *
 *      土窑        400–1100    下限就高于回火温度
 *      熔炼炉      1200–1650   只高不低
 *      砖窑        1300–1500   同上
 *      电阻炉      100–1100    不在种子那七台里
 *
 *    所以**只淬不回**：硬度到得了 HRC 50 上下，韧性一点没加。这不是"回火忘了写"，
 *    是"回火没有执行者"（第③种情形：缺设备，不是豁免）。
 *
 *    另有一处说不准：土窑是自然抽风的窑，"烧得到"不等于"恒得住"
 *    （data/machine/unblock-mill-spindle.ts 的降级③写过同一句），820–860 这条带是
 *    **写下来的要求**，不是**量出来的事实**；出炉到入水那一段路就是预冷，表面掉多少
 *    度没人知道 —— 于是三根条的硬度散差大，刃口寿命一根一个样。
 *
 * ④ 判据：量块 + 涂色，没有千分尺、没有平板、没有平尺
 *
 *    导轨面尺寸靠 K 级量块比对（`needs: ['plant/gauge-block']`），贴合靠涂色的接触
 *    斑点，平面度靠"与基准面对研"间接判断。三样都只判"在不在带里"，判不了"差多少"。
 *    与 unblock-mill-spindle.ts 的降级④同一类、同一条判据：**判据降级比能力降级更
 *    危险**，因为它不表现为"做不好"，而表现为"不知道好不好"。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 数字与写法
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * · 1 m 宽的滑块，两个数都是算出来的，不是估个整：
 *
 *     本体   长 1000 × 断面折算 2.0×10⁴ mm² = 20 dm³ × 7.2 kg/dm³ = 144 ≈ 145 kg
 *            （灰铸铁取 7.2；断面按时效后的壁与筋折算，与 data/machine/lathe.ts
 *             的床身 780 kg 同一个量级口径）
 *     刃条   φ40 圆钢 3 段各 1 m：π/4 × 40² × 1000 = 1.26×10⁶ mm³ = 1.26 dm³
 *            × 7.85 = 9.9 kg/段 → 3 段 ≈ 30 kg
 *
 * · 进 175 kg，出 1 件。产出按件计、零件没有 `mass`，模型只在**进出都以 kg 计**时
 *   才断言质量守恒（src/core/describe.ts 的 unbalanced 那一段），所以这里不写
 *   `unbalanced_zh` —— 没有需要豁免的断言，填了只是空话。账记在这里：145 + 30 = 175
 *   是净重；浇冒口、加工余量、切屑回炉，模型没有"回炉"这一栏（与 data/machine/lathe.ts
 *   "余量与浇冒口表达不了"是同一个既有缺口，不是这一条新增的）。
 *
 * · 只写 `steps`，不写路线级 `performedBy`：十二道工序接力，五台设备换着上
 *   `needs` 里只有量块 —— 它不干活，是判据；其余五台都在
 *   工序里点名，再写一遍就是 `redundant_need`。
 *
 * · 不写 `pressure`：浇、车、磨、刮、研配全在火星的 0.6 kPa 现场气压下做。
 *   0.6 kPa 低于水的三相点 610 Pa，水不能以液态敞开存在 —— 所以淬火那一桶水是
 *   密闭容器里的、少量敞口蒸发靠时间，没有一道工序要加压。
 *
 * · 不写 `unbalanced_zh` 的第二层理由：件不是 kg，kg 也不是件。给一台米级滑块
 *   编一个 kg 数才是编的 —— 这里给的 145 / 30 是有算式的，产出那一侧没有数，
 *   两边不可比。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 已知缺口（记在这里，不记进 `uses` 冒充前提）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * · 压紧件：三根刃条要压紧螺钉、垫片、楔铁。本层没有螺栓与螺钉的条目
 *   （那是 `std/` 标准件，`std/` 一律不进这条路线），所以"压紧"只能写在工序里当
 *   动作，写不进 `uses`。模型报不出"这件少装了十二颗螺钉"。
 * · 手用工具：刮刀、锉刀（`std/file-general` 要轴承钢与电阻炉）、油石。全部是缺口
 *   —— 与 unblock-sheet-frame.ts 的 `needs` 空着同一个理由。
 * · 油与刮油毡：铸铁导轨缺油会咬，而本层没有润滑油脂的条目（滑脂链未建）。
 * · 检验：平面度没有量具能直接量（见"平面度"那一节的第三级）。接触斑点是有判据的，
 *   几微米的平面度不是 —— 这一处只能等研磨平板长出来。
 */


/**
 * 冷却盘管的第二条来路 —— 没有不锈钢、没有 PTFE、没有钎焊、没有泵。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它是什么（先把既有路线读清）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 条目在 data/machine/process.ts：
 *
 *   「冷却盘管。**电解槽是放热的**（水电解、氯碱、过硫酸盐都放），
 *     而它的窗口只有 10–90 °C —— 热不走，温度就往上跑，槽就废了。
 *     盘管浸在电解液里通冷却水。它是这台设备的温度边界本身：**没有它，
 *     前面那些"60–90 °C"的条件一个都维持不住。**」
 *
 * 既有路线（`make/electrolyzer-cooling`）：
 *
 *   「不锈钢管弯成蛇形，接管穿槽壁，PTFE 垫密封。」
 *   不锈钢 1 kg + PTFE 1 kg，`needs: ['lathe']`，`performedBy: 'plant/sheet-shop'`。
 *
 * 所以它是一件**浸在碱液里的换热器**：一头接冷却水，一头是槽温。它的活儿是把
 * 276 W 量级的热从 80 °C 的碱液搬到水里。它也不磨损：在电解槽的 `composedOf` 里
 * 没有 `wear` —— 一件管子不漏就是不漏，坏了就换一件。
 *
 * 两件料把既有的这条路线卡住：**不锈钢要 10% 以上的铬与镍**（本层的钢里铬最多的
 * 是 40Cr 的 0.9%，差着一个数量级），**PTFE 要氟**（本层没有氟化学）。再加上两处
 * 工艺也不在：**钎焊**要银或铜磷钎料、**泵**要铸要车（模型里唯一的泵是
 * `plant/radiator/pump`，它是辐射散热器的零件，不是一台通用泵）。这条路线绕的就是这四样。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 判据：这条路线上的每一件料，今天都要算得出来
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   HT200        make/iron-ht200：铁 966 + 碳 34，熔化炉 1350–1450 化开
 *   45 钢        make/steel-45：铁 995.5 + 碳 4.5，1550–1650
 *   尾矿         make/free-iron-gravity 的重力选尾矿 —— 当型砂与研磨料
 *   水           make/salt 的联产水（1000 卤水出 264 盐 + 736 水）
 *
 * 设备也是：熔化炉（种子）、土窑（只有夯土窑体一件零件）、车床（种子）、
 * 磨床（种子）、铣床、机器人（种子）。**一条路线不为了灌冷却水去拉一台高压釜进来** ——
 * 所以工质是水，不是氨。氨在这套体系里是标准工质（`make/cell-cooling` 的铝槽壳
 * 水套、`plant/radiator` 的氨回路都写它），但它从哈伯法来（`make/ammonia`，
 * `plant/autoclave` 高压合成）。冻的问题不藏，写在降级⑤。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三个数：它要搬多少热、要多大面、靠什么循环
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① 热负荷 —— **141 W（1.95 V）到 276 W（2.40 V）**
 *
 *    槽压 1.95 V、热中性电压 1.48 V（ΔH/2F = 285.8 kJ/mol ÷ 2F），
 *    电流 300 A（极板 0.15 m² × 0.2 A/cm²）：
 *
 *      (1.95 − 1.48) × 300 = **141 W**
 *
 *    陶隔膜那条的槽压是 2.40 V（unblock-electrolyzer-diaphragm.ts）：
 *
 *      (2.40 − 1.48) × 300 = **276 W**
 *
 *    盘管按 276 W 配。它要同时接住两条隔膜路线（PTFE 的 1.95 V 与陶质的 2.40 V），
 *    而 1.95 V 那条会留下**一倍余量** —— 那倍余量不是浪费，它正好用来把槽压在
 *    70 °C 而不是 85 °C（见降级④）。
 *
 * ② 换热面积 —— **0.105 m²，1.67 m 管，U = 161 W/m²K**
 *
 *    串联热阻，控制项是两边的对流膜（铁壁只占 1.6%）：
 *
 *      1/U = 1/h_碱 + δ/k + 1/h_水 = 1/500 + 0.005/50 + 1/243 = 0.00622 → **U = 161**
 *      h_水 从层流定温壁的 Nu = 3.66 来：3.66 × 0.663 / 0.010 = 243 W/m²K
 *
 *    **铜在这道墙上只值 1.6%**（5 mm 铜 1.25×10⁻⁵ 对 5 mm 铁 1×10⁻⁴，而 1/h 是 2×10⁻³）——
 *    所以这条路线的换热面不许用铜，铜在那 1.6% 上买不回它的价钱。
 *
 *    温度端：槽 80 °C，水 55 → 70（环温差 15 K）
 *
 *      LMTD = (25 − 10) / ln(25/10) = 16.4 K
 *      A    = 276 / (161 × 16.4) = **0.105 m²**
 *      φ20 外径每米 0.0628 m² → **1.67 m**，做 4 根 0.42 m
 *
 * ③ 循环 —— **热虹吸，压头 59 Pa，流量 16 kg/h，循环倍率 2.7**
 *
 *    没有泵，靠"热水轻、冷水重"。环温差 15 K：
 *
 *      m = Q/(c·ΔT) = 276/(4186 × 15) = 4.4×10⁻³ kg/s = **16 kg/h**
 *
 *    **循环倍率 = 16 ÷ 5.9 = 2.7**。5.9 kg/h 是"一次通过就把 40 K 全用掉"的
 *    最小水量（276/(4186×40) = 6.4×10⁻⁴ kg/s）。倍率掉到 1 的意思是：水进盘管是
 *    55 °C、出盘管已经等于槽温 —— 后半截管子一点热也不搬，面积白给。
 *
 *    驱动压头（H = 2 m，55 → 70 °C 的密度差 7.9 kg/m³）：
 *
 *      Δp = Δρ·g·H = 7.9 × 3.71 × 2 = **59 Pa**      （地球同高度 155 Pa）
 *
 *    阻力：上升管 φ20、v = 0.014 m/s、Re 570、5 m 长 1.6 Pa；下降管 1.6 Pa；
 *    4 根盘管并联（每根 φ10、0.42 m、Re 280）0.95 Pa —— **管路一共不到 5 Pa**。
 *    59 对 5 是十几倍余量，**余下的全给散热器**。所以这台"泵"的瓶颈从来不是压头，
 *    是高度与 g（降级③），以及散热器（缺口①）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 温升的两本账：一本赚电，一本赔气
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 槽温从 60 升到 85 °C，两件事同时发生，方向相反：
 *
 *   ① 电 —— σ(30% KOH) 涨约 25%，欧姆那一项跟着降
 *      隔膜那条的欧姆 0.48 V → 0.38 V，槽压 2.40 → 2.30 V
 *      电耗 5.74 → 5.51 kWh/Nm³（**−4%**，1 Nm³ H₂ = 2391 Ah）
 *
 *   ② 气 —— 互串 ∝ 扩散系数 ∝ T/μ
 *      (358/333) × (0.467/0.335) = **1.5 倍**
 *      氢里氧 1.7% → **2.5%**（离 4% 的爆炸下限只剩 1.6 倍，原 2.4 倍）
 *      氧里氢 0.85% → 1.3%（那部分氢是白产的 ⇒ 电流效率 99.15% → 98.7%，−0.4%）
 *
 * **在火星上这笔交换不划算**：电力由种子聚变装置供给（装置可复制扩容，不是免费），
 * 赔掉的是气体纯度与安全余量 ——
 * 那两样要靠更厚的隔膜（槽压 +0.45 V）或更大的排气来买。所以盘管的判据不是
 * "把热搬走就行"，是**把槽钉在 70 °C 那一头**，而钉得越低，LMTD 越小、面积越大
 * （见降级④）。这是这条路线上最反直觉的一处：**冷却能力不是配给热的，是配给
 * "不许升温"的。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 做法：直管 + 集管箱，锥面研配，一根焊缝都没有
 * ═══════════════════════════════════════════════════════════════════════
 *
 * **为什么不弯蛇形**（这是整条路线的形状的由来）：
 *
 *   弯管的砂芯掏不出来。一根直通管的泥芯一捅就掉；一个 U 弯的芯，两头都出不去，
 *   只能做"可拆芯"或"熔模芯" —— 那又回到蜡与模料。所以铸铁的转向不能靠弯管，
 *   只能靠**接头**：4 根直管两头坐进两个铸铁集管箱，转向在箱里的水道上完成。
 *
 * 于是**接头数从 2 变成 10**（8 个锥面 + 2 个穿壁），代价见降级②。
 * 原路线真正的便宜处不是不锈钢，是"一根通管从这头到那头，中间一个接头都没有" ——
 * 那才是钎焊与 PTFE 在替它省的东西。
 *
 * **铸铁夹套不包槽壁**（用数把它否掉）：
 *
 *   夹套包在槽外、热从砖里穿过去：U = 1/(1/500 + 0.1/1.5 + 1/500) = **14 W/m²K**
 *   陶质槽体 0.6 m² 的砖壁、LMTD 16 K → **136 W**，只有 276 W 的一半。
 *   换成 6 mm 钢板槽（U = 243）就是 2330 W，够 8.5 倍 —— 而钢板槽正是
 *   unblock-electrolyzer-ceramic.ts 要绕开的那件东西。
 *
 *   所以"夹套"在这条路线上退回它的第二个身份：**盘管两头的集水箱**。热必须从
 *   碱液里直接拿走，夹套只能隔着 100 mm 陶砖看着。
 *
 * **盘管藏在阴极板背后**：浮在电场里的金属是一个双极性电极，朝阳极那一面会被
 * 极化到 1.9 V，铁在那里以高铁酸盐溶解（Fe → FeO₄²⁻，碱性电解里铁阳极就是这么
 * 没的）。所以盘管只在阴极室、只在阴极板背后，并且**用全金属路径接到阴极铜排上**
 * （盘管锥面 → 集管箱 → 铸铁端盖 → 铜排）：接上之后它是阴极的一部分，被阴极保护。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级（比较对象：原路线那根 φ12 不锈钢蛇形管 + PTFE 垫）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **面积 ×2.4、重量 ×15。** 热虹吸把环温差锁在 15 K，平均水温比"有泵"高 7 K：
 *
 *      热虹吸（水 55 → 70）  LMTD 16.4 K → 0.105 m² → 1.67 m
 *      有泵（水 40 → 41.5）  LMTD 39.3 K → 0.044 m² → 0.69 m
 *
 *    铸铁管必须 5 mm 壁（砂型灰铸铁的薄壁下限，再薄就白口、冷隔），
 *    φ20 外径只留下 φ10 的孔：1.70 kg/m 对不锈钢 φ12×1 的 0.27 kg/m ——
 *    **同样 276 W、同样有泵的工况下，管子从 0.19 kg 变成 2.9 kg；集管箱再加 3.4 kg。**
 *    这 6.3 kg 挂在槽里，不能坐在陶质槽底上（砖不承弯），只能吊在铸铁端盖上。
 *
 * ② **接头 2 → 10，而锥面自己会把力放大 10 倍。**
 *
 *    1:5 锥（半角 5.7°）的自锁靠的是楔：法向接触力 ≈ 轴向力 / sin 5.7° = **10 倍**。
 *    铸铁抗拉只有 200 MPa 级、又脆 —— 这一下敲过头，裂的会是把锥座撑开的集管箱，
 *    不是管子。所以压紧要靠"研配看色"（细尾矿粉作显示剂，研一遍看接触斑），
 *    不靠力。**这条路线没有一处焊缝可查，全部靠"研"**：10 个锥面每一个都是手工对研，
 *    热循环一次就要复紧一次。
 *
 * ③ **火星重力把驱动压头砍到 38%，而流量只按 H^(1/3) 涨。**
 *
 *      59 Pa（火星，H = 2 m）对 155 Pa（地球，同高度）
 *      m ∝ (Δρ·g·H / k)^(1/3) —— 环温差想从 15 K 压到 7.5 K（流量翻倍），
 *      H 要从 2 m 撑到 **16 m**（8 倍）
 *
 *    这就是"没有泵"的极限：**高度是唯一不花钱的压头，而火星把每一米打了 0.38 折。**
 *    厂房的层高能换多少流量，是这条路线的产能上限；泵买的是"不看层高"。
 *
 * ④ **温升买的是电，赔的是气，而火星的电由种子聚变装置供给（装置可复制扩容，
 * 不是免费）。**
 *
 *    −4% 电耗 换 互串 1.5 倍（1.7% → 2.5%，爆炸下限余量 2.4 → 1.6 倍）
 *    与 电流效率 −0.4%（99.15% → 98.7%）。所以盘管按"槽 70 °C"配而不是 80 °C：
 *
 *      槽 80、水 55 → 70：LMTD 16.4 K → **0.105 m²**
 *      槽 70、水 50 → 65：LMTD 10.8 K → **0.159 m²**（多 50%）
 *
 *    降温的每一度都要用面积买，而面积的另一头是散热板（缺口①）。**这是全路线最贵
 *    的一笔，也是最不该省的一笔**：省下的是板子，赔掉的是离爆炸下限的余量。
 *
 * ⑤ **灌的是水，而火星的夜里 −60 °C。**
 *
 *    结冰胀 9%；在封闭的 φ10 通道里，刚性约束下的冰压到几十 MPa 量级
 *    （上限约 200 MPa），而铸铁抗拉 200 MPa 级、脆 —— **裂是一条缝，不是鼓个包**。
 *    所以每次停机都要排干：这条路线多出一件"运行时灌满、停机排空"的活，
 *    而排水阀在模型里是 `plant/radiator/valves`（散热器的零件），不在槽内件里。
 *    留在系统里不排干，第一夜就冻裂。
 *
 * ⑥ **垢：有泵时是"多耗一点功"，没有泵时是直接吃温度余量。**
 *
 *    水侧 1 mm 碳酸钙（k = 2.2）只是 1/U 的 7% —— **垢不是热阻问题**。它是
 *    通道问题：φ10 的孔被圈到 φ8，层流阻力 ∝ D⁻⁴ 就是 **2.44 倍**，而热虹吸的
 *    流量 ∝ k^(−1/3) → **流量 ×0.74、环温差 15 → 20 K、面积欠 1.2 倍**。
 *    同一层垢，泵只需要多给一点功率，热虹吸直接掉出设计点。
 *
 *    碱侧的垢更麻烦，而且**是隔壁那条路线送来的**：陶隔膜在 80 °C 浓 KOH 里
 *    玻璃相被蚀（SiO₂ + 2KOH → K₂SiO₃ + H₂O），硅酸钾在碱里的溶解度随温度降，
 *    而**盘管是槽里唯一的冷面** —— 它会长在盘管上。硅酸盐是电子绝缘体，
 *    垢下的铁因此失去阴极保护，成了垢下腐蚀（缝隙腐蚀）的起点。
 *    检测花不了钱：KOH 渗出来会吸 CO₂（火星空气 95% 是 CO₂）结成白霜 ——
 *    **白霜就是漏点，针孔就是蚀穿。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 已知缺口
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① 散热端不在这条路线上。276 W 只能靠辐射走：按 `plant/radiator` 那个数
 *      （350 K 黑体 850 W/m²）是 **0.32 m²**，铸铁的 ε 只有 0.7（生锈 0.7–0.8、
 *      机加工面 0.2）→ **0.46 m²**。而 0.6 kPa 的 CO₂ 自然对流只有 0.3 W/m²K
 *      （地球是 5 量级），0.46 m² 摊下来 **8 W，占 3%** —— 对流等于没有。
 *      这块板、上升/下降管、膨胀空间都没有条目。模型里唯一的热汇设备是
 *      `plant/radiator`，而它自带一台泵（`plant/radiator/pump`，要 PTFE 与轴承）：
 *      **把它写进 `needs` 就等于把泵又请回来**，所以这里不写它，缺口照实留着。
 *
 *   ② 压力没有字段可用。回路的工作压力必须高于槽内（电解槽 `holds` 50–500 kPa，
 *      见 process.ts），而**这条路线用的设备里没有一台 `holds` pressure** ——
 *      写 `under: [{ param: 'pressure', ... }]` 就是 `no_machine`。
 *      模型里唯一 hold 压力的是 `plant/ore-beneficiary`（100–300 kPa，选矿），
 *      它不干这件事。所以：**试压、预充压只写在注释与 `note_zh` 里，不写成条件** ——
 *      条件必须有一个可追责的承担者，这里没有。
 *
 *   ③ h_碱（取 500）、U、结垢速率、锥面泄漏率、薄壁铸铁的废品率 —— 一个数都没有
 *      出处，只有量级。换热面积这个刻度模型本来就没有（隔膜那条的缺口①同源），
 *      这里算出来的是给人读的，不是给校验器看的。
 *
 *   ④ 三件"看着"的活没有仪表：隔膜两侧的液位差、盘管的垢、锥面的渗漏。
 *      电解槽的零件只有槽体、电极、隔膜、整流、气液分离、盘管 —— 一件仪表也没有。
 *
 *   ⑤ 阴极室是前提。盘管只能做在阴极板背后（阳极侧 1.9 V 下铁以高铁酸盐溶解），
 *      而"阴极室"这件事由槽体的隔墙给出（unblock-electrolyzer-ceramic.ts 那条
 *      "留极板槽与隔墙"）。没有隔墙，这 4 根 0.42 m 的直管无处可放。
 *
 * ⚠️ 时态：不锈钢、PTFE 是**现在**没有（前者要铬镍，后者要氟化学）；
 *    氨是现在**有**料但要高压釜，所以这条路线不写它。
 *
 * 不写 `under: pressure` 的理由见缺口②；不写 `under: temperature` 的工序（车、磨、
 * 铣、对研、装配）是因为那几台设备没有 `holds` —— 写上就是 `no_machine`。
 */


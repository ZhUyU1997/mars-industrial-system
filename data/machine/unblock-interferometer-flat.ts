/**
 * 干涉仪平晶的替代路线：**三块铸铁互研**（φ70、λ/4、360 h）。
 *
 * ⚠️ **路线 id 说明（读的人先看这一条）**：任务书给的 id 是 `make/interferometer-flat`，
 * 但那个 id 已经存在（data/machine/interferometer.ts 第 90 行，就是这条路线要替代的
 * 那一条：`mat/glass` + `mat/fused-alumina` + 比较仪的研磨平板）。同一条 id 出现两次
 * 就是 `duplicate_id`，编译不过 —— 所以这条叫 **`make/interferometer-flat-lap`**。
 * 它产出同一个条目（多路线 = OR），这正是"换一条做法"该有的样子。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一、原路线卡在哪：三件，两件是料、一件是"比它更精的东西"
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 既有那条（interferometer.ts 第 90 行）：
 *
 *   mat/glass            ✗ 不在这一轮的料表里（能做玻璃，但要另起一炉）
 *   mat/fused-alumina    ✗ 熔融氧化铝：要 2050 °C，本层最高 2200 的电弧炉能烧，
 *                        但那是另一个条目的事，不在料表里
 *   needs 比较仪的研磨平板 ✗ 一块 1 µm 的铸铁平板 —— 而平晶要 λ/4（0.13 µm），
 *                        **严一个量级**（差 8 倍）。拿 1 µm 的东西去研 0.13 µm，研不出来
 *
 * 第三件是这条路线上真正的结：**平晶的平面度不能由"更不平的东西"磨出来**。
 * 工业上这一关靠三样：沥青抛光盘（会自己贴伏）、母版（一块已有的更平的）、
 * 或者**三块互研**（不需要母版）。本层前两样都没有，只剩第三样。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 二、材料：玻璃不行、石英不行、**铸铁行**
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **玻璃（否）**。本层能做的玻璃只有硅钙玻璃（硅石 + 石灰 + 铜），它在薄片上
 *    成立（0.6 mm 的滤光片急冷冻住），**在厚块上不成立**：厚块必须缓冷（退火），
 *    而 550–650 的退火窗口正是它析晶的窗口 —— 一炉 φ80×30 的玻璃块，冷却时
 *    从芯部开始长方石英，出来是一块"白石头"。把 CaO 降到 10% 以下能让它不析晶，
 *    但液相线又回到 1600 以上：熔化炉（1650）只剩 50 K 余量，浇 30 mm 厚的块
 *    连模子都没流满就凝了。**两头堵。**
 *
 * ② **石英（否）**。`mat/quartz-pure` 是 99.9% 的**砂**，不是熔石英。熔石英要
 *    1713 °C，而熔化炉的上限是 1650 —— 差 63 K。这一条在光学高温计那份文件里
 *    已经算过（折射透镜做不出来），这里再撞一次：**砂不是玻璃。**
 *
 * ③ **铸铁（选）**。它有四个好处，一个坏处，而这一个坏处刚好不致命：
 *
 *    能浇       φ80×30 的块，砂型一浇三块，同一次铁水（三块必须同料同膨胀）
 *    能车能磨   车到留 0.3 mm，再用石英粉研 —— 不需要抛光机
 *    反射率 20–30%  **比裸玻璃的 4% 高五倍**：Fizeau 干涉看的正是反射光，
 *              铸铁的条纹比玻璃亮一档（工业上"钢平晶"就是这个道理）
 *    历史       惠特沃斯 1840 年代的平板就是三块铸铁互研出来的 —— 这条路
 *              **本来就是铸铁走出来的**，不是将就
 *    坏处：α = 11×10⁻⁶/K，是玻璃的两倍 —— 见第六节，靠恒温室 + 厚截面 +
 *    挡风罩对付，不是靠材料
 *
 * 铸铁的另一个毛病在第八节：石墨片。它让抛光面留下麻点，条纹背景发花。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三、平面度：三块互为基准（惠特沃斯三块互研）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 一块板要平，得有一个平的基准去磨它；而基准自己怎么平？**三块互相磨。**
 *
 *   A 研 B（A 在上、来回推、转 60° 再推）
 *   B 研 C
 *   C 研 A
 *   然后重来一遍，每轮换一个起始转角 —— **转角是随机的，误差就被平均掉了**
 *
 * 为什么三块能收敛：任何一块的凸起都会在磨对方时把对方磨凹，而凹处又不磨到 ——
 * 一轮下来三块互相"削高填低"，共有的那部分形状（比如三块同半径的球面）不会被
 * 消除，但**随机的换位会让它无法在三块上长得一样**。这就是三块法的全部道理，
 * 也是它为什么慢：**它靠的是几百个小时的随机性，不是靠一把尺。**
 *
 * 工时（这是这条路线的第二个成本，第一个是铁水）：
 *
 *   粗研（石英粉 1–3 µm）  8 h/对 × 3 对
 *   精研（0.3 µm 那一档）  40 h/对 × 3 对
 *   抛光（同上，轻压）      2 h/对 × 3 对
 *   换位与看条纹            60 h（18 个转角 × 3 对，每看一次要等热平衡 20 min）
 *   两轮（第一轮之后必然要返修）→ **合计约 360 h ≈ 45 个工作日**
 *
 * 对照：工业用沥青盘 + 机器研磨，同样的 φ70、λ/4 是 20 h 一档 —— **差 20 倍**。
 * Rowland 的平面光栅磨了几个月，我们这三块是同一个量级，只是他没有 Deadline。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 四、拿什么看：钠没有，用铜的绿线
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 干涉条纹要单色光。本层**没有钠**（`mat/salt` 不在料表里，而且盐也是氯碱的料，
 * 轮不到这里），所以"钠焰 + 缝"这条路走不通。剩两条：
 *
 * ① **铜的绿线（选）**。铜在碳弧里烧，发射 510.5 / 515.3 / 521.8 nm 三条绿线，
 *    三条挤在 11 nm 里 —— 合成后的相干长度 = λ²/Δλ = 0.515² / 0.011 = **24 µm**。
 *    而两块平的空气楔只有 1–2 µm，够用三倍。
 *    光源就是两根 φ10 的碳棒 + 一段铜丝、弧隙 3 mm、直流 10 A —— 本层最便宜的光。
 *
 * ② **铜红玻璃 + 缝（否，但理由有意思）**。铜红玻璃透的是 600–700 nm 的红 ——
 *    它会**把铜的绿线全部滤掉**，只剩碳弧的连续谱。红玻璃配铜弧，是把唯一的
 *    单色光滤成白光。**现成的东西不一定配套**：铜的红玻璃给光学高温计用，
 *    铜的绿线给干涉用，两件事用的是铜的两种性质。
 *
 * 还有一条要用眼而不是用仪器：**条纹本身就是"尺"**。两条条纹之间的距离对应
 * 空气楔变化 λ/2 = 0.26 µm；条纹弯了 1/2 条，就是差了 λ/4。**人眼能判到
 * 1/10–1/20 条** —— 所以判读精度 0.014–0.028 µm，而研磨的极限（λ/4 = 0.13 µm）
 * 比它粗 5–10 倍。**看不清不是瓶颈，磨不出来才是。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五、鸡生蛋：第一块平晶怎么验（这是本文件最要紧的一节）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 干涉仪要平晶才能工作，而平晶要干涉仪才能验 —— 这个环是假的，因为：
 *
 *   **"看条纹"不需要干涉仪。** 一块黑布、一盏铜弧、两块平晶、一双眼睛，
 *   就是全部的装置：把 A 放在 B 上，光从上方照，反射光里就有等厚条纹。
 *   干涉仪（分光板 + 目镜 + 工作台）是把这个现象**装进一台机器**，
 *   不是这个现象的前提。
 *
 * 于是第一块平晶的验收是三块钱的一次"投票"：
 *
 *   ① A 放 B 上：条纹直 → A 与 B 之差是一块平面
 *   ② B 放 C 上：条纹直
 *   ③ C 放 A 上：条纹直
 *   ④ 三块各转 60°、120° 重做 —— **弯的形状跟着哪一块转，就是哪一块的错**
 *   ⑤ 三次都直、六个转角都直 → 三块都是平的
 *
 * ⑤ 这一步要诚实：**三次互检只能证明"两两之差是平面"，不能排除三块共有的那个
 * 形状**（比如三块恰好是同一个半径的球面，三次互检的条纹也是直的）。排除它靠的
 * 不是条纹，是**研磨时的随机换位**（第三节）—— 共有的形状必须在三块上一模一样才
 * 能不被发现，而随机换位让这件事的概率低到可以不管。工业上也是这么说的：
 * 三块互研"收敛"，不是"证明"。
 *
 * 在条纹之前还有一道更粗的关，替这台表省掉 200 h：**刀口直尺的光隙法**。
 * 一根 45 钢的刀口直尺（350 mm，刃口磨到 0.1）横在平晶上，从缝里透过的光
 * 能看出 1 µm 的间隙 —— 它比条纹粗一个量级，但能拦住 10 µm 的弯。
 * **先用粗尺拦掉九成的返工，再用条纹定最后的 0.13 µm。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 六、热：两面温差 0.5 K 就毁掉 λ/4
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 均匀的热膨胀**不改形状**（整体变大，还是平的）—— 所以恒温室 ±1 K 的**温度**
 * 本身不是问题。有问题的是**梯度**：
 *
 *   两面温差 ΔT 的板，弯成半径 R = t/(α·ΔT)，中间拱起 s = D²·α·ΔT/(8t)
 *   本块：D = 70 mm、t = 25 mm、α = 11×10⁻⁶ → **s = 0.27 µm/K**
 *   → **ΔT = 0.5 K 就是 0.135 µm = λ/4**：一整块的努力被半度温差吃掉
 *
 * 所以三条纪律（都写进 steps）：
 *
 *   厚 25 mm   s ∝ 1/t：20 mm 会到 0.34 µm/K，25 mm 压到 0.27。再厚就太重、太贵
 *   挡风罩     一阵穿堂风在一面吹，就是 0.3–0.5 K 的温差 —— 量的时候罩住，人退开
 *   三点支撑   在三个点上垫平（不是四点、不是面），让板自己躺平；四点必有一条腿悬空
 *
 * 恒温室在这里的用处只有两个：**把 20 °C 定住不让它漂**（否则量一整天，尺子跟着
 * 板一起变），以及**把湿度压住**（铸铁会锈，锈层是 1 µm 量级的，一锈就废）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 七、kg 账
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   进 8.35 kg → **成品 1 件 0.69 kg（φ70×25）** + **工装 1.80 kg** + 损耗 5.86 kg。
 *
 *   成品只算一块，但必须造三块 —— 三块互研的另外两块是"再研的搭档"：
 *   平晶用十年要重研一次，**重研必须有另外两块陪着**，否则一块板自己研自己
 *   （那只会越研越凸）。所以两块随干涉仪一起交货，记在工装里，不进产品重量。
 *
 *   工装 1.80 = 另两块平晶 1.38 + 刀口直尺 0.18 + 压块 3 只 0.15 + 电极夹 0.02
 *     + 铜弧的铜丝 0.01 + 挡风毡 0.01 + 挂具 0.05
 *   损耗 5.86 = 水 2.50（研磨液与清洗，全走掉）+ 石英粉 0.80（磨料，全耗）
 *     + 耐火料 0.30（退火垫片，全耗）+ 铸铁 1.73（冒口 0.53 + 车磨掉的 1.20）
 *     + 45 钢 0.17 + 碳棒 0.10（烧掉）+ 矿棉 0.09 + 铜 0.08 + 铜线 0.04
 *     + 铁 0.05（算式在 unbalanced_zh）
 *
 * 三块板的铁水是同一包：**不同包次的铸铁，石墨形态与膨胀系数差 5%** ——
 * 三块板的 α 不同，研得再平，温度一变就各自弯成不同的球面。这是这条路线
 * 最容易被忽略的一条：**材料的一致性比平面度更难。**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 八、降级（六处，带量级）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **没有沥青抛光盘 → 边缘塌：可用口径 φ70 → φ60（面积 −27%），外圈塌 0.3–0.5 µm。** 沥青盘软，
 *    压力分布均匀，能保住 95% 的口径；铸铁盘硬，压力集中在边缘，外圈 8–10 mm
 *    塌 0.3–0.5 µm（λ – λ/2）。所以这块平晶**只有中间 φ60 是 λ/4，外圈是 λ/2** ——
 *    用它验量块时，量块必须放在 φ60 里。
 *
 * ② **磨料最细只到 0.3 µm（石英粉沉降 35 h 才分出来）→ 表面 Ra 0.02 µm
 *    （工业红粉 Ra 0.003，差 7 倍）。** 散射让条纹对比度从 60% 掉到 25%，
 *    必须在暗室里看，而且这面**研不住量块**（研合要 Ra 0.01）：这台平晶只能
 *    "看"（Fizeau 比较），不能"研"（把量块研上去测绝对长度）。
 *
 * ③ **工时 360 h 对工业 20 h（18 倍）。** 三块互研是人推的：3 对 × 2 轮 × 50 h
 *    + 看条纹 60 h。而且**它是手艺**：第 400 小时手上那点压力差，就是最后 λ/4
 *    与 λ/2 的分别。这一条没法写进数据，只能写进工时。
 *
 * ④ **热：两面温差 0.5 K = λ/4（0.27 µm/K）。** 铸铁的 α 是玻璃的两倍，所以
 *    这块平晶比玻璃版**更怕风、更怕手**；挡风罩、三点支撑、量前等 20 min 热平衡
 *    都是这条降级的兑现处。而它不能做薄（薄了 s 更大）也不能做厚（重、贵、热容大）。
 *
 * ⑤ **石墨片：抛光面每 cm² 几十个 1–2 µm 的麻点。** 条纹背景发花，数条纹要在
 *    麻点之间"找连续段"；玻璃平晶没有这个，但本层做不出厚玻璃块（第二节）。
 *    麻点还让接触面"研合"时局部悬空 —— 这是③里那些返工的来源之一。
 *
 * ⑥ **三块互检不能排除"三块共有"的形状。** 三块同半径的球面，三次互检的条纹也
 *    都是直的。排除它靠的是随机换位（每对 6 个转角 × 3 对 = 18 次，每次 3.3 h），
 *    不是靠条纹 —— 所以"三块都是平的"这句话的真实含义是"**三块都是平的，
 *    概率上**"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 九、已知缺口（都不在这条路线的范围里）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  · **工时不在模型里**：360 h、两轮返修、18 次转角检查 —— 模型没有时间维，
 *    这些只能写在注释里（与 make/pyrometer-objective 的"几百小时"同一处境）
 *  · **电不进模型**：铜弧的 10 A 直流、直流母线 —— 全表口径都不写电
 *  · **没有沥青、没有松香、没有蜂蜡**：抛光的"软盘"那一路整条走不通，
 *    这条路线因此只能靠"硬盘 + 细粉 + 时间"
 *  · **量块研合的表面要求没有被满足**：Ra 0.02 比研合要求的 0.01 粗一倍 ——
 *    这条平晶做不了"绝对长度"，只做得了"相对比较"。而本层的量块链需要的是
 *    相对比较（基准 87 块已经在），所以这一条不致命，但要说清
 *  · **铸铁会锈**：恒温室压湿度、平晶不用时涂一层油（`mat/...` 里没有油，
 *    用动物脂? 没有）—— 现实中是"涂一薄层凡士林"，本层没有，只能**放在干燥器里
 *    （石英砂袋）**。这一条与 dvm 那份文件是同一个办法
 *  · **三块必须同一包铁水**：不同包次的石墨形态差 5%，α 就差 5% —— 这是
 *    "材料一致性"这个缺口，模型里没有"同一炉次"这个概念，只能在注释里约束
 *  · **平晶的边不用抛**：φ70 的外圆留 1 mm 的倒角（研的时候手指按在那儿，
 *    直角边会崩）—— 这一条写进第③道车工序
 */


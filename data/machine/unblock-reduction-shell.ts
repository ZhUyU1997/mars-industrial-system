/**
 * 直接还原炉壳体的第二条来路 —— 砖砌圆筒 + 铸铁端件，不用一块钢板。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它补的是什么
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 严格算术（设备也算进闭包）走不到这台炉子：卡在壳体上。
 * 原来的 `make/reduction-shell`（data/material/entry.ts）要 `mat/sheet-steel`
 * 与 `plant/sheet-shop`，而钢板与钣金工位都在"第一个铁"那个环里：
 *
 *   制铁 ← 轧机 ← 钢锭 ← 制铁
 *   冷轧板 ← 钣金工位 ← 轧机 ← 制铁
 *
 * 环的入口已经写过（data/material/bootstrap.ts：锻板版钢板、镁还原制碳、
 * 水煤气制氢），但**壳体这一件仍然只有钢板一条路**。所以这不是"没写"，
 * 是"写出来也长不出来"：给壳体换一套不经过轧机、不经过钣金工位的做法。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 结构：一只砖筒，两头压着铸铁件
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   砖砌圆筒   内径 0.9 m、高 2.4 m、壁厚 344 mm（热面半砖 114 + 背衬一砖 230）
 *              —— 承温、承料柱、承 1–2 kPa 的压差
 *   铸铁炉盖   φ1.6 m × 80 mm，带水套；进料口、出气口、测温孔全在铸铁件上
 *   铸铁法兰   球锥面金属对金属密封，车后磨 —— **不用垫片**（850 °C 没有便宜垫片）
 *   铸铁环箍   3 道 60×80 箍住砖筒；8 根 φ24 的 45 钢拉杆把盖与底部法兰对拉起来
 *   灰浆涂层   砖缝与内表面刷石灰浆：封缝，外加一层将来会粉化的牺牲面
 *
 * 原则一句话：**砖只承温与承重，气密全在铸铁件上。**
 * 砖砌体上不开孔、不接管 —— 一切管口都从铸铁件上走，因为砖缝是漏的，
 * 而铸铁只要壁厚够、没有缩松，它就是气密的。
 *
 * 为什么不是"铸铁筒 + 砖衬"（Bosch 反应器壳体那条路线的做法）：那一台的筒体
 * 小，可以整件浇、整件镗。还原炉的筒是 φ1.6 × 2.4 m —— 浇这么大一件要大型
 * 砂型、要能镗内圆的镗床，本层两样都没有。所以这里只铸短件：盖、法兰、环箍。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么"钢壳 + 砖衬"不能照抄，而砖砌体又必须换一套密封思路
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 工业竖炉（Midrex、HYL 那一类）是钢壳 + 耐火衬：**钢板焊缝是唯一的气密层**，
 * 砖衬只管耐热与保温，壳体温度靠水冷或风冷压到 200 °C 以下。那条路线的难点
 * 全在钢板上，而钢板正是本层拿不到的那一件。
 *
 * 反过来做 —— 让砖承温、也让砖当壳 —— 就撞上砖砌体的天性：
 *
 *   单块砖显气孔率 25%（土法砖；工业耐火砖 18%），砖缝 1–2 mm：
 *   砌体是**限流**结构，不是**密封**结构
 *   钢板焊缝的漏率能做到 10⁻⁶ Pa·m³/s 量级，砖砌体抹浆后只能算"看得见的不漏"
 *   两者差好几个数量级 —— 这不是施工水平问题，是材料本身的性质
 *
 * 所以这条路线不按"零泄漏"设计，按"**把压差降到砖扛得住的量级**"设计：
 *
 *   工业炉内 100 kPa 量级，外面是 0.6 kPa（火星环境）—— 100 kPa 的压差，
 *   砖砌体一天也扛不住。要让它成立，只有一条路：**把炉子放进加压厂房**。
 *   厂房里（约 100 kPa）炉内跑到 100 kPa 的富氢气氛，砖墙两侧只差 1–2 kPa。
 *
 *   **砖砌体承的是压差，不是压力。** 1–2 kPa 的差，砌体与铸铁法兰都扛得住；
 *   100 kPa 的主体压差由厂房的墙承担。
 *
 * 这是本路线最贵的一笔账：**压力边界从炉子挪到了厂房。** 工业上炉子自己就是
 * 压力容器，不依赖厂房；这里反过来 —— 代价是整间厂房要气密，而本层还没有
 * 那台设备（见下面"已知缺口"）。
 *
 * 剩下那 1–2 kPa 的漏按"控制 + 处理"办，不按"堵死"办：
 *
 *   微正压（+1～2 kPa）让漏的方向朝外，别让厂房的空气往里倒灌
 *   厂房里是 CO₂ —— 氢漏进去不像在空气里那样立刻变成爆炸性混合气
 *   （CO₂ 是惰性的，这是火星的一个便宜处：它降低"炸"的概率，但不取消"漏"）
 *   炉顶排风罩把渗出的氢抽走烧掉，氢耗因此上浮（量级几个百分点）
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 850–900 °C 上的两个取舍
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 砖这一侧：850–900 °C 对烧到 1300–1400 的耐火砖是安全的（耐火度约 1500，
 * 留一档），**但铁是问题**。风化层 Fe₂O₃ 17–20%（成分表），砖里的
 * 铁在氢气里 400 °C 以上就开始还原：Fe₂O₃ → Fe₃O₄ → Fe，体积变化两成，
 * 砖面起皮、粉化。这件事 `make/refractory-brick`（data/material/bootstrap.ts）
 * 的降级①已经写过（"在还原气氛里会被侵蚀，渣线寿命短"），**这里不另立一套
 * 说法，只继承它**。所以砖衬是消耗性的，且分两层：
 *
 *   热面   耐火砖（`mat/refractory`，砖窑 1300–1400 烧成），850–900 °C，
 *          粉化最快，是牺牲层 —— 每次开停炉补砌一层
 *   背衬   就地黏土砖（土窑 1000–1100 烧成），温度压在 600 以下，粉化慢，管结构
 *
 * **本层没有低铁砖**：高铝砖要高铝矾土，火星没有。所以"热面不被还原"这一条
 * 不是这条路线能自己解决的，它只能把牺牲层做薄、做得换得起。
 *
 * 铸铁这一侧：HT250 的长期用温上限约 400 °C（再高就生长、氧化、密封面走形）。
 * 900 °C 的炉膛上盖一块铸铁，只有两条路：
 *   水冷   盖里做水套，把内表面压到 350–400 °C；水靠热虹吸循环，不要泵
 *   加厚   壁厚 60–80 mm，接受寿命掉到 2–3 年，且法兰螺栓要频繁复紧
 * 本层选水冷 —— 与排料阀同一个解法：**水冷不是为了降温，是为了让铸铁能用在
 * 800 °C**（见 data/material/entry.ts 的 `plant/reduction-furnace/discharge`）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 材料为什么只有这六样
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 这张清单是**算出来的**，不是挑出来的。按严格算术的口径查一遍：
 *
 *   `mat/refractory`           到得了 —— make/refractory-brick（风化层 + 石灰，砖窑 1300–1400）
 *   `mars/regolith`            行星地板，不要路线
 *   `mat/water`                到得了（make/water）
 *   `mat/lime`                 到得了（make/lime-gypsum，砖窑 1300–1400）
 *   `mat/iron-ht200/250/300`、`mat/iron`   到得了（make/iron-htXXX 那一组）
 *   `mat/steel-45`             到得了（make/steel-45）—— 拉杆与螺栓用它
 *
 * 拉杆与螺栓另写一个"任选其一"（`anyOf`）：45 钢韧性好、能拧，是首选；没有钢的
 * 时候用 HT300 的大截面顶上 —— 铸铁抗拉只有钢的四分之一，所以 φ24 的钢拉杆要换成
 * φ40 的铸铁拉杆。这一件不该因为一样料断供就整条路走不通。
 *
 * 而 `mat/alumina` **现在到不了**：make/alumina 要 `plant/acid-plant` 与
 * `plant/kiln`，两样现在都没有路线。所以内表面涂层只能是**石灰浆**，不是氧化铝浆。
 * 这不是省事 —— 氧化铝浆抗还原、抗渣都比石灰浆好，问题在于它到不了炉边。
 * 等酸厂建起来，把它换进 `uses` 就行，路线结构不用动。（
 * "现在没有"与"本来没有"要分开 —— 这一条是前者。）
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级（五处，按代价从大到小）
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① 压力边界挪到厂房：炉子自己不是压力容器，只能微正压运行。本层没有加压厂房，
 *    所以这条路线是"厂房建起来之后才算通"的 —— 这是它最大的缺口，不是细节。
 * ② 气密靠"限流 + 焚烧"，不靠焊缝：漏率比钢壳差几个数量级，氢耗因此上浮。
 * ③ 砖面会还原剥落（含铁 17–20%，本层没有低铁砖）：热面是牺牲层，寿命 1–2 年
 *    （工业砖衬 5–8 年），每次开停炉补砌；涂层只能用石灰浆，同样会掉。
 * ④ 铸铁不能焊：盖、法兰、环箍只能螺栓连接、只能低预紧；螺栓在 400 °C 上会松弛，
 *    每次开停炉复紧一遍。没有 45 钢时连拉杆也要换成铸铁，截面放大一倍。
 * ⑤ 筒身不能整体铸造（φ1.6 × 2.4 m 的铸铁筒要大型砂型与镗床，本层都没有），
 *    所以只铸短件：盖、法兰、环箍。**砖筒是这条路线能成立的原因，也是它所有漏
 *    的来源。**
 *
 * 已知缺口（都不在这条路线的范围里，记在这里）：
 *   加压厂房    没有这台设备。没有它，砖壳路线只能降级成"真空炉"，而 0.6 kPa 下
 *               的氢分压还原不了铁 —— 换句话说：**厂房的缺口就是这条路线的缺口**
 *   循环水箱    水套靠热虹吸绕开了泵，但水箱与管路仍然要有
 *   高温动密封  布料器的石墨盘根仍在 make/reduction-feeder 里，不在这条路线里
 */


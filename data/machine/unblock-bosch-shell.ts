/**
 * Bosch 反应器壳体（`plant/bosch-reactor/shell`）的**第二条路线** —— 砖衬 + 铸铁。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 这一条补的是哪面墙
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 原路线 `make/bosch-shell`（data/material/entry.ts）是**不锈钢板卷焊 → 法兰 → 试压**，
 * 材料 `mat/stainless-steel`，设备 `plant/sheet-shop`。两样都在严格算术的闭包之外：
 *
 *   不锈钢    18/8 要 铬铁 276 + 镍 80（`make/stainless-steel`），铬是 140:1、镍是
 *             250:1 的富集，两条都要精炼与电解的环；而那个环要设备
 *   剪板折弯  `plant/sheet-shop` 要轧机（`make/sheet-steel` 走 `plant/rolling-mill`），
 *             轧机要钢，钢要熔化炉与一块能轧的板 —— 又回到设备环上
 *
 * 于是从种子与火星料出发的那份算术里（`node tools/report.ts` 的「严格算术」一节），
 * 壳体一直长不出来 —— 写这一条时那里是 48 / 473 条目、7 / 51 台设备（这两个数会随
 * 数据漂，要真数看报告）。而它是 Bosch 反应器五件零件里唯一一件"只差材料与一台
 * 设备"的，另外四件各差一种本层还没有的材料：
 *
 *   催化剂     要 `mat/nickel` + `mat/refractory`（两条都不在闭包里）
 *   除水器     要 `mat/stainless-steel` + `mat/copper`（铜在，不锈钢不在）
 *   卸碳机构   要 `mat/steel-45`（要 1550–1650，且要散热器）
 *   加热夹套   要 `mat/refractory` + `mat/sheet-steel`
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 判据：一件零件能不能被"温度与压力分家"救回来
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 不锈钢之所以是壳体的默认材料，是因为它**同时**干三件事：承压、耐温、耐蚀。
 * 一件材料干三件事时，任何一件事上的缺口都会卡住整件东西。分家的问法是：
 *
 *   谁承压   → 铸铁外筒（HT250，抗拉 250 MPa，厚壁，能浇）
 *   谁耐温   → 砖衬（风化层黏土砖，先烧到 1050 预收缩，服务温度在 700 以上）
 *   谁耐蚀   → 没有人。这里是氢气，本来就不靠氧化膜 —— 腐蚀问题在这里换了个名字，
 *              叫**氢蚀**，写在降级二里。
 *
 * 两样材料都在闭包里：`mat/iron-ht250` 由 `plant/melting-furnace` 出（铁 970 + 碳 30，
 * 见 `make/iron-ht250`），风化层与水是火星地板，砖在 `plant/earth-kiln` 里烧
 * （`make/firebrick-clay` 已经这么干：风化层 1000 + 水 250 → 砖 800 块）。
 * 所以这条路线**一支外购件都不要**，执行设备只有五台，全在闭包里。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么砖衬 + 铸铁比不锈钢差：三处降级
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 【降级一 · 压力】不锈钢薄壁本身就是压力边界：6 mm 板卷成筒，焊缝可探伤，
 * 表压能到几百 kPa。**铸铁不能焊**，于是每一道接缝都是一处必须靠"法兰 + 螺栓 +
 * 金属对金属的锥面"压住的地方，而灰铸铁的抗拉强度随壁厚与温度一起掉。所以这条
 * 壳体的表压只能按**几十 kPa 量级**定 —— 这不算太坏：Bosch 反应在 500–700 °C 下
 * 进行，CO₂ + 2H₂ → C + 2H₂O 的平衡在 0.1 MPa 附近与高压差别不大，高压只买到
 * 体积流量。缓解就是**限制压力**：壳体按低表压设计，砖衬只承温、承压全靠铸铁筒。
 *
 * 不用垫片不是省事，是没有：橡胶与 PTFE 到不了 400，柔性石墨箔本层没有那条路线
 * （`mat/carbon` 是料，做成箔的那一步没写）。所以密封做成铸铁对铸铁的锥面，
 * 靠螺栓预紧的弹性变形压住 —— 这也是它只能低压的第二个理由。
 *
 * 【降级二 · 氢蚀】这是砖衬 + 铸铁真正比不锈钢差的地方，两条同时发生：
 *   ① 铸铁脱碳    C(石墨) + 2H₂ → CH₄。灰铸铁里的碳是片状石墨，氢顺着石墨片进去，
 *                 表层脱碳成海绵状铁：强度掉、气密性掉。600 °C 以上才显著 ——
 *                 所以**砖衬把铸铁壁温压到 400–500** 是唯一的缓解手段，砖衬不是
 *                 保温层，它是"让铸铁离氢远一点"的那一层。
 *   ② 砖被还原    风化层含 Fe₂O₃ 18%（data/machine/brick-kiln.ts 的口径），
 *                 500–700 °C 下氢把 Fe₂O₃ 还原成 FeO/Fe，体积一变砖就疏松、掉渣。
 *                 砖面先烧到 1050，让黏土玻璃相把铁氧化物颗粒包住，能**拖慢**，
 *                 不能**避免** —— 所以砖衬是消耗件。这条壳体的寿命不由壳体决定，
 *                 由砖衬与卸碳机构决定（与 entry.ts 里"寿命由卸碳机构决定"一致）。
 *
 * 【降级三 · 密封与修理】不锈钢壳漏了能焊补；灰铸铁焊补裂纹多、热影响区硬脆，
 * 现场基本只能换。于是密封只能靠**少接缝 + 多层**：
 *   ① 主密封  铸铁对铸铁的锥面，车完再磨（`lathe` → `plant/grinder`）
 *   ② 副密封  法兰外缘一圈耐火泥（石灰 + 风化层细砂）填塞，兼作隔热
 *   ③ 引漏腔  两道法兰之间留 3 mm 环形腔，把渗过去的氢引回进气侧 ——
 *              漏了不外泄，只是效率掉。这就是"多层密封"在这套材料上的样子。
 * 内表面另刷一层石灰浆封闭气孔（**涂层**）：`mat/lime`。更好的选择是铝质涂料，
 * 但 `mat/alumina` 在严格算术里还到不了（电解铝要冰晶石与电解槽），先不写。
 *
 * 代价要说清：这条壳体比不锈钢壳重得多（铸铁壁 25 mm 对钢板 6 mm），装配工时也
 * 多一倍（砌衬、磨面、热紧螺栓）。**它不是更好的壳体，它是能造出来的壳体。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 镍为什么不在 `uses` 里
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 镍是**催化剂床**，不是壳体的材料。它的位置由 `plant/bosch-reactor/catalyst`
 * 与 `make/bosch-catalyst`（镍 + 耐火料载体，浸渍后焙烧）回答。没有镍，Bosch 反应
 * 不反应；但没有镍，壳体装得起来 —— 这两件事由两个条目分别承担，不合并。
 *
 * 所以这里既不把 `mat/nickel` 写进 `uses`（那会把催化剂算成壳体的一部分，两处真相，
 * 也不写进 `needs`（`needs` 是"在场的前提"，而镍在这里既不被吃掉、
 * 也不需要在砌砖的时候在场 —— 它在另一件零件里）。附带的好处是：`mat/nickel` 要
 * 电解/精炼，不在闭包里，写进来会把壳体重新卡在它本来不该承担的那条环上。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么不开在 `plant/brick-kiln` 里
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 砖窑能到 1300–1500，但**风化层砖到不了 1300**：铁高（Fe₂O₃ 18%）在高温下是助熔剂，
 * 砖自己是按 1300 保守写的上限（data/machine/brick-kiln.ts 的降级说明）。把砖坯
 * 送进 1300 的窑里去烧，烧的是砖的软点，不是砖的强度。而这条壳体只服务 500–700，
 * 砖只要烧到 1000–1100 就够（`make/firebrick-clay` 正是这个温区，用土窑）——
 * 于是砖在这一条里走 `plant/earth-kiln`，砖窑留给玻璃与耐火料。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 已知缺口
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  · 压力：模型里没有壳体的压力条目，本层也明确不写 `under: pressure`。降级一说的
 *    "几十 kPa"是设计口径，不是被校验的量 —— 它现在只是一句注释。
 *  · 砖衬寿命：模型没有"砖被还原掉多少 / 多少运行小时"这类刻度，
 *    所以只写得出"是消耗件"，写不出更换周期。`Component.wear` 用不上 —— 砖衬不是
 *    装上去能拆下来的零件，它是砌体。
 *  · 单件质量：壳体没有 `mass`，所以下面的 kg 数字挂在**路线**上（按几何假设算的，
 *    算式写在路线注释里），不挂在零件上。哪天壳体有了质量条目，`mass_mismatch`
 *    会拿这条路线的投料去对，那时改这一处就够。
 *  · 烘干：砖砌体第一次升温要慢烘（吸附水、碳酸盐分解），工业上是一条升温曲线；
 *    模型没有升温曲线，只能在 steps 里写一句。
 *  · 型砂：湿砂型循环使用，补给量是**车间级**的（该挂在 `Item.consumption` 上，
 *    按运行小时算），而模型没有"一件铸件占多少造型工时"，所以这条账现在无处记 ——
 *    它没有进 `uses`，也不在下面的 kg 账里。
 */


/**
 * 钣金工位机身 `plant/sheet-shop/frame` 的**第二条来路** —— 不经铣镗床、不经钢板。
 *
 * 这一份是**解锁**用的：先把 frame 从断点表上拿下来，让钣金工位接着往上长。
 * 它不是要替掉原路线 —— 多条路线产出同一个 Item 是 OR，两条并存。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么需要这一条
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 原路线 `make/sheet-frame`（data/machine/tools.ts）把 `plant/milling-machine`
 * 写在 needs 里，而铣镗床在这一层自己还没长出来：它的主轴要 40Cr、进给丝杠
 * 要 45 钢，两种钢的路线都挂着 `plant/radiator` —— 散热器整机不在种子里。
 * 于是这条链停住：
 *
 *   钣金工位 ← 它的机身 ← 铣镗床 ← 主轴（40Cr）/ 进给丝杠（45 钢）← 散热器
 *
 * 严格算术（tools/report.ts 的"口径 B：设备也算在内"）只长到 48 / 473 项
 * （写这一条时的数），frame 就在剩下那 425 项里。把铣镗床从前提里拿掉之后，
 * 四台设备全是种子里已有的：熔炼炉、机器人、车床、磨床；材料只要 HT250 一种
 * （铁 970 + 碳 30，见 data/material/chain.ts 的 `make/iron-ht250`，执行者
 * 也是熔炼炉）。
 *
 * 用的不是新办法，是本层一直用的那一招：**车床带铣头**。锻炉砧座
 * （`make/forge-anvil`）、绕线机机架（`make/winder-frame`）、铣床工作台的
 * T 型槽（`make/mill-table`）都是这么写的 —— 车床上唯一能走直线的进给是溜板，
 * 而铣一个平面正好只要一条直线。代价种子里那句注释已经说清：
 *
 *   "车床带铣头也能凑，但刚性与精度都不够"（data/machine/lathe.ts）
 *
 * 这条路线的结合面就落在这句话里：**够把机器造出来，不够把机器造准。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 两处降级
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① 刚性：铸铁代钢板
 *
 *    现实的折弯机机身是钢板焊接的；焊不了是因为冷轧板要轧机，而轧机还没建
 *    （data/machine/tools.ts 的 SHEET_PARTS）。铸铁不要轧机，熔炼炉能浇 ——
 *    这一处原路线就选对了，这一条不改，但代价要写在这里：
 *
 *      · HT250 的"250"就是它的最低抗拉强度（MPa），比结构钢低一档。同样承载
 *        要更厚的壁，而铸铁密度 7.2 只比钢的 7.85 低 8%（0.65 / 7.85 = 8.3%）——
 *        壁厚补上去，机架只会更重，不会更轻。
 *      · 米级件的砂型铸造，壁厚均匀性与砂芯定位都难控，收缩与变形靠留大余量
 *        补；余量又反过来吃掉材料与刚性。
 *      · 换来的是吸振：片状石墨把振动吃掉，机床底座一直用铸铁就是这个理由。
 *        折弯时的回弹靠补偿，不靠机身硬抗。
 *
 * ② 精度：平面度靠三级递减，最后一级是手
 *
 *      粗    车床花盘上装铣头（第 5 段）   出形状，不出平面度
 *      半精  导轨磨磨面（第 6 段）         平面度的真正出处，基准是磨床台面
 *      精    配刮（第 7 段）               涂色对研、见亮点刮去，出接触斑点
 *
 *    第三级本该有一块**研磨平板**（`plant/comparator/lapping-plate`：三块两两
 *    对研，不需要任何平的基准就能把自己磨平 —— data/machine/comparator.ts）。
 *    **本层没有它**：平板要 1 kg 熔融氧化铝，刚玉要电弧炉 2000–2200 °C，氧化铝
 *    要酸法提铝那整条链（`plant/acid-plant` + 加压浸出）。显色剂（红丹 = 氧化
 *    铁粉 + 油，见 data/machine/stamping-die.ts）同样没有条目。
 *
 *    所以刮研的基准只能退到"磨床台面级"：接触斑点看得见，微米级平面度没有。
 *    这是**现在没有**，不是那时没有（CONVENTIONS 第 16 条）。它不影响这条路能
 *    不能走通，只影响走到多准 —— 等平板长出来，把它加进 needs 即可，路线本身
 *    不必重写。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四处写法要交代
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * · `needs` 空着，是**故意的**。平板与锉刀在本层都够不着（平板见上一节；锉刀
 *   `std/file-general` 的路线要轴承钢与电阻炉、锻炉），而四台执行设备已经在
 *   `steps` 里点名，再写一遍就是 `redundant_need`。手用工具是**缺口**，记在
 *   注释里，不记进 needs 冒充前提 —— 判据能跑出来：把平板写进 needs，frame
 *   在严格算术里就仍然不可达。
 *
 * · 只写 `steps`，不写路线级 `performedBy`：这是四台设备接力（熔炼炉 → 机器人
 *   → 车床 → 磨床 → 机器人），CONVENTIONS 第 19 条。
 *
 * · 不写 `unbalanced_zh`：产出按件计（`unit: '件'`，条目没有 mass），kg 进 kg 出
 *   的账在模型里不成立 —— 校验只在产出全部以 kg 计时才算质量，这里不进那张表。
 *   `q(1)` 是**配比**口径，与 data/machine/tools.ts 那十一条"1 kg → 1 件"的路线
 *   一致：证明拓扑，不证明量。给一台米级机架写一个 kg 数才是编的。
 *
 * · 型砂、涂料、浇冒口的损耗都不进 `uses` —— 铸铁件路线一律只写 HT250 一种料
 *   （`make/forge-anvil`、`make/mill-bed` 也是这样）。加工余量与浇冒口模型表达
 *   不了，这是**既有的缺口**（data/machine/lathe.ts 写过同一句话），不是这条
 *   路线新增的。
 */


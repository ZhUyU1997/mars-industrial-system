/**
 * Bosch 反应器催化剂（`plant/bosch-reactor/catalyst`）的**第二条路线** —— 铁刨花床。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 这一条补的是哪面墙
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 原路线 `make/bosch-catalyst`（data/material/entry.ts）是**氧化铝载体浸硝酸镍 →
 * 干燥 → 焙烧 → 还原**，材料 `mat/nickel` + `mat/refractory`，设备 `plant/kiln`。
 * 卡住的是第一样：镍从风化层 30 ppm 量级选到 25% 精矿是**八千倍富集**、再从精矿
 * 电解精炼，那条环要电解槽、要电极、要电 —— 也就是要设备。另一条更要紧：
 * 镍是 Bosch 五件零件里**唯一一件"缺的是一种被点名的金属"**的，其余四件缺的是
 * 材料与工序（见 data/machine/unblock-bosch-shell.ts 的清单）。
 *
 * 所以这里回答一个问题：**没有镍，Bosch 反应还做不做？**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 镍在 Bosch 里干的是什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * CO₂ + 2H₂ → C + 2H₂O，500–700 °C。热力学上这一段在几十度就"该"发生，所以镍不是
 * 提供推动力，是提供**一条把 CO₂ 拆开的路径**：
 *
 *   ① 把 CO₂ 解离吸附在金属表面（C–O 键在金属上比在气相里便宜得多）
 *   ② 让氢以原子的形式过来把氧带走
 *   ③ 把碳留在表面上 —— 也就是**产物堆在催化剂上**
 *
 * 第 ③ 步是这台设备的全部麻烦：碳是固体，它不离开床层。镍之所以胜任，是因为
 * 镍上的碳不往金属里长、也不与金属成化合物，它堆在颗粒之间的空隙里，硬颗粒之间
 * 不粘连 —— 所以 `plant/bosch-reactor/carbon-removal` 那根螺旋刮得动它。
 *
 * 换句话说：**镍做的三件事里，前两件别的金属也能做，第三件是镍独有的。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 没有镍的时候，历史用的是铁
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 这不是退而求其次的发明，是工业催化的第一种金属：
 *
 *   1913  合成氨（Haber-Bosch）   熔磁铁矿 + 助剂，破碎成 1–3 mm，氢气里还原成多孔铁
 *   350–450 高温变换（CO + H₂O）   Fe₂O₃-Cr₂O₃
 *
 * 两处都是铁，而且两处都靠同一个办法保住铁的**金属态**：**氢大过量**。合成氨的
 * 合成气是 H₂ : N₂ = 3 : 1，不是化学计量的比例 —— 氢压高，铁才不被氧化。这条路线
 * 用的是同一招，量的差别写在降级四里。
 *
 * 铁刨花（车床上的连续卷屑，钢丝棉式的）是铁在这个体系里**唯一不靠新工序**的形状：
 * 它不要求雾化、不要求球磨铸铁丸的模具、不要求羰基铁。一台车床就能把铁变成
 * "每公斤几平方米"的床层 —— 而这条路线全部降级都源于这一句。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 尺寸与 kg 账：每个数都是算的，假设写在括号里
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 床腔按壳体的 φ500 取（data/material/entry.ts 的壳体路线写着"装得下 φ500 的
 * 催化剂床"，本文件与它对齐，不另立尺寸）。篮外径 φ480、壁 8 mm、长 900，
 * 与 φ500 床腔径向各留 10 mm —— 那个 10 mm 不是装配余量，是留给灰铸铁"生长"的，
 * 见降级三。
 *
 *   篮内腔   V = π × 0.232² × 0.9 = 0.152 m³ = 152 L
 *   铁刨花   压装密度 0.48 kg/L（松散刨花堆密度 0.2–0.3，压到 0.48 是床层的要求：
 *            再松就沟流），占 124 L → **60 kg**
 *   耐火碎粒 堆密度 1.6 kg/L，占 28 L → **45 kg**（体积比 81 : 19，装成四层刨花
 *            配一层碎粒）
 *   床总重   105 kg
 *
 *   篮体（HT200，缝用砂芯铸出，只车配合面）
 *     筒壁     π × 0.472 × 0.9 × 0.008  = 0.0107 m³
 *     底板     π × 0.232² × 0.012       = 0.0020 m³
 *     上端法兰 π × (0.248² − 0.232²) × 0.016 = 0.0004 m³
 *     合计 0.0131 m³ × 7.2 t/m³ = 94 kg → 取 **100 kg**（吊耳、两道内隔板）
 *   炉次      一炉 **135 kg 铁水**，收得率 74%，浇冒口 35 kg 回炉重熔
 *
 *   进 66 铁 + 135 HT200 + 45 耐火料 + 8 石灰 + 60 水 = **314 kg**
 *   出 60 刨花 + 100 篮 + 45 碎粒 = **205 kg**（1 件）
 *   余 109 kg = 残芯（夹持段车不到）6 ＋ 浇冒口 35（回炉，模型没有回炉条目）
 *              ＋ 石灰 8（随洗液排掉，未登条目）＋ 洗水 60（蒸发，未登条目）
 *
 * ⚠️ 原路线写的是 `mat/nickel` 1 kg + `mat/refractory` 1 kg，那是**配比占位**
 * （一件按 1 起算）。这条路线按真实装填量写，因为整条论证挂在"面积差多少倍"上，
 * 而 1 kg 铁刨花只给 5–10 m²，比不出来。同理，壳体那条也把 1 kg 换成了 1000 kg。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四处降级
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 【降级一 · 活性面】这是全部问题的根。
 *
 * 镍床的面积来自**化学**：浸渍的硝酸镍焙烧还原成 20 nm 量级的晶粒，按纤维/球的
 * 几何算比表面 4/(d·ρ) = 4/(2×10⁻⁸ × 8900) ≈ **2.2×10⁴ m²/kg** —— 1 kg 镍就是
 * 两公顷多的活性面。铁刨花的面积只能来自**几何**：丝径 0.05–0.1 mm，
 * 4/(d·ρ) ≈ **5–10 m²/kg**。
 *
 *   镍  1 kg      → 2.2×10⁴ m²
 *   铁  60 kg     → 300–600 m²
 *   差 40–70 倍（按金属质量算差 2000–4000 倍；只是篮子里塞了 60 倍的金属）
 *
 * 补不回来的那部分，靠三件事各补一点：
 *   床装到满     床腔 152 L 里 105 kg，已经是 φ500 的极限，再多就吹不动
 *   温度顶到高段  600 → 700 °C，Ea ≈ 80 kJ/mol 时速率 ×3（exp(80000/8.314 × (1/873 − 1/973)) = 3.1）
 *   氢过量       这是为降级四保命的，代价是 CO₂ 被稀释到 1/2.5，速率再乘 0.4
 *
 * 净下来：面积 1/40–70 × 温度 3 × 分压 0.4 ≈ **1/30–60**，取量级 **1/50**。
 * 也就是说：同一台壳体，铁床的产碳能力是镍床的五十分之一。**这不是"差不多能用"，
 * 这是"能用，但慢五十倍"** —— 而火星上第一件催化剂本来就该是这个样子。
 *
 * 【降级二 · 积碳 = 堵床，不是"磨损"】
 *
 * 镍床上的碳堆在颗粒之间，颗粒是硬的、不粘连，螺旋刮得走，所以那台设备的设计是
 * **连续卸碳**（`plant/bosch-reactor/carbon-removal`）。铁刨花上积的碳不一样：
 * 碳在铁的表面上成核、沿着丝长，把两根丝焊在一起 —— 十几公斤碳之后，整床就是
 * **一块**，螺旋刮的是它的表面，刮不动它本身。于是这条路线把"连续卸碳"降级成
 * **批次抽床**：停机、拆法兰、把篮子抽出来、机械刮碳或直接换床、装回、重新开车。
 *
 * 一次能带多少碳，是可算的：碳层 20 µm 就够把纤维之间的空隙堵掉一半（间隙与丝径
 * 同量级），300–600 m² × 20 µm = 6–12 L，按烟炱密度 1.15 kg/L → **7–14 kg 碳**。
 * 所以：**每 7–14 kg 碳抽一次床**。
 *
 * 由此得到这条路线真正的单耗（不是钱，是铁与停机）：
 *   刨花  60 kg ÷ 7–14 kg 碳    = 4–9 kg 铁 / kg 碳
 *   篮体  100 kg ÷ (2–3 次换床) = 每 14–42 kg 碳一具 → 2–7 kg 铁 / kg 碳
 *   合计  ≈ 6–16 kg 铁 / kg 碳
 * 比镍差多少？模型里比不出来（镍床也是 1 kg 一件，没有寿命刻度）—— 能比的是机制：
 * 镍床的碳是"被刮走的"，铁床的碳是"把床带走的"。
 *
 * 【降级三 · 高温结构退化：刨花烧结，篮子长大】
 *
 *   ① 铁刨花在 650–700 自扩散快得不像话：丝与丝接触处烧结成颈，表面积**永久**
 *      损失（不是可逆的"结焦"，是冶金结合）。所以开车第一炉之后，床的活性面就比
 *      新床低一截，而且再也回不来 —— 这也是为什么高温段只能"顶到 700"而不能更高：
 *      750 以上烧结速率再快一个量级，床撑不过一次换料周期。
 *   ② 灰铸铁篮体在 700 °C 的氢气里会**生长**：石墨片被氢与残余氧沿片间侵蚀，
 *      体积涨 3–10%，同时表层脱碳成海绵铁、变脆。篮子是薄壁带缝件，长 3% 就是
 *      直径涨 14 mm —— 所以止口留的是 10 mm 而不是 1 mm 的配合间隙，
 *      而且**篮子本身就是易损件**：2–3 次换床之后跟着床一起报废。
 *
 * 【降级四 · 铁会被自己的产物氧化，而且选择性差】
 *
 * Bosch 的出气是 2 份水对 1 份碳。铁在 H₂O 里不稳定的门槛算得出来：
 *
 *   Fe + H₂O ⇌ FeO + H₂，600 °C 时 ΔG°f(FeO) ≈ −180、ΔG°f(H₂O) ≈ −192 kJ/mol
 *   → ΔG° ≈ +12 kJ/mol，K = p(H₂)/p(H₂O) ≈ exp(−12000/(8.314 × 873)) ≈ 0.2
 *   → **H₂O/H₂ > 5 时铁被氧化成 FeO**
 *
 * 按化学计量 H₂ : CO₂ = 2 : 1 进料，出口氢被吃干、H₂O/H₂ → ∞ —— 铁必然氧化。
 * 所以进料必须 **H₂ : CO₂ ≥ 5 : 1**：CO₂ 全转化时出口 H₂O/H₂ = 2/3 ≈ 0.67，
 * 离 5 还有 7 倍裕量，铁保住金属态（合成氨的 3 : 1 是同一个道理）。
 *
 * 代价三项：循环气量涨到 2.5 倍（5/2）；单程 CO₂ 转化率被稀释压低；以及铁本身的
 * 副反应 —— 它同时催化逆水煤气变换（CO₂ + H₂ → CO + H₂O）与 CO 加氢到 CH₄，
 * 于是产物里除了碳还有一氧化碳与甲烷，**碳的选择性掉一档**。镍在这两件事上干净
 * 得多，这也是当初选镍而不选铁的理由。
 *
 * 还有一处是"铁不像镍"的地方，写在这里而不藏起来：铁在含碳气氛里先渗碳成 Fe₃C，
 * 真正的活性面是**碳化铁**，它在"渗碳—脱碳"之间来回走。所以这条床的额定状态不是
 * 金属铁，是碳化到某一程度的铁，**开车头几炉要按废料算**（那几炉的碳算试车）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么载体从"载体"降级成"间隔物"
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 原路线里的 `mat/refractory` 是**载体**：氧化铝的多孔骨架把镍分散成 20 nm 的晶粒，
 * 载体自己不出催化作用，它的全部价值是"把金属摊开"。这条路线的耐火碎粒没有这个
 * 功能 —— 铁刨花是宏观的丝，碎粒摊不开它。它剩下两个用处，都不是催化剂：
 *
 *   ① 间隔物：把刨花层隔开，挡住烧结成坨（降级三 ①），也让碳堵床堵得慢一点
 *   ② 抗沟流：碎粒填在刨花团的缝隙里，气被迫穿过床层而不是沿壁走
 *
 * 所以 45 kg 碎粒是**结构性材料**，不是载体。这也是为什么不用 `mat/alumina`：
 * 铝质球在这里一样只是间隔物（铁摊不开，球也摊不开它），而 `mat/alumina` 在严格
 * 算术里到不了 —— 电解铝要冰晶石与电解槽（同一个判断写在 unblock-bosch-shell.ts
 * 的降级三末尾）。用耐火料碎粒，等于用本层真有的东西。
 *
 * 为什么耐火料里也不挑"高铝"：碎粒在这里不承担温度（床温由壳体的加热夹套维持，
 * 耐火料只要不软、不与铁反应）。风化层耐火黏土砖与高铝砖在这件事上一样。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么不开在 brick-kiln / 为什么不用 steel-45
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 砖窑（1300–1500）这条路线用不上：它不烧砖、不烧耐火料（碎粒用现成的耐火料破的），
 * 唯一的高温需求是焙烧除油 500–600 与浇注 1350–1450。前者土窑就够；后者虽然在砖窑
 * 的区间里，但砖窑**只能烧件、不能化铁**（没有坩埚，也没有出铁口），化铁是熔化炉的活。
 * 让砖窑空转一次，只是把一台窑的寿命摊到一件催化剂上。
 *
 * 刨花为什么用 `mat/iron` 而不是 `mat/steel-45`：`mat/iron` 含碳 < 0.1%（见
 * data/material/chain.ts 的条目注释），车出来是**连续长卷屑**，正是钢丝棉的形状，
 * 丝径可控、能压装。45 钢含碳 0.45%，淬硬倾向大、车屑更硬更脆，而且它要
 * 1550–1650 的炉次 —— 比铸铁高两百多度。这里要的是
 * **软的、纯的、能车成丝的铁**，不是强度。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 已知缺口
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  · 换床周期写不进模型。它本该是 `plant/bosch-reactor` 的 `composedOf` 里
 *    催化剂那一条的 `wear`（每 7–14 kg 碳换一次 ≈ 绑运行小时），但那条在
 *    data/material/entry.ts —— 本轮只新建这一个文件，所以周期只写在注释里。
 *    这也是本文件唯一一处"模型能表达、却还没表达"的东西。
 *  · 产能（kg 碳 / 批次）在模型里没有刻度，所以 1/50 那个数与"每 7–14 kg 碳抽一次床"
 *    都只能当注释，不能当断言（数字要能核，核不了的要标清是估的）。
 *  · 面积能从化学来，但这条路线没走：把刨花焙烧成 Fe₃O₄ 再用氢气还原，能长出
 *    10–20 m²/g 的多孔铁 —— 这正是 1913 年那炉催化剂的做法。本层的还原炉
 *    （`plant/reduction-furnace`，650–900）做得到，缺的是"受控氧化"那一遍工序，
 *    而它比这条路线多一道炉次。**这是可选改进，不是这条路线的一部分。**
 *  · 沟流与局部热点：装填不均会让气沿一条沟走，那里温度冲高、烧结更快。模型没有
 *    "床层均匀性"这个量，只能在最后一道工序里写一句压降检查。
 *  · 篮体与壳体的配合间隙在模型里没有条目（没有公差、没有间隙），10 mm 只写在
 *    工序注释与 `needs` 的量块说明里。
 *  · 惰性化与报废：换下来的床带碳带铁，本层没有"废料"这一类条目（`mat/slag` 是
 *    造渣的渣，不是废催化剂），所以这条账没有出口。
 */


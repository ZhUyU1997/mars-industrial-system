/**
 * 极板组（槽体）的第二条来路 —— 不用薄钢板，也不用钣金工位。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么需要这一条
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 电解槽只差一个零件就开不了工，而那个零件差两样设备：
 *
 *   make/electrolyzer-cell-stack   钢板 1 kg  ← 冷轧薄板 ← 轧机
 *                                  performedBy: plant/sheet-shop ← 自己的机架
 *
 * 两样都是"还没有"的设备。严格算术（`tools/report.ts` 那一节：从种子与火星料
 * 出发、设备也算在内）从这七台往外长，473 个条目里长出不到五十条，而电解槽
 * 一开步就停在这个零件上：`plant/electrolyzer ← plant/electrolyzer/cell-stack`。
 * 它又是全厂氢与氧的唯一来源 —— 槽体不出来，整条还原链一起停。
 *
 * 要绕开的是**薄板 + 剪切折弯**这套工艺，不是钢本身：钢换一种形态来
 * （HT200 铸铁，从**浇注**来而不是从**轧制**来），形状换一种做法来
 * （陶质砖，从**烧结**来而不是从**焊**来）。两样都是更老的工艺 ——
 * 早于轧机，也早于焊机。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 判据：这条路线上的每一件料，今天都要算得出来
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 替代路线最容易写成"纸上也能造"：料写得很讲究，可那些料自己还在别的
 * 断点上，于是路线写完了，断点一个也没少。所以这里的判据是硬的 ——
 * 只用**严格算术今天已经能长出来的料**：
 *
 *   尾矿 / 炉渣  硅铝质骨料。尾矿走 make/free-iron-gravity（机器人做重力选），
 *                炉渣是 make/iron 的脉石，水淬后当熟料骨料（高炉渣作骨料是先例）
 *   石灰         make/lime-gypsum，石膏在砖窑 1300–1400 里分解出 CaO
 *   水           make/salt：卤水晒盐联产的水（1000 卤水出 264 盐 + 736 水），
 *                靠火星低压与昼夜温差自然蒸发，不要设备
 *   HT200        make/iron-ht200：铁 966 + 碳 34，熔化炉 1350–1450 化开
 *   铜           make/copper-cement：胆铜法，硫酸浸出 + 铁置换，机器人做
 *   硫酸         make/sulfuric-acid-wet：SO₂ + 氧 + 水 + 铁，砖砌吸收池 + 陶管喷淋
 *
 * 最后一行值得单独看一眼：**这条路线要用的硫酸，本身就是砖砌池子里做出来的。**
 * 砖在这套体系里早就不是"只有土窑那一层身份"，它是化工的容器材料 ——
 * 这条槽体只是把它用在更靠前的一步。
 *
 * 反过来，四样**故意不用**的料，正好是今天还算不出来的四样：
 *
 *   耐火砖 mat/refractory   要高铝料 + 工业窑 1300–1600 + 散热器 —— 现在没有
 *   氧化铝 mat/alumina      要酸厂加压浸出（60–200 °C、100–500 kPa）—— 现在没有
 *   硅石   mat/silica       要选矿 plant/ore-beneficiary —— 现在没有
 *   烧碱   mat/naoh         要电解槽自己 —— 与这条路线的产出互为前提
 *
 * 写成"等耐火砖有了再砌"当然更好看，但那样这条路线的存在意义就没有了：
 * 它要解的正是"耐火砖还没有时，电解槽能不能有槽体"。低配版的代价写在下面。
 *
 * ⚠️ 一处化学上的纠正：这条槽**不能用耐酸砖**。
 *
 * 槽液是 KOH，碱性。而"耐酸"这个性能本身就来自高硅质 —— 恰恰 SiO₂ 是碱的
 * 猎物：SiO₂ + 2KOH → K₂SiO₃ + H₂O，60–90 °C 下不慢（玻璃被碱蚀就是这条）。
 * 耐酸砖泡在碱里，比普通陶砖烂得更快。
 *
 * 所以砖料要往**钙铝硅**那边偏：石灰把游离硅石转成钙硅酸盐与钙长石
 * （CaO·Al₂O₃·2SiO₂ 一类），游离硅石越少，耐碱性越好。这条路线的砖
 * 是按这个配的，不是按"耐酸"配的。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 做法（一遍走完）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   尾矿（或炉渣）1000 + 石灰 100 + 水 150 → 砖料
 *   压砖坯 → 阴干 → 砖窑 1300–1400 烧成（玻化，游离硅石变钙硅酸盐）
 *   稀硫酸快速刷洗，去游离铁斑
 *   错缝砌槽壁与隔墙，留极板槽、进出液口与测温孔
 *   HT200 端盖、外箍、底板座（熔化炉 1400–1450 浇注）
 *   车止口与铜排接触面 → 磨砖与铸铁的结合面 → 装配、对研、灌水看渗
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级（比较对象：原路线那条钢板焊接槽）
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① 脆 —— 陶瓷不承拉也不承弯，裂是"裂成几块"，不是"鼓个包"。所以
 *      不做整体大件，做**分块砖 + 铸铁外箍**：箍把砖体预紧成一体，端盖
 *      从两头压住。代价是砖缝成了先天弱面 —— 预紧扭矩不均，开口就在缝上。
 *
 *   ② 膨胀差 —— 陶质砖 α ≈ 5×10⁻⁶/K，铸铁 α ≈ 11×10⁻⁶/K。运行窗口
 *      10–90 °C，从 20 °C 装配态升到 90 °C 是 70 K：
 *
 *        (11 − 5)×10⁻⁶ × 70 K = 4.2×10⁻⁴   →  0.9 m 的跨度上差 0.38 mm
 *
 *      铁箍走得比砖快，预紧力在热态下松掉。所以每次升温后都要复紧，
 *      而这件事在钢板焊接槽上是不存在的（同一种材料，同一个膨胀）。
 *
 *   ③ 密封 —— 没有弹性垫片可写：PTFE 与橡胶两条链都不在这条路线上。
 *      密封只能靠**铸铁端面与砖面各自磨平、对研、压紧**。热循环一次，
 *      砖与铁的回弹不同，碱液就顺着法兰缝渗出来。维护动作从"两年检一次
 *      焊缝"变成"看见碱渍就紧一遍螺栓"。
 *
 *   ④ 耐压 —— 砖砌体有气孔、有灰缝，本质上不是压力容器的材料。压力只能
 *      由铸铁壁与端盖承担，砖只做内衬与绝缘。电解槽整机要 50–500 kPa，
 *      这条槽体只能守下限；610 Pa 三相点（水在 0.01 °C 就沸腾）那个问题
 *      **没有被这条路线解决**，见缺口④。
 *
 *   ⑤ 耐碱寿命 —— 钙硅酸盐只是"比游离硅石更耐"，不是"不被碱蚀"。
 *      60–90 °C 的 KOH 里长年泡着，砖面会起一层碱垢、逐层剥落。所以壁要
 *      按"几年一换"设计，不能像钢板槽那样按十几年算。
 *
 *   ⑥ 效率 —— 100 mm 砖壁加内衬把极板间距拉开（电解液欧姆降），导热又差，
 *      槽温更依赖冷却盘管（plant/electrolyzer/cell-cooling）。方向是
 *      "电流效率低一档"，**不写数**：这一档没有出处，写上去就是编。
 *
 *   ⑦ 重量 —— 同容积比钢板槽重 3–4 倍（1000 kg 砖 + 700 kg 铸铁，钢板槽
 *      是几百公斤钢板）。要专门的地基，搬运也不能再靠两个人抬。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 已知缺口
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   ① 酸洗的缓蚀配方没有刻度 —— "去游离铁"与"不咬钙硅酸盐结合相"之间
 *      只有手感：CaO + H₂SO₄ + H₂O → CaSO₄·2H₂O（石膏），固相体积涨近一倍，
 *      泡久了会把砖面顶裂。今天只能写"快速刷洗、随即冲净"。
 *
 *   ② 镁砂衬才是正解，但这层烧不出来 —— mat/magnesia（MgO，熔点 2852 °C）
 *      在本层**已经能长出来**（卤水 → 氢氧化镁 → 600–750 煅烧），对碱液
 *      比钙硅酸盐耐得多。可**死烧镁砂砖要 1600 °C 以上**，砖窑只有
 *      1300–1500，熔化炉能到 1650 但那是化铁的坩埚、不是砌砖的窑。
 *      等 plant/kiln（1200–1750）那条链通了，该换的就是内衬这一种砖。
 *
 *   ③ 砖的吸水率、抗折强度、抗碱侵蚀速率、烧成曲线 —— 一个数都没有。
 *      模型没有这些字段，所以"能用，但不知道能用多久"就是这条路线真实的
 *      样子；反过来，只要写了数，那个数一定是编的。
 *
 *   ④ 压力仍然由整机的承压件回答，不由槽体回答。这条路线不写
 *      `under: pressure` —— 砖砌体给不出一个可核的压力窗口，写上去就是编。
 *
 * ⚠️ 时态：上面"现在没有"的四样都是**现在**没有，
 *    不是那时没有。它们各自卡在哪台设备上，都写着。
 */


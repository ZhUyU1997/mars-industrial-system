/**
 * 火星给什么 —— 自底向上的起点。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 这一份和 data/floor/seed.ts 是同一个问题的两头
 * ═══════════════════════════════════════════════════════════════════
 *
 *   data/floor/mars.ts   行星给的 —— 挖就有，不用造
 *   data/floor/seed.ts   地球带来的 —— 挖不到，也造不出
 *
 * 两者都"没有产出路线"，但不是一回事：
 *   行星给的    没有路线是**事实**，不是待办
 *   地球带来的  没有路线是**判定**：两条路线都撞墙了
 *   其余没有路线的是**待办**：还没推到，由 `unproduced` 列出来
 *
 * 所以只有一类前缀能承担判定：`mars/…` 是行星给的。**地球带来的是"一份清单"，
 * 不是"一种前缀"** —— 清单在 data/floor/seed.ts（`SEED.items`），里面的 id 照常
 * 按"它是什么"命名（`lathe`、`plant/robot`、`std/power-device-general`），不带来源。
 * 不在这两类里、又没有产出路线的，就是还没推导。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 风化层成分
 * ═══════════════════════════════════════════════════════════════════
 *
 *   SiO₂            44–46    玻璃、硅、硅铁、水泥、耐火材料
 *   FeO + Fe₂O₃     17–20    （总铁 ~13–15%）钢铁主干、磁选原料
 *   Al₂O₃           8–10     铝、刚玉磨料、耐火材料
 *   MgO             6–8      镁、镁水泥、耐火材料
 *   CaO             5–7      钙、石膏、助熔剂
 *   SO₃             5–8      （S 2–4%）硫极富裕：硫酸、橡胶硫化
 *   Na₂O + K₂O      2–4      碱金属、玻璃助熔剂、肥料
 *   TiO₂            0.8–1.3  钛、颜料
 *   Cl              0.5–1    高氯酸盐，氯源，有毒性
 *   Cr/Ni/Mn/Zn/Cu  数百–数千 ppm   合金元素
 *
 * 关键矿物相（决定选矿路线）：
 *   铁相    磁铁矿 Fe₃O₄、赤铁矿 Fe₂O₃、钛铁矿 FeTiO₃ —— 可磁选富集，是冶金入口
 *   硅酸盐  斜长石 (Ca,Na)(Al,Si)₄O₈、辉石 (Mg,Fe,Ca)SiO₃、橄榄石 (Mg,Fe)₂SiO₄
 *   硫酸盐  黄钾铁矾 KFe₃(SO₄)₂(OH)₆、石膏 CaSO₄·2H₂O、硫酸镁 MgSO₄
 *   磷酸盐  磷灰石／白磷钙石 Ca₅(PO₄)₃(F,OH) —— 磷的唯一来源
 *   碳酸盐  菱镁矿 MgCO₃、方解石（少量，集中在特定区域）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 火星不给什么 —— 这一半同样重要
 * ═══════════════════════════════════════════════════════════════════
 *
 *   石油、煤、天然气   没有。有机环只能从 CO₂ 与 H₂ 重新合成，最慢的一条
 *   萤石 CaF₂         没有发现。土壤氟 447–833 ppm（三种口径差 17 倍，取法与算式见 unblock-hf.ts 第 315 行），而氟聚合物要它
 *                     ⚠️ "几十 ppm" 是老占位数，与下游对不上（查出三处差 17 倍）：
 *                        mars.ts（本行）几十 ppm · ores.ts 磷灰石路线隐含 833 ppm
 *                        （精矿含氟 2.5%、富集 30:1）· unblock-hf.ts 取 447 ppm（化学计量）
 *                     这个数乘在整条氟链上：50 ppm 要 83.6 万吨风化层（仍通但开不了工），
 *                     833 ppm 只要 3.9 万吨。**该由上游统一；现在三处不一致，记在这里不擅自改。**
 *   稀土               风化层总量约百 ppm，浓集一万倍才够做钕铁硼
 *   钨                 不到 1 ppm。硬质合金只能从地球带
 *   石灰岩、石英砂      几乎只有零散产出，不像地球那样成层
 *
 * 不给的那一份，就是 data/floor/seed.ts 要运的东西 —— 两张单子是同一枚硬币。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 只有六项
 * ═══════════════════════════════════════════════════════════════════
 *
 * 因为行星给的是**大宗物流**，不是零件。风化层不会按组分送到门口：
 * 分选是工业的第一环，属于路线，不属于行星。把 SiO₂ 单独列一个条目，
 * 就等于假装行星已经替你选过矿了。
 *
 * 这六项都没有产出路线，也不该有 —— 它们是地板。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 其中两项还没有下游
 * ═══════════════════════════════════════════════════════════════════
 *
 * 高氯酸盐与卤水目前**没有任何路线用到**：氯链（氯碱、PVC、盐酸）还没写。
 * 它们留在这里是"声明行星有"，不是"已经在用"。
 *
 * 校验不会因为一个东西没人用就报错 —— 只有"产出无销量"看得见，而这两项
 * 连产出都没有。所以这一条只能靠人记住，写在这里就是那个"记住"。
 */


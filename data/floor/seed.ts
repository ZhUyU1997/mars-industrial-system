/**
 * 必要种子 —— 只留最必要的。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 定义：种子是打破自举环的最小集合
 * ═══════════════════════════════════════════════════════════════════
 *
 * 火星上有料、有能量、有机器人，但什么也起不来，因为起步是自指的：
 *
 *   母机环   造机器需要机器 —— 造车床需要车床
 *   磨削环   磨需要磨 —— 砂轮主轴要磨到微米级，而微米级只有磨能出
 *   精度环   量准需要标准 —— 量块只能由量块造出来
 *
 * 环不能自己打开。只能从某一处切断，把切断它的那件东西运过来。
 * 三条环，三件东西：车床、磨床、量块。
 *
 * 还有第四件，不在环上：机器人。它不开环 —— 它是开环的那双手。
 * 它自己也是一环（机器人造机器人），只是项目前提把那一环免掉了。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 筛选：每一项都要回答一句"少了它，第一步停在哪"
 * ═══════════════════════════════════════════════════════════════════
 *
 * 答得出 → 留下。答不出 → 删掉，那是"想要"，不是"必要"。这条判据会把
 * 一份采购清单压成很短的一张：谁都想多运，但多运的每一项都在替火星回答
 * 一个本来该由火星自己回答的问题。
 *
 * 答不出而被删掉的，例如：
 *   加工中心 / 滚齿机          —— 车床能造出来，运它就是替第一次自复制作弊
 *   冶金与化工装置             —— 耐火砖、坩埚、炉体从火星壤来，电力由种子聚变装置供给；
 *                                  装置本身是设备，要能复制
 *   试剂与备件的全家桶         —— 只有撑不住第一轮的那几样才算
 *
 * ⚠️ 磨床一度也在这张名单上，理由是"车床能造出来"。那是错的：车床能造出
 * 磨床的**零件**，造不出磨床的**精度** —— 而磨床存在的全部理由就是精度。
 * 两条环看混了。判断写在下一节。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 精度问题：运来的是天花板，不是起点
 * ═══════════════════════════════════════════════════════════════════
 *
 * 三样运来的东西各管一件，既不可互换，也不互相重复：
 *
 *   车床   给形状。尺寸到 IT6–IT7（十微米级），表面留着刀痕；但它是唯一
 *          能用比它更粗的设备造出来的机床，所以母机环由它打开。
 *   磨床   给精度。表面粗糙度从 Ra 微米级降到 0.1–0.4 µm，主轴径向跳动
 *          压到 1 µm 级。磨不是"更细的一把刀"，是无数磨粒的微切削 ——
 *          车、铣、刨在这条链上都到不了那个尺度，所以磨削环只能由它打开。
 *   量块   给"对"的判据。它什么也不做，它定义什么叫准。
 *
 * 于是"精度问题"的答案是句不太舒服的话：
 *
 *   **精度不会自己长出来。运来的那台磨床就是天花板。**
 *
 * 第二台磨床由第一台磨出来，它的主轴不会比母机更准 —— 一样准，通常差一点。
 * 所以这条链能**复制**，不能**提升**：火星上做出来的每一件东西，精度都在
 * 那台运来的磨床之下。自复制给的是保真，不是更好的东西。想要更准，只有
 * 再运一件更准的 —— 那不是这一层的解法，是另一层的问题。
 *
 * 量块不能省的理由与磨床不同（两条环最容易看混）：
 *   磨床决定*能做到多细*，量块决定*知不知道自己做到了多细*。
 *   只有磨床：磨出来的东西一律"看着挺光"，1 µm 还是 5 µm 没人知道。
 *   只有量块：能量准，但做不细，量的永远是差的那件。
 * 一条管能力，一条管判据；能力推不出判据，判据也推不出能力。
 *
 * 进入种子的：能源 —— 流的来源是设备
 *
 * 前提：能源由一台 ITER 级 D-T 托卡马克提供。聚变装置是设备，所以进清单
 * （`plant/fusion-reactor`）：第一台随清单运来，第二台起必须本地造。
 *
 * 把"能量是流"读成"能量不进清单"是错的。前一件仍然成立：能量是**流**，
 * 不是物 —— 没有质量、不磨损、不要备件，本身也不需要一条产出路线。错的
 * 是后一件：流也要有来源，而来源是**设备**；设备有质量、会磨损、要备件、
 * 要复制，所以必须占清单上的一条。把"不限量"当成免掉来源，等于让全厂的
 * 电从一句前提里长出来 —— 前提没有说电从哪来。
 *
 * "不限量"只表示**可复制扩容**：第一台聚变装置运来之后，第二台、第三台靠
 * 本地链造，不再靠进口；它不表示免费，也不表示没有质量账与零件账。
 * 装置本身的质量、组成件与产出路线由数据回答，本清单只回答"第一台从哪来"。
 *
 * 参考装置取 ITER 级 D-T 托卡马克。公开事实（https://www.iter.org/facts-figures）：
 * 聚变功率 500 MW、注入功率 50 MW、Q ≥ 10、脉冲 400–600 s；整机 23 000 t；
 * 18 个环向场线圈每个约 310 t；中心螺线管 1 000 t；真空室含包层与偏滤器 8 000 t；
 * 等离子体 830 m³、1.5 亿 °C；Nb₃Sn 股线约 10 万 km、400 t 以上。
 *
 * ITER 不发电，也尚未运行。"它提供能源"是**外推假设**，不是读数：连续运行、
 * 发电模块两项没有实测记录，按假设处理，不当作测量结果。
 *
 * 核原料（D/T）按无限供应处理：本地 D/T 路线只作为能力备份，不构成来源
 * 约束，氚增殖不再是要求。
 *
 * 机器人同样"不限量"，但它进清单，因为它是**物**：会磨、会坏、
 * 关节里的轴承和电机要换。前提给的是数量，不是"火星能造"。
 * 把数量当成来源，清单上就会没有手 —— 而手是唯一一样
 * 三条环都缺不得的东西。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 关于数字
 * ═══════════════════════════════════════════════════════════════════
 *
 * 没有可靠来源的质量，不写。一辆车的重量好猜，一台精密车床的
 * 出厂重量不好猜 —— 猜出来的数字比空着更糟。
 *
 * 代价要说清：磨床比车床重得多 —— 导轨磨要做到米级工作台，整机是车床的
 * 许多倍，运它比运车床贵。但种子的判据是"少了它第一步停在哪"，不是"最轻"。
 * 为省一趟运载而假装精度可以自举，那才是真的贵。
 *
 * 清单上的条目是"第一件必须运来"的东西；其中多数没有产出路线 —— 这正是
 * "种子"的意思：等哪一条自制的路线写出来，它就自动从 `unproduced` 名单里消失
 * （但仍可能留在本清单：第一件与第二件是两件事）。这份清单越短，体系越自立。
 * 条数不写在这里 —— 写死的计数一定会漂，`pnpm check` 的报告里有真数。
 *
 * ⚠️ **判据落在条目上，不落在零件上。** 车床在清单上，它的九个零件不在 ——
 * 零件都有路线。量块同理：那一套在清单上，87 块单块不在
 * （`make/gauge-block-copy` 对着母块复制同级的块，见 data/machine/comparator.ts）。
 * 一句话：**能复制的东西不占种子条目。** 能被复制的是零件，
 * 不能被复制的才是那一套。
 *
 * ⚠️ 三台种子机器现在装了**本地造的标准电机**（`std/motor-7.5kw-4p`）。
 * 这不是写错：种子运来的是床身、主轴、导轨这些造不出来的铁，电机本地能做，
 * 所以按同一套标准件选型 —— **备件统一**，种子机器的电机坏了能直接换本地的。
 * 种子的判据是"少了哪几件第一步就停住"，不是"整机一点不本地"。
 *
 * ⚠️ 机器人是清单上唯一"数量由前提给定"的一条。它和电子元件的区别不是
 * 必然程度（两者原来都按永久外购记），而是粒度：电子元件按 kg 算，是一层材料；
 * 机器人按台算，是一台设备，所以它在 `performedBy` 里出现。
 */


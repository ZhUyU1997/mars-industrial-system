/**
 * at-wavelength（13.5 nm）面形验收的**记录链** —— 把「0.1 nm 是设计值」变成一份可查的验收记录。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 一、这条记录补的是什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   `plant/euv-stepper-hina/atw-interferometer` 早就不是「只有设备」：它有装配
 *   路线 `make/euv-hina-atw-interferometer`（240 h），交 resolution / figure /
 *   roughness **0.1 nm**、aperture **660 mm**。缺的是**记录**：`data/measure/`
 *   里原来只有 `measure/euv-hina-atw-figure`，那一条把「镜子的属性窗口」收窄到
 *   0.1 nm —— 那是**验收判据**，不是**读数**；而 0.1 nm 从头到尾是设计值
 *   （仪器的 gives 也是 0.1–0.1）。没有 `*-record` 条目
 *   就只有 L0，写不了 L3。
 *
 *   本文件补两件，只放 `data/measure/`（R13）：
 *
 *     `mat/atw-figure-record`               验收记录条目（figure / roughness /
 *                                           wavelength / aperture）
 *     `measure/euv-hina-atw-figure-record`  出这份记录的测量路线
 *
 *   数值口径：下面所有数都是**设计值（Earth 工程值）**，不是某一次实测的原始读数；
 *   记录条目里的窗口是「验收读数落在哪」，不是「仪器标称多少」。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 二、怎么做的：双焦 / 横向剪切 + 多组相位重建
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   13.5 nm 上没有能用的透射参考（所有材料 n ≈ 1、k 大，透镜与窗口都不成立），
 *   所以不走可见光那种 Fizeau 透射参考，走**两种自参考构型**再互证：
 *
 *   ① **双焦（two-focal）**：同一面镜在两个焦位各读一幅。参考面的误差与工件的
 *      误差在两组方程里的二次项符号相反 —— 解方程把参考面的球面项扣掉，
 *      残余按 **0.03 nm** 记（设计值，Earth 工程值）。它给的是**绝对**面形，
 *      不是「和参考面比出来的差」。
 *   ② **横向剪切（lateral shearing）**：波前与自己平移后的副本相干。剪切图对
 *      参考面不敏感、对波前斜率敏感，判 astigmatism / coma 这类低级像差，
 *      与双焦**独立**。两条一致才写记录；不一致就不写。
 *   ③ **多组相位重建**：8 帧移相 × **10 组**（每组重新装夹、重新对焦），
 *      组间 1σ = **0.04 nm**（设计值）。随机项按 √N 掉，系统项不掉 —— 所以
 *      不确定度账里 A 类只有 0.04，B 类（标定）才是大头，见第四节。
 *
 *   与可见光那台的差别不是倍数：`plant/ref-flat-interferometer` 的 0.52 nm 是
 *   **裸基板**的读数；13.5 nm 的相位穿透深度落在 50 对 Mo/Si 膜里，镀前镀后是
 *   同一面镜的两个不同物体（`data/measure/euv-hina.ts` 第一节已算过这 5.2 倍）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 三、口径：单幅 φ300，φ300–660 靠子孔径拼接
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   探测器 2001×2001。单幅视场 **φ300**（0.15 mm/px，设计值）：φ660 一幅就是
 *   0.33 mm/px，像方视场与条纹调制都不够 → 拼接。
 *
 *   子孔径 φ300、重叠 30 % → 步距 210 mm；3×3 覆盖
 *   **300 + 2×210 = 720 mm** ≥ 660（留 60 mm 余量）。
 *   拼接残差 **0.05 nm**（台/光栅标定 ⊗ 重叠区拟合，设计值）—— 只进 φ660 那一档。
 *
 *   所以记录的 aperture 写 **300–660**：单幅档到 φ300，拼接档到 φ660；两者共用
 *   同一台仪器、同一套相位重建，只有拼接这一笔不同。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四、不确定度：重复性 + 标定（带数）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   项                                      φ300 单幅   φ660 拼接
 *   ───────────────────────────────────────────────────────────────
 *   A  重复性（10 组重建，组间 1σ）          0.04 nm     0.04 nm
 *   B1 双焦自校准残差（参考面球面项扣掉后）  0.03        0.03
 *   B2 相位刻度 + 探测器非线性               0.02        0.02
 *   B3 支撑/重力翻转平均残差（0°/180° 两次） 0.02        0.02
 *   B4 子孔径拼接残差                        —           0.05
 *   ───────────────────────────────────────────────────────────────
 *   RSS = √ΣB²                              0.057       0.076
 *   U = 2×RSS（k=2，约 95 %）               0.11        0.15
 *   验收门 = 0.10（最好档）+ U               0.21        0.25
 *
 *   → **figure 记录窗口 0.10–0.25 nm**：下界是 IBF 修完那一档的实测（= 设计值
 *     0.10）；上界是 φ660 拼接档的判拒收线 0.25 = 0.10 + 0.15。把 0.25 写成
 *     判据、而不是把 0.10 写成结论，是这份记录与旧注释的全部差别。
 *
 *   ⚠️ **0.25 比镜子的设计窗口 0.15 宽 1.7 倍**（`make/euv-hina-mirror` 交 0–0.15）。
 *     按「实测区间 ⊆ 设计窗口」这条 L3 判据，这份记录把口径证到的是
 *     **0.25**，不是 0.15 —— 也就是说：0.15 那一档由这条验收路线**判不了**，
 *     这是 B 类降级（量具不够，不是镜子不够），升级路线就是缺口①②。
 *     所以「与可见光 0.52 nm 差 5.2 倍」要改读成「差 **2.1–5.2 倍**」：
 *     2.1 = 0.52/0.25（能证到的），5.2 = 0.52/0.10（设计值那一端）。
 *
 *   roughness 是另一本账（13.5 nm 的散射通道，不是接触式轮廓仪）：
 *
 *     TIS = (4πσ/λ)²，λ = 13.5 nm：
 *       σ = 0.08 → **0.55 %**；σ = 0.14 → **1.70 %**；σ = 0.19 → **3.13 %**
 *     镀完 50 对膜的膜面粗糙度按 σ_膜 = √(σ_基底² + σ_界面²)，界面项取 0.12 nm
 *     （设计值，Earth 工程值）：
 *       基底 0.08 → 0.144；基底 0.15 → 0.192 → 取门 **0.20**
 *
 *   → **roughness 记录窗口 0.08–0.20 nm**：0.08 是镀前最好档，0.20 是镀后门限；
 *     设计值 0.1 只在窗口下界这一端成立，不是「镀完还有 0.1」。
 *
 *   ✅ 一个交叉旁证（不冒充反射率读数）：TIS 1.7–3.1 % 把 70 % 的理想反射率压到
 *      **67.8–68.8 %**，正落在 `mirror` 的 68–70 % 窗口里 —— 说明粗糙度这条读数
 *      与反射率窗口不矛盾。反射率本身由 `plant/euv-reflectometer` 的双镜互测
 *      量（`measure/euv-mirror-mutual` 的同一手艺，±0.3 %），**不是**这台干涉仪。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 五、缺口（按 R7 记量级，不写「造不出」）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   ① **拼接残差占 φ660 预算的 43 %**（0.05² / 0.076² = 0.0025 / 0.0058）。
 *      要把整条链压到 0.10 nm，它得 ≤0.03 nm —— 差 **1.7 倍**。
 *   ② **双焦那 0.03 nm 是设计值，没有独立溯源。** 参考面的非球面项在可见光下是
 *      0.52 nm（`plant/ref-flat-interferometer`）；13.5 nm 的三面互检/球面标定
 *      是**一台量具的缺口**（要 φ660 的球面基准 + 三面互检工装），目前唯一的
 *      旁证比 0.03 粗 **17 倍**（0.52 / 0.03）。
 *      所以 0.25 nm 是**自洽**的，不是**可溯源**的：它是 L3 的读数窗口，
 *      不是一条 SI 链的末端。
 *   ③ **粗糙度是 TIS 反推的等效 σ**：TIS ±30 % → σ ±14 %；它假设单一 σ 的球面
 *      散射，分辨不了 0.1 nm 的周期结构 —— 那要 AFM（0.1 nm 垂直分辨）或
 *      近场光学，是**一台量具的缺口**（R7），不是这一类量测的终止条件。
 *   ④ **反射率只到「镜面中心 φ0.2 光斑、6° 一个角」**（`make/euv-hina-mirror`
 *      的初检步同一口径）；φ660 的面内均匀性要 X/Y 扫描台，而
 *      `plant/euv-reflectometer/sample-stage` 的 50 mm 行程只够「移出光束」
 *      （φ660 的 **7.6 %**）。
 *   ⑤ **周期没有 L3 读数**：它由镀膜工位定（原位 QCM 5 MHz，σ ≈ 0.024 nm，
 *      `make/euv-hina-mirror` 给 6.85–6.95），镀后靠 XRR 的布拉格峰（地球的独立
 *      量具，0.01 nm 档）或反射计的 2θ 峰位（11.9°，0.02° 角分辨 → 0.0005 nm）。
 *      缺的是**一台声明 period 能力的量具 + 一条 XRR 路线**，不是「量不出」。
 */


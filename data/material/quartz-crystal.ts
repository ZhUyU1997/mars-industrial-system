/**
 * 单晶石英 —— 上一节漏掉的一步。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 砂不是晶
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 写"石英谐振器：切晶 → 磨到 28 µm"，像是从一块石英上切下来的。
 * 但本层的 `mat/quartz-pure` 是**提纯的石英砂**（多晶粉末，用于坩埚），
 * 它没有压电性 —— **谐振器要的是单晶**，而且要有取向。
 *
 * 单晶石英只有两条来路：
 *
 *   天然水晶   挖出来就是单晶 —— 火星没有这种矿（有硅质沉积，没有水晶）
 *   水热法合成 **石英砂溶进碱液，在籽晶上重新长成单晶** —— 工业上 90% 的石英这么来
 *
 * 所以这一节补的是水热法。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 水热法：把一个"溶解—输运—结晶"的过程关进钢罐
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   底部   石英砂（营养料）+ 氢氧化钠溶液，350–400 °C 溶解
 *   中部   挡板（对流分隔）：热端上升、冷端下降
 *   顶部   籽晶挂在冷端（约低 30–50 °C），溶质在这里过饱和、长到籽晶上
 *   周期   30–60 天，长成 1–3 kg 的晶体
 *
 * 溶剂是碱：石英在纯水里几乎不溶，在 NaOH 里才溶得动 —— 这也是为什么
 * 长出来的晶体要**长时间冲洗**，否则残留的钠就是后面器件的污染源。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 两处硬降级
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **压力不够**：工业水热法 100–150 MPa，而本层高压釜只有 35 MPa。
 *    低压力下溶解度低、输运慢 —— 晶体长得慢、缺陷多，Q 值低一档。
 *    这一条与"轴承氧含量压不到 10 ppm"同类：**做得出，但差一个档。**
 *
 * ② **籽晶**：第一块籽晶只能带（天然水晶切一片）。这是本层又一个"环的入口"，
 *    与第一根硅芯、第一台绕线机同型 —— **环的入口是手艺或运来的那一块，不是设备。**
 *
 * 还有一件模型表示不了的：**30–60 天**。这层没有时间维度，所以"一批要两个月"
 * 这件事只能写在注释里。
 */


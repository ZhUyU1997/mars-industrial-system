/**
 * 电子元件 —— 这一层里唯一"永远从地球来"的东西。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么把它拆成四类
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 原来只有一个条目 `mat/electronics`（那时叫 `seed/electronics`），含义是
 * "几十公斤电子元件"。**太粗了** —— 因为不同路线要的是完全不同的东西：
 *
 *   中频电源   要功率器件 + 电容 + 控制板
 *   整流器     要功率器件 + 触发板
 *   焊机       只要功率器件
 *   绕线机控制  要功率器件 + 计数器
 *   **伺服电机   只要编码器**（功率级在控制柜里，不在电机上）
 *   **控制柜     要驱动器 + 电源 + 接口板**
 *
 * 一个总数掩盖了这件事：机器人的关节能不能定位，取决于**传感器**这一路有没有，
 * 而不是"有没有电子元件"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 单位为什么是件，不是 kg
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 一只晶闸管、一块控制板、一只编码器 —— 这些东西按只数，不按称。
 * 上一版写 `unit: 'kg'` 是图省事：kg 至少可加，不用编件数。**但那是编出来的
 * 另一头**：谁也不知道一块控制板多重，写 1 kg 与写 1 件的凭据一样少，
 * 而写 kg 还多了一句假话 —— 说它是按重量计量的。
 *
 * 所以按**件**记。数量没有依据时用 1:1 占位（数字要能核的同一做法），
 * 但单位必须说对：它回答"几个"，不回答"多重"。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 类别为什么是零件，前缀为什么是 std/-general
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 它们是**装上去的成品件**（坏了能换下来），不是被加工成别的形状的原料 ——
 * 所以 `category: 'part'`，不是 `material`。
 *
 * 前缀走 `std/`：它们不属于某一台机器，是共用件。
 * 规格段写 `general`，与 `std/bearing-general-p0` 的 `general` 同义：
 * **这一类按功能买，不指定型号。** 型号在这一层不存在 —— 我们只知道要一只
 * 编码器，不知道是哪个厂家的哪一种；写一个型号就是编。
 *
 * ⚠️ 这是模型的让步，不是数据的自由：`std_without_spec` 要求名字里带规格段，
 * 而这四类真没有规格可写。`-general` 是"规格就是这一档"的写法。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 没有路线，但可以逐条退出
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 半导体链不在这个体系里长出来，一行也没有 —— 所以这四条是**种子**
 * （`data/floor/seed.ts` 的清单里），不是"还没推到的待办"。
 *
 * 拆开的好处是可以**逐条退出**：无源件（电阻、电容、继电器）不需要单晶硅，
 * 有拉丝、绕线、烧结就能做 —— 哪天真造出来了，只把那一类从清单上拿掉。
 * 一个总数做不到这件事。
 *
 * **无源件那一条已经开始走了**：镍铬电阻丝有路线了，见 data/material/passive.ts。
 * 那是这一档的第一块砖（电阻、电炉、加热器的共同起点）；四类本身仍是种子，
 * 因为"类别"没有能自造，只是它的最底层有了一块。判据是"有没有产出路线"。
 */


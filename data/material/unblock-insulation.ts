/**
 * 玻璃布槽绝缘 —— 电机不用酚醛树脂的那一条来路。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 一、这一条补的是哪面墙
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 电机的铁芯路线要酚醛树脂两次：一次做**槽绝缘**
 * （`data/machine/iron-core-motor.ts` 的 `make/motor-stator-ironcore`，`uses` 里
 * 那一条 `mat/phenolic-resin`），一次做**浸漆**（同一条的 `steps`，与
 * `data/machine/motor.ts` 的 `make/motor-windings`，都落在土窑 400–450 那一格）。
 *
 * 而酚醛是一条长链，每一段的数都在 `data/material/aromatics.ts` 里：
 *
 *   酚醛树脂 1000  ← 苯酚 887 + 甲醛 283             make/phenolic-resin
 *   苯酚     1000  ← 氯苯 1196 + 石灰 298 + 水 96    make/phenol（300–400，25–30 MPa）
 *   氯苯     1000  ← 苯 694 + 氯气 630               make/chlorobenzene
 *   氯气           ← 电解食盐水                      氯碱那一卷
 *   苯       1000  ← 乙炔 1000（3C₂H₂ → C₆H₆）       make/benzene（矿热炉 1500–1700）
 *
 * 卡的是最后两环，而且是两处一起卡：氯要电解槽与整流（设备环），苯要乙炔环化
 * （矿热炉 1500–1700）。**"给电机做绝缘"这件事，现在压在一面与绝缘毫无关系的墙上。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 二、判据：把绝缘从"有机化学"搬回"硅酸盐"
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 1890–1930 年代的电机绝缘是云母、石棉、棉纱、纸 —— 酚醛（胶木）反而是后来的。
 * 玻璃纤维进绝缘比它们都晚，但它有一件它们没有的性质：**不依赖有机化学**。
 *
 *   玻璃  = 硅石 + 石灰 + 纯碱，熔了拉成丝         本表：make/glass，1400–1500
 *   酚醛  = 苯 + 氯 → 苯酚 → 缩聚                  要氯碱，要芳烃
 *
 * 前者的料在火星上到处都是（硅酸盐遍地），后者的料一半要电解、一半要刻意合成。
 * 所以这条来路的判据只有一句：**绝缘这一层，能不能只用硅酸盐做出来。**
 *
 * 判据的另一半是它做不到什么：玻璃布替不了漆的**成膜性**。漆是铜线上 5–8% 的
 * 连续薄膜（`make/enamel-wire` 的 60 kg），玻璃布复不了那一层 —— 本文件只解
 * 槽绝缘与"浸漆这一步"，不解漆包线（见缺口①）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 三、工艺：坩埚炉 + 车床卷筒 + 手织机
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ① 重熔   玻璃球料（`mat/glass` 就是球料）在坩埚炉里重熔到 1400–1500。这不是
 *          权宜之计：玻纤工业本来就有"球法"—— 池窑熔成球、运到拉丝车间再重熔，
 *          因为拉丝要的是**一小股稳定的熔体**，不是一池子玻璃。
 *          熔炼炉（感应，holds 1200–1650，见 data/floor/seed.ts）本来就是坩埚炉：
 *          感应圈套在耐火打结的坩子上，那口坩子就是坩埚。
 * ② 降温   玻璃能拉成丝的温度不是熔化温度。钠钙玻璃的软化点是 696 °C，拉丝要的是
 *          黏度 10³ Pa·s 上下 —— 对钠钙玻璃就是 1200–1250。而熔炼炉**做得稳**的
 *          是 1300 以上那一档（炼钢用不到更低，测温锥也是按那一段配的），所以坩子
 *          只能降到 1300–1350：黏度约 10² Pa·s，比理想窗口稀一档 —— 流量大、
 *          丝更粗。这是降级一的一半成因（另一半是卷筒线速度）。
 * ③ 拉丝   坩埚底一个孔（漏嘴）漏下玻璃流，绕在车床带动的 Ø300 卷筒上。
 *          没有拉丝机，没有铂铑漏嘴板（当时铂族金属本层没有；现在 Pt-Rh
 *          合金熔炼已建（`make/pt-rh-gauze-10`），但漏嘴板的成形/打孔仍未建）：孔是耐火打结料上留的，
 *          会越拉越大 —— 这是降级②的一部分。
 * ④ 织带   铸铁机架的手工织带机（火星没有木，机架只能铸铁；也没有上浆机）。
 *          幅宽 100 mm，平纹，粗纱方格布。
 * ⑤ 除湿   土窑 400–450 烘一遍，赶掉纤维表面的吸附水，趁热卷紧、干燥密封。
 *          没有漆，所以**没有浸渍这一步可做** —— 那不是漏写，是这条路线的正身
 *          （见降级④）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四、降级（六处，都带量级）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 【降级一 · 纤维直径 19 µm，工业是 9 µm】
 *   卷筒 Ø300 mm（400 mm 级车床装得下，刀架要让开），主轴 600 r/min：
 *     v = π·D·n/60 = π × 0.3 × 600 / 60 = 9.4 m/s
 *   同一漏嘴流量下 d ∝ v^(−1/2)，而工业细纤维的 9 µm 是 40 m/s 拉出来的：
 *     d = 9 × √(40 / 9.4) = 18.6 ≈ 19 µm
 *   这两个数要一起看：9.4 m/s 是**卷筒**给的，而它还是在 1300–1350 的稀熔体
 *   （10² Pa·s）上跑的 —— 理想窗口（10³ Pa·s）流量小，同一个转速能拉得更细。
 *   两件事叠起来才是 19 µm，也是"要更细只有更快"这句话的全部内容。
 *   后果：同样质量的纱，单丝根数只有细纱的 (19/9)² ≈ 4.5 分之一 —— 纱更粗更硬，
 *   绕包贴不伏；比表面积 ∝ 1/d，只有 47%，而这里没有浸润剂去填纤维之间的空隙。
 *   上限在**车床主轴转速**与**炉子能稳住的低端温度**上，不在玻璃上。
 *
 * 【降级二 · 没有浸润剂：强度保有率 30–45%】
 *   玻璃新生态强度约 3.5 GPa（细纤维），一经摩擦就掉到 1.0–1.5 GPa。工业上那层
 *   浸润剂（淀粉 / PVA / 环氧乳液，占纤维重 0.5–1.5%）干的就是集束、耐磨、
 *   抗静电这三件事。本层三样一样没有：淀粉要农业，PVA 要乙炔 + 醋酸（有机链），
 *   环氧要环氧氯丙烷（又是氯）。所以纱只能靠**捻度**集束（捻度大 → 纱更硬），
 *   布面起毛、断经随时得接。
 *   附带一处，就是那 2% 的账：坩埚按"寿命里蚀掉 1/15"算，一只 300 kg 的坩子摊到
 *   1000 kg 玻璃上正好 20 kg（2%）。它溶进熔体，黏度上去、未熔颗粒变成结石；
 *   **结石处就是断头处** —— 所以那 20 kg 既是投料，也是这一处降级的来源。
 *
 * 【降级三 · 玻璃是钠钙的，不是无碱的】
 *   `make/glass` 是钠钙玻璃：SiO₂ 72 / Na₂O 13 / CaO 11（见 data/material/alkali.ts）。
 *   绝缘纤维用的是 E 玻璃，含碱 <1%。碱金属离子在电场下迁移 —— 吸潮后表面电导高、
 *   介质损耗大、长期电老化快。"低碱"是绝缘子的硬指标，而本层只有这一种玻璃。
 *   量级：含碱 13% 对 <1%，吸潮后的表面电阻率差 1–2 个量级（玻璃成分的常识量级，
 *   本层没有实测）。
 *
 * 【降级四 · 没有漆：B 级掉到 A 级，同尺寸出力 −13%】
 *   耐温等级不是材料耐温。玻璃本身软化点 696 °C（棉、纸到 105 就完了），但
 *   **绝缘结构**的等级由三件事定：气隙、潮气、机械固定。没有漆，槽内纤维之间是空的：
 *     · 130 °C 以上槽内气隙会局放，把纤维表面的吸附水电解掉，纱慢慢"烧成粉"；
 *     · 端部没有漆粘住，振动下纱散开、绝缘磨穿。
 *   所以这条来路按 **A 级（105 °C）** 用，而酚醛浸漆是 B 级（130）。IEC 60034-1
 *   的温升限值（电阻法）是 A 60 K / B 80 K，同尺寸电机出力 ∝ √ΔT：
 *     √(60 / 80) = 0.87  →  **出力掉 13%**
 *   要保住 7.5 kW 就得把机座加大一档，或者短时按 B 级用、拿寿命赌。
 *   这一处是这条来路最贵的地方，不是纤维直径。
 *
 * 【降级五 · 布厚 0.3–0.4 mm，槽满率差约 5%】
 *   手工织出来的是 400 g/m² 的粗纱方格布（4 根/cm、480 tex），干态纤维体积分数
 *   40–45% 时厚度：
 *     t = 0.40 kg/m² ÷ (2500 kg/m³ × 40–45%) = 0.36–0.40 mm
 *   而工业槽绝缘用 0.15–0.25 mm 的细布。7.5 kW 4 极定子的槽宽按 7 mm、两边各一层：
 *     0.25 mm → 铜宽 6.5 mm；0.40 mm → 铜宽 6.2 mm
 *     铜截面少 (6.5 − 6.2) / 6.5 ≈ 4.6% ≈ 5%
 *   更细的布织不出来：22 tex 细纱要在有梭织机上跑 12 根/cm，没有上浆它必断
 *   （降级二）—— 所以"薄"这一档不是工艺选择，是缺浸润剂的下游账单。
 *
 * 【降级六 · 吸潮：绝缘电阻掉两个量级，且不能库存】
 *   玻璃布不吸水，但纤维表面有吸附水膜，而槽内没有漆封孔 —— 潮气直接进去。
 *   量级：绕组绝缘电阻（500 V 兆欧表）从 >100 MΩ 掉到 <1 MΩ（两个量级）；纤维的
 *   表面电阻率从 10¹⁴ Ω 级掉到 10¹⁰ Ω 级（四个量级）。380 V 电机按"每千伏 1 MΩ"
 *   的老口径，1 MΩ 就是不许通电的那条线。
 *   所以这条路线的电机**必须干燥密封存放、开封即装、装完即用**。它不是"差一点"，
 *   是不能长期库存 —— 这是六处降级里唯一影响"什么时候能用"的一条。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 五、账：两条路线都恰好守恒
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   拉丝   玻璃 980 + 耐火料 20 → 纤维 1000
 *     那 20 kg 不是损耗也不是辅料，是**坩埚底孔与炉衬被玻璃蚀掉、溶进熔体的那一部分**
 *     （2%）。它真的进了产品，所以必须写在 `uses` 里 —— 只写在注释里就成了没有账的
 *     物料。断头与料头不进账：它们回到坩埚，等于把同一份玻璃
 *     多走了一遍。
 *
 *   织带   纱 1000 → 布 1000
 *     织造不加料也不减料：没有浸润剂、没有上浆（这正是降级二的因，也是它的果）。
 *     布边与断经的短纱是**回炉**的（玻纤废丝当碎玻璃回坩埚，真实工厂也这么干），
 *     所以净账闭合。若按外排算，布只有 960 kg 上下 —— 那个 4% 是本层没有"废丝"
 *     条目的结果，不是真的丢了。
 *
 *     一个 7.5 kW 4 极定子的槽绝缘用量，顺手算一遍（给接线的人）：
 *       36 槽 × 每槽约 0.1 m 长（槽周 43 mm + 端部 60 mm）÷ 100 mm 幅宽 → 0.36 m²
 *       加相间与层间垫约 0.04 m² → 0.40 m²
 *       0.40 m² × 0.4 kg/m² = 0.16 kg，搭接与损耗按 1.5 倍 → **约 0.25 kg**
 *     （`make/motor-stator-ironcore` 那条线上现在写的是 `mat/phenolic-resin` q(1)，
 *     换过来时该改成 `mat/glass-cloth` q(1, 4)。）
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 六、它接到哪里（**本文件不改任何别的文件**）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   data/machine/iron-core-motor.ts   make/motor-stator-ironcore
 *     `uses`  的 `mat/phenolic-resin`（槽绝缘）→ `mat/glass-cloth`
 *     `steps` 的「浸漆烘干」那一格 → 不再是浸漆，只是除湿（同温区，400–450 照旧）
 *   data/machine/motor.ts             make/motor-windings
 *     `steps` 的「浸漆、烘干」那一格 → 同上
 *   tools/report.ts                   把它 import 进来（那两行 import 的地方）
 *
 * ⚠️ `make/enamel-wire` 的 60 kg 酚醛**不在**这条来路的射程里 —— 那是漆包线的
 * 漆膜，不是槽绝缘。要连它一起解，下一个出口是玻璃丝包线（`mat/glass-covered-wire`），
 * 那是漆包线那一面的活，不是这一份。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 七、已知缺口
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  ① 漆包线的漆膜不在这条来路的射程里。那是铜线上 5–8% 的连续薄膜
 *     （`make/enamel-wire` 的 60 kg 酚醛），要的是成膜性；玻璃布复不了那一层。
 *     下一个出口是玻璃丝包线（`mat/glass-covered-wire`），属于漆包线那一面的活。
 *  ② **这条路线不是把墙拆了，是把氯碱那面墙换成了玻璃那面更薄的墙。** 严格算术里
 *     `mat/glass` 自己也还没到（纯碱要氨与分离，窑的换热器要不锈钢 —— 见
 *     data/machine/unblock-bosch-shell.ts 文件头那份清单）。这一点必须摆在前面，
 *     不能被"不用酚醛了"这句话盖掉。玻璃那面墙薄得多，但它是墙。
 *  ③ 无碱（E）玻璃没写。成分 SiO₂ 60 / CaO 22 / Al₂O₃ 14 / 杂质 4，料三样都在本层
 *     允许表里（`mat/silica`、`mat/lime`、`mat/alumina`），1550–1600 也落在熔炼炉的
 *     1200–1650 里。它卡在**成分账**：`mat/silica` 的 90% 口径、`mat/lime` 与
 *     `mat/alumina` 的纯度口径都不在这份文件里，硬写就是编数。
 *     而它正是降级三（含碱 13%）的解药 —— 下一轮该先写它。
 *  ④ 拉丝机没有。车床带卷筒能转，但**排线**（把纱一层层排匀）与卷筒两端的塌边还是
 *     机器人用手扶 —— 属于第二种情形（前提是设备，手艺部分不值得
 *     单列一条路线）。
 *  ⑤ 织带机没有条目。它是设备（铸铁机架 + 钢筘 + 卷布轴），本层的七台设备里没有
 *     织机；铸造机架的路子（`make/iron-ht250`）已经有了，但把它拆成零件再写一条装配
 *     路线不在这一轮里。所以织造那一步的执行者写机器人（一双手），织机本身是缺口 ——
 *     是情形③，不是情形①。
 *  ⑥ 炉子被挪用作拉丝坩埚：坩埚底要对着炉底开的一个孔（倾转倒料口本来在侧面），
 *     而感应炉的坩子本来是整底的 —— 开这个孔就是在耐火打结层上留一个洞，用一次补
 *     一次。那 20 kg 耐火料一半花在这里，一半是炉衬（碱性镁砂，为炼钢）被酸性玻璃
 *     溶蚀后的补层。这是这台炉子"被挪用"的具体代价，模型里只有一个 `uses` 数字。
 *  ⑦ 电性能没有条目字段：介电常数（钠钙玻璃 6–7）、介质损耗、击穿强度（干态
 *     30–40 kV/mm）在本层没有地方挂。降级里说的电性能只能写在注释里。
 *  ⑧ 400 °C 除湿会把拉丝时冻结的表面压应力放掉一部分，纤维强度掉一到两成（量级估，
 *     本层无实测）。但绝缘的短板不在这里，在降级四的 105 °C 与降级六的潮气。
 *  ⑨ 丝径与布厚的"规格"目前只是注释里的数：本层没有"纤维直径""布厚"这样的条目字段，
 *     也没有检具（千分尺要量块那一套，`plant/gauge-block` 在种子里）。
 */


/**
 * 玻璃丝包线 —— 绕组的一条**不用漆包线、不用酚醛**的来路。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它解开的是哪一个死结
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 电机的定子、转子、绕组三件都卡在同一个条目上：`mat/enamel-wire`。
 * 而它现在的来路（`make/enamel-wire`，data/machine/motor.ts）要三样东西：
 *
 *   酚醛树脂   mat/phenolic-resin —— 酚醛链没通（苯酚 + 甲醛 + 催化剂）
 *   轧机       plant/rolling-mill —— 它自己还在设备链上
 *   烘干       plant/kiln
 *
 * 三样里两样不在闭包里。于是「电机 → 机床的电机 → 机床」这个环，
 * 一个入口都没有。
 *
 * 本文给绕组一条不要漆、不要酚醛、不要轧机的来路：**玻璃丝包线**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它是什么：把棉纱换成玻璃丝
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 绕组线的绝缘层有两种做法，**包线比漆包线老**：
 *
 *   包线（served）     纱线螺旋绕在铜线外面    19 世纪的标准做法（棉纱、丝线）
 *   漆包（enamelled）  漆膜直接烧结在铜上      1900 年代才有
 *
 * 玻璃丝包线就是同一套绕包工艺，把棉纱换成玻璃丝。棉是农产品 —— 火星没有；
 * 玻璃是硅石 + 纯碱 + 石灰，本层有（`make/glass-brick-kiln`）。所以在这颗
 * 行星上「包线」这条路走得通，「棉纱包线」走不通，而「漆包」要等酚醛。
 *
 * ⚠️ 时态要说清（规范第 16 条）：**绕包工艺是 19 世纪的，连续玻璃纤维是
 * 20 世纪的**（工业化要到 1930 年代）。火星上两样都不必从地球带 —— 工艺是
 * 手艺，玻璃是本地料。所以这一条是"这个体系能从本地料自己长出来的那一件"，
 * 不是历史上某一年真的在产的牌号。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 规格与质量账
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   铜线       φ1.00 mm
 *   绕包       两层玻璃纱反向螺旋，每层压扁后约 0.2 mm 厚
 *   成品外径   φ1.40 mm —— 比裸铜粗 40%，比同级漆包线（φ1.08）粗 30%
 *   绝缘等级   名义 B 级 130 °C；不浸漆时只能按 A 级 105 °C 用（降级 ③）
 *
 * 两条路线的账（两个新条目都以 kg 计，所以质量守恒判得动）：
 *
 *   make/copper-wire-drawn    铜 1000 → 裸铜线 1000              1 : 1
 *   make/glass-covered-wire   裸铜线 860 + 玻璃 140 → 包线 1000
 *
 * 两条**都不写 `unbalanced_zh`** —— 它们真的守恒：断头、氧化皮、坩埚残料都
 * 回到各自的炉子里，没有离开这条链。写了反而是给没有的错开豁免。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 五处降级，都能算
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ① **外径多四成，槽里占的面积翻倍。** φ1.00 裸铜 vs φ1.40 包线，同一槽里每根线
 *    占的截面比 = (1.40 / 1.00)² = 1.96；漆包线 2 级漆膜单边约 0.04 mm
 *    （外径 1.08），所以相对漆包线是 (1.40 / 1.08)² = **1.68 倍**。同一只定子的
 *    槽：匝数只剩 1 / 1.68 ≈ **60%**（少 40%）；要保持匝数，槽面积要乘 1.68。
 *    **这是本路径最贵的一笔，而且它落在电机上，不落在绕组线上。**
 *
 * ② **线径一致性靠手。** 手摇卷筒 + 模孔逐道磨损：线径按 ±0.03 mm 记
 *    （工业拉丝机 ±0.005 量级）。没有在线测径仪，只能停机用千分尺抽检，
 *    所以同一批线不同段差 0.02–0.04 mm —— 绕包厚度跟着变，① 的账再打折扣。
 *    只给量级：没有实测，按"手摇 vs 机械"取一档。
 *
 * ③ **没有浸渍漆 —— 耐潮差，这是最要紧的一条。** 玻璃纱之间是空隙（绕包层
 *    压实后约 60% 是玻璃），两层反向绕包的覆盖率按几何算
 *    1 − (1 − 0.75)² ≈ **94%**，剩下 6% 是缝。缝加空隙是一条贯通到铜的毛细
 *    通道：**潮气能直接走到铜上**。工业上的做法从来是"玻璃丝包 + 浸漆"
 *    （漆把缝灌死、把丝粘住）—— 而漆正是本文没有的东西。
 *    后果两条：钠钙玻璃吸水后强度掉一半以上（E 玻璃要 B₂O₃ 5–10%，本层没有
 *    硼）；层间空气在 130 °C 下局部放电。所以 **名义 B 级、实际只能按 A 级
 *    105 °C 用**，且整机必须密封。
 *
 * ④ **拉丝温度是"够热"，不是"正好"。** 钠钙玻璃的拉丝窗口是黏度
 *    10²·⁵–10³ Pa·s，对应 1150–1250 °C；砖窑温区是 1300–1500，而熔玻璃还要
 *    1400–1500（见 make/glass-brick-kiln）。窑里没有第二段温区，也没有铂漏板
 *    （Pt-Rh 合金漏嘴板，通电恒温在 1200 上下；当时没有铂族，现在 Pt-Rh
 *    合金熔炼已建，但漏嘴板仍未建）—— 只能把坩埚吊在窑口，借窑气的温度梯度找
 *    "正在凝固"的那一点。得到的单丝是 **15–25 µm 的粗丝**（工业连续纤维
 *    6–9 µm）：更挺、更脆、绕包时断头多。坩埚底孔还会被玻璃蚀大，丝径逐炉变粗。
 *
 *    更好的那条路是有的：让一台炉子把坩子稳在 1200–1250（感应炉调功率即可，
 *    玻璃不导电，要靠石墨或黏土坩子间接加热），丝能细到 20 µm 上下、孔蚀更慢。
 *    本文不走它 —— 这条路线的目的是**只用砖窑**（玻璃的炉子本来就是砖窑），
 *    而"砖窑熔化 + 一台炉子稳温"是两台设备接力，留给下一步。
 *
 * ⑤ **慢一到两个量级。** 手摇卷筒 φ320，一圈 1 m，一秒一圈就是 1 m/s；
 *    工业拉丝机 15–25 m/s。按 1 m/s 一直摇 8 小时 = 28.8 km，φ1.0 的铜线合
 *    0.785×10⁻⁶ m² × 28 800 m × 8 960 kg/m³ = **203 kg** —— 而实际要换道次、
 *    退火、修模、接断头，能摇到其中一小部分。模型没有产量刻度，这一条只能
 *    当注释读。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 它没有解决什么
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   · **只给了来路，没有接线。** `make/motor-windings` 与 `make/motor-rotor`
 *     （data/machine/motor.ts）的 `uses` 仍写着 `mat/enamel-wire`。要让绕组
 *     真能吃玻璃丝包线，得改那两处，或者加一条 `make/motor-windings-glass`。
 *     **本轮只加这一个文件、不动别的文件 —— 所以报告里这条链还差最后一段。**
 *   · **铜杆那一段没有单列。** 从 `mat/copper`（kg 计的精铜）到 φ8 铜杆之间
 *     是连铸 + 热轧，而轧机不在闭包里。本文按"铜以杆形态投入"写 —— 这与
 *     `make/separator-magnet` 直接拿 mat/copper 绕线圈是同一处口子。
 *     （铸态粗晶的杆不能直接拉：头几道就断。所以这里**不**假装熔铜浇杆。）
 *   · **拉丝模的口径与别处不一致。** `std/wire-die-general` 的条目注释说
 *     "工具进 needs"，而本文件按本轮约束不把 std/ 写进 needs —— 只在注释里
 *     点名它是既有工具。要统一，得改那一处注释或这条路线，不是本文能定的。
 *   · **产量与工时不在模型里。** ⑤ 只能当注释。
 */


/**
 * 镁砂 —— 从卤水来的碱性耐火料。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 一处冶金常识，本层写了很久才想明白
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 熔炼炉的炉衬一直用 `mat/refractory`（铝质，酸性）。**而炼钢的渣是碱性的。**
 *
 * 碱性渣（CaO、MgO、FeO）碰上酸性炉衬（SiO₂、Al₂O₃），会把炉衬一点点吃掉 ——
 * 这不是"用久了磨损"，是化学侵蚀，几炉就能把衬蚀穿。所以真实的炼钢炉
 * 一律用**碱性炉衬**：镁砂（MgO）、白云石（CaO·MgO）。
 *
 * 酸性与碱性不能混，这条在冶金里比什么都硬。而本层到这一轮才有 MgO。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 镁从卤水来
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 风化层里有 6–8% 的 MgO，但它在硅酸盐里，提取要打碎骨架（和铝一样麻烦）。
 * 卤水容易得多：**氯化镁溶在水里，加石灰就沉出氢氧化镁**。
 *
 *   卤水 + 消石灰 → 氢氧化镁 + 氯化钙母液
 *   氢氧化镁 →（600–750 °C 煅烧）→ 氧化镁 + 水
 *
 * 这也是海水提镁的老工艺（地球上镁的最大来源就是海水）。
 * 火星没有海，但有浓缩卤水 —— 那个孤岛继晒盐之后又有了第二个用途。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 三个用途
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   碱性炉衬   镁砂捣打料，替掉炼钢炉里的酸性砖 —— 这一层的主要目的
 *   烧结助剂   氧化铝陶瓷加 0.1% MgO 能抑制晶粒长大（本层还没用上）
 *   镁水泥     氯化镁加氧化镁得氯氧镁水泥，是火星上唯一不需要石灰石的水泥
 *
 * 第三条本层没建：建筑不进这一层。
 */


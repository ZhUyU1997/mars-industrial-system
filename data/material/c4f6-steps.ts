/**
 * C4F6 三步拆链 —— 让每一步的收率都能单独核对。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么拆
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 原来三步写在 `c4f6.ts` 的一条 `make/c4f6` 里，只有一个 55–70 % 的累积收率，
 * 质量账是一笔 5958 kg 的进出。那样写有两个后果：
 *   · 哪一步亏了多少看不出来 —— 55–70 % 只能整体估，不能逐步复算；
 *   · 中间物不存在，②的 ZnI₂、③的 ZnCl₂ 与未反应物混在同一个差额里。
 *
 * 拆成三条路线、两个中间物：
 *
 *   ① make/c4f6-adduct   CTFE + I₂ + Cl₂（ICl 现做）→ 加合物 CF₂Cl–CFClI
 *   ② make/c4f6-hftcb    加合物 + Zn + Cl₂ → HFTCB C₄Cl₄F₆ + ZnCl₂ + 2 ICl（回①）
 *   ③ make/c4f6          HFTCB + 2 Zn → C4F6 + 2 ZnCl₂（仍在 c4f6.ts）
 *
 * 每段的产物是一个可核对的 kg 数，收率 = 出料（按化学计量折回主产物）/ 进料。
 * **可核对 ≠ 已实测**：下面所有数字都是化学计量算的，本层没有实测
 * （为什么没有记录路线，见最后一节）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 收率窗口：三个数相乘 = 55.05–67.74 %（标称 59.88 % ≈ 60 %）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   ① 68–72 %   （标称 70）
 *   ② 88–98 %   （标称 91）
 *   ③ 92–96 %   （标称 94）
 *
 *   下界 0.68 × 0.88 × 0.92 = 0.550528 → 55.05 %
 *   上界 0.72 × 0.98 × 0.96 = 0.677376 → 67.74 %
 *   标称 0.70 × 0.91 × 0.94 = 0.598780 → 59.88 %
 *
 * 三个乘积都落在旧的 55–70 % 里（下界 55.05 > 55，上界 67.74 < 70）。
 * **旧的 55–70 是估算，不是实测** —— 这里只是把它拆成三个可复算的因子，
 * 并没有把它变成实测值。
 *
 * ⚠️ `yield` 的基：`mat/c4f6-adduct` / `mat/c4f6-hftcb` 写**单步**
 * （68–72 / 88–98）；`mat/c4f6` 写**累积 55.05–67.74**（对外口径，
 * 55–70 % 就是按这个口径写的）。三步乘积就是 `mat/c4f6` 的
 * `gives.yield`；`make/c4f6` 的单步 92–96 只写在 `c4f6.ts` 的注释与账里，
 * 不写进 `gives`（`mat/c4f6` 没有 `stepYield` 属性，加它要改
 * `fluorocarbon.ts`，不在本轮可改范围）。
 *
 * 为什么不能把文献的三个宽窗口直接相乘：
 *
 *   ① 17–68 %（一锅法 72 %，按 ICl 计）
 *   ② 72–98 %（工程 75–90 %）
 *   ③ 86–96 %（水相；水-醇共沸 78–83 %）
 *
 *   0.17 × 0.72 × 0.86 = 10.5 % —— 那是把三个不同操作点的低端乘在一起
 *   （−5–0 °C/CH₂Cl₂ 的①、未优化偶联的②、水-醇共沸的③），不是本层这条线。
 *   三个宽窗口各自跨着不同的反应器与溶剂，端点不是同一次运行，
 *   乘在一起没有物理意义。
 *
 * 本层取的三个工程段，逐条说清是怎么从文献值缩到这里的：
 *
 * ① 68–72 %：文献 17–68 % 是跨操作点的单程窗口；一锅法 72 % 是按 ICl 计的
 *   （加成 1:1，摩尔收率与按 CTFE 计相同）。本段的产物定义为**进入②的总加成物**
 *   （主/次两种 1,2-加成物都进②，见 `c4f6.ts` 原文件头），所以取窗口高端 68
 *   与一锅法 72。17 % 那一端是原文件头记的 −5–0 °C / CH₂Cl₂ 工业点；本层酸厂
 *   下限 20 °C，达不到那个低温，副产物只会更多。**68–72 是"按总加成物计"的
 *   口径选择，不是本层实测**；主/次比例没有查到（缺口③），若次异构体不能偶联，
 *   ① 会向 17 % 掉，55 % 的下界立刻守不住。
 *
 * ② 88–98 %：文献 72–98 %，工程估计 75–90 %。下界取 88（工程估计的上段），
 *   上界保留文献的 98。能站住的有利条件只有一条：温度压 20–35 °C
 *   （>25 °C 就消除回 CTFE，RU 2248844 例 9 在 50 °C 收率 ≤20 %）。
 *   **88–98 是工程判断，不是本层实测**；标称 91 不是窗口中点（93）——
 *   偶联对温度极敏感，取偏保守的一侧。
 *
 * ③ 92–96 %：文献水相 86–96 %、水-醇共沸 78–83 %。本层取水相的上半段：
 *   甲醇只是过程介质（`c4f6.ts` 原文件头），不按水-醇共沸体系的操作点
 *   78–83 % 取。92 这个下界是 55 % 累积下界成立的必要条件
 *   （0.68×0.88×0.92 = 55.05）—— 如果③落到水相的 86 %，累积下界就是
 *   0.68×0.88×0.86 = 51.5 %，旧窗口破了。这是本文件最脆弱的一格，不藏。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 化学计量与每步质量账（每 1000 kg 主产物；M 取 C 12.011 / F 18.998 /
 * Cl 35.453 / I 126.904 / Zn 65.38）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   加合物 C₂Cl₂F₃I  278.826      HFTCB C₄Cl₄F₆  303.844
 *   C4F6 C₄F₆        162.032      ZnCl₂           136.286
 *   ZnI₂             319.188      I₂              253.808
 *
 * ── ① 加成（make/c4f6-adduct）─────────────────────────────────────────────
 *   2 C₂ClF₃ + I₂ + Cl₂ → 2 C₂Cl₂F₃I        （ICl 现做：I₂ + Cl₂ → 2 ICl）
 *   每 1000 kg 加合物（3.5865 kmol）：
 *     CTFE 417.7 + I₂ 455.1 + Cl₂ 127.2 = 1000.0 ✓
 *   按 70 % 标称投料：
 *     CTFE 596.7 + I₂ 650.2 + Cl₂ 181.6 = 1428.6 → 加合物 1000
 *     差 428.6 = 未反应 CTFE 179.0 + I₂ 195.1 + Cl₂ 54.5（回①）
 *   碘不是消耗：650.2 是整批循环量（455.1 / 0.70）；净补 22.7 kg/1000 kg
 *   加合物（5 %，②的 ICl 返回后只补物理损失）。折到最终产品是
 *   **91.6 g/kg C4F6**：三步收率把每 kg C4F6 的加合物需求从化学计量的
 *   3.442 kg 抬到 4.023 kg（3.442/0.91/0.94），碘循环量从 1.566 涨到
 *   1.831 kg/kg，5 % 就是 91.6 g。旧文件的 78 g/kg 只按 1.566 算，没算
 *   收率损失；**10 kg 碘种子 ⇒ 约 109 kg C4F6，不是 128 kg**。
 *   ⚠️ `c4f6-etch.ts`、`iodine-seed.ts`、`ctfe.ts`、`fluorocarbon.ts` 的注释
 *   已同步改成 91.6 g/kg / 约 109 kg（原来是 78 g/kg / 128 kg）。
 *   ⚠️ ① 的 `uses` 写的是"开环起步"的整批 I₂ + Cl₂；稳态下 ① 的 ICl 由②返回
 *   （2 ICl/HFTCB = 1068.8 kg/1000 kg HFTCB = 582.3 kg/1000 kg 加合物，
 *   正好等于①的 ICl 化学计量），新鲜 I₂ 只剩 22.7 kg 净补，新鲜 Cl₂ 落在②的
 *   再生段（254.3 kg/1000 kg 加合物）。两笔账都写出来，免得把 inventory 当消耗。
 *
 * ── ② 偶联 + 碘再生（make/c4f6-hftcb）────────────────────────────────────
 *   2 C₂Cl₂F₃I + Zn → C₄Cl₄F₆ + ZnI₂
 *   ZnI₂ + 2 Cl₂ → ZnCl₂ + 2 ICl
 *   合并：2 加合物 + Zn + 2 Cl₂ → HFTCB + ZnCl₂ + 2 ICl
 *   每 1000 kg HFTCB（3.2912 kmol）：
 *     加合物 1835.3 + Zn 215.2 + Cl₂ 466.9 = 2517.4 ✓
 *     出 HFTCB 1000 + ZnCl₂ 448.6 + ICl 1068.8 = 2517.4 ✓
 *   按 91 % 标称投料：
 *     加合物 2016.8 + Zn 236.5 + Cl₂ 513.1 = 2766.4 → 2517.4
 *     差 249.0 = 未反应加合物 181.5 + Zn 21.3 + Cl₂ 46.2（回②）
 *   ICl 1068.8 回①，不是产品；ZnCl₂ 448.6 是这一步的锌盐出口。
 *
 * ── ③ 脱氯（make/c4f6，在 c4f6.ts）───────────────────────────────────────
 *   C₄Cl₄F₆ + 2 Zn → C₄F₆ + 2 ZnCl₂
 *   每 1000 kg C4F6（6.1716 kmol）：
 *     HFTCB 1875.2 + Zn 807.0 = 2682.2 ✓
 *     出 C4F6 1000 + ZnCl₂ 1682.2 = 2682.2 ✓
 *   按 94 % 标称投料：
 *     HFTCB 1994.9 + Zn 858.5 = 2853.4 → 2682.2
 *     差 171.2 = 未反应 HFTCB 119.7 + Zn 51.5（回③）
 *   这一步的账写在 `c4f6.ts` 的 `make/c4f6` 里，本文件只列出来对总账。
 *
 * 整条链的净式（碘循环只补损失）不变：
 *   2 C₂ClF₃ + 3 Zn + 2 Cl₂ → C₄F₆ + 3 ZnCl₂
 * 三个 ZnCl₂ = ②的 1 个（ZnI₂ 再生）+ ③的 2 个；碘在①与②之间闭合成环。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 记账单位 1000 kg ≠ 一锅 5.46 kg（碘库存定的）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 本文件沿用全库的“每 1000 kg 主产物”记账单位（`qty: q(1000)`），
 * **它不是反应釜一锅的装料量**。一锅的上限由碘库存定：
 *
 *   循环碘 1.831 kg I₂/kg C4F6 ⇒ 10 kg 碘种子最多撑 10/1.831 = **5.46 kg C4F6/锅**。
 *
 * 1000 kg 一批要 1831 kg 碘在循环，是种子的 183 倍，开不了。所以：
 *   · 一锅 5.46 kg；1000 kg 记账单位 = 183 锅；
 *   · 10 kg 碘按 91.6 g/kg 补损，总共只能产出约 109 kg C4F6 = 20 锅；
 *   · 1000 kg 是**记账比例尺**，不是可完成的 campaign；可完成的 campaign 是 109 kg。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 三个可核对的点，以及为什么没有记录路线
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 三个点（每段一进一出，全是 kg）：
 *   ① 进 CTFE 597 + I₂ 650 + Cl₂ 182；出加合物 1000
 *   ② 进加合物 2017 + Zn 237 + Cl₂ 513；出 HFTCB 1000 + ZnCl₂ 448（ICl 1069 另称）
 *   ③ 进 HFTCB 1995 + Zn 859；出 C4F6 1000 + ZnCl₂ 1682
 *
 * 本层没有实测：收率测量是**验证缺口**，不是制造缺口。本文件只把三段分开，
 * 让三个点可以逐段核对。
 * 升级路径：**外委做三步的质量/组成分析**（对方的天平/色谱，不本地造仪器、
 * 不写设备路线）；拿回三段进出料数据再回填。
 *
 * ⚠️ 68–72 / 88–98 / 55.05–67.74 仍是验收窗口，不是实测值。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 边界
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * · `make/c4f6` 的 id 不变，`mat/c4f6` 的消费者（`make/rie-oxide-trench-c4f6`）
 *   一条都不动。
 * · 中间物两个条目：`mat/c4f6-adduct`、`mat/c4f6-hftcb`。
 * · 甲醇仍按"过程介质、不消耗"处理，不建条目（缺口②）。
 * · ICl 不建条目：它是①与②之间的循环流，写在②的 `unbalanced_zh` 里（1068.8 kg）。
 * · ①的主/次加成物比例未查到（缺口③）。
 */


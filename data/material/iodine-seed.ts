/**
 * 碘 —— 有本地路线了，但路线建在一个设计值上。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 先说什么没变
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 火星没有海藻、没有硝石；高氯酸盐是氯不是碘。公开的 2024–2026 数据没有
 * 给出火星卤水的碘品位。所以本层仍然不建“碘矿 → 碘”的路线 —— 那会是编矿。
 *
 * 现在建的是另一条：**卤水里的碘离子 → 碘**（`make/iodine`，声明在
 * data/material/reagents.ts）。它把“没有路线”变成“有路线，但品位是设计值”。
 * 这是本条目的全部诚实性所在：路线能跑，前提是卤水真的含碘。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 用量仍是种子级
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   RTA 卤素灯      24 只 × 1–5 mg = 24–120 mg/套；1 g 够 8–40 套
 *   碘稳频激光      1–10 mg/只
 *   偏振片          0.5–2 g/m²
 *   碘量法/碘值     100–500 g KI ≈ 76–380 g I
 *   C4F6            91.6 g I/kg（95 % 回收）⇒ 10 kg 约 **109 kg C4F6**
 *
 * ⇒ **初始 10 kg 碘**（约 2 L，密度 4.93 g/cm³）仍是第一套要运来的量：
 * RTA 灯、激光、偏振、分析、C4F6 研发都能覆盖很多年。它是“一桶进口料”，
 * 不是“一座矿”；本地路线只说明这桶料理论上能续，不说明已经续上。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 本地路线：氯气氧化卤水里的碘离子
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   2I⁻ + Cl₂ → I₂ + 2Cl⁻
 *
 *   卤水 2778（按 400 ppm I 设计）+ 氯 0.30 + 硫酸 5 + 洗涤水 10
 *     → 碘 1.000 + 提碘卤水 2792.30
 *
 * 三步：酸化/氯氧化（湿法槽）→ 过滤洗涤（机器人）→ 升华精制（升华井）。
 *
 * 400 ppm 是**设计值**：USGS 给智利 caliche 的典型含碘 0.04%（400 ppm），
 * Iofina 的油田卤水 50–2000 ppm；火星卤水的碘品位没有实测。90% 收率同样
 * 是设计值，没有中试。两处都在 `make/iodine` 的注释里。
 *
 * 为什么不用亚硝酸钠：`mat/sodium-nitrite` 全表 0 条目，氧化剂只有氯气。
 * 氯从 Deacon/氯碱来，硫酸从湿法/接触法来 —— 两样都在本层。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 可复制性：从“不能”改成“有条件地能”
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   本地能否复制：**能，前提是卤水含碘**。路线按 400 ppm 设计；火星卤水的
 *                    碘品位没有实测，这是本条目的缺口①。
 *   能复制的是什么：**碘离子氧化 + 升华**，不是“碘矿”。卤水里的碘以 I⁻ 计；
 *                    若实际是 IO₃⁻（caliche 那种），要先还原，本层未写。
 *   回收仍是主路：C4F6 的 ZnI₂ → ICl 再生 >95%；91.6 g/kg 的补充量就是按
 *                    5% 物理损失记的。
 *   库存耗尽会怎样：C4F6 先停（10 kg → 109 kg），RTA 灯还能靠 0.12 g/套撑；
 *                    激光/偏振/分析也停 —— 本地路线只解决“料从哪来”，
 *                    不解决“够不够快”。
 *   不许把它写成“已闭环”：10 kg 仍是第一套；路线是设计值，没有实测。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 它不解锁什么
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 有碘条目 + 本地路线 ≠ 碘稳频激光：那还要 I₂ 池、10 kHz 相敏、温控；
 * 也不解锁“偏振片”：那还要定向 PVA 膜与拉伸设备。
 *
 * C4F6 路线（c4f6.ts）仍按“进口碘 + CTFE”写；本地碘只说明理论上可以续。
 */


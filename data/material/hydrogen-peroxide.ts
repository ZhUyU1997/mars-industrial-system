/**
 * 过氧化氢 —— CMP 的氧化剂，而它一直不在表上。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 一、它缺得和硝酸一样不是地方
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * `cmp-integration.ts:410–412` 的原话：
 *
 *   「**`mat/hydrogen-peroxide` 全表 0 命中**（`peroxide` 也 0）。任务书的投料清单里
 *     把它写成"若存在"——**不存在**。所以本文件的氧化剂仍是重铬酸钠（Cr(VI)，
 *     废液只能用石灰还原中和，没有铬的检测手段）。」
 *
 * 同一处缺口另有两份文件记着：`cmp-slurry.ts:366`（R8 ⑤，"氧化剂仍是 Cr(VI)"）与
 * `cmp-slurry.ts:490`（铜浆配方里 0.5 wt% 重铬酸钠）。也就是说：**CMP 的化学被钉在
 * Cr(VI) 上，不是因为 Cr(VI) 好，是因为 H₂O₂ 这一格是空的。**
 *
 * 代价不在"氧化剂弱不弱"，在金属：Cr 是金属污染源（`car-resist.ts:324` 把重铬酸盐胶
 * 的 Cr 面密度算到 1.2×10¹⁶ /cm² 那一笔，是同一个元素）。H₂O₂ 分解成水与氧，
 * **不带金属、不带氯**（本路线是硫酸体系，见 §三）—— 这是它值得单独写一条链的理由。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 二、为什么是电化学，不是蒽醌法
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 工业上绝大多数 H₂O₂ 走蒽醌法（AO，2-乙基蒽醌氢化 → 氧化 → 萃取）。它要四样东西，
 * 本层 grep 的结果是**四样都缺**（Pd 现在有海绵料，缺的是催化剂形态与另外三样）：
 *
 *   2-乙基蒽醌     `mat/anthraquinone` 0 条
 *   Pd 催化剂      `mat/palladium` / `mat/platinum` 当时 0 条；现在 `pgm.ts` 有海绵
 *                  Pt/Pd，但 Pd/Al₂O₃ 催化剂（浸渍/焙烧）路线未建
 *   重芳烃 + 磷酸三辛酯   `organic.ts` 只到 C1 甲烷与 C2 乙炔（`ores.ts:18–27`：
 *                  "火星的有机化学只有 PTFE 与 Bosch 碳：没有醇、没有苯、没有脂肪酸"）
 *   氢循环         `mat/hydrogen` 有，但蒽醌法要的是"无水无氧的氢化塔" —— 塔 0 座
 *
 * ⇒ **蒽醌法整条不在，这不是降级，是另一条问题**（R3）。剩下的是比它老半个世纪的
 * 一条：**在阴极上把氧直接还原成过氧化氢**（1890 年代就有，氯碱厂用它做副产）。
 *
 *   阴极   O₂ + 2H⁺ + 2e⁻ → H₂O₂        E° = +0.695 V（文献值）
 *   阳极   H₂O → ½O₂ + 2H⁺ + 2e⁻        E° = +1.229 V（文献值）
 *   ────────────────────────────────────────────────────
 *   净     **½O₂ + H₂O → H₂O₂**          E°cell = 0.53 V（文献值）
 *
 * 净反应就是全部质量账的来源：**1 kg H₂O₂ 要 O₂ 0.470 kg + 水 0.530 kg**（16.00/34.015
 * 与 18.015/34.015）。阳极那 ½O₂ 正是阴极要的一半 —— **所以阳极氧必须回阴极**，
 * 不回就是氧单耗翻倍（§四）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 三、用哪台设备 —— `plant/electrolyzer`，先读它的窗口
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * `process.ts:343–347` 给的 holds 是 **10–90 °C、50–500 kPa**。本路线要的是
 * **20–60 °C、50–200 kPa**（阴极过电位随温度掉、但 H₂O₂ 在 60 °C 以上开始明显分解；
 * 常压不行，610 Pa 下水在 0.01 °C 就沸腾 —— 与 `make/hydrogen` 同一条理由）。
 *
 *   ⇒ **窗口落在里面，不需要新建一台"H₂O₂ 电解槽"。** 这是本文件能落地的那一半。
 *
 * 但有一件要换：`process.ts:335–336` 写这台槽是「镍电极、PTFE 隔膜、晶闸管整流」。
 * **镍在阴极上会把 H₂O₂ 催化分解**（Ni 是过氧化氢分解的经典催化剂），而 O₂ 还原要的是
 * **碳/石墨的气体扩散阴极**。所以：
 *
 *   槽体、隔膜、整流、气液分离 —— 全用既有的 `plant/electrolyzer`；
 *   阴、阳两极 —— 从 `std/carbon-electrode-300` 锯两段（φ300×600 一支 72 kg，
 *                  `oxygen-metrology.ts:1143`）。碳不催化 H₂O₂ 分解，且在稀硫酸里稳定。
 *
 * 电极写进 `needs`（在场的前提），**不改 `plant/electrolyzer` 的 `composedOf`** ——
 * 换一件阴极不是换一台槽。⚠️ 不能写进 `uses`：`std/carbon-electrode-300` 是
 * `part`，模型的 `part_as_raw_material` 会拦（这条路线不产出机器）。电极消耗按
 * 寿命另记，本层没有磨损模型，不假装它按批吃掉。
 *
 * 槽电压与电流效率（都是文献值，本层无出处）：
 *
 *   槽压 **2.5–4.0 V**（理论 0.53 V；差额是阳极氧析出过电位 + 欧姆降 + 隔膜）
 *   电流效率 **70–90 %**（氧还原到 H₂O₂ 是 2e⁻ 路径，副反应是 4e⁻ 直接到水）
 *
 * 阴极室（稀硫酸）循环，H₂O₂ 累积到 **3–5 wt%** 就连续抽出 —— 这是"阴极液循环"模式，
 * 不是先做浓再稀释。**所以本文件的交付形态就是 3–5 wt% 溶液，不是 30 %。**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 四、质量账（1000 kg 5 wt% 溶液）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *   进   氧 **23.52** + 水 **976.48** + 硫酸 10 + 石墨 1 kg（电极，按件计不进 kg 账）
 *   出   5 wt% 溶液 **1000**（其中 H₂O₂ 50 kg）
 *
 *   50 kg H₂O₂ 的化学计量：O₂ 23.52（= 50 × 0.470）+ 水 26.48（= 50 × 0.530）
 *   余下的 950 kg 水是稀释水 ⇒ 总水 976.48，加氧正好 1000 ✓
 *
 *   23.52 与 976.48 的分数形式是 q(588,25) 与 q(24412,25)，模型里存的是有理数。
 *
 * **两笔必须写明的账：**
 *
 *   ① **阳极氧要回收。** 阴极按 2e⁻ 吃 47.04 kg O₂、阳极放出 23.52 kg —— 净 23.52。
 *      阳极气直接排掉，进料就得写 47.04，**氧单耗翻一倍**。本路线按"回收"写，
 *      回收动作落在 `plant/electrolyzer/gas-separator`（它本来就是干这个的）。
 *   ② **硫酸是循环的，10 kg 只是补充。** 硫在阴极室不消耗；走掉的那一点是
 *      **酸雾（H₂SO₄ 气溶胶）随阳极氧与尾气带出**，按产品的 1 wt% 估（**估，待查**）。
 *      酸雾没有条目，记在 `unbalanced_zh` 里。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 五、R8 —— 这条链的四处降级与升级路线
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * | # | 降级（现在） | 原规格 | 恢复它要什么 | 缺口量级 |
 * |---|---|---|---|---|
 * | ① | 浓度 **3–5 wt%**（阴极液循环的直接产物） | 蒽醌法 **30–50 wt%**（商品级） | 蒽醌 + 重芳烃 + Pd 催化剂 + 氢化塔，**四样都缺**（Pd 有海绵料，催化剂形态与另外三样仍缺；§二）；或真空蒸发浓缩 —— 但水先走、H₂O₂ 跟着热分解，**这条路本身不成立**（不是缺设备，是原理） | **6–10×** |
 * | ② | 电耗 **7–9 kWh/kg**（100 % 基准） | 蒽醌法更低（本层无出处，不写数） | 降槽压（催化阴极、薄隔膜、高电导电解液）与提电流效率 | 算式：1 kg = 29.4 mol × 2F = **1 576 Ah**；3.5–4.2 V ÷ 0.7–0.8 ⇒ **6.9–9.5 kWh/kg 电**。**估，待查** |
 * | ③ | **无稳定剂**（`stability = unstabilized`） | 锡酸钠 20–50 ppm 或焦磷酸钠（商品 H₂O₂ 的标配） | 锡酸钠要锡 + 碱熔氧化（`mat/tin` 有，euv-metals.ts:213；锡酸钠 0 条）；焦磷酸钠要磷酸 + 纯碱（两样都有，焦磷酸钠 0 条）| 分解速率**待查**（本层没有测 H₂O₂ 浓度的手段，见缺口④）；**3–5 % 的稀液分解比 30 % 慢**，这是降级里唯一自带的补偿 |
 * | ④ | **CMP 只用 0.5 wt%**（cmp-slurry.ts:490） | — | 3–5 % 稀释 **6–10 倍**即到 | **这一格是闭合的**：差的是"浓品/储运"，不是"有没有" |
 *
 * **第④行是本文件的结论**：3–5 wt% 对 CMP 不是降级 —— 工业铜浆的 H₂O₂ 也是
 * "买 30 %、现场稀释到 0.5–2 %"。本层没有 30 %，但**从 5 % 稀释到 0.5 % 只要水**，
 * 而水是火星最便宜的东西。所以 CMP 这一格从 Cr(VI) 换成 H₂O₂ 是**功能闭合**的；
 * 挂着的只是浓品（≤1 wt% 的运费/储罐体积在模型里不存在，因为模型没有体积）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 六、已知缺口（"现在没有"，不是"暂未实现"）
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  ① **阴极要换件。** `plant/electrolyzer` 的零件清单里没有碳电极（镍电极 + PTFE 隔膜），
 *     本路线把石墨写在 `needs` 里，**没有改那台设备的定义**（那是 `process.ts` 的地盘）。
 *     所以严格说：这台槽"能执行"，但要换一件阴极 —— 这一句必须留在这里，不能藏。
 *     电极是零件（`part`），写进 `uses` 会被 `part_as_raw_material` 拦；寿命本层没有磨损模型。
 *  ② **没有稳定剂**（锡酸钠/焦磷酸钠 0 条）。3–5 % 的 H₂O₂ 无稳定剂也会缓慢分解，
 *     分解速率本层**测不了也查不到出处** ⇒ 只能按"现做现用、不库存"写。
 *  ③ **没有测 H₂O₂ 浓度的手段。** 碘量法要碘化钾（`mat/potassium-iodide` 0 条）、
 *     高锰酸钾法要高锰酸钾（0 条）、分光/电极法要量具（0 台）。所以 `gives` 里的
 *     **3–5 wt% 是按法拉第电量记账算出来的，不是量出来的** —— 与"没有量具就算未测"
 *     同型（失败与漂移都不出声）。`cmp-integration.ts:404` 的"氧化剂浓度测不了"
 *     在换成 H₂O₂ 之后**并没有变好**，只是把"Cr(VI) 测不了"换成了"H₂O₂ 测不了"。
 *  ④ **氯离子没有量具。** 硫酸体系理论上不带氯（水与氧是仅有的两样液体/气体进料），
 *     但"理论上"不是"测过" —— CMP 对 Cl⁻ 敏感（它咬铜），这一格是开环。
 *  ⑤ **模型没有焓。** 配 1 M 电解液的稀释热、稀释到 0.5 wt% 的混合热，都没有栏可记。
 *     它们只影响温控（`plant/electrolyzer` 的 10–90 °C 够宽），不影响物料 —— 记在这里。
 *  ⑥ **本文件还没接进 `tools/report.ts`。** 按任务约束没有动那份文件，所以
 *     `mat/hydrogen-peroxide` 暂时不出现在汇总里，也**不会被报成 `unproduced`**。
 *     接线的动作只有一行 import + 两处展开（与 `unblock-hf.ts` 同一种接法）。
 */


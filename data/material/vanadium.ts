/**
 * 钒 —— 我判错过一次，这里把账算清。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * "不划算"是个拍脑袋的判断
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 上一版把钒催化剂留在地球，理由是：
 *
 *   "钒在风化层里百 ppm 级，富集到 5% 是 500:1，再加焙烧、浸出、沉钒三步。
 *    而一台转化器一层只用几十公斤 —— 为它建一条线，线的零件比催化剂重几百倍。"
 *
 * 那段话里"500:1"听起来吓人，于是结论就滑到了"不划算"。**但富集比不是判据，
 * 绝对量才是。** 算一遍：
 *
 *   风化层含钒 100 ppm，V₂O₅ 含钒 56%，回收率 90%
 *   → 每 kg V₂O₅ 要 19,841 kg 风化层
 *   → 一层催化剂 50 kg V₂O₅ 要 **992 吨风化层**
 *
 * 992 吨听起来也不少？换算一下：**约等于 30 吨铝的土方量**（铝 33.4 kg/kg）。
 *
 * 一座厂要烧的铝是几百吨 —— **那点钒的土方量，连铝的零头都不算。**
 *
 * 所以"不划算"这个判断是错的。真正的结论是：**钒比镍贵、比铜便宜、
 * 比钨便宜五十倍**。它一直该自己造。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 教训写在这里，因为它比钒本身重要
 * ═══════════════════════════════════════════════════════════════════════
 *
 * **富集比（500:1、8333:1、515000:1）是"每单位产品的代价"，不是"总代价"。**
 * 判一样东西该不该自己造，要看的是**总代价 = 单价 × 用量**。
 *
 * 钒：500:1 × 几十公斤 → 便宜
 * 磁铁的铁氧体：锶痕量 × 几十公斤 → 也便宜？但它的富集要到 20000:1，且要先找到天青石
 *
 * 反例更清楚：钨的富集是 515,000:1，而刀片的用量以公斤计 —— 它贵，
 * 但因为用量少，仍然是"造"而不是"运"。
 *
 * 所以真正的判据是**用量 × 单价**，两个都要看。只看一个，就会得出这种错误结论。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 工艺：钠化焙烧 → 水浸 → 沉钒 → 煅烧
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 钒在风化层里分散在辉石与磁铁矿里（V³⁺ 替位 Fe³⁺）。提取靠三步：
 *
 *   ① 钠化焙烧   精矿 + 纯碱，850–900 °C，钒变成可溶的钒酸钠
 *   ② 水浸       钒酸钠溶进水里，其余留在渣里
 *   ③ 加酸沉钒   调 pH 到 2 左右，红色多钒酸铵/钒酸沉淀出来（"红饼"）
 *   ④ 煅烧       红饼在 500–600 °C 分解成 V₂O₅
 *
 * 前三步是湿法，酸吸收装置够用；第④步在窑或气氛炉里。
 */


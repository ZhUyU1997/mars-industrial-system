/**
 * 无源件 —— 电子元件里唯一"看起来能自己做"的一档。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 先说结论：四类电子元件，只有这一档的门槛不在半导体
 * ═══════════════════════════════════════════════════════════════════════
 *
 *   std/power-device-general     单晶硅 + 深结扩散 + 封装      → 不是本层的事
 *   std/control-board-general    光刻 + 贴装 + 处理器          → 同上
 *   std/sensor-general           编码器要光栅、要标定          → 一半能碰（见下）
 *   std/passive-component-general 电阻、电容、继电器、端子      → **材料与绕制**
 *
 * 无源件不需要单晶硅：
 *
 *   电阻     镍铬丝绕在陶瓷骨架上 —— 电阻率由合金成分给，不靠几何精度
 *   电容     **箔式**薄膜电容：两张铝箔夹两层塑料膜卷起来 —— 卷得紧就行
 *   继电器   线圈 + 铁芯 + 触点（钨铜）—— 与接触器同一条路
 *   端子     铜排 + 绝缘 + 螺钉 —— 最简单的一件
 *
 * ⚠️ 电容那一行要说准：薄膜电容有**两种做法**，本层只能做箔式那一种。
 *
 *   箔式       铝箔 + 塑料膜，四层卷绕            → 能做（轧箔与分切即可）
 *   金属化膜式 塑料膜上真空蒸镀一层铝当电极        → 不能（要真空蒸镀）
 *
 * 两者的区别是**电极从哪来**：箔式的电极是现成的铝箔，金属化膜式的电极是镀上去的
 * 一层几十纳米的铝。后者省体积、自愈性好，但离不开真空蒸镀 —— 那是另一条链。
 * 说"金属化膜"就等于说了一件本层做不到的事，所以下面一律写箔式。
 *
 * 所以这一档的"复制"不是复制半导体，是**把电工材料做成电工件** —— 熔炼、拉丝、
 * 绕制、烧结，全是本层已有的动作。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么先做电阻丝
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 因为它是这一档的**第一块砖**：电阻、电炉、加热器、继电器线圈的阻尼，全从它起。
 * 它也是唯一一个"做出来立刻有人吃"的：恒温机组（data/machine/metrology.ts）
 * 一直写着"加热丝"，而那条路线里没有这一项 —— 现在有了。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 真正的回报不是电阻，是电阻炉
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 镍铬丝能到 1200 °C 不氧化。这意味着可以造**电阻炉** —— 而本层一直缺一台
 * 热处理炉：淬火、回火、球化退火、时效都在借还原炉的温度窗口（650–900），
 * 氮化（520–560）连借的地方都没有。
 *
 * **下游已经落地了**：`plant/resistance-furnace`（100–1100 °C）见
 * data/machine/resistance-furnace.ts —— 淬火/回火/球化退火归它，
 * 氮化靠它那只密封罐通氨。柔轮因此从调质改回氮化（一次降级撤销）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 降级在哪
 * ═══════════════════════════════════════════════════════════════════════
 *
 * 铬从**高碳铬铁**来（本层没有真空脱气，也没有电解铬）：碳跟着进丝，
 * 丝脆、寿命短一档。成分对，杂质不对 —— 与轴承钢氧含量那一条同型（数字要能核
 * 不许编数，所以这里只说方向，不给寿命）。
 */

